"""从全量场景构造小实例。

用途：
- E1 精确基准；
- E4 灵敏度、E5 可扩展性；
- 不修改原场景，返回一个新的 `场景` 对象。

原则：
- 只保留选定的服务区与其货箱；
- 航段表只保留节点子集；
- 机队与电池可按机型缩编（用于小实例精确求解）。
"""
from __future__ import annotations

import sys
from dataclasses import dataclass
from pathlib import Path

项目根 = Path(__file__).resolve().parents[2]
if str(项目根) not in sys.path:
    sys.path.insert(0, str(项目根))

from 源代码.公共库.通信中继.场景装配 import 场景, 装载场景  # noqa: E402
from 源代码.公共库.基础内核.数据读取 import 按服务区归组货箱  # noqa: E402


@dataclass
class 实验实例:
    名称: str
    场景: 场景
    说明: str = ""


def 子场景(
    全场景: 场景,
    服务区列表: list[str],
    每型无人机数: int | None = None,
    每型电池数: int | None = None,
) -> 场景:
    """按服务区子集与机队缩编构造新场景。"""
    编号顺序 = tuple(服务区列表)
    节点集 = {"O01", *编号顺序}
    服务区表 = {k: 全场景.服务区表[k] for k in 编号顺序}
    货箱 = [b for b in 全场景.货箱 if b["服务区编号"] in 编号顺序]
    货箱.sort(key=lambda b: b["货箱编号"])
    货箱归属 = 按服务区归组货箱(货箱)
    航段表 = {
        k: v for k, v in 全场景.航段表.items() if k[0] in 节点集 and k[1] in 节点集
    }

    无人机表 = dict(全场景.无人机表)
    if 每型无人机数 is not None:
        计数: dict[str, int] = {}
        保留 = {}
        for 编号, 记录 in 无人机表.items():
            型 = 记录["机型编号"]
            计数[型] = 计数.get(型, 0) + 1
            if 计数[型] <= 每型无人机数:
                保留[编号] = 记录
        无人机表 = 保留

    电池表 = {k: dict(v) for k, v in 全场景.电池表.items()}
    if 每型电池数 is not None:
        for 型 in 电池表:
            电池表[型]["组数"] = min(int(电池表[型]["组数"]), 每型电池数)

    return 场景(
        调度中心=全场景.调度中心,
        服务区表=服务区表,
        编号顺序=编号顺序,
        机型表=dict(全场景.机型表),
        无人机表=无人机表,
        电池表=电池表,
        货箱=货箱,
        货箱索引={b["货箱编号"]: b for b in 货箱},
        货箱归属=货箱归属,
        航段表=航段表,
        地面高程=全场景.地面高程,
        纬度向量=全场景.纬度向量,
        经度向量=全场景.经度向量,
    )


def 截断货箱(原场景: 场景, 每区上限: int) -> 场景:
    """每个服务区只保留前 `每区上限` 个货箱，用于更小的精确实例。"""
    货箱 = []
    for 区 in 原场景.编号顺序:
        本区 = sorted(原场景.货箱归属.get(区, []), key=lambda b: b["货箱编号"])
        货箱.extend(本区[:每区上限])
    货箱.sort(key=lambda b: b["货箱编号"])
    return 场景(
        调度中心=原场景.调度中心,
        服务区表=原场景.服务区表,
        编号顺序=原场景.编号顺序,
        机型表=原场景.机型表,
        无人机表=原场景.无人机表,
        电池表=原场景.电池表,
        货箱=货箱,
        货箱索引={b["货箱编号"]: b for b in 货箱},
        货箱归属=按服务区归组货箱(货箱),
        航段表=原场景.航段表,
        地面高程=原场景.地面高程,
        纬度向量=原场景.纬度向量,
        经度向量=原场景.经度向量,
    )


def 小实例(名称: str = "small_4区") -> 实验实例:
    """默认小实例：4 个服务区、每型 1 架无人机、每型 2 组电池。"""
    全 = 装载场景()
    # 选 4 个有货箱、彼此距离适中的服务区；可按需要替换
    候选 = ["S009", "S010", "S011"]
    场景 = 子场景(全, 候选, 每型无人机数=1, 每型电池数=2)
    return 实验实例(名称=名称, 场景=场景, 说明=f"服务区 {候选}")


