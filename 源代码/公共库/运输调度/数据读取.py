"""
数据读取 —— 多点多架次调度所需输入数据的统一入口。

单点往返与组批已经用到的四张表（调度中心/服务区、机型、货箱清单、DEM）**直接复用**
`公共库.数据读取`，不重复解析；本模块只增补单点往返与组批未用到的两张表：

    * `运输无人机`   实体无人机清单（U01–U08）与所属机型、初始位置
    * `共享电池`     各机型共享电池组总数与等效完全充电时间

数据源口径：`基础数据/无人机数据/json/`（UTF-8）。JSON 键名自带单位后缀
（如 "共享电池组总数（组）"），本模块负责剥离为纯量纲字段。
"""
from __future__ import annotations

import json

from 源代码.公共库.基础内核 import 数据读取 as _单点往返与组批读取
from 源代码.公共库.基础内核.配置 import 无人机数据目录


# ===================== 原始 JSON =====================
def _读表(文件名: str, 表名: str) -> list[dict]:
    路径 = 无人机数据目录 / f"{文件名}.json"
    数据 = json.loads(路径.read_text(encoding="utf-8"))
    if 表名 not in 数据["tables"]:
        raise KeyError(f"{文件名}.json 中不存在表 [{表名}]，实际有 {list(数据['tables'])}")
    return 数据["tables"][表名]


# ===================== 单点往返与组批已有表的转口 =====================
读取调度中心 = _单点往返与组批读取.读取调度中心
读取服务区 = _单点往返与组批读取.读取服务区
读取机型 = _单点往返与组批读取.读取机型
读取货箱 = _单点往返与组批读取.读取货箱
按服务区归组货箱 = _单点往返与组批读取.按服务区归组货箱
读取DEM = _单点往返与组批读取.读取DEM


# ===================== 多点多架次调度增补：实体运输无人机 =====================
def 读取运输无人机() -> list[dict]:
    """返回 [{无人机编号, 机型编号, 初始位置}, ...]，按编号升序。"""
    结果 = []
    for 行 in _读表("运输无人机数据", "运输无人机"):
        结果.append(
            {
                "无人机编号": 行["无人机编号"],
                "机型编号": 行["机型编号"],
                "初始位置": 行["初始位置"],
            }
        )
    return sorted(结果, key=lambda x: x["无人机编号"])


# ===================== 多点多架次调度增补：共享电池库存 =====================
def 读取共享电池() -> dict[str, dict]:
    """返回 {机型编号: {组数, 等效完全充电时间}}。

    "共享电池组总数包含实体无人机初始使用及备用周转所需电池"
    （《电池与能源组件充电周转规则》原文）。
    """
    结果: dict[str, dict] = {}
    for 行 in _读表("运输无人机数据", "共享电池"):
        结果[行["机型编号"]] = {
            "机型编号": 行["机型编号"],
            "组数": int(行["共享电池组总数（组）"]),
            "等效完全充电时间": float(行["等效完全充电时间（s）"]),
        }
    return 结果
