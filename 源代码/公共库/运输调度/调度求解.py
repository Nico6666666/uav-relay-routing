"""
调度求解 —— 把一组"已确定机型与访问顺序"的架次落到 (无人机, 共享电池, 开始时刻) 上。

方法：**确定性列表调度（list scheduling）+ 多序择优**。

对每个架次，在**该机型**的无人机与共享电池中选一对 (u, b)，使
`开始时刻 = max(u.可用时刻, b.可用时刻)` 取最小；并列时按编号升序。
这正是 `P||Cmax` 的经典列表调度，规则简单、完全确定、无随机性。

为降低"排序顺序决定解质量"的敏感性，本模块对每个架次集合尝试**若干种固定排序**，
按 `(完成时间, 全部货箱送达时刻之和)` 字典序取最优。排序策略与并列规则全部固定，
因此同一份输入必然得到同一份调度。

资源口径（详见 `资源模型`）：
    * 无人机在 [开始时刻, 返回时刻] 内被占用；返回后立即可再派下一架次
    * 电池在 [开始时刻, 返回时刻] 内被占用；随后必须充至 100% 才能再投入
      （"再次投入任务前应充至 100%"，问题设定）
    * 同一架次的无人机与电池必须同机型；不同机型之间不可混用
"""
from __future__ import annotations

from 源代码.公共库.运输调度.方案结构 import 架次, 硬截止时间, 调度记录
from 源代码.公共库.运输调度.资源模型 import 结束SOC as 计算结束SOC
from 源代码.公共库.运输调度.资源模型 import 构造资源池
from 源代码.公共库.运输调度.配置 import 数值容差

# 固定排序策略（全部确定性；顺序固定 ⇒ 择优结果确定）
排序策略集 = ("最紧截止", "时长降序", "载质量降序")


def _排序键(策略: str):
    if 策略 == "最紧截止":
        # 最早截止优先（EDF）：硬截止紧的先排；无硬截止视为无穷
        return lambda a: (a.最紧硬截止 if a.最紧硬截止 is not None else float("inf"), a.序号)
    if 策略 == "时长降序":
        return lambda a: (-a.作业时间, a.序号)
    if 策略 == "载质量降序":
        return lambda a: (-a.总载质量, a.序号)
    raise KeyError(策略)


def 单次调度(场景, 架次列表: list[架次], 策略: str) -> dict[int, 调度记录]:
    """按 `策略` 给定顺序做一次贪心列表调度。"""
    池 = 构造资源池(场景)
    顺序 = sorted(架次列表, key=_排序键(策略))
    记录表: dict[int, 调度记录] = {}

    for 架 in 顺序:
        机型编号 = 架.机型编号
        无人机编号表 = 池.机型无人机列表(机型编号)
        电池编号表 = 池.机型电池列表(机型编号)
        if not 无人机编号表 or not 电池编号表:
            raise RuntimeError(f"机型 {机型编号} 无可用无人机或共享电池")

        最佳 = None
        for 无人机序, 无人机编号 in enumerate(无人机编号表):
            for 电池序, 电池编号 in enumerate(电池编号表):
                开始 = max(
                    池.无人机[无人机编号].可用时刻,
                    池.电池[电池编号].可用时刻,
                )
                键 = (开始, 无人机序, 电池序)
                if 最佳 is None or 键 < 最佳[0]:
                    最佳 = (键, 无人机编号, 电池编号)

        _, 无人机编号, 电池编号 = 最佳
        开始 = 最佳[0][0]
        返回 = 开始 + 架.作业时间

        机 = 场景.机型表[机型编号]
        本次结束 = 计算结束SOC(机, 架.能耗)
        充电完成 = 池.电池[电池编号].释放(
            返回, 本次结束, 池.等效完全充电时间(机型编号)
        )

        无人机 = 池.无人机[无人机编号]
        无人机.可用时刻 = 返回
        无人机.架次数 += 1
        无人机.累计作业时间 += 架.作业时间
        无人机.累计飞行时间 += 架.飞行时间
        无人机.累计能耗 += 架.能耗
        无人机.最后返回时刻 = 返回

        记录表[架.序号] = 调度记录(
            架次序号=架.序号,
            机型编号=机型编号,
            无人机编号=无人机编号,
            电池编号=电池编号,
            开始时刻=开始,
            返回时刻=返回,
            起始SOC=1.0,
            结束SOC=本次结束,
            电池可用时刻=充电完成,
        )

    return 记录表


def _调度键(场景, 架次列表: list[架次], 记录表: dict[int, 调度记录]) -> tuple:
    """择优键：**先看硬时限是否被违反**，再看完成时间，最后看全部货箱送达时刻之和。

    硬时限优先是必须的：只看完成时间会选出让"长架次先飞"的非 EDF 顺序，
    把首批截止 3600 s 的货箱推到几千秒之后（实测可造成 8 箱违反）。
    """
    违反箱数, 超出量 = _硬时限违反(场景, 架次列表, 记录表)
    完成时间 = max((r.返回时刻 for r in 记录表.values()), default=0.0)
    送达时刻和 = 0.0
    for 架 in 架次列表:
        记录 = 记录表[架.序号]
        for 位, 偏移 in enumerate(架.代价.送达偏移):
            送达时刻和 += (记录.开始时刻 + 偏移) * 架.代价.各区箱数[位]
    return (违反箱数, 超出量, 完成时间, 送达时刻和)


def _硬时限违反(场景, 架次列表: list[架次], 记录表: dict[int, 调度记录]) -> tuple[int, float]:
    """统计该调度下违反硬时限（首批截止 / 医疗期望时间）的货箱数与超出量。"""
    箱数 = 0
    超出 = 0.0
    for 架 in 架次列表:
        记录 = 记录表[架.序号]
        for 位, 偏移 in enumerate(架.代价.送达偏移):
            时刻 = 记录.开始时刻 + 偏移
            for 编号 in 架.各区箱编号[位]:
                箱 = 场景.取货箱(编号)
                截止 = 硬截止时间(箱)
                if 截止 is not None and 时刻 > 截止 + 数值容差:
                    箱数 += 1
                    超出 += 时刻 - 截止
    return 箱数, 超出


def 调度架次(场景, 架次列表: list[架次], 策略集: tuple[str, ...] | None = None) -> dict[int, 调度记录]:
    """对架次集合做确定性列表调度，返回 {架次序号: 调度记录}。

    对 `策略集` 中每种固定排序各调度一次，按 `(完成时间, 送达时刻之和)` 字典序取最优。
    """
    if not 架次列表:
        return {}
    策略列表 = 策略集 if 策略集 is not None else 排序策略集
    最佳键 = None
    最佳记录: dict[int, 调度记录] = {}
    for 策略 in 策略列表:
        记录 = 单次调度(场景, 架次列表, 策略)
        键 = _调度键(场景, 架次列表, 记录)
        if 最佳键 is None or 键 < 最佳键:
            最佳键 = 键
            最佳记录 = 记录
    return 最佳记录
