"""
口径自检 —— 多点多架次调度公共库的内核级验证。

三个检查，全部是"算出来的，不是写出来的"，每次运行多目标优化 / 方案检验主程序都会执行：

    1. 退化一致性  多点架次代价在 k = 1 时是否与单点往返与组批 `单点往返代价` **逐位一致**
                   （这是多点多架次调度"继承单点往返与组批口径"的自动化证明）
    2. 能量守恒    Σ 逐航段能耗 == 架次总能耗；Σ 逐航段飞行时间 == 架次飞行时间；
                   作业时间 == 末次送达偏移 + 返航航段飞行时间；逐段载荷 == 剩余载荷
    3. 充电模型    两阶段等效充电在 SOC = 0.9 处连续、关于 SOC 单调不增、
                   SOC = 0 时为一整个等效完全充电时间、SOC = 100% 时为 0
"""
from __future__ import annotations

from 源代码.公共库.基础内核.飞行模型 import 单点往返代价
from 源代码.公共库.运输调度.多点飞行模型 import 多点架次代价
from 源代码.公共库.运输调度.资源模型 import 快慢充分界SOC, 充电时长, 快充阶段时间占比, 慢充阶段时间占比
from 源代码.公共库.运输调度.配置 import 数值容差


# ===================== 1. 退化一致性 =====================
def 退化一致性检查(场景) -> tuple[bool, str]:
    """对全部 (机型, 服务区) 组合比较 k=1 的多点代价与单点往返与组批单点往返代价。"""
    最大差_能耗 = 0.0
    最大差_飞行时间 = 0.0
    最大差_作业时间 = 0.0
    最大差_送达偏移 = 0.0
    样本数 = 0

    for 服务区编号 in 场景.编号顺序:
        项 = 场景.服务区表[服务区编号]
        for 机型编号 in sorted(场景.机型表):
            机 = 场景.机型表[机型编号]
            需求质量 = sum(b["质量"] for b in 场景.货箱归属.get(服务区编号, []))
            载荷 = min(需求质量, 机.最大载货质量)
            if 载荷 <= 0:
                continue

            几何 = 场景.取航段("O01", 服务区编号)

            # —— 单点往返与组批口径 ——
            对照 = 单点往返代价(
                机, 几何.水平距离, 几何.巡航海拔, 场景.调度中心["海拔"], 项["海拔"], 载荷
            )
            # 单点往返与组批的单架次作业时间口径（公共库.组批求解.单架次代价 内联展开）
            箱数 = 1
            对照作业时间 = (
                机.工位固定准备时间
                + 机.每箱装载时间 * 箱数
                + 对照.去程时间
                + 机.接收点基础交接时间
                + 机.每箱增加交接时间 * 箱数
                + 对照.回程时间
            )
            对照送达偏移 = (
                机.工位固定准备时间
                + 机.每箱装载时间 * 箱数
                + 对照.去程时间
                + 机.接收点基础交接时间
                + 机.每箱增加交接时间 * 箱数
            )

            # —— 多点多架次调度口径（k = 1）——
            箱列表 = [[{"货箱编号": f"{服务区编号}-校验", "质量": 载荷, "体积": 0.0}]]
            多点 = 多点架次代价(场景, 机, (服务区编号,), 箱列表)

            最大差_能耗 = max(最大差_能耗, abs(多点.总能耗 - 对照.架次总能耗))
            最大差_飞行时间 = max(最大差_飞行时间, abs(多点.飞行时间 - 对照.架次总时间))
            最大差_作业时间 = max(最大差_作业时间, abs(多点.作业时间 - 对照作业时间))
            最大差_送达偏移 = max(最大差_送达偏移, abs(多点.送达偏移[0] - 对照送达偏移))
            样本数 += 1

    最大差 = max(最大差_能耗, 最大差_飞行时间, 最大差_作业时间, 最大差_送达偏移)
    通过 = 最大差 <= 1e-9
    描述 = (
        f"[内核自检1] 退化一致性（{样本数} 个 (机型,服务区) 组合，k=1 多点 vs 单点往返与组批单点往返）："
        f"能耗偏差 {最大差_能耗:.3e}、飞行时间偏差 {最大差_飞行时间:.3e}、"
        f"作业时间偏差 {最大差_作业时间:.3e}、送达偏移偏差 {最大差_送达偏移:.3e} "
        f"→ {'一致' if 通过 else '不一致（口径漂移！）'}"
    )
    return 通过, 描述


# ===================== 2. 能量守恒与载荷剖面 =====================
def 能量守恒检查(场景, 抽样路由: list[tuple[str, ...]] | None = None) -> tuple[bool, str]:
    """对若干多点路由校验逐段累加的自洽性。"""
    样本 = 0
    最大差_能耗 = 0.0
    最大差_时间 = 0.0
    最大差_作业时间 = 0.0
    载荷剖面错误 = 0

    路由表 = 抽样路由
    if 路由表 is None:
        路由表 = [
            ("S001", "S011"),
            ("S013", "S014"),
            ("S006", "S007", "S010"),
            ("S005", "S009", "S002"),
            ("S012", "S010", "S013", "S014"),
        ]

    for 路由 in 路由表:
        for 机型编号 in sorted(场景.机型表):
            机 = 场景.机型表[机型编号]
            各区箱列表 = []
            合法 = True
            for 服务区编号 in 路由:
                候选 = 场景.货箱归属.get(服务区编号, [])
                取用 = 候选[:1]      # 每个服务区取 1 箱，保证质量与体积都在上限内
                if not 取用:
                    合法 = False
                    break
                各区箱列表.append(list(取用))
            if not 合法:
                continue
            if not 多点架次代价_体量可行(场景, 机, 各区箱列表):
                continue

            代价 = 多点架次代价(场景, 机, 路由, 各区箱列表)

            最大差_能耗 = max(最大差_能耗, abs(sum(段.能耗 for 段 in 代价.航段) - 代价.总能耗))
            最大差_时间 = max(最大差_时间, abs(sum(段.飞行时间 for 段 in 代价.航段) - 代价.飞行时间))
            最大差_作业时间 = max(
                最大差_作业时间,
                abs(代价.送达偏移[-1] + 代价.航段[-1].飞行时间 - 代价.作业时间),
            )

            # 逐段载荷 = 总载质量 - 已投送质量
            已投 = 0.0
            for 位, 段 in enumerate(代价.航段):
                期望载荷 = 代价.总载质量 - 已投
                if abs(段.载荷 - 期望载荷) > 1e-9:
                    载荷剖面错误 += 1
                if 位 < len(代价.各区质量):
                    已投 += 代价.各区质量[位]
            样本 += 1

    最大差 = max(最大差_能耗, 最大差_时间, 最大差_作业时间)
    通过 = 最大差 <= 1e-9 and 载荷剖面错误 == 0
    描述 = (
        f"[内核自检2] 能量守恒与载荷剖面（{样本} 个多点架次样本）："
        f"能耗合计偏差 {最大差_能耗:.3e}、飞行时间合计偏差 {最大差_时间:.3e}、"
        f"作业时间闭合偏差 {最大差_作业时间:.3e}、载荷剖面错误 {载荷剖面错误} 处 "
        f"→ {'自洽' if 通过 else '不自洽！'}"
    )
    return 通过, 描述


def 多点架次代价_体量可行(场景, 机, 各区箱列表) -> bool:
    """载质量与装载体积是否在上限内（供本模块抽样使用，避免能量超限样本）。"""
    总质量 = sum(b["质量"] for 箱 in 各区箱列表 for b in 箱)
    总体积 = sum(b["体积"] for 箱 in 各区箱列表 for b in 箱)
    return (
        总质量 <= 机.最大载货质量 + 数值容差
        and 总体积 <= 机.可用装载体积 + 数值容差
    )


# ===================== 3. 充电模型 =====================
def 充电模型检查() -> tuple[bool, str]:
    """校验两阶段等效充电的分段线性、交界值、单调性与端点值。

    不去用 ±ε 探针跨分段点（那会引入 O(slope·ε) 的数值假象），
    而是直接验证**两段各自的线性式**与**交界值相等**。
    """
    等效时间 = [1800.0, 2400.0, 3000.0]
    网格 = [i / 1000 for i in range(1001)]

    最大误差_交界 = 0.0
    最大误差_线性 = 0.0
    最大误差_端点 = 0.0
    单调错误 = 0

    for T in 等效时间:
        # (a) 交界值：两段在 SOC = 0.9 处相等，等于慢充阶段时间占比 × T
        最大误差_交界 = max(
            最大误差_交界, abs(充电时长(T, 快慢充分界SOC) - 慢充阶段时间占比 * T)
        )

        # (b) 分段线性：逐点比对解析式
        for s in 网格:
            if s >= 快慢充分界SOC:
                期望 = 慢充阶段时间占比 * T * (1.0 - s) / (1.0 - 快慢充分界SOC)
            else:
                期望 = T * (
                    快充阶段时间占比 * (快慢充分界SOC - s) / 快慢充分界SOC
                    + 慢充阶段时间占比
                )
            最大误差_线性 = max(最大误差_线性, abs(充电时长(T, s) - 期望))

        # (c) 单调不增
        值 = [充电时长(T, s) for s in 网格]
        for 甲, 乙 in zip(值, 值[1:]):
            if 乙 > 甲 + 1e-9:
                单调错误 += 1

        # (d) 端点：SOC = 0 → 整个等效完全充电时间；SOC = 100% → 0
        最大误差_端点 = max(
            最大误差_端点, abs(充电时长(T, 0.0) - T), abs(充电时长(T, 1.0))
        )

    最大误差 = max(最大误差_交界, 最大误差_线性, 最大误差_端点)
    通过 = 最大误差 <= 1e-9 and 单调错误 == 0
    描述 = (
        f"[内核自检3] 两阶段等效充电：交界值误差 {最大误差_交界:.3e} s、"
        f"分段线性误差 {最大误差_线性:.3e} s、端点误差 {最大误差_端点:.3e} s、"
        f"单调性错误 {单调错误} 处 "
        f"→ {'合规' if 通过 else '不合规！'}"
    )
    return 通过, 描述


# ===================== 汇总 =====================
def 内核自检(场景) -> tuple[bool, list[str]]:
    """执行全部内核自检，返回 (是否全部通过, 记录列表)。"""
    记录 = []
    全部通过 = True
    for 检查 in (退化一致性检查, 能量守恒检查):
        通过, 描述 = 检查(场景)
        全部通过 = 全部通过 and 通过
        记录.append(描述)
    通过, 描述 = 充电模型检查()
    全部通过 = 全部通过 and 通过
    记录.append(描述)
    return 全部通过, 记录
