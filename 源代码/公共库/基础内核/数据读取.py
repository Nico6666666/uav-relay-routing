# ===================== 逐箱货箱清单 =====================
def 读取货箱() -> list[dict]:
    """返回 80 个货箱，字段：货箱编号 / 服务区编号 / 物资类型 / 质量 / 体积 /
    是否首批保障 / 首批截止时间 / 期望送达时间 / 应急优先系数。"""
    结果 = []
    for 行 in _读表("物资需求与配送时限", "货箱清单"):
        结果.append(
            {
                "货箱编号": 行["货箱编号"],
                "服务区编号": 行["服务区编号"],
                "物资类型": 行["物资类型"],
                "质量": float(行["单箱质量（kg）"]),
                "体积": float(行["单箱体积（m³）"]),
                "是否首批保障": 行["是否首批保障"] == "是",
                "首批截止时间": 行["首批截止时间（s）"],
                "期望送达时间": 行["期望送达时间（s）"],
                "应急优先系数": int(行["应急优先系数"]),
            }
        )
    return 结果


def 按服务区归组货箱(货箱列表: list[dict]) -> dict[str, list[dict]]:
    结果: dict[str, list[dict]] = {}
    for 箱 in 货箱列表:
        结果.setdefault(箱["服务区编号"], []).append(箱)
    for 编号 in 结果:
        结果[编号].sort(key=lambda b: b["货箱编号"])
    return 结果


# ===================== DEM =====================
def 读取DEM() -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """返回 (地面高程 [行,列] float64, 纬度向量 [行], 经度向量 [列])。

    纬度向量自北向南递减，经度向量自西向东递增；无效值置为 NaN。
    """
    数据 = sio.loadmat(DEM路径)
    地面高程 = np.asarray(数据["dem"], dtype=np.float64)
    纬度向量 = np.asarray(数据["latitude"]).ravel().astype(np.float64)
    经度向量 = np.asarray(数据["longitude"]).ravel().astype(np.float64)

    if 地面高程.shape != (纬度向量.size, 经度向量.size):
        raise ValueError(f"DEM 形状 {地面高程.shape} 与经纬度向量 {(纬度向量.size, 经度向量.size)} 不一致")

    地面高程 = 地面高程.copy()
    地面高程[地面高程 <= DEM无效值阈值] = np.nan
    return 地面高程, 纬度向量, 经度向量
