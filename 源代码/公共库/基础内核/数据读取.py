"""
数据读取 —— 输入数据 JSON（UTF-8）与镇龙乡 30 米 DEM。

数据源口径（已确认）：以 基础数据/无人机数据/json/ 为准。
注意：JSON 键名自带单位后缀（如 "单箱质量（kg）"），本模块负责剥离为纯量纲字段。
"""
from __future__ import annotations

import json

import numpy as np
import scipy.io as sio

from 源代码.公共库.基础内核.配置 import DEM无效值阈值, DEM路径, 无人机数据目录


# ===================== 原始 JSON =====================
def _读表(文件名: str, 表名: str) -> list[dict]:
    路径 = 无人机数据目录 / f"{文件名}.json"
    数据 = json.loads(路径.read_text(encoding="utf-8"))
    if 表名 not in 数据["tables"]:
        raise KeyError(f"{文件名}.json 中不存在表 [{表名}]，实际有 {list(数据['tables'])}")
    return 数据["tables"][表名]


# ===================== 调度中心与服务区 =====================
def 读取调度中心() -> dict:
    """返回 {编号, 名称, 经度, 纬度, 海拔}"""
    行 = _读表("调度中心与服务区", "调度中心")[0]
    return {
        "编号": 行["调度中心编号"],
        "名称": 行["调度中心名称"],
        "经度": float(行["经度（°）"]),
        "纬度": float(行["纬度（°）"]),
        "海拔": float(行["海拔（m）"]),
    }


def 读取服务区() -> list[dict]:
    """返回 [{编号, 名称, 经度, 纬度, 海拔, 人口}, ...]，按编号升序。"""
    结果 = []
    for 行 in _读表("调度中心与服务区", "服务区"):
        结果.append(
            {
                "编号": 行["服务区编号"],
                "名称": 行["服务区名称"],
                "经度": float(行["经度（°）"]),
                "纬度": float(行["纬度（°）"]),
                "海拔": float(行["海拔（m）"]),
                "人口": int(行["本次需保障人口（人）"]),
            }
        )
    return sorted(结果, key=lambda x: x["编号"])


# ===================== 运输无人机机型 =====================
def 读取机型() -> dict[str, dict]:
    """返回 {机型编号: {字段: 值}}，字段名已去单位。"""
    结果 = {}
