"""
地理计算 —— 经纬度 ↔ 平面米制、DEM 像元定位、航段沿线地形净空。

口径（见 配置.py）：
    * 水平距离   中纬度等距投影：x = Δlon * 米每度 * cos(φ)，y = Δlat * 米每度
    * 节点像元   最近像元（argmin |Δlon|, |Δlat|）
    * 沿线净空   取两节点像元连线上**线段覆盖到的全部像元**的最高地面高程
                 （闭像元方形与线段相交判定；不设采样步长，故不会漏像元）

**为什么不用等距采样**：DEM 为 1 角秒栅格，纬向像元间距 = 1 角秒纬度 ≈ 30.9 m，
经向像元间距 = 1 角秒经度 ≈ 30.9·cos(纬度) ≈ 28.5 m。若按固定的米制步长（如 30 m）
沿航段均匀取样，则在东西向为主的航段上取样点数会**少于**线段穿过的像元数，
**漏掉沿线峰值**，使"计划巡航海拔 = 沿线最高地面高程 + 50 m"这一规则被低估。
本模块改用线段–像元相交的精确覆盖，与步长无关。
"""
from __future__ import annotations

import numpy as np

from 源代码.公共库.基础内核.配置 import DEM无效值阈值, 米每度


def 最近像元(经度: float, 纬度: float, 纬度向量: np.ndarray, 经度向量: np.ndarray) -> tuple[int, int]:
    """经纬度 → DEM 像元 (行, 列)。取最近像元。"""
    行 = int(np.argmin(np.abs(纬度向量 - 纬度)))
    列 = int(np.argmin(np.abs(经度向量 - 经度)))
    return 行, 列


def 水平距离_m(经度1: float, 纬度1: float, 经度2: float, 纬度2: float) -> float:
    """两点水平直线距离（m），中纬度等距投影。"""
    平均纬度 = (纬度1 + 纬度2) / 2.0
    东向 = (经度2 - 经度1) * 米每度 * np.cos(np.deg2rad(平均纬度))
    北向 = (纬度2 - 纬度1) * 米每度
    return float(np.hypot(东向, 北向))


def 线段覆盖像元(行1: int, 列1: int, 行2: int, 列2: int) -> tuple[np.ndarray, np.ndarray]:
    """线段（两端为像元索引坐标）**覆盖到的全部像元**。

    判定口径：像元视为**闭方形** [行 − 0.5, 行 + 0.5] × [列 − 0.5, 列 + 0.5]，
    线段与其相交即计入 —— 这是「线段所经过的像元」的**包容（不漏）口径**：
    端点像元必然计入，与像元间距是否各向异性无关，
    并且**只擦过一个角的像元也计入**（对地形净空与视线遮挡都取安全侧）。

    > 为什么不能用"按步长取最近像元"的游走：游走只会取到最近的像元，
    > 会系统性漏掉只被擦角的像元。实测（上游 120 条航段）游走口径会把
    > 最高地面高程低估最多 16.40 m。

    实现：沿跨度较大的那个轴**逐格扫描** —— 对每一格求出线段落在该格内的
    另一轴区间，再取该区间覆盖到的整格。全程向量化，
    复杂度 O(覆盖像元数)，**无 Python 逐像元循环**（联合调度与中继的视线遮挡是热路径）。

    返回 `(行索引, 列索引)`；未做栅格边界裁剪，调用方按需 clip。
    """
    行距 = abs(行2 - 行1)
    列距 = abs(列2 - 列1)
    if 行距 == 0 and 列距 == 0:
        return np.array([行1]), np.array([列1])

    if 列距 >= 行距:
        # 沿列扫描：每一列内，线段占一段行区间；该区间闭覆盖到的整格即为命中像元
        扫 = np.arange(int(min(列1, 列2)), int(max(列1, 列2)) + 1, dtype=float)
        低 = np.maximum(扫 - 0.5, min(列1, 列2))
        高 = np.minimum(扫 + 0.5, max(列1, 列2))
        斜率 = (行2 - 行1) / (列2 - 列1)
        端甲 = 行1 + (低 - 列1) * 斜率
        端乙 = 行1 + (高 - 列1) * 斜率
        首 = np.ceil(np.minimum(端甲, 端乙) - 0.5).astype(np.int64)
        末 = np.floor(np.maximum(端甲, 端乙) + 0.5).astype(np.int64)
        个数 = 末 - 首 + 1
        另一轴 = _展开区间(首, 个数)
        返回轴 = np.repeat(扫.astype(np.int64), 个数)
        return 另一轴, 返回轴

    # 沿行扫描：对称处理
    扫 = np.arange(int(min(行1, 行2)), int(max(行1, 行2)) + 1, dtype=float)
    低 = np.maximum(扫 - 0.5, min(行1, 行2))
    高 = np.minimum(扫 + 0.5, max(行1, 行2))
    斜率 = (列2 - 列1) / (行2 - 行1)
    端甲 = 列1 + (低 - 行1) * 斜率
    端乙 = 列1 + (高 - 行1) * 斜率
    首 = np.ceil(np.minimum(端甲, 端乙) - 0.5).astype(np.int64)
    末 = np.floor(np.maximum(端甲, 端乙) + 0.5).astype(np.int64)
    个数 = 末 - 首 + 1
    另一轴 = _展开区间(首, 个数)
    返回轴 = np.repeat(扫.astype(np.int64), 个数)
    return 返回轴, 另一轴


def _展开区间(首: np.ndarray, 个数: np.ndarray) -> np.ndarray:
    """把「首 + 0, 1, …, 个数−1」的若干段首尾相接展开成一维数组（向量化）。"""
    偏移 = np.arange(int(个数.sum())) - np.repeat(np.cumsum(个数) - 个数, 个数)
    return np.repeat(首, 个数) + 偏移


def 沿线最高地面高程(
    经度1: float,
    纬度1: float,
    经度2: float,
    纬度2: float,
    地面高程: np.ndarray,
    纬度向量: np.ndarray,
    经度向量: np.ndarray,
) -> float:
    """航段沿线 DEM 像元的最高地面高程（m）。

    **航段定义为两端点像元中心之间的直线段**（端点像元 = 距节点经纬度最近的像元，
    与本模块 `最近像元` 同口径）。取该线段**覆盖到的全部像元**（见 `线段覆盖像元`）
    中有效地面高程的最大值；两端点像元必然计入。

    若沿线全部为无效值，回退为两端点地面高程的较大者（本场景不触发）。
    """
    行1, 列1 = 最近像元(经度1, 纬度1, 纬度向量, 经度向量)
    行2, 列2 = 最近像元(经度2, 纬度2, 纬度向量, 经度向量)

    行序列, 列序列 = 线段覆盖像元(行1, 列1, 行2, 列2)
    行序列 = np.clip(行序列, 0, 地面高程.shape[0] - 1)
    列序列 = np.clip(列序列, 0, 地面高程.shape[1] - 1)

    高程序列 = 地面高程[行序列, 列序列]
    有效 = 高程序列[高程序列 > DEM无效值阈值]
    if 有效.size == 0:
        return float(max(地面高程[行1, 列1], 地面高程[行2, 列2]))
    return float(有效.max())


def 节点地面高程(
    经度: float,
    纬度: float,
    地面高程: np.ndarray,
    纬度向量: np.ndarray,
    经度向量: np.ndarray,
) -> float:
    """节点所在像元的地面高程（m）。仅用于诊断对照，**作业高度不取此值**。"""
    行, 列 = 最近像元(经度, 纬度, 纬度向量, 经度向量)
    return float(地面高程[行, 列])
