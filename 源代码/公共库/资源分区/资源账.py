"""资源账 —— 需求、库存、缺口与「跨组复用丢失」。

职责
----
把一处算出的量收口成一本可核对的账，并把「缺口 = 跨组复用丢失 Δ」这一**恒等式**
显式化：

    Δ  = Σ各组峰值 − 全局峰值            （≥ 0；分区切断了组间的资源池）
    缺口 = max(各组峰值之和 − 库存, 0)
         = max(Δ + 全局峰值 − 库存, 0)

口径
----
* **全局峰值** = 「分区结构不变、时刻表不变、但该类资源**在组间可自由调配**」时的需求。
  由于区间表与任务时刻都未变，合并资源池后的需求恰是全体区间的峰值并发 —— 这是与
  「不分区基线」唯一可比的口径。
* **各组峰值之和** 对**中继能源组件**含**刻意的重复计数**：跨组的中继架次在它触及的
  每个组各计一次（各组独立执行时须各自起飞中继覆盖属于本组的片段）。这不是计算错误。
* **库存**来自数据文件（`数据读取.库存`）。

⚠️ 两条必须显式区分的事实
------------------------
1. `Δ > 0` **不等于**有缺口：若全局峰值 < 库存，库存余量会把 Δ 吸收掉。
   （实例：中继能源组件全局峰值 2、库存 6，k=3 时 Δ=4 但缺口 = 0。）
2. `Δ > 0` 的**成因未必是"时间错峰丢失"**：若某类资源存在跨组重复计数，
   哪怕两组的高峰完全重叠，合并也省不下东西（合并树某步「省 0」即此情形）。
   归因由 `缺口归因` 用证据给出，本模块只负责算术。

依据：分区与资源核算的问题要求 2。
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class 资源账:
    """一类资源（含机型子类）的需求与库存对照。"""

    资源类: str
    子类: str
    库存: int
    全局峰值: int
    各组峰值: tuple[int, ...]
    各组峰值之和: int
    跨组复用丢失: int
    全局余量: int
    全局亏空: int
    缺口: int
    冗余: int

    @property
    def 显示名(self) -> str:
        return f"{self.资源类}{self.子类}"

    @property
    def 余量吸收(self) -> bool:
        """`Δ > 0` 但库存余量把它吃掉的情形（缺口仍为 0）。"""
        return self.跨组复用丢失 > 0 and self.全局峰值 < self.库存


def 建资源账(
    资源类: str,
    子类: str,
    库存: int,
    全局峰值: int,
    各组峰值: tuple[int, ...],
) -> 资源账:
    """三处独立算出的量在此收口，恒等式由 `资源账自检` 核对。"""
    和 = sum(各组峰值)
    丢失 = 和 - 全局峰值
    if 丢失 < 0:
        raise RuntimeError(
            f"{资源类}{子类}：各组峰值之和 {和} < 全局峰值 {全局峰值}，"
            f"违反「合并资源池只会降低需求」的单调性 —— 分区归属或峰值计算有误"
        )
    return 资源账(
        资源类=资源类,
        子类=子类,
        库存=库存,
        全局峰值=全局峰值,
        各组峰值=tuple(各组峰值),
        各组峰值之和=和,
        跨组复用丢失=丢失,
        全局余量=max(库存 - 全局峰值, 0),
        全局亏空=max(全局峰值 - 库存, 0),
        缺口=max(和 - 库存, 0),
        冗余=max(库存 - 和, 0),
    )


def 资源账字典(账: 资源账) -> dict:
    """落盘用的扁平字典（供 `资源缺口_逐资源.csv` 与 JSON）。"""
    return {
        "资源类": 账.资源类,
        "子类": 账.子类,
        "库存": 账.库存,
        "全局峰值": 账.全局峰值,
        "各组峰值": list(账.各组峰值),
        "各组峰值之和": 账.各组峰值之和,
        "跨组复用丢失": 账.跨组复用丢失,
        "全局余量": 账.全局余量,
        "全局亏空": 账.全局亏空,
        "缺口": 账.缺口,
        "冗余": 账.冗余,
    }


def 资源账自检(账表: tuple[资源账, ...]) -> list[str]:
    """恒等式、非负性与反例保护。"""
    错 = []
    反例 = []
    for 账 in 账表:
        预期缺口 = max(账.跨组复用丢失 + 账.全局峰值 - 账.库存, 0)
        if 账.缺口 != 预期缺口:
            错.append(
                f"{账.显示名} 缺口 {账.缺口} ≠ max(Δ {账.跨组复用丢失} + 全局峰值 "
                f"{账.全局峰值} − 库存 {账.库存}, 0) = {预期缺口}"
            )
        if 账.跨组复用丢失 < 0:
            错.append(f"{账.显示名} 跨组复用丢失 {账.跨组复用丢失} < 0")
        if 账.缺口 > 0 and 账.冗余 > 0:
            错.append(f"{账.显示名} 缺口 {账.缺口} 与冗余 {账.冗余} 同时为正")
        if 账.余量吸收:
            反例.append(
                f"{账.显示名}：Δ = {账.跨组复用丢失} > 0，但全局峰值 {账.全局峰值} < "
                f"库存 {账.库存}，余量 {账.全局余量} 将其吸收 ⇒ 缺口 = 0"
                f"（Δ 不等于缺口）"
            )
    if 错:
        raise RuntimeError("资源账恒等式核对失败：" + "；".join(错))

    条目 = [
        "[自检] 资源账恒等式：逐资源 缺口 == max(Δ + 全局峰值 − 库存, 0)，"
        f"共 {len(账表)} 类资源全部成立"
    ]
    for 条 in 反例:
        条目.append(f"[自检] 反例保护（Δ>0 但缺口为 0）：{条}")
    return 条目
