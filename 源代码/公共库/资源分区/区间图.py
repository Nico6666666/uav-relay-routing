"""区间图 —— 峰值并发、紧约束团取证、单位分配证书。

职责
----
分区与资源核算的资源需求口径是「固定时间表下的**峰值并发占用**」（区间图团数）。本模块
把该口径做成一个通用、可取证的工具：

* `峰值并发`：扫描法（事件 +1/−1）；
* `紧约束团`：把「谁真正顶住了峰值」取出来 —— 峰值不是断言，而是一组**可列举的
  成员区间**（区间图的 Helly 性质保证存在大小为峰值的团）；
* `最少单位分配`：按左端点扫描的贪婪着色。区间图是**完美图**，色数 = 团数，
  故分配占用的单位数**恒等于**峰值并发 —— 这给出「用 峰值 个单位就够」的
  **构造性上界**，与团给出的下界夹紧，使需求值可证最优。

口径（两端点约定）
------------------
占用区间一律取**左闭右开** `[左, 右)`：资源在 `右` 时刻已经释放，故「上一段结束」
与「下一段开始」落在同一时刻时**不构成重叠**。

时刻先按 `配置.时间网格_s` 量化成整数刻度再比较。这是**离散单位**而非容差：
联合调度与中继的共享电池是**无缝接力**的（某架次起飞时刻恰好等于其所占电池的充电完成时刻，
全精度下两侧端点严格相等），量化后两段必然落在同一刻度上，左闭右开自动判为不重叠 ——
无需任何 epsilon 比较。方案中真实不同端点的最小间距 ≥ 0.2 s，比网格大 6 个数量级，
故量化不可能合并两个真实不同的事件。

依据：区间图完美性（色数 = 团数）。
"""
from __future__ import annotations

import heapq
from dataclasses import dataclass
from typing import Iterable, Sequence

from 源代码.公共库.资源分区.配置 import 数值容差, 时间网格_s


@dataclass(frozen=True)
class 占用区间:
    """一段资源占用。`左_s` / `右_s` 为未量化的原值，供输出与复核。

    `服务架次` 是该占用**为哪些运输架次而存在**（升序、去重）：

    * 运输无人机 / 共享电池：就是承载它的那个架次；
    * 中继无人机（驻留段）：该段驻留所保障的全部运输架次；
    * 中继能源组件：该中继架次所保障的全部运输架次。

    有了它，「这段占用落在哪个任务组」就是纯查表 —— 一个中继架次往往同时服务多个组，
    这正是「跨组中继架次在其触及的每组各计一次」这一口径的判定依据。
    """

    资源类: str  # "运输无人机" / "共享电池" / "中继无人机" / "中继能源组件"
    子类: str  # 机型 "A"/"B"/"C"；中继侧为 ""
    载体: str  # "架次11" / "中继1站2" / "中继1"
    左_s: float
    右_s: float
    来源: str = "架次区间"  # "架次区间" / "复算充电" / "接力收口"
    服务架次: tuple[int, ...] = ()


@dataclass(frozen=True)
class 团证据:
    """取到峰值的紧约束区间集合（区间图的一个最大团）。"""

    峰值: int
    峰段起刻度: int
    峰段终刻度: int
    代表刻度: int  # 确定性地取峰段起点
    成员: tuple[占用区间, ...]  # len(成员) == 峰值

    @property
    def 峰段起_s(self) -> float:
        return self.峰段起刻度 * 时间网格_s

    @property
    def 峰段终_s(self) -> float:
        return self.峰段终刻度 * 时间网格_s


def 刻度(时刻_s: float) -> int:
    """把时刻量化到 `时间网格_s` 的整数刻度（确定性：同一输入必得同一刻度）。"""
    return round(时刻_s / 时间网格_s)


def 量化区间(区间: 占用区间) -> tuple[int, int]:
    """→ (刻度起, 刻度终)，约定左闭右开 `[刻度起, 刻度终)`。"""
    return 刻度(区间.左_s), 刻度(区间.右_s)


def _段表(区间表: Sequence[占用区间]) -> list[tuple[int, int, int]]:
    """(刻度起, 刻度终, 该段上的并发数) 的升序段表。相邻段共享端点刻度。"""
    事件: list[tuple[int, int]] = []
    for 区间 in 区间表:
        起, 终 = 量化区间(区间)
        事件.append((起, +1))
        事件.append((终, -1))
    事件.sort(key=lambda e: (e[0], e[1]))  # 同一刻度：终点先于起点 ⇒ 交接点不重叠
    段 = []
    当前 = 0
    i = 0
    while i < len(事件):
        此刻度 = 事件[i][0]
        while i < len(事件) and 事件[i][0] == 此刻度:
            当前 += 事件[i][1]
            i += 1
        if 当前 > 0:  # 并发为 0 的区段不入表
            下刻度 = 事件[i][0] if i < len(事件) else 此刻度
            段.append((此刻度, 下刻度, 当前))
    return 段


def 峰值并发(区间表: Iterable[占用区间]) -> int:
    """区间图团数 = 最大重叠数。"""
    段 = _段表(list(区间表))
    return max((并发 for _, _, 并发 in 段), default=0)


def 并发段(区间表: Sequence[占用区间]) -> tuple[tuple[float, float, int], ...]:
    """并发数的**阶梯段** `(起_s, 终_s, 并发数)`，相邻段共享端点。

    供时序图使用：把每段画成一条水平线即得并发曲线。段序按时间升序。
    """
    return tuple((起 * 时间网格_s, 终 * 时间网格_s, 并发) for 起, 终, 并发 in _段表(list(区间表)))


def 峰值暴力(区间表: Sequence[占用区间]) -> int:
    """O(n²) 独立实现：在**每个区间的左端点**处数覆盖它的区间个数，取最大。

    这是实测点法而非事件扫描法，与被测实现走不同的算法路径。正确性依据：区间图
    的最大重叠数必然在某个区间的左端点处取到（左闭右开下，任一重叠区段的起点
    必是某区间的左端点）。**注意**不能数「与某区间相交的区间个数」—— 区间相交
    不传递（`[0,10) [1,2) [8,9)` 三者两两不相交），那样会高估。
    """
    刻度区间 = [量化区间(x) for x in 区间表]
    峰 = 0
    for 点 in {起 for 起, _ in 刻度区间}:
        重 = sum(1 for 起, 终 in 刻度区间 if 起 <= 点 < 终)
        峰 = max(峰, 重)
    return 峰


def 紧约束团(区间表: Sequence[占用区间]) -> 团证据:
    """峰值 + 达到峰值的紧约束成员。

    成员判定 `刻度起 ≤ 代表刻度 < 刻度终` 是**纯整数比较**，不参与浮点比较。
    """
    区间表 = list(区间表)
    if not 区间表:
        return 团证据(0, 0, 0, 0, ())
    段 = _段表(区间表)
    峰 = max(并发 for _, _, 并发 in 段)
    峰段 = [(起, 终) for 起, 终, 并发 in 段 if 并发 == 峰]
    代表 = 峰段[0][0]
    成员 = tuple(x for x in 区间表 if 量化区间(x)[0] <= 代表 < 量化区间(x)[1])
    if len(成员) != 峰:
        raise RuntimeError(
            f"紧约束团大小 {len(成员)} 与峰值 {峰} 不一致（区间图 Helly 性质被破坏），"
            f"成员={[x.载体 for x in 成员]}"
        )
    return 团证据(
        峰值=峰,
        峰段起刻度=峰段[0][0],
        峰段终刻度=max(终 for _, 终 in 峰段),
        代表刻度=代表,
        成员=成员,
    )


def 最少单位分配(区间表: Sequence[占用区间]) -> tuple[int, ...]:
    """按左端点扫描的贪婪着色 → 每个区间占用的**单位号**（0 起）。

    区间图是完美图（团数 = 色数），故 `len(set(返回)) == 峰值并发(区间表)`；
    这正是调用方要的「所需资源数」的**构造性证书**：编号相同的区间两两不重叠，
    即同一号单位可以依次承担这些任务。
    """
    序号 = sorted(range(len(区间表)), key=lambda i: (量化区间(区间表[i])[0], 量化区间(区间表[i])[1]))
    占用堆: list[tuple[int, int]] = []  # (释放刻度, 单位号)
    空闲号: list[int] = []  # 已释放、可复用的单位号
    分配 = [0] * len(区间表)
    用量 = 0
    for i in 序号:
        起, 终 = 量化区间(区间表[i])
        while 占用堆 and 占用堆[0][0] <= 起:  # 左闭右开：释放刻度 == 起刻度 即可复用
            heapq.heappush(空闲号, heapq.heappop(占用堆)[1])
        if 空闲号:
            号 = heapq.heappop(空闲号)  # 复用已释放的单位，不新开
        else:
            号 = 用量
            用量 += 1
        分配[i] = 号
        heapq.heappush(占用堆, (终, 号))
    return tuple(分配)


def 区间图自检(区间表: Sequence[占用区间], 显示名: str) -> list[str]:
    """四路对拍：扫描法 / 暴力 O(n²) / 团大小 / 分配单位数。不一致即 raise。"""
    区间表 = list(区间表)
    峰 = 峰值并发(区间表)
    暴力 = 峰值暴力(区间表)
    团 = 紧约束团(区间表)
    分配 = 最少单位分配(区间表)
    用量 = len(set(分配))
    错 = []
    if 暴力 != 峰:
        错.append(f"暴力={暴力} vs 扫描={峰}")
    if 团.峰值 != 峰:
        错.append(f"团={团.峰值} vs 扫描={峰}")
    if 用量 != 峰:
        错.append(f"分配单位数={用量} vs 扫描={峰}")
    if 错:
        raise RuntimeError(f"{显示名} 区间图四路不一致：" + "；".join(错))
    return [
        f"[自检] {显示名} 区间图四路一致：峰值 {峰}（扫描=暴力=团=分配单位数），"
        f"紧约束团成员 {len(团.成员)} 个，最早峰段 [{团.峰段起_s:.3f}, {团.峰段终_s:.3f}) s"
    ]


def 端点位移(区间表: Sequence[占用区间]) -> float:
    """量化引入的最大端点位移（s）。用于自检报告「量化没有挪动真实事件」。"""
    最大 = 0.0
    for 区间 in 区间表:
        起, 终 = 量化区间(区间)
        最大 = max(最大, abs(起 * 时间网格_s - 区间.左_s), abs(终 * 时间网格_s - 区间.右_s))
    if 最大 > 时间网格_s / 2 + 数值容差:
        raise RuntimeError(f"量化位移 {最大!r} s 超过网格半格 {时间网格_s / 2}")
    return 最大
