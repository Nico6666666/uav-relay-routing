# ===================== 离散单位 =====================
#: 区间端点量化用的时间网格（s）。这是**离散单位**，不是容差：
#: 联合调度与中继的共享电池是**无缝接力**的 —— 某架次的起飞时刻恰好等于它所占用电池的
#: 充电完成时刻（实测 4 处，全精度下两侧端点严格相等）。把时刻摆到 1e-6 s 的固定
#: 刻度上，左闭右开的区间在接力点自动判为**不重叠**，无需任何 epsilon 比较；
#: 而本方案中真实不同端点的最小间距 ≥ 0.2 s（联合调度与中继最小周转为 300 s），
#: 比网格大 6 个数量级，不可能把两个真实不同的事件合并。
时间网格_s = 1e-6

# ===================== 与上游打印精度的对照容差 =====================
#: `方案检验/各方案/<名>/*.csv` 是**打印精度**（不足全精度），故对照容差按该源的小数位数
#: 取半刻度。**这些数字不是物理判据的容差** —— 物理判据一律用转口的 `数值容差`。
#: 实测边界值 4.912e-04 s 距 5e-04 仅 1.8%，故不可再放松。
对照容差_共享电池充电完成_s = 5e-4    # 源：`充电完成_s`，3 位小数
对照容差_共享电池结束SOC = 5e-5      # 源：`结束SOC`，4 位小数
对照容差_中继充电完成_s = 5e-3       # 源：`充电完成时刻_s`，2 位小数
对照容差_中继结束SOC = 5e-7          # 源：`结束SOC`，6 位小数

