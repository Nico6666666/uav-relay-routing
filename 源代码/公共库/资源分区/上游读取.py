"""上游读取 —— 联合调度与中继的代表方案 → 冻结数据类，并读取权威充电对照表。

职责
----
把 `源代码/求解器/联合调度与中继/五目标优化/输出/代表方案.json` 的 `代表方案.<方案名>` 读成不可变数据类，
供 `资源占用` 构造资源占用区间。

**为什么以这份 JSON 为唯一主通道**（「下游只读上游 `输出/*.json`」）
-----------------------------------------------------------------------------
它是联合调度与中继交付的**自解释**成果（顶层含 `说明` / `口径` / `★ 准入结论`），且
`分区基线.运输架次[]` 的 `开始时刻_s` / `返回时刻_s` / `能耗_kWh` 是**全精度**浮点，
而 `方案检验/各方案/<名>/*.csv` 与 `中继架次台账[]` 都是**打印精度**（不足全精度）。
精度在此处是**结论性**的：见 `资源占用.共享电池区间` 的无缝接力收口说明 ——
用 4 位小数的 `结束SOC` 复算会把 C 型共享电池的全局峰值从真值 4 虚增到 5。

对照源（§10.2「必须复算对照」）
------------------------------
`权威对照()` 读 `方案检验/各方案/<名>/` 的两张充电表，**仅用于自检比对**：
其值**不得进入任何计算**。上游若被改动，本库会立刻失败而不是悄悄用旧数。

依据：`文档/使用说明.md` §5《数据继承关系》。
"""
from __future__ import annotations

import csv
import hashlib
import json
from dataclasses import dataclass
from pathlib import Path

from 源代码.公共库.资源分区.配置 import 上游代表方案文件, 上游各方案目录, 方案名可选值


# ===================== 冻结数据类 =====================
@dataclass(frozen=True)
class 上游运输架次:
    """一个运输架次。`开始时刻_s` / `返回时刻_s` / `能耗_kWh` 为**全精度**。"""

    序号: int
    服务区集合: tuple[str, ...]
    各区箱编号: tuple[tuple[str, ...], ...]  # 与 `服务区集合` 同序的逐区货箱编号
    机型: str
    无人机: str
    共享电池: str
    开始时刻_s: float
    返回时刻_s: float
    能耗_kWh: float

    @property
    def 箱数(self) -> int:
        return sum(len(箱) for 箱 in self.各区箱编号)


@dataclass(frozen=True)
class 上游悬停站:
    """中继在某个悬停点上的一段持续服务（口径 E 的「驻留段」）。"""

    经度: float
    纬度: float
    悬停海拔_m: float
    服务起_s: float
    服务终_s: float
    保障缺口: tuple[int, ...]


@dataclass(frozen=True)
class 上游中继架次:
    """一个中继架次。`站` 即其驻留段序列。"""

    序号: int
    中继机: str
    能源组件: str
    起飞时刻_s: float
    返回时刻_s: float
    能耗_kWh: float
    保障运输架次: tuple[int, ...]
    站: tuple[上游悬停站, ...]


@dataclass(frozen=True)
class 上游保障记录:
    """一条通信保障关系：某中继架次的某驻留段保障某运输架次的某缺口。"""

    中继架次序号: int
    中继机: str
    站序: int
    运输架次序号: int
    缺口序号: int
    起时刻_s: float
    终时刻_s: float


@dataclass(frozen=True)
class 驻留段:
    """驻留段 —— 一架中继在某个悬停点上的一段持续服务。

    **为什么中继无人机需求按驻留段而非保障记录算**：口径 E（一对多守点覆盖）下
    一个驻留段**同时**保障多架运输机，保障记录条数远多于驻留段数 —— 按保障记录算
    峰值并发会把需求**高估**成「同时在服务的运输机数」。真正的物理约束是
    「一个驻留段要一架中继在场」，故两类口径下都取驻留段的峰值并发。
    """

    中继架次序号: int
    中继机: str
    站序: int
    经度: float
    纬度: float
    悬停海拔_m: float
    服务起_s: float
    服务终_s: float
    保障运输架次: tuple[int, ...]


@dataclass(frozen=True)
class 上游基线:
    """一个代表方案的完整联合调度（分区与资源核算的输入基线）。"""

    方案名: str
    来源文件: Path
    文件SHA256: str
    目标向量: tuple[str, ...]
    运输架次: tuple[上游运输架次, ...]
    中继架次: tuple[上游中继架次, ...]
    保障关系: tuple[上游保障记录, ...]


# ===================== 读取 =====================
def _校验方案名(方案名: str, 可选: tuple[str, ...]) -> None:
    if 方案名 not in 可选:
        raise KeyError(f"代表方案中无方案「{方案名}」，可选：{sorted(可选)}")


def 读取基线(方案名: str | None = None) -> 上游基线:
    """读 `代表方案.json` 的 `代表方案.<方案名>`。

    文件缺失 → `FileNotFoundError`（含可操作的下一步）；方案名不存在 → `KeyError`；
    字段缺失 → `KeyError`（不给默认值，见）。
    """
    if not 上游代表方案文件.exists():
        raise FileNotFoundError(
            f"未找到上游成果 {上游代表方案文件}，"
            f"请先运行 源代码/求解器/联合调度与中继/五目标优化/主程序.py"
        )
    if 方案名 is None:
        from 源代码.公共库.资源分区.配置 import 方案名 as 默认方案名

        方案名 = 默认方案名

    文档 = json.loads(上游代表方案文件.read_text(encoding="utf-8"))
    可选 = tuple(文档["代表方案"].keys())
    _校验方案名(方案名, 可选)
    方案 = 文档["代表方案"][方案名]
    基线 = 方案["分区基线"]

    运输 = tuple(
        上游运输架次(
            序号=int(r["架次序号"]),
            服务区集合=tuple(r["服务区集合"]),
            各区箱编号=tuple(tuple(区) for 区 in r["各区箱编号"]),
            机型=r["机型"],
            无人机=r["无人机"],
            共享电池=r["共享电池"],
            开始时刻_s=float(r["开始时刻_s"]),
            返回时刻_s=float(r["返回时刻_s"]),
            能耗_kWh=float(r["能耗_kWh"]),
        )
        for r in 基线["运输架次"]
    )
    中继 = tuple(
        上游中继架次(
            序号=int(r["中继架次序号"]),
            中继机=r["中继机"],
            能源组件=r["能源组件"],
            起飞时刻_s=float(r["起飞时刻_s"]),
            返回时刻_s=float(r["返回时刻_s"]),
            能耗_kWh=float(r["能耗_kWh"]),
            保障运输架次=tuple(sorted(int(x) for x in r["保障运输架次"])),
            站=tuple(
                上游悬停站(
                    经度=float(站["经度"]),
                    纬度=float(站["纬度"]),
                    悬停海拔_m=float(站["悬停海拔_m"]),
                    服务起_s=float(站["服务起_s"]),
                    服务终_s=float(站["服务终_s"]),
                    保障缺口=tuple(sorted(int(g) for g in 站["保障缺口"])),
                )
                for 站 in r["站"]
            ),
        )
        for r in 基线["中继架次"]
    )
    保障 = tuple(
        上游保障记录(
            中继架次序号=int(g["中继架次序号"]),
            中继机=g["中继机"],
            站序=int(g["站序"]),
            运输架次序号=int(g["运输架次序号"]),
            缺口序号=int(g["缺口序号"]),
            起时刻_s=float(g["起时刻_s"]),
            终时刻_s=float(g["终时刻_s"]),
        )
        for g in 方案["保障记录"]
    )

    return 上游基线(
        方案名=方案名,
        来源文件=上游代表方案文件,
        文件SHA256=hashlib.sha256(上游代表方案文件.read_bytes()).hexdigest(),
        目标向量=tuple(方案["目标向量"]),
        运输架次=运输,
        中继架次=中继,
        保障关系=保障,
    )


def 缺口到架次(基线: 上游基线) -> dict[int, int]:
    """{缺口序号: 运输架次序号}。缺口与架次是所属关系，一个缺口只属于一个架次。"""
    映射: dict[int, int] = {}
    for 记录 in 基线.保障关系:
        已有 = 映射.setdefault(记录.缺口序号, 记录.运输架次序号)
        if 已有 != 记录.运输架次序号:
            raise RuntimeError(
                f"缺口 {记录.缺口序号} 同时属于架次 {已有} 与 {记录.运输架次序号}，上游数据结构异常"
            )
    return 映射


def 驻留段表(基线: 上游基线) -> tuple[驻留段, ...]:
    """`中继架次.站` → 驻留段，并把 `保障缺口` 映射成它实际保障的**运输架次**集合。

    映射依据 `保障记录`：一条保障记录把 (中继架次, 站序, 缺口) 与运输架次绑在一起。
    若某驻留段的某缺口在 `保障记录` 中不存在，说明该缺口未被覆盖 —— 报错而不是忽略。
    """
    缺口映射 = 缺口到架次(基线)
    段 = []
    for 架 in 基线.中继架次:
        for 站序, 站 in enumerate(架.站, start=1):
            缺 = [g for g in 站.保障缺口 if g in 缺口映射]
            缺集 = set(缺)
            if len(缺集) != len(站.保障缺口):
                丢失 = sorted(set(站.保障缺口) - 缺集)
                raise RuntimeError(
                    f"中继架次 {架.序号} 站 {站序} 的缺口 {丢失} 在保障记录中无对应运输架次，"
                    f"无法判定其影响哪些任务组"
                )
            段.append(
                驻留段(
                    中继架次序号=架.序号,
                    中继机=架.中继机,
                    站序=站序,
                    经度=站.经度,
                    纬度=站.纬度,
                    悬停海拔_m=站.悬停海拔_m,
                    服务起_s=站.服务起_s,
                    服务终_s=站.服务终_s,
                    保障运输架次=tuple(sorted({缺口映射[g] for g in 缺})),
                )
            )
    return tuple(段)


# ===================== 权威对照（仅供自检） =====================
def 权威对照(方案名: str) -> dict[str, dict[int, float]]:
    """读 `方案检验/各方案/<名>/` 的两张充电表，作为**复算对照**的上游证据。

    返回::

        {"共享电池充电完成_s": {架次序号: 值},
         "共享电池结束SOC":   {架次序号: 值},
         "中继充电完成时刻_s": {中继架次序号: 值},
         "中继结束SOC":       {中继架次序号: 值}}

    同一架次若动用多块电池（本方案实测为 1 架次 1 块），取最晚完成者。
    """
    目录 = 上游各方案目录 / 方案名
    电池表 = 目录 / "共享电池使用与充电.csv"
    组件表 = 目录 / "中继能源组件使用与充电.csv"
    for p in (电池表, 组件表):
        if not p.exists():
            raise FileNotFoundError(
                f"未找到对照源 {p}，请先运行 源代码/求解器/联合调度与中继/方案检验/主程序.py"
            )

    电池完成: dict[int, float] = {}
    电池SOC: dict[int, float] = {}
    with 电池表.open(encoding="utf-8-sig", newline="") as f:
        for 行 in csv.DictReader(f):
            架 = int(行["架次序号"])
            if 行["充电完成_s"] and float(行["充电完成_s"]) >= 电池完成.get(架, float("-inf")):
                电池完成[架] = float(行["充电完成_s"])
                电池SOC[架] = float(行["结束SOC"])

    组件完成: dict[int, float] = {}
    组件SOC: dict[int, float] = {}
    with 组件表.open(encoding="utf-8-sig", newline="") as f:
        for 行 in csv.DictReader(f):
            架 = int(行["中继架次序号"])
            if float(行["充电完成时刻_s"]) >= 组件完成.get(架, float("-inf")):
                组件完成[架] = float(行["充电完成时刻_s"])
                组件SOC[架] = float(行["结束SOC"])

    return {
        "共享电池充电完成_s": 电池完成,
        "共享电池结束SOC": 电池SOC,
        "中继充电完成时刻_s": 组件完成,
        "中继结束SOC": 组件SOC,
    }


