"""资源占用 —— 四类资源 → 半开量化区间表。

职责
----
按联合调度与中继固定的时间表，把四类资源的**占用区间**列举出来，供 `区间图` 求峰值并发：

===========  ==========================================  ==========
资源          占用区间                                    口径
===========  ==========================================  ==========
运输无人机    架次 `[开始, 返回]`                           每架次占用 1 架该型机
共享电池      架次 `[开始, 返回 + 充电时长(结束SOC)]`        两阶段等效充电模型
中继无人机    **驻留段** `[服务起, 服务终]`                  口径 E：一段驻留占 1 架中继
中继能源组件  中继架次 `[起飞, 返回 + 充电时长(结束SOC)]`      每个中继架次占 1 组组件
===========  ==========================================  ==========

口径 E（一对多守点覆盖）
------------------------
通信规则 只限制「**每架运输无人机**在任一时刻只能由 G01 或一架中继无人机提供通信
保障」，那是对**运输机侧**的限制，并未限制一架中继同时服务几架。故一个驻留段可
**同时**保障多架运输机 ⇒ 中继无人机需求按**驻留段**计，而非按保障记录计
（后者会把需求高估成「同时在服务的运输机数」）。

无缝接力收口（本模块的关键细节）
--------------------------------
联合调度与中继的共享电池是**无缝接力**的：某些架次的起飞时刻**恰好等于**它所占用电池的
充电完成时刻（实测 4 处，全精度下两侧端点严格相等）。而分区与资源核算只能从上游 JSON 的
**全精度** `能耗_kWh` + 数据文件机型参数复算充电完成时刻，复算会有末位残差 —— 若该残差
为正，紧约束扫描就会在接力点判出一次**并不存在**的重叠，使峰值虚增 1 组
（实测：用 `方案检验` CSV 的 4 位小数 `结束SOC` 复算，C 型共享电池峰值 4 → 5）。

收口规则：占用右端取 `min(复算充电完成, 该块电池下次起飞时刻)`。其理由不是调参 ——
后一架次能被联合调度与中继排上，说明该电池在那一刻已被取用，物理上不可能「还在充」。
同时设**硬门槛**：若复算充电完成**晚于**下次起飞超过一格网格，直接 `raise`
（不掩盖系统性口径漂移）。

依据：`源代码/公共库/通信中继/资源模型`（充电时长 / 结束SOC 的唯一实现）；
`源代码/公共库/通信中继/中继模型`（中继侧口径）。
"""
from __future__ import annotations

from collections import defaultdict
from dataclasses import dataclass

from 源代码.公共库.资源分区.上游读取 import 上游基线, 驻留段
from 源代码.公共库.资源分区.区间图 import 占用区间
from 源代码.公共库.资源分区.配置 import 时间网格_s
from 源代码.公共库.通信中继.资源模型 import 结束SOC as 计算结束SOC
from 源代码.公共库.通信中继.资源模型 import 充电时长
from 源代码.公共库.通信中继.飞行模型 import 机型


@dataclass(frozen=True)
class 能量载体:
    """把中继能源组件适配成 `结束SOC` 的入参形状（只暴露它用到的字段）。

    这样资源分区 不必再写第二份 SOC 公式。上游
    `中继模型.py` 内已有一处内联的同式实现，本库不重复第三份。
    """

    电池可用能量: float


@dataclass(frozen=True)
class 收口记录:
    """一次无缝接力收口：复算充电完成与下次起飞之间存在 ≤ 一格网格的差异。"""

    载体: str
    收口量_s: float


@dataclass(frozen=True)
class 资源区间表:
    """四类资源的区间表 + 收口证据。"""

    区间: dict[tuple[str, str], tuple[占用区间, ...]]
    收口: tuple[收口记录, ...]

    def 取(self, 资源类: str, 子类: str) -> tuple[占用区间, ...]:
        return self.区间.get((资源类, 子类), ())

    def 按资源类(self, 资源类: str) -> tuple[占用区间, ...]:
        """该类资源的**全部**子类区间合并（子类 = 机型，合并即「不区分机型」）。"""
        return tuple(x for (类, _), 表 in self.区间.items() if 类 == 资源类 for x in 表)


# ===================== 各类资源的占用区间 =====================
def 运输无人机区间(基线: 上游基线) -> dict[tuple[str, str], tuple[占用区间, ...]]:
    """架次 `[开始, 返回]`，按机型分组。"""
    分组: dict[tuple[str, str], list[占用区间]] = defaultdict(list)
    for 架 in 基线.运输架次:
        分组[("运输无人机", 架.机型)].append(
            占用区间(
                "运输无人机", 架.机型, f"架次{架.序号}", 架.开始时刻_s, 架.返回时刻_s,
                服务架次=(架.序号,),
            )
        )
    return {k: tuple(v) for k, v in 分组.items()}


def 复算充电完成(
    基线: 上游基线,
    机型表: dict[str, 机型],
    电池表: dict[str, dict],
) -> dict[int, tuple[float, float]]:
    """逐个运输架次复算 `(结束SOC, 充电完成时刻_s)`。

    唯一的复算入口：`共享电池区间` 与本库自检都从这里取值，避免同一公式两处实现。
    输入必须是上游 JSON 的**全精度** `能耗_kWh`（见 `上游读取` 的说明）。
    """
    结果: dict[int, tuple[float, float]] = {}
    for 架 in 基线.运输架次:
        型 = 架.机型
        if 型 not in 机型表:
            raise KeyError(f"架次 {架.序号} 的机型 {型} 不在数据文件的机型表中")
        if 型 not in 电池表:
            raise KeyError(f"架次 {架.序号} 的机型 {型} 不在数据文件的共享电池表中")
        本次结束 = 计算结束SOC(机型表[型], 架.能耗_kWh)
        终 = 架.返回时刻_s + 充电时长(电池表[型]["等效完全充电时间"], 本次结束)
        结果[架.序号] = (本次结束, 终)
    return 结果


def 复算组件充电完成(
    基线: 上游基线,
    中继机型: dict[str, dict],
    中继无人机: list[dict],
    组件表: dict[str, dict],
) -> dict[int, tuple[float, float]]:
    """逐个中继架次复算 `(结束SOC, 充电完成时刻_s)`（同一入口原则）。"""
    机型_可查 = {编号: 记录["能源组件可用能量_kWh"] for 编号, 记录 in 中继机型.items()}
    中继机_机型 = {r["中继无人机编号"]: r["机型编号"] for r in 中继无人机}
    等效 = next(iter(组件表.values()))["等效完全充电时间_s"]
    结果: dict[int, tuple[float, float]] = {}
    for 架 in 基线.中继架次:
        if 架.中继机 not in 中继机_机型:
            raise KeyError(f"中继架次 {架.序号} 的中继机 {架.中继机} 不在数据文件的中继无人机表中")
        型 = 中继机_机型[架.中继机]
        if 型 not in 机型_可查:
            raise KeyError(f"中继机 {架.中继机} 的机型 {型} 不在数据文件的中继机型表中")
        本次结束 = 计算结束SOC(能量载体(机型_可查[型]), 架.能耗_kWh)
        结果[架.序号] = (本次结束, 架.返回时刻_s + 充电时长(等效, 本次结束))
    return 结果


def 共享电池区间(
    基线: 上游基线,
    机型表: dict[str, 机型],
    电池表: dict[str, dict],
) -> tuple[dict[tuple[str, str], tuple[占用区间, ...]], tuple[收口记录, ...]]:
    """架次 `[开始, 返回 + 充电时长(结束SOC)]`，按机型分组，含无缝接力收口。

    `结束SOC = 结束SOC(机型, 能耗)`（数据文件 `电池可用能量（kWh）` 唯一来源）。
    """
    复算 = 复算充电完成(基线, 机型表, 电池表)
    按电池: dict[str, list[tuple[float, float, str, str, int]]] = defaultdict(list)
    for 架 in 基线.运输架次:
        _结束SOC, 终 = 复算[架.序号]
        按电池[架.共享电池].append((架.开始时刻_s, 终, 架.机型, f"架次{架.序号}", 架.序号))

    分组: dict[tuple[str, str], list[占用区间]] = defaultdict(list)
    收口: list[收口记录] = []
    for 块, 用 in sorted(按电池.items()):
        用.sort()
        for i, (起, 终, 型, 载体, 序号) in enumerate(用):
            来源 = "复算充电"
            if i + 1 < len(用):
                下次起 = 用[i + 1][0]
                Δ = 下次起 - 终
                if Δ < -时间网格_s:
                    raise RuntimeError(
                        f"共享电池 {块} 的复算充电完成时刻 {终!r} 晚于下一架次开始 {下次起!r}"
                        f"（早 {-Δ:.6f} s），与联合调度与中继输出不一致：请核对机型参数与结束SOC口径"
                    )
                if abs(Δ) <= 时间网格_s:
                    终 = 下次起  # 无缝接力：精确对齐到同一刻度，消除复算残差
                    来源 = "接力收口"
                    收口.append(收口记录(载体=f"{块}·{载体}", 收口量_s=Δ))
            分组[("共享电池", 型)].append(
                占用区间("共享电池", 型, 载体, 起, 终, 来源, 服务架次=(序号,))
            )
    return {k: tuple(v) for k, v in 分组.items()}, tuple(收口)


def 中继无人机区间(
    基线: 上游基线,
    驻留段表: tuple[驻留段, ...],
) -> dict[tuple[str, str], tuple[占用区间, ...]]:
    """驻留段 `[服务起, 服务终]`。口径 E 下这段驻留同时保障其覆盖的全部运输机。"""
    区间 = [
        占用区间(
            "中继无人机", "", f"中继{d.中继架次序号}站{d.站序}", d.服务起_s, d.服务终_s,
            服务架次=d.保障运输架次,
        )
        for d in 驻留段表
    ]
    return {("中继无人机", ""): tuple(区间)}


def 中继能源组件区间(
    基线: 上游基线,
    中继机型: dict[str, dict],
    中继无人机: list[dict],
    组件表: dict[str, dict],
) -> tuple[dict[tuple[str, str], tuple[占用区间, ...]], tuple[收口记录, ...]]:
    """中继架次 `[起飞, 返回 + 充电时长(结束SOC)]`，含无缝接力收口。

    `结束SOC = 结束SOC(能量载体(组件可用能量), 能耗)` —— 复用上游唯一实现。
    中继机 → 机型 → 组件可用能量，逐级查表，缺一即 `KeyError`（不给默认值）。
    """
    复算 = 复算组件充电完成(基线, 中继机型, 中继无人机, 组件表)

    按组件: dict[str, list[tuple[float, float, str, tuple[int, ...]]]] = defaultdict(list)
    for 架 in 基线.中继架次:
        _结束SOC, 终 = 复算[架.序号]
        按组件[架.能源组件].append((架.起飞时刻_s, 终, f"中继{架.序号}", 架.保障运输架次))

    分组: dict[tuple[str, str], list[占用区间]] = defaultdict(list)
    收口: list[收口记录] = []
    for 块, 用 in sorted(按组件.items()):
        用.sort()
        for i, (起, 终, 载体, 保障架次) in enumerate(用):
            来源 = "复算充电"
            if i + 1 < len(用):
                下次起 = 用[i + 1][0]
                Δ = 下次起 - 终
                if Δ < -时间网格_s:
                    raise RuntimeError(
                        f"中继能源组件 {块} 的复算充电完成时刻 {终!r} 晚于下一次起飞 {下次起!r}"
                        f"（早 {-Δ:.6f} s），与联合调度与中继输出不一致"
                    )
                if abs(Δ) <= 时间网格_s:
                    终 = 下次起
                    来源 = "接力收口"
                    收口.append(收口记录(载体=f"{块}·{载体}", 收口量_s=Δ))
            分组[("中继能源组件", "")].append(
                占用区间("中继能源组件", "", 载体, 起, 终, 来源, 服务架次=保障架次)
            )
    return {k: tuple(v) for k, v in 分组.items()}, tuple(收口)


def 全部区间(
    基线: 上游基线,
    机型表: dict[str, 机型],
    电池表: dict[str, dict],
    中继机型: dict[str, dict],
    中继无人机: list[dict],
    组件表: dict[str, dict],
    驻留段表: tuple[驻留段, ...],
) -> 资源区间表:
    """四类资源的区间表。键为 (资源类, 子类)，中继侧子类为空串。"""
    区间: dict[tuple[str, str], tuple[占用区间, ...]] = {}
    区间.update(运输无人机区间(基线))
    电池区间, 电池收口 = 共享电池区间(基线, 机型表, 电池表)
    区间.update(电池区间)
    区间.update(中继无人机区间(基线, 驻留段表))
    组件区间, 组件收口 = 中继能源组件区间(基线, 中继机型, 中继无人机, 组件表)
    区间.update(组件区间)
    return 资源区间表(区间=区间, 收口=电池收口 + 组件收口)
