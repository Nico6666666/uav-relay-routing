"""内核口径自检 —— 上游对照、区间图对拍、可疑信号。

职责
----
把与具体子任务无关的内核检查集中在这里，供 `分区配置` 与 `资源缺口` 共用：

1. **上游成果对照**（§10.2 硬性要求）：本库按上游全精度输入复算出的 `结束SOC` 与
   **充电完成时刻**，逐架次与 `方案检验/各方案/<名>/*.csv` 的打印值比对，超容差即 `raise`。
   这样「上游若被改动，下游立刻失败」而不是悄悄用旧数。
2. **区间图对拍**：扫描法 / 暴力 O(n²) / 紧约束团 / 单位分配证书四路一致。
3. **可疑信号**：接力类资源的峰值恰为 `库存 + 1` 时报警 —— 这是"复算精度把峰值顶高
   了一格"的典型形态（实测：用 4 位小数 SOC 复算会把 C 型共享电池峰值 4 顶成 5）。
   **仅提示不中断**：该形态也可能是真实的，故不由内核替决策者下结论。

容差口径
--------
物理判据一律用 `配置.数值容差`（转口自上游）；与 `方案检验` 的 CSV 对照则用
`配置.对照容差_*`（按对照源打印位数取半刻度）。二者**不可混用**：
用 1e-9 对照会把正常舍入判成错误，用 1e-3 则会把 0.1 s 级的口径漂移放行。

依据： / §10.2。
"""
from __future__ import annotations

from 源代码.公共库.资源分区.上游读取 import 上游基线, 权威对照
from 源代码.公共库.资源分区.区间图 import 区间图自检, 峰值并发
from 源代码.公共库.资源分区.资源占用 import (
    复算充电完成,
    复算组件充电完成,
    资源区间表,
)
from 源代码.公共库.资源分区.配置 import (
    对照容差_中继结束SOC,
    对照容差_共享电池结束SOC,
    对照容差_中继充电完成_s,
    对照容差_共享电池充电完成_s,
)


def _对照一批(
    复算: dict[int, tuple[float, float]],
    对照: dict[int, float],
    对照SOC: dict[int, float],
    容差完成: float,
    容差SOC: float,
    名称: str,
    序号名: str,
) -> list[str]:
    """逐序号比对 (结束SOC, 充电完成)，超容差即 raise。"""
    缺 = sorted(set(复算) - set(对照))
    if 缺:
        raise RuntimeError(f"{名称}对照源缺少 {len(缺)} 个记录：{缺}（对照源与基线不同源？）")

    完成差 = [(abs(复算[i][1] - 对照[i]), i) for i in 复算]
    最大完成 = max(完成差)
    SOC差 = [(abs(复算[i][0] - 对照SOC[i]), i) for i in 复算]
    最大SOC = max(SOC差)

    错 = []
    if 最大完成[0] > 容差完成:
        i = 最大完成[1]
        错.append(
            f"{名称} {序号名}{i} 充电完成时刻偏差 {最大完成[0]:.3e} s > 容差 {容差完成:g}"
            f"（本库复算 {复算[i][1]!r} vs 上游打印 {对照[i]!r}）"
        )
    if 最大SOC[0] > 容差SOC:
        i = 最大SOC[1]
        错.append(
            f"{名称} {序号名}{i} 结束SOC 偏差 {最大SOC[0]:.3e} > 容差 {容差SOC:g}"
            f"（本库复算 {复算[i][0]!r} vs 上游打印 {对照SOC[i]!r}）"
        )
    if 错:
        raise RuntimeError("上游成果对照失败：" + "；".join(错))

    return [
        f"[自检] 上游对照 · {名称}：{len(复算)} 个{序号名}，"
        f"充电完成最大偏差 {最大完成[0]:.3e} s（容差 {容差完成:g}）、"
        f"结束SOC 最大偏差 {最大SOC[0]:.3e}（容差 {容差SOC:g}）"
    ]


def 上游成果对照(
    基线: 上游基线,
    机型表: dict,
    电池表: dict,
    中继机型: dict,
    中继无人机: list[dict],
    组件表: dict,
) -> list[str]:
    """本库复算 vs 上游打印值，逐架次对照；超容差即 `raise RuntimeError`。"""
    对照 = 权威对照(基线.方案名)
    电池条目 = _对照一批(
        复算充电完成(基线, 机型表, 电池表),
        对照["共享电池充电完成_s"],
        对照["共享电池结束SOC"],
        对照容差_共享电池充电完成_s,
        对照容差_共享电池结束SOC,
        "共享电池",
        "架次",
    )
    组件条目 = _对照一批(
        复算组件充电完成(基线, 中继机型, 中继无人机, 组件表),
        对照["中继充电完成时刻_s"],
        对照["中继结束SOC"],
        对照容差_中继充电完成_s,
        对照容差_中继结束SOC,
        "中继能源组件",
        "中继架次",
    )
    return 电池条目 + 组件条目


def 区间图对拍(区间表: 资源区间表, 库存: dict | None = None) -> list[str]:
    """逐 (资源类, 子类) 做四路对拍，并给出可疑信号。"""
    条目 = []
    警告 = []
    for 键, 区间 in sorted(区间表.区间.items()):
        if not 区间:
            continue
        资源类, 子类 = 键
        条目.extend(区间图自检(区间, f"{资源类}{子类}"))
        if 库存 is not None:
            大 = 库存[资源类]
            现有 = 大[子类] if isinstance(大, dict) else 大
            if 峰值并发(区间) == 现有 + 1:
                警告.append(
                    f"[提示] {资源类}{子类} 的不分区峰值 {峰值并发(区间)} 恰为库存 {现有} + 1，"
                    f"而该类资源存在无缝接力（{sum(1 for x in 区间 if x.来源 == '接力收口')} 处）——"
                    f"请核对复算源是否为上游全精度输入（用打印精度 SOC 复算会顶高 1 格）"
                )
    return 条目 + 警告


def 内核自检(
    基线: 上游基线,
    机型表: dict,
    电池表: dict,
    中继机型: dict,
    中继无人机: list[dict],
    组件表: dict,
    区间表: 资源区间表,
    库存: dict | None = None,
) -> list[str]:
    """内核自检统一入口：上游对照 → 区间图对拍。"""
    return 上游成果对照(基线, 机型表, 电池表, 中继机型, 中继无人机, 组件表) + 区间图对拍(
        区间表, 库存
    )
