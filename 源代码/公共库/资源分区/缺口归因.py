"""缺口归因 —— 用紧约束团与合并树把「跨组复用丢失」变成证据。

职责
----
任务要求 2 要「给出相应的资源缺口及其**原因**」。定性地说「分区切断了跨组时间复用」
是不够的 —— 本模块给出三类**可核对的证据**：

1. **紧约束团明细**：某资源在某组内的峰值由**哪几个**占用区间顶住（区间图的 Helly
   性质保证存在大小为峰值、两两相交的团）。这是「为什么需要这么多」的直接证人。
2. **单位分配证书**：贪婪着色给出「用 峰值 个单位就够」的**构造性**方案（区间图是
   完美图，色数 = 团数），与团给出的下界夹紧 ⇒ 需求值可证最优，不是估计。
3. **合并树分解**：按组序累进合并各组的区间集合，
   `Σ 各步省下 == Δ`（整数逐位相等）。**某一步「省 0」意味着这两组的高峰完全重叠** ——
   这是区分「时间错峰丢失」与「跨组架次在每组各计一次」的唯一判据。本基线的中继侧
   正是后者（中继架次触及所有组），若写成「错峰」就是错误归因。

错峰判定（下界，不可相加）
--------------------------
逐组对比较两组的峰段：不相交 ⇒「至少 min(P_g, P_h) 个单位被两组各自重复购置」。
这是**下界**：多组之间的重叠可能同时发生，故各项不可相加，报告时必须标注。

依据：分区与资源核算的问题要求 2。
"""
from __future__ import annotations

from dataclasses import dataclass
from itertools import permutations

from 源代码.公共库.资源分区.分区方案 import 分区方案
from 源代码.公共库.资源分区.区间图 import 占用区间, 峰值并发
from 源代码.公共库.资源分区.资源占用 import 资源区间表
from 源代码.公共库.资源分区.资源核算 import 归属组, 组资源需求
from 源代码.公共库.资源分区.资源账 import 资源账


@dataclass(frozen=True)
class 合并步:
    """合并树上的一步：并入某组后，相比「两组各自独立」省下了多少单位。"""

    并入组: int  # 组号（1 起）
    本步省下: int
    合并后峰值: int


@dataclass(frozen=True)
class 组序分解:
    """按某一组序做的累进合并分解。k=2 时组序唯一；k=3 时有 3 种。"""

    组序: tuple[int, ...]  # 组号（1 起）
    步: tuple[合并步, ...]
    合计省下: int

    @property
    def 全程无重叠(self) -> bool:
        """每步都省 0 ⇒ 各组高峰完全重叠，合并资源池也救不回任何单位。"""
        return all(s.本步省下 == 0 for s in self.步)


@dataclass(frozen=True)
class 错峰项:
    """一对组的峰段错峰情况（重复购置下界）。"""

    组甲: int
    组乙: int
    甲峰段_s: tuple[float, float]
    乙峰段_s: tuple[float, float]
    错峰: bool
    重复购置下界: int


@dataclass(frozen=True)
class 归因项:
    """一类资源的缺口归因结论。"""

    账: 资源账
    主因: str
    组序分解: tuple[组序分解, ...]
    错峰: tuple[错峰项, ...]
    跨组段数: int = 0
    重复计数增量: int = 0


def _区间(区间表: 资源区间表, 键: tuple[str, str]) -> tuple[占用区间, ...]:
    return 区间表.取(*键)


def 重复计数增量(
    键: tuple[str, str],
    区间表: 资源区间表,
    方案: 分区方案,
) -> tuple[int, int]:
    """跨组占用的重复计数证据 → (跨组占用段数, Σ(触及组数 − 1))。

    中继侧的占用段（驻留段、中继架次）常同时服务多个组的架次，于是**同一段占用**
    在每组各计一次。这是「资源不得跨组调配」的直接后果，也是中继侧 Δ 的主要来源 ——
    与「时间错峰被切断」是**两回事**，必须分开陈述（前者的物理含义是：每个组都要
    独立持有一份完整的中继能力）。
    """
    架次组 = {序号: g for g, 组 in enumerate(方案.组) for 序号 in 组.架次序号}
    跨组段数 = 0
    增量 = 0
    for x in _区间(区间表, 键):
        触及 = 归属组(x, 架次组)
        if len(触及) > 1:
            跨组段数 += 1
            增量 += len(触及) - 1
    return 跨组段数, 增量


def 合并树分解(
    键: tuple[str, str],
    区间表: 资源区间表,
    方案: 分区方案,
    各组峰值: tuple[int, ...],
) -> tuple[组序分解, ...]:
    """按组序累进合并，把 Δ 分摊到每一步。k=2 唯一、k=3 有 3 种组序。

    **合并时按区间去重**：同一段占用（如同一趟中继架次）会同时出现在多个组里，
    它是**同一份**占用能力，合并后不得重复计数 —— 否则峰值会凭空翻倍、分解不闭合。
    """
    架次组 = {序号: g for g, 组 in enumerate(方案.组) for 序号 in 组.架次序号}
    各组区间 = [
        [x for x in _区间(区间表, 键) if g in 归属组(x, 架次组)] for g in range(方案.k)
    ]
    分解表 = []
    for 序 in permutations(range(方案.k)):
        已合并: list[占用区间] = []
        峰 = 0
        步 = []
        for i, g in enumerate(序):
            已合并 = list(dict.fromkeys(已合并 + 各组区间[g]))  # 按区间值去重
            新峰 = 峰值并发(已合并)
            省 = (峰 + 各组峰值[g] - 新峰) if i > 0 else 0
            步.append(合并步(并入组=g + 1, 本步省下=省, 合并后峰值=新峰))
            峰 = 新峰
        分解表.append(
            组序分解(组序=tuple(g + 1 for g in 序), 步=tuple(步), 合计省下=sum(s.本步省下 for s in 步))
        )
    return tuple(分解表)


def 错峰判定(组需求表: tuple[组资源需求, ...], 键: tuple[str, str]) -> tuple[错峰项, ...]:
    """逐组对比较峰段；不相交者给出「至少 min(P_g,P_h) 被重复购置」的**下界**。"""
    项 = []
    for i in range(len(组需求表)):
        for j in range(i + 1, len(组需求表)):
            甲, 乙 = 组需求表[i], 组需求表[j]
            甲团, 乙团 = 甲.紧约束.get(键), 乙.紧约束.get(键)
            if 甲团 is None or 乙团 is None:
                continue
            甲段 = (甲团.峰段起_s, 甲团.峰段终_s)
            乙段 = (乙团.峰段起_s, 乙团.峰段终_s)
            错峰 = 甲段[1] <= 乙段[0] or 乙段[1] <= 甲段[0]
            项.append(
                错峰项(
                    组甲=甲.组号,
                    组乙=乙.组号,
                    甲峰段_s=甲段,
                    乙峰段_s=乙段,
                    错峰=错峰,
                    重复购置下界=min(甲团.峰值, 乙团.峰值) if 错峰 else 0,
                )
            )
    return tuple(项)


def 判主因(账: 资源账, 跨组段数: int, 重复计数增量: int) -> str:
    """给出主因结论（可追溯到账、跨组重复计数与合并树的下述字段）。

    **必须区分两种成因**（它们物理含义完全不同，写混就是错误归因）：

    * **跨组重复计数**：同一段占用（如一趟中继架次）同时服务多个组，于是每组各计一次。
      含义是「每个组都要独立持有一份完整的中继能力」，与时间错峰无关。
    * **时间错峰被切断**：各组的高峰落在不同时段，合并资源池本可复用。
    """
    if 账.缺口 == 0:
        if 账.余量吸收:
            return (
                f"余量吸收：Δ = {账.跨组复用丢失} > 0，但全局峰值 {账.全局峰值} "
                f"低于库存 {账.库存}，余量 {账.全局余量} 将其全部吸收 ⇒ 无缺口"
            )
        return f"无缺口：各组峰值之和 {账.各组峰值之和} ≤ 库存 {账.库存}，冗余 {账.冗余}"

    前缀 = f"跨组复用丢失 Δ = {账.跨组复用丢失}"
    if 账.全局亏空 > 0:
        前缀 = (
            f"全局绝对亏空 {账.全局亏空}（不分区即已超库存 {账.库存}）；"
            f"分区另外造成的部分为 Δ = {账.跨组复用丢失}"
        )
    if 重复计数增量 > 0:
        return (
            前缀
            + f"；其中 {跨组段数} 段占用跨组，被其触及的各组各计一次（重复计数合计 "
            f"{重复计数增量}）—— 这类 Δ 来自「跨组任务在每组各备一份能力」，"
            f"与时间错峰被切断无关"
        )
    return 前缀 + "；无跨组占用段，Δ 全部来自各组独立执行后高峰不再错峰（合并资源池可省下单位）"


def 归因(
    账表: tuple[资源账, ...],
    区间表: 资源区间表,
    方案: 分区方案,
    组需求表: tuple[组资源需求, ...],
) -> tuple[归因项, ...]:
    """逐资源给出证据化归因。"""
    项 = []
    for 账 in 账表:
        键 = (账.资源类, 账.子类)
        if not _区间(区间表, 键):
            continue
        分解 = 合并树分解(键, 区间表, 方案, 账.各组峰值)
        跨组段数, 增量 = 重复计数增量(键, 区间表, 方案)
        项.append(
            归因项(
                账=账,
                主因=判主因(账, 跨组段数, 增量),
                组序分解=分解,
                错峰=错峰判定(组需求表, 键),
                跨组段数=跨组段数,
                重复计数增量=增量,
            )
        )
    return tuple(项)


def 紧约束明细(
    区间表: 资源区间表,
    全局需求: 组资源需求,
    组需求表: tuple[组资源需求, ...],
) -> list[dict]:
    """证据表：每个 (资源类, 子类, 口径, 载体) 一行，供落盘与报告引用行号。"""
    行: list[dict] = []
    口径表 = [("全局", 全局需求)] + [(f"组{需求.组号}", 需求) for 需求 in 组需求表]
    for 键 in 区间表.区间:
        资源类, 子类 = 键
        for 口径, 需求 in 口径表:
            团 = 需求.紧约束.get(键)
            if 团 is None or 团.峰值 == 0:
                continue
            for 成员 in 团.成员:
                起, 终 = 成员.左_s, 成员.右_s
                行.append(
                    {
                        "资源类": 资源类,
                        "子类": 子类,
                        "口径": 口径,
                        "峰值": 团.峰值,
                        "峰段起_s": round(团.峰段起_s, 3),
                        "峰段终_s": round(团.峰段终_s, 3),
                        "载体": 成员.载体,
                        "来源": 成员.来源,
                        "成员左_s": round(起, 3),
                        "成员右_s": round(终, 3),
                        "已持续_s": round(团.峰段起_s - 起, 3),
                        "剩余_s": round(终 - 团.峰段起_s, 3),
                        "服务架次": " ".join(str(x) for x in 成员.服务架次),
                    }
                )
    return 行


def 归因自检(项表: tuple[归因项, ...]) -> list[str]:
    """闭合性与下界标注核对。"""
    for 项 in 项表:
        账 = 项.账
        for 分解 in 项.组序分解:
            if 分解.合计省下 != 账.跨组复用丢失:
                raise RuntimeError(
                    f"{账.显示名} 组序 {分解.组序} 的分解合计 {分解.合计省下} ≠ Δ {账.跨组复用丢失}"
                )
        if 项.重复计数增量 < 0 or 项.跨组段数 < 0:
            raise RuntimeError(f"{账.显示名} 重复计数为负：{项.跨组段数} 段 / 增量 {项.重复计数增量}")
    if any(d.错峰 and d.重复购置下界 <= 0 for 项 in 项表 for d in 项.错峰):
        raise RuntimeError("错峰判定给了 0 下界，逻辑矛盾")
    组序数 = len(项表[0].组序分解) if 项表 else 0
    条目 = [
        f"[自检] 合并树分解闭合：{len(项表)} 类资源 × {组序数} 种组序，"
        f"各序「Σ各步省下 == Δ」逐位成立",
        "[自检] 错峰判定的重复购置下界仅用于定性说明，**各项不可相加**（已在输出中标注）",
    ]
    跨组 = [(项.账.显示名, 项.跨组段数, 项.重复计数增量) for 项 in 项表 if 项.跨组段数]
    if 跨组:
        条目.append(
            "[自检] 跨组重复计数证据："
            + "；".join(f"{名} {段} 段占用跨组、重复计数合计 {增}" for 名, 段, 增 in 跨组)
        )
    return 条目
