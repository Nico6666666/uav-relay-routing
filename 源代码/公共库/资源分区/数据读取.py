"""输入数据读取 —— 库存 / 人口 / 机型与电池参数。

职责
----
把 `基础数据/无人机数据/json/` 的数据表读成内存对象，供分区与资源核算核算资源需求与
比对库存。**全部数值来自数据文件**：问题描述只给了「共配置 8 架实体运输无人机」
一类的架数描述，电池组数与能源组件组数只存在于输入数据 JSON（
「机型与设备参数一律从输入数据 JSON 读取，禁止硬编码」）。

口径
----
* 运输无人机架数 = 数据文件 `运输无人机` 表**逐架清单的长度**（8 架：U01–U08）；
* 共享电池组数 = 数据文件 `共享电池` 表的 `共享电池组总数（组）`（A6/B4/C4）；
* 中继无人机架数 = 数据文件 `中继无人机` 表逐架清单的长度（2 架：R01–R02）；
* 中继能源组件组数 = 数据文件 `中继能源库存` 的 `共享能源组件总数（组）`（6 组）；
* 服务区人口 = 数据文件 `服务区` 表的 `本次需保障人口（人）`。

读取动作本身复用 `通信中继.数据读取`（该模块已统一剥离数据文件键名里的全角单位），
本模块只做**归类与库存口径的组装**，不重复实现读取逻辑。

依据：《基础数据文件说明》。
"""
from __future__ import annotations

from 源代码.公共库.资源分区.配置 import 项目根
from 源代码.公共库.通信中继 import 数据读取 as 数据读取
from 源代码.公共库.通信中继.飞行模型 import 机型


# ===================== 机型与电池 =====================
def 机型表() -> dict[str, 机型]:
    """返回 {机型编号: 机型}。字段缺失时 `机型.由字典` 抛 KeyError（不补默认值）。"""
    return {编号: 机型.由字典(记录) for 编号, 记录 in 数据读取.读取机型().items()}


def 共享电池表() -> dict[str, dict]:
    """返回 {机型编号: {组数, 等效完全充电时间}}（A 1800 / B 2400 / C 3000 s）。"""
    return 数据读取.读取共享电池()


def 中继机型表() -> dict[str, dict]:
    """返回 {机型编号: {剥离单位后的字段}}（含 `能源组件可用能量_kWh`）。"""
    return 数据读取.读取中继机型()


def 中继无人机表() -> list[dict]:
    """返回 [{中继无人机编号, 机型编号, 初始位置}, ...]。"""
    return 数据读取.读取中继无人机()


def 中继能源组件表() -> dict[str, dict]:
    """返回 {机型编号: {组数, 等效完全充电时间_s}}。"""
    return 数据读取.读取中继能源组件()


# ===================== 服务区 =====================
def 服务区表() -> dict[str, dict]:
    """返回 {服务区编号: {编号, 名称, 经度, 纬度, 海拔, 人口}}。"""
    return {记录["编号"]: 记录 for 记录 in 数据读取.读取服务区()}


# ===================== 库存 =====================
def 库存() -> dict:
    """数据文件给出的现有资源数量 —— 分区方案要与它比对才谈得上「缺口」。

    结构::

        {"运输无人机": {"A": 4, "B": 2, "C": 2},
         "共享电池":   {"A": 6, "B": 4, "C": 4},
         "中继无人机": 2,
         "中继能源组件": 6}

    **零硬编码**：每个数都由数据文件的逐架清单 `len()` 或总数列表得出。
    """
    运输无人机 = 数据读取.读取运输无人机()
    机 = {型: 0 for 型 in ("A", "B", "C")}
    for 记录 in 运输无人机:
        机[记录["机型编号"]] += 1

    电池 = {型: 记录["组数"] for 型, 记录 in 共享电池表().items()}
    组件 = {型: 记录["组数"] for 型, 记录 in 中继能源组件表().items()}

    return {
        "运输无人机": 机,
        "共享电池": 电池,
        "中继无人机": len(中继无人机表()),
        "中继能源组件": sum(组件.values()),
    }


def 库存来源清单() -> list[str]:
    """逐项说明「哪个数来自数据文件的哪一列」，供文档《数据来源》与自检引用。"""
    数据目录 = (项目根 / "基础数据" / "无人机数据" / "json")
    return [
        f"运输无人机 A/B/C = {库存()['运输无人机']}"
        f"（{数据目录 / '运输无人机数据.json'} 的 `运输无人机` 表逐架清单长度）",
        f"共享电池 A/B/C = {库存()['共享电池']}"
        f"（同文件 `共享电池` 表 `共享电池组总数（组）`）",
        f"中继无人机 = {库存()['中继无人机']}"
        f"（{数据目录 / '中继无人机数据.json'} 的 `中继无人机` 表逐架清单长度）",
        f"中继能源组件 = {库存()['中继能源组件']}"
        f"（同文件 `中继能源库存` 表 `共享能源组件总数（组）`）",
        f"服务区人口（合计 {sum(r['人口'] for r in 服务区表().values())} 人）"
        f"（{数据目录 / '调度中心与服务区.json'} 的 `服务区` 表 `本次需保障人口（人）`）",
    ]
