"""
场景装配 —— 把多点多架次调度输入数据 + 全部节点对的航段几何量组装成可直接消费的场景对象。

与单点往返与组批 `场景装配` 的差别：
    单点往返与组批每个架次只服务**一个**服务区，因此只需 O01→Si 的 15 条航段；
    多点多架次调度一个架次可连续访问**多个**服务区，航段可能是 Si→Sj，
    故本模块预计算 {O01} ∪ 15 个服务区的**全部节点对**航段几何，共 C(16,2) = 120 条。

    航段几何对两端对称（水平直线 + 沿线地面高程最大值），故按无序对存储。

口径（时间与能源规则）：
    * 水平距离  中纬度等距投影（`公共库.地理计算.水平距离_m`）
    * 巡航海拔  该航段所经过 DEM 像元的最高地面高程 + 50 m
    * 作业高度  O01 = 地面海拔；服务区 = 地面海拔 + 30 m
"""
from __future__ import annotations

from dataclasses import dataclass
from itertools import combinations

from 源代码.公共库.通信中继 import 地理计算 as 地理计算
from 源代码.公共库.通信中继 import 数据读取 as 数据读取
from 源代码.公共库.通信中继.配置 import (
    巡航净空_m,
    服务区作业高度增量_m,
    调度中心作业高度增量_m,
    调度中心编号,
)
from 源代码.公共库.通信中继.飞行模型 import 机型


# ===================== 航段几何 =====================
@dataclass(frozen=True)
class 航段几何:
    """两个任务节点之间的航段几何量（与方向无关）。"""

    起点编号: str
    终点编号: str
    水平距离: float          # d（m）
    沿线最高地面高程: float  # 沿线 DEM 像元最高地面高程（m）
    巡航海拔: float          # H = 沿线最高地面高程 + 50（m）

    def 对端(self, 编号: str) -> str:
        """给定航段的一端，返回另一端编号。"""
        if 编号 == self.起点编号:
            return self.终点编号
        if 编号 == self.终点编号:
            return self.起点编号
        raise KeyError(f"{编号} 不是航段 {self.起点编号}—{self.终点编号} 的端点")


# ===================== 场景 =====================
@dataclass(eq=False)
class 场景:
    """多点多架次调度的全部输入。

    采用 `eq=False`：场景以**对象身份**比较与哈希，从而可作为 `lru_cache` 的键
    （见 `构造启发式._包代价缓存`），避免反复重算同一载荷包的代价。
    """
    调度中心: dict
    服务区表: dict[str, dict]                 # 编号 -> 服务区记录
    编号顺序: tuple[str, ...]                 # 服务区编号升序
    机型表: dict[str, 机型]
    无人机表: dict[str, dict]                 # 无人机编号 -> {机型编号, 初始位置}
    电池表: dict[str, dict]                   # 机型编号 -> {组数, 等效完全充电时间}
    货箱: list[dict]                          # 80 个货箱，按编号升序
    货箱索引: dict[str, dict]                 # 货箱编号 -> 货箱记录（O(1) 查表）
    货箱归属: dict[str, list[dict]]           # 服务区编号 -> 该区货箱
    航段表: dict[tuple[str, str], 航段几何]   # 无序节点对 -> 航段几何
    地面高程: object = None                   # np.ndarray，仅诊断用
    纬度向量: object = None
    经度向量: object = None

    # ---------- 节点 ----------
    @property
    def 节点编号列表(self) -> tuple[str, ...]:
        """O01 + 全部服务区，O01 恒为首项。"""
        return (调度中心编号,) + self.编号顺序

    def 城区(self, 编号: str) -> bool:
        return 编号 != 调度中心编号

    def 节点地面海拔(self, 编号: str) -> float:
        if 编号 == 调度中心编号:
            return self.调度中心["海拔"]
        return self.服务区表[编号]["海拔"]

    def 节点作业高度(self, 编号: str) -> float:
        """时间与能源规则：O01 作业高度取地面海拔；服务区取地面海拔以上 30 m。"""
        if 编号 == 调度中心编号:
            return self.调度中心["海拔"] + 调度中心作业高度增量_m
        return self.服务区表[编号]["海拔"] + 服务区作业高度增量_m

    def 节点名称(self, 编号: str) -> str:
        if 编号 == 调度中心编号:
            return self.调度中心["名称"]
        return self.服务区表[编号]["名称"]

    # ---------- 航段 ----------
    def 取航段(self, 甲: str, 乙: str) -> 航段几何:
        """取两个不同节点之间的航段几何（自动处理方向）。"""
        if 甲 == 乙:
            raise ValueError(f"{甲} → {乙}：航段两端不能是同一节点")
        键 = (甲, 乙) if (甲, 乙) in self.航段表 else (乙, 甲)
        try:
            return self.航段表[键]
        except KeyError as 错:
            raise KeyError(f"航段表中不存在 {甲}—{乙}") from 错

    # ---------- 资源 ----------
    @property
    def 无人机清单(self) -> dict[str, list[str]]:
        """{机型编号: [无人机编号, ...]}，按编号升序。"""
        出: dict[str, list[str]] = {}
        for 编号, 记录 in self.无人机表.items():
            出.setdefault(记录["机型编号"], []).append(编号)
        for 机型编号 in 出:
            出[机型编号].sort()
        return 出

    @property
    def 电池清单(self) -> dict[str, list[str]]:
        """{机型编号: [电池编号, ...]}，编号形如 `A-BAT-01`。"""
        出: dict[str, list[str]] = {}
        for 机型编号 in sorted(self.电池表):
            组数 = self.电池表[机型编号]["组数"]
            出[机型编号] = [f"{机型编号}-BAT-{i:02d}" for i in range(1, 组数 + 1)]
        return 出

    def 取货箱(self, 货箱编号: str) -> dict:
        try:
            return self.货箱索引[货箱编号]
        except KeyError as 错:
            raise KeyError(f"未知货箱编号 {货箱编号}") from 错


# ===================== 装配 =====================
def 装载场景() -> 场景:
    """读取全部输入数据，并预计算 {O01} ∪ 服务区 的**全部节点对**航段几何。"""
    调度中心 = 数据读取.读取调度中心()
    服务区列表 = 数据读取.读取服务区()
    服务区表 = {区["编号"]: 区 for 区 in 服务区列表}
    编号顺序 = tuple(区["编号"] for 区 in 服务区列表)

    机型表 = {k: 机型.由字典(v) for k, v in 数据读取.读取机型().items()}
    无人机表 = {d["无人机编号"]: d for d in 数据读取.读取运输无人机()}
    电池表 = 数据读取.读取共享电池()

    货箱 = 数据读取.读取货箱()
    货箱.sort(key=lambda b: b["货箱编号"])
    货箱归属 = 数据读取.按服务区归组货箱(货箱)

    地面高程, 纬度向量, 经度向量 = 数据读取.读取DEM()

    # 节点坐标：O01 + 全部服务区
    坐标 = {调度中心编号: (调度中心["经度"], 调度中心["纬度"])}
    for 区 in 服务区列表:
        坐标[区["编号"]] = (区["经度"], 区["纬度"])

    航段表: dict[tuple[str, str], 航段几何] = {}
    for 甲, 乙 in combinations(坐标, 2):
        经度甲, 纬度甲 = 坐标[甲]
        经度乙, 纬度乙 = 坐标[乙]
        距离 = 地理计算.水平距离_m(经度甲, 纬度甲, 经度乙, 纬度乙)
        沿线最高 = 地理计算.沿线最高地面高程(
            经度甲, 纬度甲, 经度乙, 纬度乙, 地面高程, 纬度向量, 经度向量
        )
        航段表[(甲, 乙)] = 航段几何(
            起点编号=甲,
            终点编号=乙,
            水平距离=距离,
            沿线最高地面高程=沿线最高,
            巡航海拔=沿线最高 + 巡航净空_m,
        )

    return 场景(
        调度中心=调度中心,
        服务区表=服务区表,
        编号顺序=编号顺序,
        机型表=机型表,
        无人机表=无人机表,
        电池表=电池表,
        货箱=货箱,
        货箱索引={b["货箱编号"]: b for b in 货箱},
        货箱归属=货箱归属,
        航段表=航段表,
        地面高程=地面高程,
        纬度向量=纬度向量,
        经度向量=经度向量,
    )
