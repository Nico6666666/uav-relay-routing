"""
时限模型 —— 货箱时限的判定与「配送及时性」指标。

时限处理的三档规则（多点多架次调度）：

    * **医疗物资**：应满足数据文件给出的**期望送达时间**要求            → 硬约束
    * **首批保障货箱**：应满足**首批截止时间**要求                  → 硬约束
    * **其他物资**：期望送达时间用于衡量**配送及时性**              → 软指标（进入目标 f1）

本模块据此划分判定口径（**已与出题方确认**）：

    ┌ 硬约束（必须满足，违反即方案不可行）───────────────────────┐
    │ 物资类型 == 医疗物资   → 送达时刻 ≤ 期望送达时间              │
    │ 是否首批保障 == 是     → 送达时刻 ≤ 首批截止时间              │
    └──────────────────────────────────────────────────────────┘
    ┌ 软目标 f1 = 配送及时性（最小化）──────────────────────────┐
    │ 仅统计**非医疗物资**（医疗物资已由硬约束覆盖，不重复计入）     │
    │   f1 = Σ_b 应急优先系数_b · max(0, 送达_b − 期望_b)          │
    └──────────────────────────────────────────────────────────┘

送达时刻的口径：**完成该服务区交接的时刻**（见 `多点飞行模型`）。
本模块另提供最大延误 / 准时率 / 平均送达时刻等**诊断量**（统计全部箱），
用于论文中刻画解的分布，但它们不进入目标函数。
"""
from __future__ import annotations

from dataclasses import dataclass

from 源代码.公共库.通信中继.配置 import 数值容差

医疗物资类型 = "医疗物资"


# ===================== 时限摘要 =====================
@dataclass(frozen=True)
class 时限摘要:
    """一个货箱的送达时刻与时限的对照结果。"""

    货箱编号: str
    服务区编号: str
    物资类型: str
    应急优先系数: int
    是否首批保障: bool
    首批截止时间: float | None
    期望送达时间: float
    送达时刻: float

    # ---------- 判定 ----------
    @property
    def 是否医疗物资(self) -> bool:
        return self.物资类型 == 医疗物资类型

    @property
    def 计入及时性(self) -> bool:
        """医疗物资由硬约束覆盖，**不**计入 f1（已确认口径）。"""
        return not self.是否医疗物资

    @property
    def 延误(self) -> float:
        """相对期望送达时间的延误（s），早到为 0。"""
        return max(0.0, self.送达时刻 - self.期望送达时间)

    @property
    def 加权延误(self) -> float:
        """应急优先系数 × 延误，仅对计入及时性的货箱有效。"""
        return self.应急优先系数 * self.延误 if self.计入及时性 else 0.0

    @property
    def 是否准时(self) -> bool:
        return self.送达时刻 <= self.期望送达时间 + 数值容差

    @property
    def 首批是否满足(self) -> bool:
        if not self.是否首批保障 or self.首批截止时间 is None:
            return True
        return self.送达时刻 <= self.首批截止时间 + 数值容差

    @property
    def 期望硬约束是否满足(self) -> bool:
        """医疗物资的期望送达时间是硬约束；其他物资是软指标。"""
        if not self.是否医疗物资:
            return True
        return self.是否准时

    @property
    def 硬约束是否满足(self) -> bool:
        return self.首批是否满足 and self.期望硬约束是否满足

    @property
    def 违反量(self) -> float:
        """硬约束超出量（s），用于修复算子的排序与罚函数。0 表示不违反。"""
        超 = 0.0
        if self.是否首批保障 and self.首批截止时间 is not None:
            超 = max(超, self.送达时刻 - self.首批截止时间)
        if self.是否医疗物资:
            超 = max(超, self.送达时刻 - self.期望送达时间)
        return max(超, 0.0)


# ===================== 构造 =====================
def 构造时限摘要(场景, 逐箱送达: list[tuple[str, str, float]]) -> list[时限摘要]:
    """把 `[(货箱编号, 服务区编号, 送达时刻), ...]` 装配成时限摘要表。"""
    出 = []
    for 箱编号, 服务区编号, 时刻 in 逐箱送达:
        箱 = 场景.取货箱(箱编号)
        出.append(
            时限摘要(
                货箱编号=箱编号,
                服务区编号=服务区编号,
                物资类型=箱["物资类型"],
                应急优先系数=int(箱["应急优先系数"]),
                是否首批保障=bool(箱["是否首批保障"]),
                首批截止时间=箱["首批截止时间"],
                期望送达时间=float(箱["期望送达时间"]),
                送达时刻=float(时刻),
            )
        )
    return 出


# ===================== 目标 f1：配送及时性 =====================
def 加权总延误(摘要: list[时限摘要]) -> float:
    """f1 = Σ 应急优先系数 · 延误，**仅统计非医疗物资**（s·权重，越小越好）。"""
    return sum(条.加权延误 for 条 in 摘要)


# ===================== 硬约束 =====================
def 硬约束违反(摘要: list[时限摘要]) -> list[时限摘要]:
    """返回违反硬时限（首批截止 或 医疗期望时间）的货箱摘要。"""
    return [条 for 条 in 摘要 if not 条.硬约束是否满足]


def 硬约束超出量合计(摘要: list[时限摘要]) -> float:
    return sum(条.违反量 for 条 in 摘要)


# ===================== 诊断量（不进入目标函数）=====================
def 总延误(摘要: list[时限摘要]) -> float:
    return sum(条.延误 for 条 in 摘要)


def 最大延误(摘要: list[时限摘要]) -> float:
    return max((条.延误 for 条 in 摘要), default=0.0)


def 准时箱数(摘要: list[时限摘要]) -> int:
    return sum(1 for 条 in 摘要 if 条.是否准时)


def 准时率(摘要: list[时限摘要]) -> float:
    return 准时箱数(摘要) / len(摘要) if 摘要 else 1.0


def 平均送达时刻(摘要: list[时限摘要]) -> float:
    return sum(条.送达时刻 for 条 in 摘要) / len(摘要) if 摘要 else 0.0


def 加权平均送达时刻(摘要: list[时限摘要]) -> float:
    """按应急优先系数加权的平均送达时刻，反映"重要物资是否来得早"。"""
    权 = sum(条.应急优先系数 for 条 in 摘要)
    if 权 == 0:
        return 0.0
    return sum(条.应急优先系数 * 条.送达时刻 for 条 in 摘要) / 权
