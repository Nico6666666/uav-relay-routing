"""
悬停高度 —— 中继悬停**最优高度**的求解。

结论（本模块的核心）
--------------------
**最优悬停高度 = 最小可行高度**，可解析求出，**不需要在高度维度做搜索**。

最优性依据（三条命题，缺一不可）：

    命题 1  遮挡 b(H) 随高度**单调不增**
            视线的运输机端固定、中继端抬升 ⇒ 视线上每一点按线性插值抬升，
            地面高程不变 ⇒ 被判为遮挡的采样点集合只减不增。
    命题 2  链路可用性是**高度的 0/1 判定**
            可行性是布尔量：一旦某高度可行，再升高不会"更可行"，不带来连续收益。
    命题 3  中继能耗随高度**严格递增**
            巡航项 $P_R^{巡} \\cdot t$ 与高度无关；爬升项
            $m_R^{起飞} g \\Delta h^{+} / \\eta_R^{\\uparrow}$ 关于
            $\\Delta h^{+} = \\max(H - h^{作}_{O01}, 0)$ 严格递增；
            等待可在最优策略下取 0（精确按时到位，Q7 的等待耗能即不发生）。

⇒ 在给定平面位置上，可行高度集合非空时 $H^{*} = \\min\\{$可行高度$\\}$ **是全局最优**。

直觉上"越高通信越顺畅、但爬升能耗越大"两者并不需要权衡：**通畅是布尔量，
达标即封顶；能耗却一直涨**。真正的权衡发生在**平面维度** —— 中继贴近运输机可以把
遮挡临界高度压下来，飞得高一点则能以更远的平面距离达成同样覆盖。本模块把两者解耦：
平面由网格搜索（Q3），每个平面位置的最小可行高度由本模块直接给出，能耗 $E(H^{*})$
直接可比。这正是"哪个高度最优"的完整答案。

算法（三层）
------------
**第 1 层 · 解析定界**（零 DEM 调用）

    $H_{hi} = \\min\\big(h^{地}(c) + H^{max}_R,\\ \\min_p (h_p + \\sqrt{D_{无}^2 - d_p^2})\\big)$

其中 $D_{无}$ 为无遮挡时的**接入**上限（6.270 km），$d_p$ 为该位姿的水平距离。
若某位姿 $d_p > D_{无}$ ⇒ 该平面位置物理上无法覆盖，直接判不可行。

**第 2 层 · 扫描求首个可行高度**（**不假定可行集是单区间**）

以 `悬停高度扫描步长_m` 正扫描 $[h^{地}, H_{hi}]$，逐个判定
"**全部位姿的接入链路 ＋ 回传链路同时可用**"。命中首个可行点后，
若其余扫描点全部可行则记 `单调 = True`，并在该括号内二分 `悬停高度二分迭代次数`
次定到亚毫米；若非单调，则退化为 1 m 细扫描取最小可行值，并如实报告。

**第 3 层 · 最小性校验**

在 $H^{*}$ 处确认可行、在 $H^{*} - $ `悬停高度校验步长_m` 处确认不可行
—— 这是"最小"二字的证据，而不是靠二分收敛的假定。

对拍自检
--------
`悬停高度自检` 用 **1 m 全网格暴力解**与解析结果逐点对拍，偏差须 ≤ 1 m。
暴力解不做任何单调性或定界假设，是本模块正确性的独立证据。

参数依赖
--------
悬停离地上限取自数据文件「中继无人机数据 · 最大悬停离地高度（m）」（值 300 m），
**不硬编码**。本模块不 import 中继模型，只依赖 `通信模型`（链路判定）
与 `通信剖面`（节点坐标访问器）。
"""
