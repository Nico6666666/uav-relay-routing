"""
通信模型 —— **通信规则的唯一实现**。

本模块是全局通信链路计算的唯一口径来源：地形遮挡判定、接收门限与双向链路预算、
自由空间传播损耗、总传播损耗、单链路双向可用性、通信服务三态判定。
五目标优化/方案检验的主程序与 `通信剖面` / `缺口解析` / `可行性检验` 都调用这里，
不另行实现任何通信公式。

口径（通信规则原文，对应联合调度与中继求解条件.md §3.6）
------------------------------------------------
（1）地形遮挡      端点视线连线与沿途 30 m DEM 是否相交 ⇒ b_ij(t) ∈ {0,1}
（2）接收门限      P_th = P_sens + M
    链路预算      L_max^{a→b} = P_t^a + G_t^a + G_r^b - L_sys - P_th^b
    双向门限      L_max^{a↔b} = min(L_max^{a→b}, L_max^{b→a})
（3）传播损耗      L_FSPL = 32.45 + 20·log10(f_MHz) + 20·log10(D_km)
                  L_path = L_FSPL + L_obs · b_ij(t)
（4）可用性        A_ij = 1 当且仅当 L_path ≤ L_max^{i↔j}
（5）服务状态      直连 / 中继（接入与回传须**同时**可用）/ 中断

判定粒度（口径 Q1，已确认）
---------------------------
**不设采样步长。** 判定枚举视线**地面轨迹覆盖到的全部 DEM 像元**
（`地理计算.线段覆盖像元`，像元闭方形与轨迹相交即计入），
逐个比较该像元的地面高程与视线在该处的绝对高度。

之所以放弃「按 30 m 步长取最近像元」的游走：DEM 像元间距纬向约 30.9 m、
经向约 28.5 m，游走会**系统性漏掉只被轨迹擦角的像元**，
从而把"有遮挡"误判为"无遮挡"（上游在同类几何量上实测最多低估 16.40 m）。
本判定的误判方向必须是保守的：宁可判为遮挡。

两通信端点的**自身所在像元不参与判定**（端点必然高于其脚下地面，不构成遮挡）。

性能设计
--------
`通信环境` 持有 DEM 与参数，并对**视线遮挡**做按量化位姿的记忆化
（量化到 1 m / 0.1 m，远细于口径要求的精度）。遮挡判定只依赖两个端点的
三维位置，与端点类型无关，故不同类型的端点共用同一份缓存。
"""
