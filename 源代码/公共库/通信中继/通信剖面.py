"""
通信剖面 —— 两张预计算表：**表A 航段直连剖面** 与 **表B 节点直连临界高度**。

为什么要两张表
--------------
`缺口解析` 要对**每一个**运输架次的**每一段**判定直连可用性。若逐时刻现算，
每个方案需 $10^4 \\sim 10^5$ 次 DEM 视线判定，五目标搜索无法承受。

Q2 的三段式位置模型带来一个结构性便利：**只有巡航段是二维的**（沿航线移动），
**爬升段与下降段是一维的**（水平位置固定在节点正上方，只有高度变化）。
于是两段可以分别预计算成表，之后**任何架次的缺口都能 O(1) 查出**：

    表A  120 条航段**巡航段**的直连可用区间（沿航线的里程区间）
    表B  16 个节点的**直连临界高度** $h^*$：海拔 $\\ge h^*$ 直连可用，$< h^*$ 中断

有了两表，缺口解析对每一段的判定方式变为：

    阶段         判定方式                        是否需算 DEM
    起点爬升     水平位置固定在起点上方 ⇒ 查表B(起点)      否
    巡航段       查表A：里程落在可用区间内？              否
    终点下降     水平位置固定在终点上方 ⇒ 查表B(终点)      否
    投送交接     高度 = 作业高度 ⇒ 查表B(终点)             否
    回程         同上，按对称处理                        否

口径
----
* 直连可用性**严格按通信规则原文**判定（遮挡是**加性损耗**，不是硬阻断）：

      $L_{path} = L_{FSPL} + L_{obs}\\,b_{ij}(t)$,　$A = 1 \\iff L_{path} \\le L^{运输机\\leftrightarrow G01}_{max}$

  依据 [`联合调度与中继求解条件.md`](../../联合调度与中继求解条件.md) §2.7 的《⚠️ 2026-09-24 更正》。
  判定完全复用 `通信模型.通信环境`，**本模块不另写任何通信公式**。
* 巡航海拔取该航段沿线 DEM 最高地面高程 + 50 m（时间与能源规则）。
* 采样步长与 DEM 像元同尺度（30 m），满足口径 Q1。

设计要点
--------
* **表A 与方向无关**：巡航海拔 $H_{ij}$ 只由航段两端决定，故可用区间对称。
* **表B 的临界高度是绝对海拔**；离地高度由 `临界离地` 按需折算。
* 「始终可用」用 `临界海拔 = None` 表示 —— 距 $G01 \\le 3.956$ km 的节点在被遮挡时
  直连仍然可用，**不存在临界高度**（这正是 §2.7 更正指出的情形）。
* **不假定可用性关于海拔单调**：表B 先正扫描全区间（不跳过任何一段），
  再在首个可用点所在括号内二分。若扫描发现「不可用—可用」之外还有反复，
  记为 `单调 = False` 并如实报告，绝不静默取首个可用点。

本模块同时提供联合调度与中继各模块共用的 `节点水平坐标` —— 场景对象只暴露作业高度与
地面海拔，不暴露坐标，而沿航段插值需要坐标。
"""
from __future__ import annotations

import math
from dataclasses import dataclass, field

from 源代码.公共库.通信中继.通信模型 import 运输机端点, 通信环境, 通信端点
