"""
中继模型 —— 中继机型、悬停站、中继架次的**时间与能耗构成**，以及能源组件周转。

口径（《中继无人机时间与能耗规则》与《求解条件》§3.5）
----------------------------------------------------------------
**飞行**：中继机由 $O01$ 出发 → 到达悬停位置 → 完成建链后提供服务 → 服务结束返回 $O01$。
飞行时间与能耗**沿用与运输机完全相同的三段式**（爬升 → 巡航 → 下降）：

    $t = h^{+}/v_R^{\\uparrow} + d/v_R^{c} + h^{-}/v_R^{\\downarrow}$
    $E^{巡} = P_R^{巡} \\cdot t^{巡} / 3600$
    $E^{升} = m_R^{起飞}\\, g\\, h^{+} / \\big(\\eta_R^{\\uparrow} \\cdot 3.6\\times10^{6}\\big)$

其中**质量取计划起飞总质量** $m_R^{起飞} = 23.5$ kg（时间与能源规则原文）；
下降能耗效率取 0 ⇒ 不单独计算下降附加能耗。
往返与转场的地形净空按航段规则确定：巡航海拔 = 该段沿线 DEM 最高地面高程 + 50 m。

**服务**：通信服务能耗由**悬停功率与通信附加功率共同确定**

    $E^{通} = (P_R^{悬} + P_R^{通}) \\cdot \\tau^{服} / 3600 = 1.10\\ \\text{kW} \\cdot \\tau^{服}/3600$

**等待**（口径 Q7）：提前到位后等待期间**等就悬停**，按 $P_R^{悬} = 1.05$ kW 计；
**通信附加功率 0.05 kW 仅在实际服务时段计**。建链的 30 s 亦归入悬停（尚未提供服务）。

**时间构成**（三个中继专属时间参数必须计入；Q4 已确认一架次可悬停多站）

    $t_R^{任务} = t_R^{备} + t_R^{飞}(O01 \\to p_1)
                  + \\sum_{m}\\big[t_R^{链} + \\tau_m^{服}\\big]
                  + \\sum_{m<M} t_R^{飞}(p_m \\to p_{m+1}) + t_R^{飞}(p_M \\to O01)$

**两条派生规则**：

1. **建链按站重复计**（Q4b）：每抵达一个新的悬停点须重新建链 $t_R^{链} = 30$ s
   ⇒ 悬停点越多累计建链开销越大，构成"**多站 vs 少站**"的内在权衡。
2. **站间移动按航段三段式计算**，地形净空取该段沿线最高地面高程 + 50 m。

**返航电量**：$E_R^{总} = E_R^{飞} + E_R^{通} + E_R^{等} \\le (1 - \\rho_R) E_R^{use}
= 0.8 \\times 3.2 = 2.56$ kWh。相邻两架次之间还需 $t_R^{周} = 300$ s 周转。

设计说明
--------
* **不写任何通信公式**：链路判定一律调用 `通信模型`。
* **不写任何物理公式**：爬升能耗 / 时间的三段式与运输机共用时间与能源规则的同一套关系。
* 能源组件状态**直接复用** `资源模型.电池状态` 与 `资源模型.充电时长`
  （两阶段等效充电对运输电池与中继能源组件是**同一条规则**，问题时间与能源规则原文）。
* 中继机型的全部参数（含质量、功率、时间参数、悬停上限）一律从输入数据 JSON 读取，
  **不硬编码**。
"""
