# ===================== 中继机型 =====================
@dataclass(frozen=True)
class 中继机:
    """中继机型参数（全部来自输入数据 JSON）。"""

    编号: str
    名称: str
    空载总质量_kg: float            # 含能源组件空载总质量
    通信模块质量_kg: float
    计划起飞总质量_kg: float
    巡航速度: float                 # m/s
    巡航功率_kW: float
    能源组件可用能量_kWh: float
    返航电量下限: float             # 百分数（20）
    工位固定准备时间_s: float
    建链时间_s: float
    架次周转时间_s: float
    最大爬升速度: float             # m/s
    最大下降速度: float             # m/s
    爬升能耗效率: float
    下降能耗效率: float             # 0 ⇒ 不计下降附加能耗
    悬停功率_kW: float
    通信附加功率_kW: float
    最大悬停离地高度_m: float

    @classmethod
    def 由字典(cls, 字典: dict) -> 中继机:
        return cls(
            编号=字典["编号"],
            名称=字典["名称"],
            空载总质量_kg=float(字典["含能源组件空载总质量_kg"]),
            通信模块质量_kg=float(字典["中继通信模块质量_kg"]),
            计划起飞总质量_kg=float(字典["计划起飞总质量_kg"]),
            巡航速度=float(字典["计划巡航速度"]),
            巡航功率_kW=float(字典["巡航功率_kW"]),
            能源组件可用能量_kWh=float(字典["能源组件可用能量_kWh"]),
            返航电量下限=float(字典["返航电量下限"]),
            工位固定准备时间_s=float(字典["工位固定准备时间_s"]),
            建链时间_s=float(字典["建链时间_s"]),
            架次周转时间_s=float(字典["架次周转时间_s"]),
            最大爬升速度=float(字典["最大爬升速度"]),
            最大下降速度=float(字典["最大下降速度"]),
            爬升能耗效率=float(字典["爬升能耗效率"]),
            下降能耗效率=float(字典["下降能耗效率"]),
            悬停功率_kW=float(字典["悬停功率_kW"]),
            通信附加功率_kW=float(字典["通信附加功率_kW"]),
            最大悬停离地高度_m=float(字典["最大悬停离地高度_m"]),
        )

    @property
    def 返航电量比例(self) -> float:
        """rho_R，无量纲。"""
        return self.返航电量下限 / 100.0

    @property
    def 架次能量上限_kWh(self) -> float:
        """(1 − rho_R)·E_R^use = 2.56 kWh —— 返航电量约束的右端项。"""
        return (1.0 - self.返航电量比例) * self.能源组件可用能量_kWh

    @property
    def 通信服务功率_kW(self) -> float:
        """服务时段功率 = 悬停功率 + 通信附加功率 = 1.10 kW。"""
        return self.悬停功率_kW + self.通信附加功率_kW


def 读取中继机() -> 中继机:
    """从数据文件读取唯一的中继机型。"""
    表 = 数据读取.读取中继机型()
    if 中继机型编号 not in 表:
        raise KeyError(f"中继机型表中不存在机型 [{中继机型编号}]，实际有 {sorted(表)}")
    return 中继机.由字典(表[中继机型编号])


# ===================== 中继航段 =====================
@dataclass(frozen=True)
class 中继航段:
    """中继机两点之间的一段飞行（三段式：爬升 → 巡航 → 下降）。"""

    起点名称: str
    终点名称: str
    水平距离: float          # d（m）
    巡航海拔: float          # 该段沿线最高地面高程 + 50（m，绝对海拔）
    起点高度: float          # 起点处的机载高度（m，绝对海拔）
    终点高度: float          # 终点处的机载高度（m，绝对海拔）
    爬升: float              # h+（m）
    下降: float              # h-（m）
    飞行时间: float          # s
    巡航能耗: float          # kWh
    爬升能耗: float          # kWh

    @property
    def 能耗(self) -> float:
        """下降效率为 0 ⇒ 只有巡航项与爬升项。"""
        return self.巡航能耗 + self.爬升能耗


def 中继航段代价(
    环境: 通信环境,
    机: 中继机,
    起点名称: str,
    终点名称: str,
    起经度: float,
    起纬度: float,
    起点高度: float,
    终经度: float,
    终纬度: float,
    终点高度: float,
) -> 中继航段:
    """中继机一段飞行的**时间与能耗**（时间与能源规则 三段式，质量取计划起飞总质量）。"""
    距离 = 水平距离_m(起经度, 起纬度, 终经度, 终纬度)
    沿线最高 = 沿线最高地面高程(
        起经度, 起纬度, 终经度, 终纬度, 环境.地面高程, 环境.纬度向量, 环境.经度向量
    )
    巡航海拔 = 沿线最高 + 巡航净空_m

    爬升 = max(巡航海拔 - 起点高度, 0.0)
    下降 = max(巡航海拔 - 终点高度, 0.0)
    巡航时间 = 距离 / 机.巡航速度

    return 中继航段(
        起点名称=起点名称,
        终点名称=终点名称,
        水平距离=距离,
        巡航海拔=巡航海拔,
        起点高度=起点高度,
        终点高度=终点高度,
        爬升=爬升,
        下降=下降,
        飞行时间=爬升 / 机.最大爬升速度 + 巡航时间 + 下降 / 机.最大下降速度,
        巡航能耗=机.巡航功率_kW * 巡航时间 / 3600.0,
        爬升能耗=(
            机.计划起飞总质量_kg * 重力加速度 * 爬升
            / (机.爬升能耗效率 * 焦耳每千瓦时)
            if 爬升 > 0.0
            else 0.0
        ),
    )


# ===================== 悬停站 =====================
@dataclass(frozen=True)
class 悬停站:
    """中继架次中的一个**悬停点**及其服务时段。

    `悬停海拔` 由 `悬停高度.最优悬停高度` 给出（最小可行高度 = 最优高度）；
    `服务起` / `服务终` 是**建链完成后开始服务**到**结束服务**的区间。
    """

    经度: float
    纬度: float
    地面海拔: float
    悬停海拔: float
    服务起: float
    服务终: float
    保障缺口: tuple[int, ...] = ()
    保障架次: tuple[int, ...] = ()
    有效服务时长: float | None = None
    """**真正在通信**的时长；`None` ⇒ 取 `服务终 − 服务起`（即口径 D 的行为）。

    口径 D（一对一）：一个站只保障一个缺口 ⇒ 服务窗内每一时刻都在通信，
    故有效服务时长 == 服务时长，无需设置本字段。

    口径 E（一对多守点）：一个驻留段同时保障若干缺口，**驻留窗是各缺口窗的凸包**，
    窗内可能夹着两段缺口之间的空档（那段时间中继在白悬停但不通信）。
    此时必须显式给出 ∪(成员缺口窗) 的测度，否则会按 1.10 kW 多算那部分空档的能耗。
    """

    @property
    def 离地高度(self) -> float:
        return self.悬停海拔 - self.地面海拔

    @property
    def 服务时长(self) -> float:
        return self.服务终 - self.服务起

    @property
    def 通信时长(self) -> float:
        """计入通信附加功率的时长（口径 D 下 == `服务时长`）。"""
        return self.服务时长 if self.有效服务时长 is None else self.有效服务时长


# ===================== 中继架次代价 =====================
@dataclass(frozen=True)
class 中继架次代价:
    """一个中继架次的完整时间与能耗构成。"""

    中继机型编号: str
    站数: int
    起飞时刻: float                  # 开始工位准备
    返回时刻: float
    飞行航段: tuple[中继航段, ...]     # O01→p1, p1→p2, …, pM→O01
    建链次数: int
    服务时长: float
    等待时长: float
    飞行时间: float
    飞行能耗: float
    服务能耗: float
    等待能耗: float
    架次能量上限: float
    结束SOC: float

    @property
    def 总时长(self) -> float:
        """自开始工位准备到返回 O01。"""
        return self.返回时刻 - self.起飞时刻

    @property
    def 总能耗(self) -> float:
        return self.飞行能耗 + self.服务能耗 + self.等待能耗

    @property
    def 满足返航电量(self) -> bool:
        return self.总能耗 <= self.架次能量上限 + 数值容差

    @property
    def 能量上限占用率(self) -> float:
        if self.架次能量上限 <= 0:
            return float("inf")
        return self.总能耗 / self.架次能量上限

    @property
    def 建链时长(self) -> float:
        return 0.0  # 建链时长已计入各站的到达→服务起间隔，此处不重复计


def 中继架次代价计算(
    环境: 通信环境,
    机: 中继机,
    站序列: tuple[悬停站, ...],
    起飞时刻: float,
    中心经度: float,
    中心纬度: float,
    中心作业高度: float,
) -> 中继架次代价:
    """给定站序列与起飞时刻，算出一个中继架次的完整时间与能耗。

    时间推进（与《求解条件》§3.5 的公式逐项对应）：

        起飞时刻 → += 工位固定准备 → 飞到 p1 → 到达
        对每站 m：到达_m → 等/建链直到 服务起_m → 服务至 服务终_m → 离开_m
                  （m < M 时）离开_m + 转场 = 到达_{m+1}
        最后一站离开 → 飞回 O01 = 返回时刻

    等待（Q7）：`到达_m` 到 `服务起_m − 建链时间` 之间的悬停按 $P_R^{悬}$ 计能耗；
    建链的 30 s 同样归入悬停；`[服务起_m, 服务终_m]` 按 $P_R^{悬}+P_R^{通}$ 计。
    """
    if not 站序列:
        raise ValueError("中继架次至少需要一个悬停站")

    飞行航段: list[中继航段] = []
    等待时长 = 0.0
    服务时长 = 0.0
    通信时长 = 0.0

    # 起飞 → 工位准备 → 飞抵第一站
    时刻 = 起飞时刻 + 机.工位固定准备时间_s
    段 = 中继航段代价(
        环境, 机, 调度中心编号, "P1",
        中心经度, 中心纬度, 中心作业高度,
        站序列[0].经度, 站序列[0].纬度, 站序列[0].悬停海拔,
    )
    飞行航段.append(段)
    到达 = 时刻 + 段.飞行时间

    for 位, 站 in enumerate(站序列):
        建链起 = 站.服务起 - 机.建链时间_s
        if 建链起 < 到达 - 数值容差:
            raise ValueError(
                f"第 {位 + 1} 站无法按时建链：到达 {到达:.1f} s 晚于建链起 "
                f"{建链起:.1f} s（服务起 {站.服务起:.1f} s，建链 {机.建链时间_s:.0f} s）"
            )
        等待时长 += 建链起 - 到达
        服务时长 += 站.服务时长
        通信时长 += 站.通信时长
        离开 = 站.服务终

        if 位 + 1 < len(站序列):
            下一站 = 站序列[位 + 1]
            段 = 中继航段代价(
                环境, 机, f"P{位 + 1}", f"P{位 + 2}",
                站.经度, 站.纬度, 站.悬停海拔,
                下一站.经度, 下一站.纬度, 下一站.悬停海拔,
            )
            飞行航段.append(段)
            到达 = 离开 + 段.飞行时间

    返航段 = 中继航段代价(
        环境, 机, f"P{len(站序列)}", 调度中心编号,
        站序列[-1].经度, 站序列[-1].纬度, 站序列[-1].悬停海拔,
        中心经度, 中心纬度, 中心作业高度,
    )
    飞行航段.append(返航段)
    返回时刻 = 站序列[-1].服务终 + 返航段.飞行时间

    飞行能耗 = sum(段.能耗 for 段 in 飞行航段)
    # 能耗口径按「是否使用口径 E 的多缺口驻留段」分两种。两种下**总能耗恒等**：
    #   口径 D：1.05·等待 + 1.10·窗口          （窗口内每一时刻都在通信）
    #   口径 E：1.05·(等待 + 窗口) + 0.05·并集  （窗口内的空档只白悬停，不通信）
    # 分支写法是为了让口径 D 的浮点结果与历史**逐位一致**（不重排求和次序）。
    if 通信时长 == 服务时长:
        服务能耗 = 机.通信服务功率_kW * 服务时长 / 3600.0
        等待能耗 = 机.悬停功率_kW * 等待时长 / 3600.0
    else:
        服务能耗 = 机.通信附加功率_kW * 通信时长 / 3600.0
        等待能耗 = 机.悬停功率_kW * (等待时长 + 服务时长) / 3600.0

    return 中继架次代价(
        中继机型编号=机.编号,
        站数=len(站序列),
        起飞时刻=起飞时刻,
        返回时刻=返回时刻,
        飞行航段=tuple(飞行航段),
        建链次数=len(站序列),
        服务时长=服务时长,
        等待时长=等待时长,
        飞行时间=sum(段.飞行时间 for 段 in 飞行航段),
        飞行能耗=飞行能耗,
        服务能耗=服务能耗,
        等待能耗=等待能耗,
        架次能量上限=机.架次能量上限_kWh,
        结束SOC=1.0 - (飞行能耗 + 服务能耗 + 等待能耗) / 机.能源组件可用能量_kWh,
    )


# ===================== 单架次可行性（唯一判定）=====================
def 单架次可行(
    环境: 通信环境,
    机: 中继机,
    站序列: tuple[悬停站, ...] | list[悬停站],
    起飞时刻: float,
    中心经度: float,
    中心纬度: float,
    中心作业高度: float,
) -> 中继架次代价 | None:
    """**中继单架次可行性的唯一判定**（排程与 `可行性检验` ⑭/⑯ 共用的口径）。

    三关，缺一不可：

    ① **时间窗**（首站 + 各站间转场）—— 与 `可行性检验` ⑯ 的 C17/C18 逐字相同的两个不等式：

           首站： 起飞 + 工位固定准备 + 去程.飞行时间 ≤ 首站.服务起 − 建链时间
           转场： 前站.服务终 + 转场.飞行时间   ≤ 后站.服务起 − 建链时间

    ② **返航电量**：$E^{\\text{总}} \\le (1 - \\rho_R) E_R^{use}$；
    ③ 时长 / 能耗 / 结束SOC 的自洽由 `中继架次代价计算` 保证。

    返回 `中继架次代价`；任一间不通过返回 `None`。

    ⚠️ **为什么必须只有这一个判定**：`数值容差 = 1e-9`。若排程侧的增量式窗口比较与
    ⑯ 的独立重推差一个 ulp，就会出现「排程认为可行、检验判违反」的悬崖 —— 这是最难查
    的一类失败。凡涉及建链窗口的比较，一律以本函数（或其**逐字相同**的解析增量版）为准。
    """
    站序列 = tuple(站序列)
    if not 站序列:
        return None
    try:
        代价 = 中继架次代价计算(
            环境, 机, 站序列, 起飞时刻, 中心经度, 中心纬度, 中心作业高度
        )
    except ValueError:
        return None

    # ① 复检建链窗口 —— 复用已算出的航段，不重复做 DEM 采样
    空档 = 机.建链时间_s
    首段 = 代价.飞行航段[0]
    if (
        起飞时刻 + 机.工位固定准备时间_s + 首段.飞行时间
        > 站序列[0].服务起 - 空档 + 数值容差
    ):
        return None
    for 位 in range(1, len(站序列)):
        转场 = 代价.飞行航段[位]
        if (
            站序列[位 - 1].服务终 + 转场.飞行时间
            > 站序列[位].服务起 - 空档 + 数值容差
        ):
            return None

    # ② 返航电量
    if not 代价.满足返航电量:
        return None
    return 代价


# ===================== 中继架次 =====================
@dataclass(frozen=True)
class 中继架次:
    """一架中继无人机的一次出动。"""

    序号: int
    中继机编号: str              # R01 / R02
    站序列: tuple[悬停站, ...]
    能源组件编号: str
    代价: 中继架次代价

    @property
    def 起飞时刻(self) -> float:
        return self.代价.起飞时刻

    @property
    def 返回时刻(self) -> float:
        return self.代价.返回时刻

    @property
    def 总能耗(self) -> float:
        return self.代价.总能耗

    @property
    def 站数(self) -> int:
        return len(self.站序列)

    @property
    def 保障架次(self) -> tuple[int, ...]:
        return tuple(sorted({架次 for 站 in self.站序列 for 架次 in 站.保障架次}))

    @property
    def 保障缺口数(self) -> int:
        return sum(len(站.保障缺口) for 站 in self.站序列)


# ===================== 中继能源组件池 =====================
@dataclass
class 中继能源池:
    """2 架中继机 + 6 组共享能源组件。

    能源组件的占用与充电周转规则与运输侧共享电池**完全一致**
    （问题时间与能源规则原文："运输无人机共享电池与中继无人机能源组件均作为独立能源资源
    记录荷电状态"），故直接复用 `资源模型.电池状态` 与 `资源模型.充电时长`。
    """

    组件: dict[str, 电池状态] = field(default_factory=dict)
    中继机表: tuple[str, ...] = ()
    等效完全充电时间_s: float = 0.0
    架次周转时间_s: float = 0.0

    @property
    def 全部组件(self) -> list[电池状态]:
        return [self.组件[k] for k in sorted(self.组件)]

    @property
    def 在架中继(self) -> tuple[str, ...]:
        return self.中继机表


def 构造中继资源() -> 中继能源池:
    """按数据中的库存构造中继资源：2 架中继机、6 组能源组件，初始 SOC = 100%。"""
    无人机表 = 数据读取.读取中继无人机()
    能源表 = 数据读取.读取中继能源组件()
    if 中继机型编号 not in 能源表:
        raise KeyError(f"中继能源库存中不存在机型 [{中继机型编号}]，实际有 {sorted(能源表)}")
    库存 = 能源表[中继机型编号]
    组数 = int(库存["组数"])

    return 中继能源池(
        组件={
            f"{中继机型编号}-ENG-{序:02d}": 电池状态(
                编号=f"{中继机型编号}-ENG-{序:02d}", 机型编号=中继机型编号
            )
            for 序 in range(1, 组数 + 1)
        },
        中继机表=tuple(d["中继无人机编号"] for d in 无人机表),
        等效完全充电时间_s=float(库存["等效完全充电时间_s"]),
        架次周转时间_s=读取中继机().架次周转时间_s,
    )


def 中继资源容量摘要() -> dict:
    """中继资源库存摘要（供论文与自检引用）。"""
    池 = 构造中继资源()
    机 = 读取中继机()
    return {
        "中继无人机": list(池.中继机表),
        "能源组件组数": len(池.组件),
        "等效完全充电时间_s": 池.等效完全充电时间_s,
        "能源组件可用能量_kWh": 机.能源组件可用能量_kWh,
        "架次能量上限_kWh": 机.架次能量上限_kWh,
        "悬停功率_kW": 机.悬停功率_kW,
        "通信附加功率_kW": 机.通信附加功率_kW,
        "建链时间_s": 机.建链时间_s,
        "架次周转时间_s": 机.架次周转时间_s,
        "最大悬停离地高度_m": 机.最大悬停离地高度_m,
        "单组能源纯悬停续航_s": 机.架次能量上限_kWh * 3600.0 / 机.悬停功率_kW,
    }


# ===================== 自检 =====================
def 中继模型自检(场景, 环境: 通信环境) -> tuple[bool, list[str]]:
    """中继模型与时间与能源规则的一致性检查。

    (a) 返航电量口径：0.8 × 3.2 = 2.56 kWh；
    (b) 单站架次的**时间闭合**：总时长 == 工位准备 + 飞行 + 建链 + 服务；
    (c) 单站架次的**能量闭合**：总能耗 == 飞行 + 服务 + 等待，且 SOC 与能耗一致；
    (d) 服务功率 == 悬停 + 通信附加 == 1.10 kW；
    (e) **建链按站重复计**：M 站的建链次数 == M，转场航段数 == M − 1。
    """
    机 = 读取中继机()
    中心 = 场景.调度中心

    中心作业高度 = 中心["海拔"] + 调度中心作业高度增量_m

    # 构造一个单站架次（悬停点取 S008 上方 150 m 离地，服务 300 s）
    项 = 场景.服务区表["S008"]
    地面 = 环境.地面高程_at(项["经度"], 项["纬度"])
    站 = 悬停站(
        经度=项["经度"], 纬度=项["纬度"], 地面海拔=地面,
        悬停海拔=地面 + 150.0, 服务起=1000.0, 服务终=1300.0,
        保障缺口=(0,), 保障架次=(1,),
    )
    单站 = 中继架次代价计算(
        环境, 机, (站,), 起飞时刻=0.0,
        中心经度=中心["经度"], 中心纬度=中心["纬度"], 中心作业高度=中心作业高度,
    )

    时间闭合 = abs(
        单站.总时长
        - (
            机.工位固定准备时间_s
            + 单站.飞行时间
            + 机.建链时间_s
            + 单站.服务时长
            + 单站.等待时长
        )
    )
    能量闭合 = abs(单站.总能耗 - (单站.飞行能耗 + 单站.服务能耗 + 单站.等待能耗))
    SOC一致 = abs(
        单站.结束SOC - (1.0 - 单站.总能耗 / 机.能源组件可用能量_kWh)
    )

    # 双站架次：检查建链按站累计与转场航段
    站2 = 悬停站(
        经度=场景.服务区表["S010"]["经度"], 纬度=场景.服务区表["S010"]["纬度"],
        地面海拔=环境.地面高程_at(
            场景.服务区表["S010"]["经度"], 场景.服务区表["S010"]["纬度"]
        ),
        悬停海拔=环境.地面高程_at(
            场景.服务区表["S010"]["经度"], 场景.服务区表["S010"]["纬度"]
        ) + 120.0,
        服务起=2000.0, 服务终=2200.0, 保障缺口=(1,), 保障架次=(2,),
    )
    双站 = 中继架次代价计算(
        环境, 机, (站, 站2), 起飞时刻=0.0,
        中心经度=中心["经度"], 中心纬度=中心["纬度"], 中心作业高度=中心作业高度,
    )

    返航电量口径 = abs(机.架次能量上限_kWh - 0.8 * 3.2) <= 1e-12
    服务功率口径 = abs(机.通信服务功率_kW - 1.10) <= 1e-12
    多站规则 = 双站.建链次数 == 2 and len(双站.飞行航段) == 3

    通过 = (
        返航电量口径 and 服务功率口径 and 多站规则
        and 时间闭合 <= 1e-9 and 能量闭合 <= 1e-12 and SOC一致 <= 1e-12
    )
    return 通过, [
        f"[自检·中继1] 返航电量与服务功率口径：架次能量上限 {机.架次能量上限_kWh:.4f} kWh"
        f"（应 2.56）、服务功率 {机.通信服务功率_kW:.4f} kW（应 1.10）→ "
        f"{'一致' if 返航电量口径 and 服务功率口径 else '不一致！'}",
        f"[自检·中继2] 单站架次时间闭合（工位准备 {机.工位固定准备时间_s:.0f} + 飞行 "
        f"{单站.飞行时间:.3f} + 建链 {机.建链时间_s:.0f} + 服务 {单站.服务时长:.0f} + 等待 "
        f"{单站.等待时长:.3f} vs 总时长 {单站.总时长:.3f}）：偏差 {时间闭合:.3e} s → "
        f"{'闭合' if 时间闭合 <= 1e-9 else '不闭合！'}",
        f"[自检·中继3] 单站架次能量闭合与 SOC：能耗闭合偏差 {能量闭合:.3e} kWh、"
        f"SOC 偏差 {SOC一致:.3e}；飞行 {单站.飞行能耗:.4f} + 服务 {单站.服务能耗:.4f} "
        f"+ 等待 {单站.等待能耗:.4f} = {单站.总能耗:.4f} kWh → "
        f"{'自洽' if 能量闭合 <= 1e-12 and SOC一致 <= 1e-12 else '不自洽！'}",
        f"[自检·中继4] 多站规则（Q4/Q4b）：双站架次的建链次数 {双站.建链次数}（应 2）、"
        f"飞行航段数 {len(双站.飞行航段)}（应 3 = 去 + 转场 + 回）→ "
        f"{'合规' if 多站规则 else '不合规！'}",
    ]
