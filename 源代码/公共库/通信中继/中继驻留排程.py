# ===================== 驻留段 =====================
@dataclass(frozen=True)
class 驻留段:
    """一个悬停点在一段窗口内对所有可见运输机的持续保障。"""

    段号: int
    点序: int
    经度: float
    纬度: float
    地面海拔: float
    悬停海拔: float
    窗口起: float
    窗口终: float
    成员: tuple[int, ...]        # 成员缺口序号（升序）
    保障架次: tuple[int, ...]    # 成员的运输架次序号（升序去重）
    有效服务时长: float          # |∪ 成员缺口窗|
    去程飞行时间: float
    去程能耗: float
    回程飞行时间: float
    回程能耗: float
    最近起飞: float              # 窗口起 − 建链 − 去程 − 工位准备
    单段能耗: float              # 该段单独成一个架次时的总能耗（生成期排序用）

    @property
    def 服务时长(self) -> float:
        return self.窗口终 - self.窗口起

    @property
    def 成员掩码(self) -> int:
        位 = 0
        for i in self.成员:
            位 |= 1 << i
        return 位

    def 化为悬停站(self) -> 悬停站:
        """投影成 `m41` 的悬停站（`服务起/终` 取驻留窗，并显式给出有效服务时长）。"""
        return 悬停站(
            经度=self.经度, 纬度=self.纬度, 地面海拔=self.地面海拔,
            悬停海拔=self.悬停海拔,
            服务起=self.窗口起, 服务终=self.窗口终,
            保障缺口=self.成员, 保障架次=self.保障架次,
            有效服务时长=self.有效服务时长,
        )


def _并集测度(区间: list[tuple[float, float]]) -> float:
    """区间并集的总长度。"""
    if not 区间:
        return 0.0
    总 = 0.0
    起, 终 = sorted(区间)[0]
    for 甲, 乙 in sorted(区间)[1:]:
        if 甲 <= 终 + 数值容差:
            终 = max(终, 乙)
        else:
            总 += 终 - 起
            起, 终 = 甲, 乙
    return 总 + (终 - 起)


# ===================== 段工厂 =====================
class _段工厂:
    """按 (驻留点, 成员集) 造驻留段；往返航段按 (点序, 海拔) 记忆化。"""

    def __init__(self, 覆盖表, 缺口表, 环境: 通信环境, 中心经度, 中心纬度, 中心作业高度):
        self.覆盖表 = 覆盖表
        self.缺口表 = 缺口表
        self.环境 = 环境
        self.中心经度 = 中心经度
        self.中心纬度 = 中心纬度
        self.中心作业高度 = 中心作业高度
        self.机 = 读取中继机()
        self.起 = [缺.起时刻 for 缺 in 缺口表]
        self.终 = [缺.终时刻 for 缺 in 缺口表]
        self.架次 = [缺.架次序号 for 缺 in 缺口表]
        self._往返: dict[tuple[int, float], tuple] = {}

    def 往返(self, 点序: int, 悬停海拔: float):
        """`(去程航段, 回程航段)`，按 (点序, 海拔) 记忆化。"""
        键 = (点序, round(悬停海拔, 1))
        值 = self._往返.get(键)
        if 值 is None:
            点 = self.覆盖表.候选点表[点序]
            去 = 中继航段代价(
                self.环境, self.机, 调度中心编号, "P1",
                self.中心经度, self.中心纬度, self.中心作业高度,
                点.经度, 点.纬度, 悬停海拔,
            )
            回 = 中继航段代价(
                self.环境, self.机, "P1", 调度中心编号,
                点.经度, 点.纬度, 悬停海拔,
                self.中心经度, self.中心纬度, self.中心作业高度,
            )
            值 = (去, 回)
            self._往返[键] = 值
        return 值

    def 闭包(self, 可覆: list[int], 成员) -> tuple[int, ...]:
        """把窗口 `hull(成员)` 内该点能覆盖的缺口全部并入（不动点）。"""
        当前 = set(成员)
        while True:
            t0 = min(self.起[i] for i in 当前)
            t1 = max(self.终[i] for i in 当前)
            新 = frozenset(
                i for i in 可覆
                if self.起[i] >= t0 - 数值容差 and self.终[i] <= t1 + 数值容差
            )
            if 新 == 当前:
                return tuple(sorted(当前))
            当前 = set(新)

    def 造段(self, 段号: int, 点序: int, 成员) -> 驻留段 | None:
        """按成员集造段；超离地上限或超单架次能量则返回 None。"""
        if not 成员:
            return None
        点 = self.覆盖表.候选点表[点序]
        t0 = min(self.起[i] for i in 成员)
        t1 = max(self.终[i] for i in 成员)
        悬停海拔 = max(self.覆盖表.海拔(点序, i) for i in 成员)
        if 悬停海拔 - 点.地面海拔 > self.机.最大悬停离地高度_m + 数值容差:
            return None
        有效 = _并集测度([(self.起[i], self.终[i]) for i in 成员])
        去, 回 = self.往返(点序, 悬停海拔)
        能耗 = (
            去.能耗 + 回.能耗
            + self.机.悬停功率_kW * (t1 - t0) / 3600.0
            + self.机.通信附加功率_kW * 有效 / 3600.0
        )
        if 能耗 > self.机.架次能量上限_kWh + 数值容差:
            return None
        return 驻留段(
            段号=段号, 点序=点序,
            经度=点.经度, 纬度=点.纬度, 地面海拔=点.地面海拔, 悬停海拔=悬停海拔,
            窗口起=t0, 窗口终=t1,
            成员=tuple(sorted(成员)),
            保障架次=tuple(sorted({self.架次[i] for i in 成员})),
            有效服务时长=有效,
            去程飞行时间=去.飞行时间, 去程能耗=去.能耗,
            回程飞行时间=回.飞行时间, 回程能耗=回.能耗,
            最近起飞=t0 - self.机.建链时间_s - 去.飞行时间 - self.机.工位固定准备时间_s,
            单段能耗=能耗,
        )


# ===================== 段族生成 =====================
def 生成驻留段族(覆盖表, 缺口表, 环境: 通信环境, 中心经度, 中心纬度, 中心作业高度):
    """由覆盖关系生成候选驻留段族（锚定 + 向右扩展 + 闭包 + 按成员集去重）。

    对每个候选驻留点、每个锚缺口 `a`，把该点的可覆缺口按服务起排序，
    **依次并入 a 之后的每一个可覆缺口**并闭包，每一步产出一个段（"阶梯"）。
    阶梯把「窗口从小到大的各个成员集」都列出来，**选择权交给排程器**，
    而不是在生成期就砍死。
    """
    厂 = _段工厂(覆盖表, 缺口表, 环境, 中心经度, 中心纬度, 中心作业高度)
    候选: dict[tuple[int, ...], 驻留段] = {}
    段号 = 0
    for 点序 in 覆盖表.驻留点序:
        位 = 覆盖表.掩码.get(点序, 0)
        if not 位:
            continue
        可覆 = sorted(
            (i for i in range(覆盖表.缺口数) if 位 >> i & 1),
            key=lambda i: (厂.起[i], i),
        )
        for 甲 in range(len(可覆)):
            成员 = 厂.闭包(可覆, {可覆[甲]})
            for 乙 in range(甲 + 1, len(可覆) + 1):
                if 乙 > 甲 + 1:
                    成员 = 厂.闭包(可覆, set(成员) | {可覆[乙 - 1]})
                if len(成员) > 单段成员上限:
                    break
                段 = 厂.造段(段号, 点序, 成员)
                段号 += 1
                if 段 is None:
                    continue
                旧 = 候选.get(段.成员)
                if 旧 is None or 段.单段能耗 < 旧.单段能耗:
                    候选[段.成员] = 段

    段族 = sorted(候选.values(), key=lambda 段: (段.窗口起, 段.点序))
    if len(段族) > 段族上限:
        段族 = sorted(段族, key=lambda 段: (-len(段.成员), 段.单段能耗))[:段族上限]
        段族 = sorted(段族, key=lambda 段: (段.窗口起, 段.点序))
    return tuple(replace(段, 段号=序) for 序, 段 in enumerate(段族))


# ===================== 架次装配（唯一权威判定 = m41.单架次可行）=====================
@dataclass(frozen=True)
class 架次草稿:
    段列: tuple[int, ...]        # 段号，按窗口起升序
    起飞时刻: float
    代价: object                 # 中继架次代价

    @property
    def 返回时刻(self) -> float:
        return self.代价.返回时刻


def 装配架次(环境, 机, 段表, 段列, 起飞下限, 中心经度, 中心纬度, 中心作业高度):
    """把 `段列` 组成一个架次；返回 `架次草稿` 或 None。

    起飞时刻取 P2 的「最近起飞」= `首段.窗口起 − 建链 − 去程 − 工位准备`（首站零等待、
    能耗最小）。它必须 **≥ 0**（否则中继来不及飞到首站，该段不能作架次首段）。

    `起飞下限` 是**新开**架次时轨道的可用时刻（上一个架次返回 + 周转 + 准备）；
    **向已在飞的架次追加段时传 `None`** —— 此时该架次已经起飞，轨道可用时刻是留给
    *下一个* 架次的，不能拿它去否决当前架次（早先版本在这里出错，导致任何架次都
    追加不进第二段、每次出动恒为单站）。
    """
    首 = 段表[段列[0]]
    起飞 = 首.最近起飞
    if 起飞 < -数值容差:
        return None
    if 起飞下限 is not None and 起飞 < 起飞下限 - 数值容差:
        return None
    起飞 = max(起飞, 0.0)
    站序列 = tuple(段表[号].化为悬停站() for 号 in 段列)
    代价 = 单架次可行(环境, 机, 站序列, 起飞, 中心经度, 中心纬度, 中心作业高度)
    if 代价 is None:
        return None
    return 架次草稿(段列=tuple(段列), 起飞时刻=起飞, 代价=代价)


# ===================== 构造排程（贪心，轨道按时刻插入）=====================
@dataclass
class _轨道:
    """一条中继轨道（= 一架中继机的完整时间线），架次按起飞时刻升序存放。"""

    架次表: list = field(default_factory=list)

    def 间隔(self, 机) -> float:
        """同一轨道上相邻两个架次之间必须留出的时间。"""
        return 机.架次周转时间_s + 机.工位固定准备时间_s

    def 插入位置(self, 起飞时刻: float) -> int:
        import bisect

        return bisect.bisect_left([架.起飞时刻 for 架 in self.架次表], 起飞时刻)

    def 可插入(self, 草案, 机, 替换位: int | None = None) -> bool:
        """把 `草案` 放进本轨道是否与前后架次冲突（`替换位` 给追加用：原地替换该位）。"""
        转 = self.间隔(机)
        其余 = [架 for 位, 架 in enumerate(self.架次表) if 位 != 替换位]
        序 = 0
        for 位, 架 in enumerate(其余):
            if 架.起飞时刻 <= 草案.起飞时刻:
                序 = 位 + 1
        前 = 其余[序 - 1] if 序 > 0 else None
        后 = 其余[序] if 序 < len(其余) else None
        if 前 is not None and 草案.起飞时刻 < 前.返回时刻 + 转 - 数值容差:
            return False
        return 后 is None or 后.起飞时刻 >= 草案.返回时刻 + 转 - 数值容差

    def 落位(self, 草案, 替换位: int | None = None) -> None:
        if 替换位 is None:
            import bisect

            键 = [架.起飞时刻 for 架 in self.架次表]
            self.架次表.insert(bisect.bisect_left(键, 草案.起飞时刻), 草案)
        else:
            self.架次表[替换位] = 草案


def 构造排程(环境, 机, 段表, 缺口数, 中心经度, 中心纬度, 中心作业高度, 日志=None):
    """贪心构造：每轮挑「**新增覆盖最多**」的一次落位，直到无改进。

    * **追加**到某个已有架次的末尾**不新增往返飞行**，代价远低于新开一架次，故优先；
    * 一次落位只要与**前后相邻架次**不冲突即可 —— 架次表按起飞时刻**插入**，
      而不是只能往后排。早先版本用「轨道可用时刻」单调递增地约束，会导致
      一个晚期架次占住轨道后，**所有更早的架次永远排不进去**；
    * **新开**架次的草案按段预计算一次（`单段草案`）—— 它与轨道无关，
      避免每轮对上千个段重复调用昂贵的 `单架次可行`。
    """
    单段草案: dict[int, 架次草稿] = {}
    for 段 in 段表:
        草 = 装配架次(环境, 机, 段表, (段.段号,), None,
                      中心经度, 中心纬度, 中心作业高度)
        if 草 is not None and 草.起飞时刻 >= -数值容差:
            单段草案[段.段号] = 草

    轨道 = [_轨道() for _ in range(中继线数)]
    覆盖掩码 = 0

    for _ in range(放置轮数上限):
        最好 = None
        for 轨号, 轨 in enumerate(轨道):
            # ① 追加到本轨道某个已有架次的末尾
            for 位, 末 in enumerate(轨.架次表):
                if len(末.段列) >= 单架次段数上限:
                    continue
                可追 = [
                    段 for 段 in 段表
                    if 段.段号 > 末.段列[-1]
                    and 段.窗口起 >= 段表[末.段列[-1]].窗口终 - 数值容差
                    and 段.成员掩码 & ~覆盖掩码
                ]
                if not 可追:
                    continue
                可追.sort(key=lambda 段: (-bin(段.成员掩码 & ~覆盖掩码).count("1"),
                                         段.单段能耗, 段.段号))
                for 段 in 可追[:追加候选数]:
                    草案 = 装配架次(
                        环境, 机, 段表, (*末.段列, 段.段号),
                        None, 中心经度, 中心纬度, 中心作业高度,
                    )
                    if 草案 is None or not 轨.可插入(草案, 机, 替换位=位):
                        continue
                    增 = bin(段.成员掩码 & ~覆盖掩码).count("1")
                    键 = (-增, 0, 草案.返回时刻, 轨号, 位, 段.段号)
                    if 最好 is None or 键 < 最好[0]:
                        最好 = (键, 轨号, 草案, 位)
                    break
            # ② 新开一个架次
            for 段 in 段表:
                增 = bin(段.成员掩码 & ~覆盖掩码).count("1")
                if not 增:
                    continue
                草案 = 单段草案.get(段.段号)
                if 草案 is None or not 轨.可插入(草案, 机):
                    continue
                键 = (-增, 1, 草案.返回时刻, 轨号, 段.段号)
                if 最好 is None or 键 < 最好[0]:
                    最好 = (键, 轨号, 草案, None)
        if 最好 is None:
            break
        _, 轨号, 草案, 位 = 最好
        轨道[轨号].落位(草案, 替换位=位)
        for 号 in 草案.段列:
            覆盖掩码 |= 段表[号].成员掩码

    统计 = {
        "段族数": len(段表),
        "可单独成架次的段数": len(单段草案),
        "中继架次数": sum(len(轨.架次表) for 轨 in 轨道),
        "覆盖缺口数": bin(覆盖掩码).count("1"),
    }
    if 日志 is not None:
        日志.append(统计)
    return 轨道, 覆盖掩码, 统计


# ===================== 装配中继方案 =====================
def 装配中继方案(环境, 机, 段表, 缺口表, 轨道, 资源, 中心经度, 中心纬度, 中心作业高度):
    """把轨道上的架次落成 `中继方案`（逐架次用 `单架次可行` 权威复核）。

    ⚠️ **每个缺口只能由一条保障记录承担**。贪心放置时，增量判据是「成员掩码有新增位」，
    并不排除两个驻留段的成员**部分重叠** —— 若照单全收，同一个缺口会同时被两条记录
    覆盖（⑪ 的运输机侧独占与 ⑰ 的缺口账目都会判违反）。故此处先按确定的架次序把
    每个缺口**指派给第一个覆盖它的段**，再据此重建每个站的 `保障缺口` 与
    `有效服务时长`，最后用 `单架次可行` 复核。

    驻留窗**不收紧**（仍取原段的凸包窗口）：中继本来就在那里悬停，
    收紧只会改动起飞时刻、可能打乱轨道上相邻架次的周转。缩小 `保障缺口` 只会**减少**
    通信附加能耗，故复核必然仍然通过。
    """
    中继机表 = 资源.中继机表
    扁平: list[tuple[int, 架次草稿]] = []
    for 轨号, 轨 in enumerate(轨道):
        for 草稿 in 轨.架次表:
            扁平.append((轨号, 草稿))

    # ① 逐缺口指派给唯一承载段（确定序：轨道序 → 架次起飞序 → 段序）
    已分配: set[int] = set()
    分配表: list[list[tuple[驻留段, tuple[int, ...]]]] = []
    for _, 草稿 in 扁平:
        条目 = []
        for 段号 in 草稿.段列:
            段 = 段表[段号]
            得 = tuple(i for i in 段.成员 if i not in 已分配)
            已分配.update(得)
            if 得:
                条目.append((段, 得))
        分配表.append(条目)

    # ② 按指派重建悬停站，逐架次权威复核
    架次列表 = []
    保障 = []
    未覆盖 = set(range(len(缺口表))) - 已分配
    序号 = 0
    for 位, (轨号, 草稿) in enumerate(扁平):
        if not 分配表[位]:
            continue
        编号 = 中继机表[轨号 % len(中继机表)]
        站序列 = tuple(
            replace(
                段.化为悬停站(),
                保障缺口=得,
                保障架次=tuple(sorted({缺口表[i].架次序号 for i in 得})),
                有效服务时长=_并集测度([(缺口表[i].起时刻, 缺口表[i].终时刻) for i in 得]),
            )
            for 段, 得 in 分配表[位]
        )
        代价 = 单架次可行(
            环境, 机, 站序列, 草稿.起飞时刻,
            中心经度, 中心纬度, 中心作业高度,
        )
        if 代价 is None:
            # 复核否决 ⇒ 该架次不成立。把它本应保障的缺口**如实退回未覆盖**，继续装配
            # 其余架次 —— 而不是终止整轮搜索。口径 E 的「未覆盖缺口」本就是一等概念
            # （`未覆盖` 集合、`覆盖下界`、五目标里的「中断时长」都建立在它上面），
            # 故降级是语义正确的；而一个硬 raise 会让整轮外层搜索前功尽弃。
            未覆盖 |= {i for _, 得 in 分配表[位] for i in 得}
            continue
        序号 += 1
        架次列表.append(
            中继架次(
                序号=序号, 中继机编号=编号,
                站序列=站序列, 能源组件编号="", 代价=代价,
            )
        )
        for 站位, (段, 得) in enumerate(分配表[位], start=1):
            for 缺口序 in 得:
                保障.append(
                    保障记录(
                        中继架次序号=序号, 中继机编号=编号, 站序=站位,
                        运输架次序号=缺口表[缺口序].架次序号, 缺口序号=缺口序,
                        # ⚠️ 起止取**缺口自己的窗口**（不是驻留窗）：否则 ⑩ 的
                        # 全采样复核会去验窗内两个缺口之间的直连空档位姿。
                        起时刻=缺口表[缺口序].起时刻,
                        终时刻=缺口表[缺口序].终时刻,
                        悬停经度=段.经度, 悬停纬度=段.纬度, 悬停海拔=段.悬停海拔,
                    )
                )

    草稿表 = [
        (架.序号, 架.中继机编号, 架.站序列, 架.起飞时刻, 架.代价) for 架 in 架次列表
    ]
    if 草稿表:
        台账, 组件缺口数, 池统计 = 分配能源组件(草稿表, 资源)
        来源 = {条["中继架次序号"]: 条["能源组件编号"] for 条 in 台账}
        架次列表 = [replace(架, 能源组件编号=来源.get(架.序号, "")) for 架 in 架次列表]
    else:
        台账, 组件缺口数, 池统计 = [], 0, {}

    完成时刻 = max((架.返回时刻 for 架 in 架次列表), default=0.0)
    服务需求 = sum(缺.时长 for 缺 in 缺口表)
    方案 = 中继方案(
        架次列表=tuple(架次列表),
        保障记录=tuple(保障),
        能源组件使用=tuple(台账),
        未覆盖缺口=tuple(sorted(未覆盖)),
    )
    在位 = sum(
        min(架.返回时刻, 完成时刻) - max(架.起飞时刻, 0.0) for 架 in 架次列表
    )
    摘要 = {
        "缺口数": len(缺口表),
        "站数": sum(架.站数 for 架 in 架次列表),
        "中继架次数": len(架次列表),
        "中继站数": sum(架.站数 for 架 in 架次列表),
        "一次出动的站数分布": _站数分布(架次列表),
        "中继总能耗_kWh": 方案.总能耗,
        "中继完成时刻_s": 完成时刻,
        "中继总服务时长_s": 方案.总服务时长,
        "中继总飞行时间_s": 方案.总飞行时间,
        "中继总等待时长_s": 方案.总等待时长,
        "中继在位时长_s": 在位,
        "组件缺口数": 组件缺口数,
        "池统计": 池统计,
        "充电余量": 充电余量(机, 台账, len(资源.组件), 完成时刻) if 台账 else {},
        "服务需求_s": 服务需求,
    }
    摘要["在位率"] = round(在位 / 服务需求, 4) if 服务需求 > 0 else 0.0
    摘要["等待占比"] = round(方案.总等待时长 / 在位, 4) if 在位 > 0 else 0.0
    摘要["飞行占比"] = round(方案.总飞行时间 / 在位, 4) if 在位 > 0 else 0.0
    return 方案, 摘要


def _站数分布(架次列表) -> dict[int, int]:
    出: dict[int, int] = {}
    for 架 in 架次列表:
        出[架.站数] = 出.get(架.站数, 0) + 1
    return dict(sorted(出.items()))


# ===================== 证书 =====================
def 覆盖下界(覆盖表, 缺口表) -> tuple[int, list[dict]]:
    """口径 E 的严格下界（`LB-A`）：任意时刻的活跃缺口必须被 ≤ 中继线数 个驻留点覆盖。

    设 `A(t)` = 时刻 t 活跃的缺口集，`C_i` = 能覆盖缺口 i 的候选驻留点集，则任何
    可行排程在 t 时刻至多只有 `中继线数` 个驻留段在位（一条轨道同一时刻只能在一处），
    故 `|A(t) \\ 未覆盖| ≤ M₂(t) := max{|(C_a ∪ C_b) ∩ A(t)| : a,b}`。
    把缺额 `μ(t) = max(0, |A(t)| − M₂(t))` 沿时间积分，再按「最长的 m 个缺口的
    时长之和 ≥ ∫μ」换算成**至少有多少个缺口盖不住**。

    ⚠️ `M₂` 必须取**上界**。这里用 `b₁ + b₂`（单点覆盖数的前两名）作为上界：
    `|C_a ∪ C_b| ≤ |C_a| + |C_b| ≤ b₁ + b₂`。**绝不能用贪心解代替** ——
    贪心 ≤ 最优会使下界偏大，出现「下界 > 实现值」的自相矛盾。
    """
    n = len(缺口表)
    点序列 = list(覆盖表.驻留点序)
    if n == 0 or not 点序列:
        return 0, []
    点下标 = {点序: 位 for 位, 点序 in enumerate(点序列)}
    覆盖掩码 = []
    for i in range(n):
        位 = 0
        for 点序 in 覆盖表.点集表[i]:
            位 |= 1 << 点下标[点序]
        覆盖掩码.append(位)

    事件: dict[float, int] = {}
    for 缺 in 缺口表:
        事件[缺.起时刻] = 事件.get(缺.起时刻, 0) + 1
        事件[缺.终时刻] = 事件.get(缺.终时刻, 0) - 1
    时刻列 = sorted(事件)
    当前 = 0
    段 = []
    for 位, 时刻 in enumerate(时刻列):
        当前 += 事件[时刻]
        if 位 + 1 < len(时刻列):
            段.append((时刻, 时刻列[位 + 1], 当前))

    积分缺额 = 0.0
    明细 = []
    for 起, 终, _ in 段:
        if 终 - 起 <= 数值容差:
            continue
        活跃 = [
            i for i in range(n)
            if 缺口表[i].起时刻 <= 起 + 数值容差
            and 缺口表[i].终时刻 >= 终 - 数值容差
        ]
        if not 活跃:
            continue
        覆盖数 = sorted(
            (sum(1 for i in 活跃 if 覆盖掩码[i] >> 位 & 1) for 位 in range(len(点序列))),
            reverse=True,
        )
        前二 = 覆盖数[:2]
        m2 = min(len(活跃), sum(前二))
        缺额 = max(0, len(活跃) - m2)
        if 缺额:
            积分缺额 += 缺额 * (终 - 起)
        明细.append({
            "起_s": 起, "终_s": 终, "活跃缺口数": len(活跃),
            "M2上界": m2, "缺额": 缺额,
        })

    下界 = 0
    if 积分缺额 > 数值容差:
        累计 = 0.0
        for 长 in sorted((缺.时长 for 缺 in 缺口表), reverse=True):
            累计 += 长
            下界 += 1
            if 累计 >= 积分缺额 - 数值容差:
                break
    return 下界, 明细


# ===================== 主入口 =====================
def 驻留排程(剖面表, 环境: 通信环境, 缺口集合, 候选点表=None, 缓存: dict | None = None):
    """口径 E 的中继求解入口：缺口集合 → `(中继方案, 摘要)`。

    与 `中继包络排程.包络排程` 同级的替换实现（由 `中继排程.评估` 按口径分派）。
    """
    场景 = 剖面表.场景
    中心 = 场景.调度中心
    中心经度, 中心纬度 = float(中心["经度"]), float(中心["纬度"])
    中心作业高度 = float(中心["海拔"])
    机 = 读取中继机()
    资源 = 构造中继资源()
    缺口表 = list(缺口集合.缺口列表)

    覆盖表 = 候选覆盖表(剖面表, 环境, 缺口集合, 候选点表, 缓存)
    段族 = 生成驻留段族(
        覆盖表, 缺口表, 环境, 中心经度, 中心纬度, 中心作业高度,
    )
    轨道, _, 放置统计 = 构造排程(
        环境, 机, 段族, len(缺口表), 中心经度, 中心纬度, 中心作业高度,
    )
    方案, 摘要 = 装配中继方案(
        环境, 机, 段族, 缺口表, 轨道, 资源,
        中心经度, 中心纬度, 中心作业高度,
    )
    下界, 明细 = 覆盖下界(覆盖表, 缺口表)
    无覆盖点 = [i for i in range(len(缺口表)) if not 覆盖表.点集表[i]]
    摘要["无可覆盖点缺口数"] = len(无覆盖点)
    摘要["无可覆盖点缺口"] = 无覆盖点
    摘要["未覆盖缺口数"] = len(方案.未覆盖缺口)
    摘要["未覆盖缺口"] = list(方案.未覆盖缺口)
    摘要["未覆盖下界"] = 下界
    摘要["覆盖下界明细"] = 明细
    摘要["是否已达下界"] = len(方案.未覆盖缺口) <= 下界
    摘要["覆盖表统计"] = dict(覆盖表.统计)
    摘要["段族规模"] = len(段族)
    摘要["段覆盖缺口集"] = {
        i for 段 in 段族 for i in 段.成员
    }
    摘要["放置统计"] = 放置统计
    return 方案, 摘要
