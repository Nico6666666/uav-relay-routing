"""
中继驻留排程 —— 缺口集合 $\\mathcal{G}(\\pi)$ → **中继方案**（口径 E「一对多守点覆盖」）。

模型
----
一个**中继架次** = 自 O01 出动 → 依次在若干**驻留段**悬停 → 返回 O01。
一个**驻留段** `D = (悬停点 c, 悬停海拔 H, 驻留窗 [t0,t1], 成员集 S)`：中继在
`[t0,t1]` 内悬停于 `c`、海拔 `H`，**同时**保障所有满足

    i ∈ S  ⟺  [s_i, e_i] ⊆ [t0, t1]  且  c/H 对缺口 i 的全部位姿链路可行

的缺口 —— **与此刻有几架运输机同时在无关**。这正是口径 E 与口径 D 的分野：
通信规则 只限制「**每架运输无人机**在任一时刻只能由 G01 或一架中继保障」，
从未限制一架中继能同时服务几架运输机。

三条定义性规则（改动它们会破坏 `覆盖下界` 的正确性）
----------------------------------------------------
1. **成员判定是整窗的**（不允许只覆盖缺口的一部分）；
2. **驻留窗取成员窗口的凸包** `[min s_i, max e_i]` —— 能量随窗口长单调增，
   而更长的窗口不带来任何成员，故这是最优窗 ⇒ 驻留段与「(点, 窗口)」**一一对应**；
3. **闭包**：窗内该点能覆盖的缺口必须**全部**计入。

与口径 D 的关系
--------------
**本模型严格涵盖口径 D**：「一串单缺口驻留段 + 段间转场」就是口径 D 的解。
故 `中继包络排程` 原样保留，作为可切换的对照实现。

能耗口径
--------
驻留窗内中继**全程悬停**（1.05 kW），但只有成员缺口窗的**并集**期间才需要通信
（附加 0.05 kW）。故能耗 = 飞行 + 1.05·(等待 + Σ窗口长)/3600 + 0.05·Σ|∪成员窗|/3600。
落点在 `中继模型.中继架次代价计算`（该处按 `悬停站.有效服务时长` 分支），
本模块只负责把 `悬停站.有效服务时长` 填对 —— **时间与能耗一律调用 `m41`**，
单架次可行性一律以 `m41.单架次可行` 为唯一权威，不另写公式。
"""
