"""
构造启发式 —— 载荷包数据结构、访问顺序优化、机型分配、解码与修复、确定性种子构造。

**载荷包**是多点多架次调度搜索的基本单位：一个"待装上一架无人机"的载荷。

    染色体 = (箱表, 访问顺序) 的有序元组        （见 `多目标求解`）

**机型不进入染色体**，理由是场景的机队结构决定的（见 `分子机型分配` 的说明）：
运输无人机是 4 架 A + 2 架 B + 2 架 C，而首批截止时间 3600 s 的服务区恰好 8 个，
首波最多只能起飞 8 个架次。因此"哪个架次用哪种机型"是一个**对着机队求解**的
分配问题，把它拆成"每个载荷包各自挑一个机型"的独立基因在结构上就是错的。
本模块用 `分配机型` 统一在解码阶段按机队负载均衡地指派机型，
既保证首波可行，又缩小了搜索空间。

解码的确定性规则
----------------
1. **访问顺序**：随染色体传入；集合变化时（合并/拆分后）用 `优化访问顺序` 重初始化
   （最近邻初值 + 以架次总能耗为目标的 2-opt）。
2. **机型**：`分配机型` 按"最早截止优先"处理载荷包，在**可行机型**中取
   `(已派架次+1)/该机型无人机数` 最小者（并列时取能耗小者）——
   使各机型的派出架次数与机队规模成正比，首波不出现机型瓶颈。
3. **不可行包切分**：若某载荷包对**任何**机型都不可行，按访问顺序贪心切分；
   单个服务区仍装不下时再按质量递减首次适应装箱（FFD）。
"""
