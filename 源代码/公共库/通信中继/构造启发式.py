from 源代码.公共库.通信中继.配置 import 数值容差

机型顺序 = ("A", "B", "C")
无穷 = float("inf")


# ===================== 载荷包 =====================
@dataclass(frozen=True)
class 载荷包:
    """一架次的载荷：逐服务区的货箱编号 + 访问顺序。

    `箱表` 采用**规范形式**（按服务区编号升序），`访问顺序` 是 `箱表` 键的一个排列。
    两者分离使"改顺序"与"改配载"两类算子互不干扰，也保证 hash 稳定。
    """

    箱表: tuple[tuple[str, tuple[str, ...]], ...]
    访问顺序: tuple[str, ...]

    # ---------- 基本信息 ----------
    def 箱(self, 服务区编号: str) -> tuple[str, ...]:
        for 编号, 箱编号 in self.箱表:
            if 编号 == 服务区编号:
                return 箱编号
        return ()

    @property
    def 服务区集合(self) -> tuple[str, ...]:
        return tuple(编号 for 编号, _ in self.箱表)

    @property
    def 总箱数(self) -> int:
        return sum(len(箱) for _, 箱 in self.箱表)

    @property
    def 箱编号列表(self) -> tuple[str, ...]:
        return tuple(编号 for _, 箱 in self.箱表 for 编号 in 箱)

    @property
    def 服务区数(self) -> int:
        return len(self.箱表)


def 建包(
    场景: 场景,
    各区箱编号: dict[str, list[str]] | dict[str, tuple[str, ...]],
    访问顺序: tuple[str, ...] | list[str] | None = None,
) -> 载荷包:
    """由"服务区 → 货箱编号"装配载荷包；未给出访问顺序时用最近邻初值。"""
    箱表 = tuple(
        (编号, tuple(sorted(各区箱编号[编号])))
        for 编号 in sorted(各区箱编号)
        if len(各区箱编号[编号]) > 0
    )
    if not 箱表:
        raise ValueError("载荷包不能为空")

    集合 = tuple(编号 for 编号, _ in 箱表)
    if 访问顺序 is not None and set(访问顺序) == set(集合):
        顺序 = tuple(访问顺序)
    else:
        顺序 = 优化访问顺序(场景, 箱表)

    return 载荷包(箱表=箱表, 访问顺序=顺序)


def 换箱表(场景: 场景, 包: 载荷包, 各区箱编号: dict[str, list[str]]) -> 载荷包:
    """保持原访问顺序（仍相容时）替换箱表，供算子使用。"""
    return 建包(场景, 各区箱编号, 访问顺序=包.访问顺序)


def 包各区箱列表(场景: 场景, 包: 载荷包) -> list[list[dict]]:
    """按 `访问顺序` 展开为逐区货箱字典列表。"""
    return [[场景.取货箱(编号) for 编号 in 包.箱(区)] for 区 in 包.访问顺序]


def 包质量体积(场景: 场景, 包: 载荷包) -> tuple[float, float]:
    质量 = 体积 = 0.0
    for 编号 in 包.箱编号列表:
        箱 = 场景.取货箱(编号)
        质量 += 箱["质量"]
        体积 += 箱["体积"]
    return 质量, 体积


def 包最紧截止(场景: 场景, 包: 载荷包) -> float:
    """包内货箱的最紧硬截止时间（无硬截止则为 +inf），用于排序与机型分配。"""
    候选 = [硬截止时间(场景.取货箱(b)) for b in 包.箱编号列表]
    候选 = [d for d in 候选 if d is not None]
    return min(候选) if 候选 else 无穷


# ===================== 代价（按 (机型, 顺序, 箱表) 缓存）=====================
def _按顺序(箱表: tuple, 顺序: tuple[str, ...]) -> tuple:
    查 = dict(箱表)
    return tuple((编号, 查[编号]) for 编号 in 顺序)


@lru_cache(maxsize=200_000)
def _包代价缓存(场景: 场景, 机型编号: str, 顺序: tuple[str, ...], 箱表: tuple) -> 架次代价:
    return 多点架次代价(
        场景,
        场景.机型表[机型编号],
        顺序,
        [[场景.取货箱(编号) for 编号 in 箱] for _, 箱 in _按顺序(箱表, 顺序)],
    )


def 机型可行(场景: 场景, 机型编号: str, 包: 载荷包) -> bool:
    机 = 场景.机型表[机型编号]
    质量, 体积 = 包质量体积(场景, 包)
    if 质量 > 机.最大载货质量 + 数值容差 or 体积 > 机.可用装载体积 + 数值容差:
        return False
    return _包代价缓存(场景, 机型编号, 包.访问顺序, 包.箱表).满足返航余量


def 可行机型(场景: 场景, 包: 载荷包) -> list[str]:
    """返回对该载荷可行的全部机型，按机型顺序。"""
    return [g for g in 机型顺序 if g in 场景.机型表 and 机型可行(场景, g, 包)]


def 包最优机型(场景: 场景, 包: 载荷包) -> tuple[str | None, 架次代价 | None]:
    """在可行机型中取**总能耗最小**者；并列时取载货质量较小者（更省资源）。"""
    候选 = []
    for g in 可行机型(场景, 包):
        代价 = _包代价缓存(场景, g, 包.访问顺序, 包.箱表)
        候选.append((代价.总能耗, 场景.机型表[g].最大载货质量, g, 代价))
    if not 候选:
        return None, None
    候选.sort()
    return 候选[0][2], 候选[0][3]


def 包代价(场景: 场景, 包: 载荷包, 机型编号: str) -> 架次代价:
    return _包代价缓存(场景, 机型编号, 包.访问顺序, 包.箱表)


# ===================== 访问顺序 =====================
def _最近邻顺序(场景: 场景, 服务区集合: tuple[str, ...]) -> tuple[str, ...]:
    剩余 = list(sorted(服务区集合))
    顺序: list[str] = []
    当前 = "O01"
    while 剩余:
        下一个 = min(剩余, key=lambda x: (场景.取航段(当前, x).水平距离, x))
        顺序.append(下一个)
        剩余.remove(下一个)
        当前 = 下一个
    return tuple(顺序)


def 优化访问顺序(
    场景: 场景,
    箱表: tuple,
    初始顺序: tuple[str, ...] | None = None,
    _机型: str | None = None,
) -> tuple[str, ...]:
    """以**架次总能耗**为目标，用最近邻初值 + 2-opt 求访问顺序的局部最优。

    机型尚未指派时（解码阶段）对三种机型分别优化，取能耗最小者的顺序。
    """
    集合 = tuple(编号 for 编号, _ in 箱表)
    if len(集合) <= 1:
        return 集合
    初值 = 初始顺序 if (初始顺序 and set(初始顺序) == set(集合)) else _最近邻顺序(场景, 集合)

    if _机型 is not None:
        return _2opt(场景, _机型, 箱表, 初值)

    最佳顺序 = 初值
    最佳能耗 = None
    for g in 机型顺序:
        if g not in 场景.机型表:
            continue
        顺序 = _2opt(场景, g, 箱表, 初值)
        能耗 = _包代价缓存(场景, g, 顺序, 箱表).总能耗
        if 最佳能耗 is None or 能耗 < 最佳能耗:
            最佳能耗 = 能耗
            最佳顺序 = 顺序
    return 最佳顺序


def _2opt(场景: 场景, 机型编号: str, 箱表: tuple, 顺序: tuple[str, ...]) -> tuple[str, ...]:
    当前 = tuple(顺序)
    当前能耗 = _包代价缓存(场景, 机型编号, 当前, 箱表).总能耗
    k = len(当前)
    if k < 3:
        return 当前
    for _ in range(20):        # 轮数上限，防止病态循环
        改进 = False
        for i in range(k - 1):
            for j in range(i + 1, k):
                候选 = 当前[:i] + 当前[i : j + 1][::-1] + 当前[j + 1 :]
                能耗 = _包代价缓存(场景, 机型编号, 候选, 箱表).总能耗
                if 能耗 < 当前能耗 - 1e-12:
                    当前, 当前能耗, 改进 = 候选, 能耗, True
        if not 改进:
            break
    return 当前


# ===================== 机型分配（机队均衡）=====================
def 分配机型(场景: 场景, 包列表: list[载荷包] | tuple[载荷包, ...]) -> list[str]:
    """给载荷包序列指派机型，使各机型的派出架次数与机队规模相称。

    规则：按**最紧硬截止时间升序**处理载荷包；每个包在其可行机型中取
    `(该机型已派架次 + 1) / 该机型无人机数` 最小者，并列时取总能耗最小者。

    这样首波（截止 3600 s 的 8 个服务区）不会被单一机型卡住：
    4A/2B/2C 的机队会把前 8 个紧迫包自动铺成 4/2/2。
    """
    无人机数 = {g: max(len(场景.无人机清单.get(g, [])), 1) for g in 机型顺序}
    计数 = {g: 0 for g in 机型顺序}
    指派 = [""] * len(包列表)

    顺序 = sorted(
        range(len(包列表)),
        key=lambda i: (包最紧截止(场景, 包列表[i]), i),
    )
    for i in 顺序:
        包 = 包列表[i]
        候选 = 可行机型(场景, 包)
        if not 候选:
            候选 = [机型顺序[0]]
        指派[i] = min(
            候选,
            key=lambda g: (
                (计数[g] + 1) / 无人机数[g],
                _包代价缓存(场景, g, 包.访问顺序, 包.箱表).总能耗,
                g,
            ),
        )
        计数[指派[i]] += 1
    return 指派


# ===================== 切分、修复与解码 =====================
def 单区装箱(场景: 场景, 服务区编号: str, 箱编号列表: list[str]) -> list[dict[str, list[str]]]:
    """把**单个服务区**的货箱按质量递减首次适应装箱（FFD）。

    保证每个分组对**至少一种**机型可行。
    """
    待装 = sorted(
        箱编号列表,
        key=lambda b: (-场景.取货箱(b)["质量"], -场景.取货箱(b)["体积"], b),
    )
    分组: list[dict[str, list[str]]] = []
    for 编号 in 待装:
        放好 = False
        for 组 in 分组:
            试 = {服务区编号: 组[服务区编号] + [编号]}
            if 可行机型(场景, 建包(场景, 试)) :
                组[服务区编号].append(编号)
                放好 = True
                break
        if not 放好:
            分组.append({服务区编号: [编号]})
    return 分组


def 切分包(场景: 场景, 包: 载荷包) -> list[载荷包]:
    """把**对任何机型都不可行**的载荷包切成若干可行子包。

    按访问顺序贪心累积服务区；累积到装不下时先落一个子包。
    单个服务区自身就装不下时，改用 `单区装箱` 拆箱。
    """

    def 可行(箱区: dict[str, list[str]]) -> bool:
        return not 箱区 or bool(可行机型(场景, 建包(场景, 箱区)))

    出: list[载荷包] = []
    当前: dict[str, list[str]] = {}

    for 区 in 包.访问顺序:
        箱s = list(包.箱(区))
        试 = dict(当前)
        试[区] = 箱s
        if 可行(试):
            当前 = 试
            continue

        if 当前:
            出.append(建包(场景, 当前))
            当前 = {}

        if 可行({区: 箱s}):
            当前 = {区: 箱s}
            continue

        # 单区自身装不下 → FFD 拆箱，最后一组留给下一轮继续组包
        分组 = 单区装箱(场景, 区, 箱s)
        出.extend(建包(场景, 组) for 组 in 分组[:-1])
        当前 = dict(分组[-1])

    if 当前:
        出.append(建包(场景, 当前))
    return 出


def 修复(场景: 场景, 包列表: list[载荷包] | tuple[载荷包, ...]) -> list[载荷包]:
    """把任意载荷包序列修复为"每个包都可被至少一种机型承运"的序列。"""
    出: list[载荷包] = []
    for 包 in 包列表:
        if 包.总箱数 == 0:
            continue
        if 可行机型(场景, 包):
            出.append(包)
        else:
            出.extend(切分包(场景, 包))
    return 出


def 解码(场景: 场景, 包列表: list[载荷包] | tuple[载荷包, ...]) -> list[架次]:
    """载荷包序列 → 架次列表（修复不可行包 + 机队均衡指派机型）。序号从 1 连续编号。"""
    有效 = 修复(场景, 包列表)
    机型指派 = 分配机型(场景, 有效)
    架次列表: list[架次] = []
    for 包, 机型编号 in zip(有效, 机型指派):
        架次列表.append(
            构造架次(
                场景,
                序号=len(架次列表) + 1,
                机型编号=机型编号,
                服务区序列=包.访问顺序,
                各区箱列表=包各区箱列表(场景, 包),
            )
        )
    return 架次列表


# ===================== 确定性种子构造 =====================
def 种子_单点(场景: 场景) -> list[载荷包]:
    """每个服务区独立做 FFD 装箱（每架次仅服务一个区，对照单点往返与组批的组批口径）。"""
    出: list[载荷包] = []
    for 服务区编号 in 场景.编号顺序:
        箱编号 = [b["货箱编号"] for b in 场景.货箱归属.get(服务区编号, [])]
        if not 箱编号:
            continue
        出.extend(建包(场景, 组) for 组 in 单区装箱(场景, 服务区编号, 箱编号))
    return 出


def 种子_限期优先(场景: 场景, 服务区上限: int = 3) -> list[载荷包]:
    """按**硬截止时间**升序装包：限期最紧的箱先排，尽量并入已有包。

    `服务区上限` 限制单个包的服务区数（默认 3），避免出现超长访问链。
    """
    有序 = sorted(
        场景.货箱,
        key=lambda b: (_箱截止(b), -b["应急优先系数"], b["货箱编号"]),
    )
    箱区表: list[dict[str, list[str]]] = []
    for 箱 in 有序:
        编号 = 箱["货箱编号"]
        区 = 箱["服务区编号"]
        放好 = False
        for 序 in range(len(箱区表)):
            组 = 箱区表[序]
            if 区 not in 组 and len(组) >= 服务区上限:
                continue
            试 = {k: list(v) for k, v in 组.items()}
            试[区] = 试.get(区, []) + [编号]
            if 可行机型(场景, 建包(场景, 试)):
                箱区表[序] = 试
                放好 = True
                break
        if not 放好:
            箱区表.append({区: [编号]})
    return [建包(场景, 组) for 组 in 箱区表]


def 种子_地理邻近(场景: 场景, 服务区上限: int = 3) -> list[载荷包]:
    """按**最近邻链**把服务区聚成若干组（每组不超过 `服务区上限` 个），再各自装箱。"""
    剩余 = set(场景.编号顺序)
    分组: list[list[str]] = []
    while 剩余:
        起点 = min(剩余, key=lambda x: (场景.取航段("O01", x).水平距离, x))
        链 = [起点]
        剩余.discard(起点)
        while 剩余 and len(链) < 服务区上限:
            当前 = 链[-1]
            下一个 = min(剩余, key=lambda x: (场景.取航段(当前, x).水平距离, x))
            链.append(下一个)
            剩余.discard(下一个)
        分组.append(链)

    出: list[载荷包] = []
    for 链 in 分组:
        箱区 = {区: [b["货箱编号"] for b in 场景.货箱归属.get(区, [])] for 区 in 链}
        出.extend(修复(场景, [建包(场景, 箱区, 访问顺序=链)]))
    return 出


def 种子_限期拆分(场景: 场景, 紧迫阈值: float = 3600.0) -> list[载荷包]:
    """把**硬截止时间紧迫的箱**单独拆成一区一包，其余箱再按服务区 FFD 装箱。

    必要性：首批截止 3600 s 的服务区恰好 8 个，而机队是 4A+2B+2C，
    首波最多起飞 8 个架次。紧迫箱必须落在**小载荷包**里（每个区约 17 kg，
    体积 0.039 m³），这样 A/B/C 三种机型都能承运，
    `分配机型` 的机队均衡规则才能把首波正好铺成 4A+2B+2C。
    若把紧迫箱与大宗箱混装，包体量必然只有 C 能承运，2 架 C 无法承担 8 个区的首波。
    """
    紧迫: dict[str, list[str]] = {}
    其余: dict[str, list[str]] = {}
    for 箱 in 场景.货箱:
        截止 = 硬截止时间(箱)
        区 = 箱["服务区编号"]
        桶 = 紧迫 if (截止 is not None and 截止 <= 紧迫阈值) else 其余
        桶.setdefault(区, []).append(箱["货箱编号"])

    出: list[载荷包] = [建包(场景, {区: 箱s}) for 区, 箱s in sorted(紧迫.items())]
    for 区 in sorted(其余):
        出.extend(建包(场景, 组) for 组 in 单区装箱(场景, 区, 其余[区]))
    return 出


def 种子_首批集中(
    场景: 场景, 紧迫阈值: float = 3600.0, 服务区上限: int = 6
) -> list[载荷包]:
    """第 7 类种子（联合调度与中继 · **通信铺开**）：把首批箱尽量并进**少数多区架次**。

    动机（联合调度与中继实测，2026-09-25）
    ------------------------------
    `种子_限期拆分` 把首批箱拆成**一区一包**（8 包），于是有 **9 个架次**的最紧硬截止是
    3600 s。它们必须早起飞 ⇒ 通信缺口全挤在 `[400, 3500] s` 里 ⇒ 超出 2 架中继的串接
    能力：实测「最少架次数」方案未覆盖 **6** 个缺口，且这个 6 正是**严格下界**
    （见 本文的零中断不可行性定理）。

    把首批箱**并成少数几个多区架次**后，需要早起的架次数大幅下降，其余架次就能沿时间轴
    铺开错峰 —— 而"铺开"正是把未覆盖降到 0 的**唯一手段**（实测：均匀错峰 1800 s 时
    未覆盖 = 下界 = 0，但会把首批截止顶破 27 箱）。

    本种子与 `种子_限期拆分` 是**同一组箱的相反组批**，两者都进种子池，
    由搜索按五目标 + 通信违反量自行取舍。
    """
    紧迫: dict[str, list[str]] = {}
    其余: dict[str, list[str]] = {}
    for 箱 in 场景.货箱:
        截止 = 硬截止时间(箱)
        区 = 箱["服务区编号"]
        桶 = 紧迫 if (截止 is not None and 截止 <= 紧迫阈值) else 其余
        桶.setdefault(区, []).append(箱["货箱编号"])

    # ① 首批箱：先按区 FFD 切分（保证每个分组的体量对某机型可行），
    #    再**尽量跨区合并** —— 合并后每个架次可一次覆盖多个首批区，早起的架次数随之下降。
    首批包: list[载荷包] = []
    for 区 in sorted(紧迫):
        首批包.extend(建包(场景, 组) for 组 in 单区装箱(场景, 区, 紧迫[区]))

    # ② 其余箱：按服务区 FFD，与首批箱**分开组批**。
    #    这样首批架次是"轻包"（A/B/C 三种机型都能承运，机队均衡机型分配才铺得开），
    #    而非首批架次可以自由错峰。
    出: list[载荷包] = list(
        合并可并包(场景, 首批包, 服务区上限=服务区上限)
    )
    for 区 in sorted(其余):
        出.extend(建包(场景, 组) for 组 in 单区装箱(场景, 区, 其余[区]))
    return 出


def 合并可并包(
    场景: 场景,
    包列表: list[载荷包],
    轮数上限: int = 6,
    服务区上限: int = 6,
    只合无期限: bool = True,
) -> list[载荷包]:
    """反复尝试把两个包合成一个（**总能耗下降**且仍可行），直到不再改进。

    合并的收益来自水平巡航能耗关于载荷的凸性：集中载荷比平均分摊更省能。

    `只合无期限=True` 时，只合并**不含硬时限货箱**的包。这是必要的护栏：
    紧迫箱（首批截止 3600 s）必须待在 22 kg / 0.06 m³ 以内的小包里，
    三种机型才能都承运，首波才能铺满 4A+2B+2C；一旦与大宗货合并，
    包体量只有 C 能承运，而全机队只有 2 架 C。
    """
    当前 = list(包列表)
    for _ in range(轮数上限):
        最优 = None
        for i in range(len(当前)):
            for j in range(i + 1, len(当前)):
                甲, 乙 = 当前[i], 当前[j]
                if 只合无期限 and (包最紧截止(场景, 甲) < 无穷 or 包最紧截止(场景, 乙) < 无穷):
                    continue
                if len(set(甲.服务区集合) | set(乙.服务区集合)) > 服务区上限:
                    continue          # 规模护栏：避免出现超长访问链
                合并: dict[str, list[str]] = {k: list(v) for k, v in 甲.箱表}
                for k, v in 乙.箱表:
                    合并[k] = 合并.get(k, []) + list(v)
                试 = 建包(场景, 合并)
                甲机型, 甲代价 = 包最优机型(场景, 甲)
                乙机型, 乙代价 = 包最优机型(场景, 乙)
                试机型, 试代价 = 包最优机型(场景, 试)
                if 试机型 is None or 甲机型 is None or 乙机型 is None:
                    continue
                增量 = 试代价.总能耗 - 甲代价.总能耗 - 乙代价.总能耗
                if 增量 < -1e-9:
                    键 = (增量, i, j)
                    if 最优 is None or 键 < 最优[0]:
                        最优 = (键, i, j, 试)
        if 最优 is None:
            break
        _, i, j, 试 = 最优
        当前 = [p for k, p in enumerate(当前) if k not in (i, j)] + [试]
    return 当前


def 构造种子(场景: 场景) -> list[tuple[str, list[载荷包]]]:
    """返回若干**确定性**初始载荷包序列，供多目标搜索建立初始种群。

    前 6 类为多点多架次调度口径（搬运自上游，逐字未动）；第 7 类 `首批集中` 为联合调度与中继新增，
    专门为**通信铺开**设计（见 `种子_首批集中` 的 docstring）。
    """
    单点 = 种子_单点(场景)
    限期 = 种子_限期优先(场景)
    邻近 = 种子_地理邻近(场景)
    拆分 = 种子_限期拆分(场景)
    集中 = 种子_首批集中(场景)
    return [
        ("单点", 修复(场景, 单点)),
        ("单点合并", 修复(场景, 合并可并包(场景, 单点))),
        ("限期优先", 修复(场景, 限期)),
        ("限期拆分", 修复(场景, 拆分)),
        ("限期拆分合并", 修复(场景, 合并可并包(场景, 拆分))),
        ("地理邻近", 修复(场景, 邻近)),
        ("首批集中（通信铺开）", 修复(场景, 集中)),
    ]


