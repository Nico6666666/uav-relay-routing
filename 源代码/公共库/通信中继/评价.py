联合目标名称 = (
    "物资配送及时性",
    "联合任务完成时间",
    "联合总能耗",
    "运输无人机架次数",
    "中继无人机架次数",
)
联合目标单位 = ("s·权重", "s", "kWh", "次", "次")


@dataclass(frozen=True)
class 联合评价结果:
    """一个**联合方案**的五目标取值与诊断量。

    ⚠️ **零中断不进目标向量**：它是准入条件（`配置.py`《★ 前置条件》），
    只进 `是否满足全部硬约束` 与 `违反量`。目标向量恒为 5 维，与解的可行性无关 ——
    这样 `支配向量` 才能在搜索中间态对不可行解也有定义。
    """

    # ---- 五目标 ----
    加权总延误: float          # f1，与运输侧同定义（s·权重）
    联合完成时间: float        # f2 = max(运输.完成时间, 中继.完成时间)，含中继返场
    联合总能耗: float          # f3 = 运输.总能耗 + 中继.总能耗
    运输架次数: int            # f4
    中继架次数: int            # f5

    # ---- 通信与中继侧诊断（不进目标）----
    中断时长: float            # Σ 未覆盖缺口时长（s）—— 与时限违反量同量纲
    未覆盖缺口数: int
    未覆盖下界: int            # 严格下界；−1 表示未计算（未传摘要时）
    零中断: bool
    可证不可行: bool           # 下界 > 0 ⇒ 该运输方案零中断不可能
    已达下界: bool             # 实现未覆盖数 ≤ 下界 ⇒ 中继侧已最优
    中继总服务时长: float
    中继在位时长: float
    中继在位率: float          # 在位时长 / Σ缺口时长（口径 I）
    中继总等待时长: float
    组件缺口数: int

    # ---- 运输侧诊断（沿用多点多架次调度口径）----
    运输评价: 评价结果

    # ---- 可选：`中继排程.评估` 的四层归因 ----
    四层归因: dict = field(default_factory=dict)

    @property
    def 目标向量(self) -> tuple[float, float, float, int, int]:
        """五目标向量（全部最小化）。"""
        return (
            self.加权总延误, self.联合完成时间, self.联合总能耗,
            self.运输架次数, self.中继架次数,
        )

    @property
    def 硬约束违反量(self) -> float:
        """约束支配用的标量超出量 = **时限超出量 + 中断时长**（两者同为秒量纲）。

        仅用于搜索**中间态**的 Deb 支配比较；交付解以 `是否满足全部硬约束` 为准。
        """
        return self.运输评价.硬约束超出量 + self.中断时长

    @property
    def 是否满足全部硬约束(self) -> bool:
        """运输侧硬时限全部满足 **且** 通信零中断（准入条件）。"""
        return self.运输评价.是否满足全部硬约束 and self.零中断

    def 向量文本(self) -> str:
        return " / ".join(
            f"{名}={值:.4g}" for 名, 值 in zip(联合目标名称, self.目标向量)
        )


def 评价联合方案(剖面表, 联合, 摘要: dict | None = None) -> 联合评价结果:
    """对一个**联合方案**计算五目标与诊断量。

    `剖面表` 用于重算缺口集合（**零 DEM**，只用两张预计算表），从而得到中断时长与
    在位率 —— `联合方案` 自身只有运输方案与中继方案，不含缺口集合。

    `摘要` 建议传入 `中继排程.评估` 返回的摘要：其中含**严格下界**与四层归因，
    否则 `未覆盖下界 = −1`、`可证不可行` / `已达下界` 一律记为 `False`（未知）。
    """
    运输评价 = 评价方案(剖面表.场景, 联合.运输方案)

    摘要 = 摘要 or {}
    未覆盖 = set(联合.中继方案.未覆盖缺口)

    # 优先复用摘要里已算好的缺口量（`中继排程.评估` 给出）：**外层搜索每代都要评价，
    # 重复解析缺口是纯浪费**。仅当摘要缺这些键时才自己解析一次。
    if "中断时长_s" in 摘要 and "缺口总时长_s" in 摘要:
        中断时长 = float(摘要["中断时长_s"])
        服务需求 = float(摘要["缺口总时长_s"])
    else:
        from 源代码.公共库.通信中继.缺口解析 import 解析缺口

        缺口表 = list(解析缺口(剖面表, 联合.运输方案).缺口列表)
        中断时长 = sum(缺.时长 for 序, 缺 in enumerate(缺口表) if 序 in 未覆盖)
        服务需求 = sum(缺.时长 for 缺 in 缺口表)

    在位 = sum(架.返回时刻 - 架.起飞时刻 for 架 in 联合.中继方案.架次列表)

    下界 = int(摘要.get("未覆盖下界", -1))
    未覆盖数 = len(未覆盖)
    零中断 = not 未覆盖

    return 联合评价结果(
        加权总延误=运输评价.加权总延误,
        联合完成时间=联合.完成时间,
        联合总能耗=联合.总能耗,
        运输架次数=联合.运输方案.架次数,
        中继架次数=联合.中继方案.架次数,
        中断时长=中断时长,
        未覆盖缺口数=未覆盖数,
        未覆盖下界=下界,
        零中断=零中断,
        可证不可行=下界 > 0,
        已达下界=(下界 >= 0 and 未覆盖数 <= 下界),
        中继总服务时长=联合.中继方案.总服务时长,
        中继在位时长=在位,
        中继在位率=(在位 / 服务需求) if 服务需求 > 0 else 0.0,
        中继总等待时长=联合.中继方案.总等待时长,
        组件缺口数=int(摘要.get("组件缺口数", 0)),
        运输评价=运输评价,
        四层归因=dict(摘要.get("四层归因", {})),
    )


def 约束支配(甲: 联合评价结果, 乙: 联合评价结果) -> bool:
    """**Deb 约束支配**：甲是否按约束支配规则优于乙（用于搜索中间态）。

    1. 甲可行、乙不可行 ⇒ 甲优（**可行性优先于一切目标**，这是"通信是准入条件"的落实）；
    2. 都不可行 ⇒ 硬约束违反量小者优（量纲统一为秒：时限超出量 + 中断时长）；
    3. 都可行 ⇒ 五目标 Pareto 支配。

    注意 `是否满足全部硬约束` 要求**零中断**，故"不可行解"既包含违反时限的、
    也包含留下通信中断的 —— 二者被同一个标量违反量比较，可比性由量纲统一保证。
    """
    甲可行 = 甲.是否满足全部硬约束
    乙可行 = 乙.是否满足全部硬约束
    if 甲可行 != 乙可行:
        return 甲可行
    if not 甲可行:
        return 甲.硬约束违反量 < 乙.硬约束违反量 - 数值容差
    return 支配向量(甲.目标向量, 乙.目标向量)


def 联合非支配子集(结果列表: list[联合评价结果]) -> list[联合评价结果]:
    """按 `约束支配` 筛出非支配子集（保留输入顺序）。"""
    return [
        甲
        for 甲 in 结果列表
        if not any(约束支配(乙, 甲) for 乙 in 结果列表 if 乙 is not 甲)
    ]


# ===================== 自检 =====================
def 联合评价自检(剖面表, 环境) -> tuple[bool, list[str]]:
    """**联合评价的五目标口径**检查（不依赖具体方案的规模）。

    (a) **退化一致性**：`中继方案` 为空时，五目标退化为「运输四目标 + 中继架次 0」；
    (b) **口径闭合**：`f2 = max(运输.完成时间, 中继.完成时间)`、
        `f3 = 运输.总能耗 + 中继.总能耗`；
    (c) **中断时长**：等于未覆盖缺口的时长之和，且 `零中断 ⇔ 中断时长 == 0`；
    (d) **约束支配的基本性质**：可行支配不可行；两个不可行按违反量比较；
    (e) **准入条件的落实**：留下中断的解，即使五目标全优也判为不可行。
    """
    from dataclasses import replace as _replace

    from 源代码.公共库.通信中继.中继排程 import _构造方案, _样例架次, 评估
    from 源代码.公共库.通信中继.缺口解析 import 解析缺口
    from 源代码.公共库.通信中继.联合方案 import 中继方案 as _中继方案
    from 源代码.公共库.通信中继.联合方案 import 联合方案

    场景 = 剖面表.场景
    架次列表 = _样例架次(剖面表)
    if not 架次列表:
        return True, ["[自检·联合评价] 无可用样例架次，跳过"]

    运输方案 = _构造方案(架次列表, 场景, {})
    联合, 摘要 = 评估(剖面表, 环境, 架次列表)
    评 = 评价联合方案(剖面表, 联合, 摘要)

    # (b) 口径闭合
    f2对 = abs(评.联合完成时间 - max(运输方案.完成时间, 联合.中继方案.完成时间)) <= 1e-9
    f3对 = abs(评.联合总能耗 - (运输方案.总能耗 + 联合.中继方案.总能耗)) <= 1e-9
    f4对 = 评.运输架次数 == 运输方案.架次数
    f5对 = 评.中继架次数 == 联合.中继方案.架次数

    # (a) 退化：把中继方案清空
    空联合 = 联合方案(运输方案=运输方案, 中继方案=_中继方案())
    空评 = 评价联合方案(剖面表, 空联合, {})
    退化对 = (
        空评.中继架次数 == 0
        and 空评.联合总能耗 == 运输方案.总能耗
        and 空评.加权总延误 == 评.加权总延误
        and 空评.运输架次数 == 评.运输架次数
    )

    # (c) 中断时长
    缺口集合 = 解析缺口(剖面表, 运输方案)
    缺表 = list(缺口集合.缺口列表)
    未覆盖 = set(联合.中继方案.未覆盖缺口)
    期望中断 = sum(缺.时长 for 序, 缺 in enumerate(缺表) if 序 in 未覆盖)
    中断对 = (
        abs(评.中断时长 - 期望中断) <= 1e-9
        and (评.零中断 == (评.中断时长 == 0.0))
        and (评.未覆盖缺口数 == len(未覆盖))
    )

    # (d)(e) 约束支配
    可行解 = _replace(评, 零中断=True, 未覆盖缺口数=0, 中断时长=0.0)
    不可行解 = _replace(评, 零中断=False, 未覆盖缺口数=1, 中断时长=600.0)
    更不可行解 = _replace(评, 零中断=False, 未覆盖缺口数=2, 中断时长=2000.0)
    更优解 = _replace(
        可行解, 联合完成时间=可行解.联合完成时间 - 1000.0,
    )
    支配对 = (
        约束支配(可行解, 不可行解)
        and not 约束支配(不可行解, 可行解)
        and 约束支配(不可行解, 更不可行解)
        and 约束支配(更优解, 可行解)
        and not 约束支配(可行解, 更优解)
    )
    准入对 = (not 不可行解.是否满足全部硬约束) and 可行解.是否满足全部硬约束

    通过 = f2对 and f3对 and f4对 and f5对 and 退化对 and 中断对 and 支配对 and 准入对
    return 通过, [
        f"[自检·联合评价1] 五目标口径闭合：f2=max(运输,中继)={f2对}、"
        f"f3=运输+中继={f3对}、f4={f4对}、f5={f5对}；"
        f"f2={评.联合完成时间:.1f} s，f3={评.联合总能耗:.3f} kWh，"
        f"f4={评.运输架次数}，f5={评.中继架次数} → "
        f"{'合规' if (f2对 and f3对 and f4对 and f5对) else '不合规！'}",
        f"[自检·联合评价2] 退化一致性（中继方案清空 ⇒ 五目标退化为运输四目标 + 中继架次 0）→ "
        f"{'成立' if 退化对 else '不成立！'}",
        f"[自检·联合评价3] 中断时长口径：{评.中断时长:.0f} s = Σ 未覆盖缺口时长，"
        f"零中断 ⇔ 中断时长 == 0；未覆盖 {评.未覆盖缺口数} 个 / 缺口 {len(缺表)} 个，"
        f"严格下界 {评.未覆盖下界}，可证不可行 {评.可证不可行} → "
        f"{'合规' if 中断对 else '不合规！'}",
        f"[自检·联合评价4] 准入条件与约束支配：可行支配不可行 = {约束支配(可行解, 不可行解)}；"
        f"留下中断的解判为不可行 = {not 不可行解.是否满足全部硬约束}；"
        f"两不可行按违反量比较 = {约束支配(不可行解, 更不可行解)}；"
        f"同可行域内 Pareto 支配 = {约束支配(更优解, 可行解)} → "
        f"{'合规' if (支配对 and 准入对) else '不合规！'}",
    ]
