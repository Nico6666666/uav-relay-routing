目标名称 = ("配送及时性", "全部任务完成时间", "运输能耗", "架次数")
目标单位 = ("s·权重", "s", "kWh", "次")


@dataclass(frozen=True)
class 评价结果:
    """一个解的四目标取值与诊断量。"""

    # ---- 四目标 ----
    加权总延误: float
    完成时间: float
    总能耗: float
    架次数: int

    # ---- 诊断量 ----
    准时率: float
    总延误: float
    最大延误: float
    平均送达时刻: float
    加权平均送达时刻: float
    准时箱数: int
    总箱数: int
    硬约束违反箱数: int
    硬约束超出量: float
    首批违反箱数: int
    医疗违反箱数: int
    按机型架次数: dict[str, int] = field(default_factory=dict)
    按机型能耗: dict[str, float] = field(default_factory=dict)
    按机型载质量: dict[str, float] = field(default_factory=dict)
    无人机架次数: dict[str, int] = field(default_factory=dict)

    @property
    def 目标向量(self) -> tuple[float, float, float, int]:
        """四目标向量（全部最小化）。"""
        return (self.加权总延误, self.完成时间, self.总能耗, self.架次数)

    @property
    def 是否满足全部硬约束(self) -> bool:
        return self.硬约束违反箱数 == 0

    def 向量文本(self, 位: int | None = None) -> str:
        向量 = self.目标向量
        if 位 is None:
            return " / ".join(f"{名}={值:.4g}" for 名, 值 in zip(目标名称, 向量))
        return f"{目标名称[位]}={向量[位]:.4g} {目标单位[位]}"


def 评价方案(场景, 方案: 全局方案, 摘要: list | None = None) -> 评价结果:
    """计算一个全局方案的四目标与诊断量。

    `摘要` 可由 `可行性检验.检验全局方案` 一并得到，避免重复构造。
    """
    if 摘要 is None:
        摘要 = 时限模型.构造时限摘要(场景, 方案.逐箱送达())

    首批违反 = [条 for 条 in 摘要 if 条.是否首批保障 and not 条.首批是否满足]
    医疗违反 = [条 for 条 in 摘要 if 条.是否医疗物资 and not 条.期望硬约束是否满足]

    按机型载质量: dict[str, float] = {}
    无人机架次数: dict[str, int] = {}
    for 架 in 方案.架次列表:
        按机型载质量[架.机型编号] = 按机型载质量.get(架.机型编号, 0.0) + 架.总载质量
        记录 = 方案.调度表.get(架.序号)
        if 记录 is not None:
            无人机架次数[记录.无人机编号] = 无人机架次数.get(记录.无人机编号, 0) + 1

    return 评价结果(
        加权总延误=时限模型.加权总延误(摘要),
        完成时间=方案.完成时间,
        总能耗=方案.总能耗,
        架次数=方案.架次数,
        准时率=时限模型.准时率(摘要),
        总延误=时限模型.总延误(摘要),
        最大延误=时限模型.最大延误(摘要),
        平均送达时刻=时限模型.平均送达时刻(摘要),
        加权平均送达时刻=时限模型.加权平均送达时刻(摘要),
        准时箱数=时限模型.准时箱数(摘要),
        总箱数=len(摘要),
        首批违反箱数=len(首批违反),
        医疗违反箱数=len(医疗违反),
        硬约束违反箱数=len(时限模型.硬约束违反(摘要)),
        硬约束超出量=时限模型.硬约束超出量合计(摘要),
        按机型架次数=方案.按机型架次数,
        按机型能耗=方案.按机型能耗,
        按机型载质量=按机型载质量,
        无人机架次数=无人机架次数,
    )


def 评价并检验(场景, 方案: 全局方案) -> tuple[评价结果, list, list]:
    """一次性完成"检验 + 评价"，返回 (评价结果, 检验项表, 时限摘要)。"""
    检验项表, 摘要 = 检验全局方案(场景, 方案)
    return 评价方案(场景, 方案, 摘要), 检验项表, 摘要


# ===================== 支配关系 =====================
def 支配(甲: 评价结果, 乙: 评价结果) -> bool:
    """甲是否支配乙（四目标全部不劣，且至少一项严格更优）。"""
    甲向量 = 甲.目标向量
    乙向量 = 乙.目标向量
    if any(a > b + 数值容差 for a, b in zip(甲向量, 乙向量)):
        return False
    return any(a < b - 数值容差 for a, b in zip(甲向量, 乙向量))


def 支配向量(甲: tuple, 乙: tuple) -> bool:
    """目标向量层面的支配判定（供多目标搜索内部使用，避免构造 评价结果）。"""
    if any(a > b + 数值容差 for a, b in zip(甲, 乙)):
        return False
    return any(a < b - 数值容差 for a, b in zip(甲, 乙))


def 非支配子集(结果列表: list[评价结果]) -> list[评价结果]:
    """筛出非支配子集（保留输入顺序）。"""
    出 = []
    for 甲 in 结果列表:
        if not any(支配(乙, 甲) for 乙 in 结果列表):
            出.append(甲)
    return 出


