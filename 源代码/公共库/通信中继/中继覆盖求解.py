"""
中继覆盖求解 —— 缺口集合 $\\mathcal{G}(\\pi)$ → **悬停站选址**（纯几何，与时刻无关）。

本模块的职责边界（2026-09-25 收窄）
-----------------------------------
「选址」与「排程」已拆成两个模块：

    中继覆盖求解     候选悬停点 + 逐缺口求最优悬停站     ← **本模块**（纯几何、可缓存）
    中继包络排程     把悬停站拼成 2 条中继线上的架次       ← 依赖整个缺口集合的时刻结构

拆分的理由：悬停站的平面位置与海拔只取决于**缺口的位姿集合**，与绝对时刻无关，
故可跨方案缓存复用（外层搜索会对成千上万个运输方案各跑一次）；而"哪些站拼成一个架次、
分给哪条线"依赖全部缺口的时间结构，且要用动态规划求解。见 `逐缺口选址` 的 docstring。

两步求解（全部确定性）
----------------------
**第一步 · 候选悬停点**（口径 Q3）

在全体服务区外接矩形 + `悬停候选外扩_m` 内按 `悬停候选格距_m` 网格生成，剪枝：
① DEM 有效（C6）；② 距 $G01$ 水平距离 ≤ 6.270 km（有遮挡回传上限；水平距离是
三维距离的下界 ⇒ 该剪枝**不会**误删可行解）。

**第二步 · 逐缺口求最优悬停站**

先做必要条件粗筛：候选点到该缺口**每个**位姿的水平距离都 ≤ 无遮挡接入上限
6.270 km（该判据由 `口径自检·通信5` 实测验证）；再对幸存点调用
`悬停高度.最优悬停高度` 求**最小可行高度**（= 最优高度），按**代理代价**取最优：

    代理代价 = 中继机 O01 往返该点的飞行能耗 + 该缺口时长的服务能耗

（不含等待与转场 —— 它们取决于架次内的站位序，由 `中继包络排程` 决定。）

性能设计（能否跑通的关键）
--------------------------
外层多目标搜索会对**成千上万个运输方案**各跑一次选址，故：

1. **按缺口位形记忆化**：一个悬停站的平面位置与高度只取决于**缺口的位姿集合**，
   与绝对时刻无关（时刻只是平移服务窗口）。故以**全采样位姿的量化指纹**为键缓存
   站解，跨方案复用 —— 同一路线结构在不同开始时刻下**零重复计算**。
   （指纹不含时间，故同一条垂直下降段在不同运输架次里会命中同一站址 —— 这是
   缓存复用生效的证据，实测确有 2 组站址完全重合。）
2. **候选点按"到位姿质心"距离升序**取前 `候选点评估上限` 个（可行的悬停点恰恰是
   **贴近运输机**的那些，往往离 O01 较远，故不能按距 O01 排序）；
   **最终校验仍用全采样**逐一复核覆盖性。
3. 位姿抽稀（`站位姿抽稀上限`）只用于搜索期选址；`中继排程` 与 `可行性检验`
   一律用**全 30 m 采样**复核，插值误差不会外泄到交付方案。

口径
----
链路判定一律调用 `通信模型`；悬停高度一律调用 `悬停高度.最优悬停高度`；
时间与能耗一律调用 `中继模型`。**本模块不写任何通信或物理公式**。
"""
