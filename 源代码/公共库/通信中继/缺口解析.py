# ===================== 轨迹子段 =====================
@dataclass(frozen=True)
class 子段:
    """一个架次轨迹子段：时间区间 + 几何 + 该子段内的直连可用时间区间。

    `起点节点 == 终点节点` 表示**垂直段**（爬升 / 下降 / 交接，水平位置固定）；
    否则表示**巡航段**（沿两节点连线的水平直线）。
    """

    架次序号: int
    类别: str                 # "爬升" / "巡航" / "下降" / "交接"
    起点节点: str
    终点节点: str
    起时刻: float             # 绝对时刻（相对任务起点 0）
    终时刻: float
    海拔起: float             # 段首的运输机绝对海拔（m）
    海拔终: float             # 段末的运输机绝对海拔（m）
    可直连区间: tuple[tuple[float, float], ...]   # **绝对时刻**的直连可用区间
    说明: str = ""

    @property
    def 时长(self) -> float:
        return self.终时刻 - self.起时刻

    @property
    def 垂直段(self) -> bool:
        return self.起点节点 == self.终点节点

    @property
    def 全程可直连(self) -> bool:
        return (
            bool(self.可直连区间)
            and self.可直连区间[0][0] <= self.起时刻 + 数值容差
            and self.可直连区间[-1][1] >= self.终时刻 - 数值容差
        )


# ===================== 缺口 =====================
@dataclass(frozen=True)
class 缺口:
    """一段连续的通信失联时段，**必须由中继覆盖**（C10 硬约束）。"""

    架次序号: int
    起时刻: float
    终时刻: float
    运输机位姿: tuple[通信端点, ...]        # 全 30 m 采样（按时间升序）
    途经节点: tuple[str, ...]               # 该缺口经过的节点（诊断用）
    位姿时刻: tuple[float, ...] = ()        # 与 运输机位姿 对齐的采样时刻

    def __post_init__(self) -> None:
        if not self.运输机位姿:
            raise ValueError("缺口的运输机位姿不能为空")
        if self.位姿时刻 and len(self.位姿时刻) != len(self.运输机位姿):
            raise ValueError("位姿时刻与运输机位姿长度不一致")

    @property
    def 时长(self) -> float:
        return self.终时刻 - self.起时刻

    @property
    def 位姿数(self) -> int:
        return len(self.运输机位姿)

    def 抽稀(self, 上限: int) -> 缺口:
        """均匀抽稀位姿到不超过 `上限` 个（**保两端**），供搜索期使用。

        抽稀只影响搜索期的算力，不改变判定口径：最终校验一律用
        `缺口.运输机位姿` 的全采样。为此保留被抽掉的位姿**不作校验依据**，
        而由 `中继排程` / `可行性检验` 用全采样复核。
        """
        if self.位姿数 <= 上限:
            return self
        位数 = self.位姿数
        取位 = sorted({round(位 * (位数 - 1) / (上限 - 1)) for 位 in range(上限)})
        return 缺口(
            架次序号=self.架次序号,
            起时刻=self.起时刻,
            终时刻=self.终时刻,
            运输机位姿=tuple(self.运输机位姿[位] for 位 in 取位),
            途经节点=self.途经节点,
            位姿时刻=tuple(self.位姿时刻[位] for 位 in 取位) if self.位姿时刻 else (),
        )


# ===================== 并发剖面 =====================
@dataclass(frozen=True)
class 并发剖面:
    """分段常数的 $N(t)$：$t$ 时刻处于通信缺口中的运输机数量。

    `断点` 长度为 `值` + 1：第 $k$ 段为 $[断点_k, 断点_{k+1})$，取值为 $值_k$。
    """

    断点: tuple[float, ...]
    值: tuple[int, ...]

    def __post_init__(self) -> None:
        if len(self.断点) != len(self.值) + 1:
            raise ValueError("断点数应为段数 + 1")

    @property
    def 峰值(self) -> int:
        return max(self.值, default=0)

    @property
    def 直方图(self) -> dict[int, float]:
        """{并发数: 该并发数持续的总时长（s）}。"""
        出: dict[int, float] = {}
        for 位, 值 in enumerate(self.值):
            出[值] = 出.get(值, 0.0) + (self.断点[位 + 1] - self.断点[位])
        return {键: 值 for 键, 值 in sorted(出.items())}

    def 取(self, 时刻: float) -> int:
        for 位, 值 in enumerate(self.值):
            if self.断点[位] <= 时刻 < self.断点[位 + 1]:
                return 值
        return 0

    def 超限时长(self, 容量: int) -> float:
        """并发数超过 `容量` 的总时长。"""
        return sum(
            值 for 键, 值 in self.直方图.items() if 键 > 容量
        )


# ===================== 缺口集合 =====================
@dataclass(eq=False)
class 缺口集合:
    """一个运输方案的全部缺口与派生统计。

    采用 `eq=False`（对象身份比较与哈希），与 `场景` / `剖面表` 一致。
    """

    剖面表: object
    方案: object
    子段列表: tuple[子段, ...] = ()
    缺口列表: tuple[缺口, ...] = ()
    统计: dict = field(default_factory=dict)

    # ---------- 聚合 ----------
    @property
    def 缺口数(self) -> int:
        return len(self.缺口列表)

    @property
    def 总缺口时长(self) -> float:
        return sum(缺.时长 for 缺 in self.缺口列表)

    @property
    def 按架次(self) -> dict[int, list[缺口]]:
        出: dict[int, list[缺口]] = {}
        for 缺 in self.缺口列表:
            出.setdefault(缺.架次序号, []).append(缺)
        return 出

    @property
    def 并发(self) -> 并发剖面:
        return 构造并发剖面(self.缺口列表)

    def 抽稀(self, 上限: int) -> 缺口集合:
        """把全部缺口按位姿数上限抽稀（供搜索期使用）。"""
        return 缺口集合(
            剖面表=self.剖面表,
            方案=self.方案,
            子段列表=self.子段列表,
            缺口列表=tuple(缺.抽稀(上限) for 缺 in self.缺口列表),
            统计=self.统计,
        )

    @property
    def 需中继的架次数(self) -> int:
        return len({缺.架次序号 for 缺 in self.缺口列表})

    @property
    def 全直连架次数(self) -> int:
        return len(self.方案.架次列表) - self.需中继的架次数


# ===================== 轨迹展开 =====================
def _机(场景, 架):
    return 场景.机型表[架.机型编号]


def 展开架次轨迹(场景, 架, 开始时刻: float) -> list[子段]:
    """把一个运输架次展开为有序子段（爬升 / 巡航 / 下降 / 交接），**带绝对时刻**。

    时刻口径与 `多点飞行模型` 的 `送达偏移` **逐项一致**（同一套地面作业时间口径）：
    自"工位固定准备 + 每箱装载 × 总箱数"之后开始计飞行时间。
    """
    机 = _机(场景, 架)
    代价 = 架.代价
    节点 = 代价.节点序列
    航段 = 代价.航段
    各区箱数 = 代价.各区箱数

    偏移 = 机.工位固定准备时间 + 机.每箱装载时间 * 代价.总箱数
    出: list[子段] = []

    for 位, 段 in enumerate(航段):
        起节点 = 节点[位]
        终节点 = 节点[位 + 1]

        # —— 爬升段：原地在起节点上方升至巡航海拔 ——
        if 段.爬升 > 数值容差:
            时长 = 段.爬升 / 机.最大爬升速度
            出.append(
                子段(
                    架次序号=架.序号, 类别="爬升",
                    起点节点=起节点, 终点节点=起节点,
                    起时刻=开始时刻 + 偏移, 终时刻=开始时刻 + 偏移 + 时长,
                    海拔起=段.起点作业高度, 海拔终=段.巡航海拔,
                    可直连区间=(),
                    说明=f"{起节点} 上方升至 {段.巡航海拔:.1f} m",
                )
            )
            偏移 += 时长

        # —— 巡航段：沿 起节点 → 终节点 的水平直线平飞 ——
        if 段.水平距离 > 数值容差:
            时长 = 段.水平距离 / 机.巡航速度
            出.append(
                子段(
                    架次序号=架.序号, 类别="巡航",
                    起点节点=起节点, 终点节点=终节点,
                    起时刻=开始时刻 + 偏移, 终时刻=开始时刻 + 偏移 + 时长,
                    海拔起=段.巡航海拔, 海拔终=段.巡航海拔,
                    可直连区间=(),
                    说明=f"{起节点} → {终节点}，{段.水平距离 / 1000:.2f} km",
                )
            )
            偏移 += 时长

        # —— 下降段：原地在终节点上方降至作业高度 ——
        if 段.下降 > 数值容差:
            时长 = 段.下降 / 机.最大下降速度
            出.append(
                子段(
                    架次序号=架.序号, 类别="下降",
                    起点节点=终节点, 终点节点=终节点,
                    起时刻=开始时刻 + 偏移, 终时刻=开始时刻 + 偏移 + 时长,
                    海拔起=段.巡航海拔, 海拔终=段.终点作业高度,
                    可直连区间=(),
                    说明=f"{终节点} 上方降至 {段.终点作业高度:.1f} m",
                )
            )
            偏移 += 时长

        # —— 投送交接：悬停在作业高度 —— 只在访问服务区时发生（返航段没有）——
        if 位 < len(各区箱数):
            箱数 = 各区箱数[位]
            时长 = 机.接收点基础交接时间 + 机.每箱增加交接时间 * 箱数
            if 时长 > 数值容差:
                出.append(
                    子段(
                        架次序号=架.序号, 类别="交接",
                        起点节点=终节点, 终点节点=终节点,
                        起时刻=开始时刻 + 偏移, 终时刻=开始时刻 + 偏移 + 时长,
                        海拔起=段.终点作业高度, 海拔终=段.终点作业高度,
                        可直连区间=(),
                        说明=f"{终节点} 交接 {箱数} 箱",
                    )
                )
                偏移 += 时长

    return 出


# ===================== 子段的直连可用区间（查表，零 DEM）=====================
def 判定子段可用(剖面表, 场景, 子段: 子段) -> tuple[tuple[float, float], ...]:
    """由表A / 表B 判定一个子段的**绝对时刻**直连可用区间。

    这是"零 DEM 调用"的实现点：任何架次的缺口都能 O(1) 查出。
    """
    段 = 子段
    if 段.垂直段:
        if 段.类别 == "交接":
            可用 = 剖面表.节点可直连(段.起点节点, 段.海拔起)
            return ((段.起时刻, 段.终时刻),) if 可用 else ()

        if 段.海拔终 >= 段.海拔起:
            # 爬升：海拔由低到高。表B 的"可直连"关于海拔单调 ⇒ 看最低点
            if 剖面表.节点可直连(段.起点节点, 段.海拔起):
                return ((段.起时刻, 段.终时刻),)
            临界 = 剖面表.取节点(段.起点节点).临界海拔
            if 临界 is None or 临界 > 段.海拔终:
                return ()
            比例 = (临界 - 段.海拔起) / (段.海拔终 - 段.海拔起)
            return ((段.起时刻 + 比例 * 段.时长, 段.终时刻),)

        # 下降：海拔由高到低。可直连时段在**前段**
        if 剖面表.节点可直连(段.起点节点, 段.海拔终):
            return ((段.起时刻, 段.终时刻),)
        临界 = 剖面表.取节点(段.起点节点).临界海拔
        if 临界 is None or 临界 < 段.海拔终:
            return ()
        比例 = (段.海拔起 - 临界) / (段.海拔起 - 段.海拔终)
        return ((段.起时刻, 段.起时刻 + 比例 * 段.时长),)

    # 巡航段：里程 → 时间（时间与里程成正比）
    航段 = 剖面表.取航段(段.起点节点, 段.终点节点)
    距离 = 航段.水平距离
    if 距离 <= 数值容差:
        return ((段.起时刻, 段.终时刻),)
    出 = []
    for 里起, 里终 in 航段.可用区间:
        if 里起 < 0.0:
            里起 = 0.0
        if 里终 > 距离:
            里终 = 距离
        if 里终 <= 里起:
            continue
        出.append(
            (
                段.起时刻 + 段.时长 * (里起 / 距离),
                段.起时刻 + 段.时长 * (里终 / 距离),
            )
        )
    return tuple(出)


# ===================== 位姿采样 =====================
def 子段位姿(场景, 子段: 子段, 起时刻: float, 终时刻: float) -> list[tuple[float, 通信端点]]:
    """在子段的 [起时刻, 终时刻] 子区间内按 剖面采样步长_m 采样 (时刻, 位姿)。

    垂直段按高度步长采样、巡航段按地面里程步长采样，二者都等价于"飞行 30 m 采一点"。
    """
    段 = 子段
    区间时长 = 终时刻 - 起时刻
    if 区间时长 <= 数值容差:
        return []

    if 段.垂直段:
        经度, 纬度 = 节点水平坐标(场景, 段.起点节点)
        总高差 = abs(段.海拔终 - 段.海拔起)
        份数 = max(int(math.ceil(总高差 / 剖面采样步长_m)), 1)
    else:
        经度甲, 纬度甲 = 节点水平坐标(场景, 段.起点节点)
        经度乙, 纬度乙 = 节点水平坐标(场景, 段.终点节点)
        距离 = _航段距离(场景, 段.起点节点, 段.终点节点)
        份数 = max(int(math.ceil(距离 / 剖面采样步长_m)), 1)

    出 = []
    已采样时刻: set[float] = set()
    for 位 in range(份数 + 1):
        t = 位 / 份数
        时刻 = 段.起时刻 + t * 段.时长
        if 时刻 < 起时刻 - 数值容差 or 时刻 > 终时刻 + 数值容差:
            continue
        键 = round(时刻, 6)
        if 键 in 已采样时刻:
            continue
        已采样时刻.add(键)

        if 段.垂直段:
            海拔 = 段.海拔起 + t * (段.海拔终 - 段.海拔起)
            出.append((时刻, 运输机端点(经度, 纬度, 海拔)))
        else:
            出.append(
                (
                    时刻,
                    运输机端点(
                        经度甲 + t * (经度乙 - 经度甲),
                        纬度甲 + t * (纬度乙 - 纬度甲),
                        段.海拔起,
                    ),
                )
            )
    return 出


def _航段距离(场景, 甲: str, 乙: str) -> float:
    return 场景.取航段(甲, 乙).水平距离


# ===================== 主入口 =====================
def 解析缺口(剖面表, 方案, 开始时刻表: dict[int, float] | None = None) -> 缺口集合:
    """把一个运输方案解析为缺口集合与并发剖面。

    `方案` 为多点多架次调度的 `全局方案`（含 `架次列表` 与 `调度表`）；
    架次开始时刻取自 `调度表`，也可由 `开始时刻表` 覆盖（供错峰试验使用）。
    """
    场景 = 剖面表.场景
    全部子段: list[子段] = []

    for 架 in 方案.架次列表:
        if 开始时刻表 is not None and 架.序号 in 开始时刻表:
            开始 = 开始时刻表[架.序号]
        else:
            记录 = 方案.调度表.get(架.序号)
            开始 = 记录.开始时刻 if 记录 is not None else 0.0

        子段列表 = 展开架次轨迹(场景, 架, 开始)
        全部子段.extend(
            replace(段, 可直连区间=判定子段可用(剖面表, 场景, 段))
            for 段 in 子段列表
        )

    缺口列表 = _抽取缺口(场景, 全部子段)

    统计 = {
        "架次数": len(方案.架次列表),
        "子段数": len(全部子段),
        "子段失联数": sum(1 for 段 in 全部子段 if not 段.全程可直连),
        "缺口数": len(缺口列表),
        "总缺口时长_s": sum(缺.时长 for 缺 in 缺口列表),
        "需中继的架次数": len({缺.架次序号 for 缺 in 缺口列表}),
        "全直连架次数": len(方案.架次列表) - len({缺.架次序号 for 缺 in 缺口列表}),
        "位姿采样点数": sum(缺.位姿数 for 缺 in 缺口列表),
    }
    return 缺口集合(
        剖面表=剖面表, 方案=方案,
        子段列表=tuple(全部子段), 缺口列表=tuple(缺口列表), 统计=统计,
    )


def _抽取缺口(场景, 全部子段: list[子段]) -> list[缺口]:
    """把所有子段的失联时段按架次合并成缺口，并采样位姿。"""
    按架次: dict[int, list[子段]] = {}
    for 段 in 全部子段:
        按架次.setdefault(段.架次序号, []).append(段)

    缺口列表: list[缺口] = []
    for 架次序号 in sorted(按架次):
        子段表 = sorted(按架次[架次序号], key=lambda 段: 段.起时刻)
        失联区间 = _失联区间的补集(子段表)
        失联区间 = _合并相邻(失联区间)
        for 起, 终 in 失联区间:
            if 终 - 起 <= 数值容差:
                continue
            位姿时刻, 位姿 = _区间内位姿(场景, 子段表, 起, 终)
            if not 位姿:
                continue
            途经 = sorted({段.起点节点 for 段 in 子段表 if 段.起时刻 < 终 and 段.终时刻 > 起}
                          | {段.终点节点 for 段 in 子段表 if 段.起时刻 < 终 and 段.终时刻 > 起})
            缺口列表.append(
                缺口(
                    架次序号=架次序号, 起时刻=起, 终时刻=终,
                    运输机位姿=tuple(位姿), 途经节点=tuple(途经),
                    位姿时刻=tuple(位姿时刻),
                )
            )
    缺口列表.sort(key=lambda 缺: (缺.起时刻, 缺.架次序号))
    return 缺口列表


def _失联区间的补集(子段表: list[子段]) -> list[tuple[float, float]]:
    """由各子段的可直连时间区间求整条时间轴上的失联区间（未覆盖即失联）。"""
    if not 子段表:
        return []
    起点 = min(段.起时刻 for 段 in 子段表)
    终点 = max(段.终时刻 for 段 in 子段表)

    可用段: list[tuple[float, float]] = []
    for 段 in 子段表:
        for 起, 终 in 段.可直连区间:
            可用段.append((max(起, 起点), min(终, 终点)))
    可用段.sort()

    失联: list[tuple[float, float]] = []
    游标 = 起点
    for 起, 终 in 可用段:
        if 起 > 游标 + 数值容差:
            失联.append((游标, min(起, 终点)))
        游标 = max(游标, 终)
        if 游标 >= 终点:
            break
    if 游标 < 终点 - 数值容差:
        失联.append((游标, 终点))
    return 失联


def _合并相邻(区间: list[tuple[float, float]]) -> list[tuple[float, float]]:
    出: list[tuple[float, float]] = []
    for 起, 终 in sorted(区间):
        if 出 and 起 <= 出[-1][1] + 数值容差:
            出[-1] = (出[-1][0], max(出[-1][1], 终))
        else:
            出.append((起, 终))
    return 出


def _端点位姿(场景, 子段表: list[子段], 时刻: float) -> 通信端点 | None:
    """按 Q2 三段式位置模型重建 `时刻` 的运输机位姿（区间端点的线性插值）。

    与 `可行性检验._位姿_at` **同一口径** —— 那里是 `⑩ 通信连续性` 全采样复核时
    补区间两端点用的。本函数存在的唯一理由：让**缺口自己的位姿集**与**复核用的位姿集**
    逐点一致（见 `_区间内位姿` 的说明）。
    """
    for 段 in 子段表:
        if 段.起时刻 - 数值容差 <= 时刻 <= 段.终时刻 + 数值容差:
            比例 = 0.0 if 段.时长 <= 数值容差 else (时刻 - 段.起时刻) / 段.时长
            比例 = min(max(比例, 0.0), 1.0)
            海拔 = 段.海拔起 + 比例 * (段.海拔终 - 段.海拔起)
            经甲, 纬甲 = 节点水平坐标(场景, 段.起点节点)
            if 段.垂直段:
                return 运输机端点(经甲, 纬甲, 海拔)
            经乙, 纬乙 = 节点水平坐标(场景, 段.终点节点)
            return 运输机端点(
                经甲 + 比例 * (经乙 - 经甲),
                纬甲 + 比例 * (纬乙 - 纬甲),
                海拔,
            )
    return None


def _区间内位姿(
    场景, 子段表: list[子段], 起: float, 终: float
) -> tuple[list[float], list[通信端点]]:
    """取 [起, 终] 内的运输机采样位姿（按时刻升序，去重）。

    ⚠️ **区间两端点必须显式补上**。`子段位姿` 是在**整条子段**上按 30 m 等分采样的，
    再按 [起, 终] 过滤 —— 故采到的首/末点一般**不在** `起`/`终` 上，可以差到近一个步长。
    而 `可行性检验._服务区间位姿`（⑩ 的全采样复核）会**额外插值出**这两端点。
    若本函数不补，缺口自己的位姿集就**不含**复核要用的那两个位姿：
    选址按前者定悬停高度 H*，复核却按后者验 —— 端点恰好更难覆盖时，就会出现
    「排程判可行、检验判违反」的悬崖。补上两端点后两个集合逐点一致，该类失败被根除。
    """
    记录: list[tuple[float, 通信端点]] = []
    for 段 in 子段表:
        重叠起 = max(段.起时刻, 起)
        重叠终 = min(段.终时刻, 终)
        if 重叠终 - 重叠起 <= 数值容差:
            if 段.类别 != "交接" or not (段.起时刻 <= 起 <= 段.终时刻):
                continue
            重叠起, 重叠终 = 段.起时刻, 段.终时刻
        记录.extend(子段位姿(场景, 段, 重叠起, 重叠终))
    for 端点时刻 in (起, 终):
        位姿 = _端点位姿(场景, 子段表, 端点时刻)
        if 位姿 is not None:
            记录.append((端点时刻, 位姿))

    记录.sort(key=lambda 项: 项[0])
    去重: list[tuple[float, 通信端点]] = []
    for 项 in 记录:
        if 去重 and abs(项[0] - 去重[-1][0]) <= 1e-6:
            continue
        去重.append(项)
    return [项[0] for 项 in 去重], [项[1] for 项 in 去重]


# ===================== 并发剖面与闸门 A =====================
def 构造并发剖面(缺口列表: tuple[缺口, ...] | list[缺口]) -> 并发剖面:
    """由缺口列表构造分段常数的 $N(t)$。"""
    if not 缺口列表:
        return 并发剖面(断点=(0.0,), 值=())
    事件: dict[float, int] = {}
    for 缺 in 缺口列表:
        事件[缺.起时刻] = 事件.get(缺.起时刻, 0) + 1
        事件[缺.终时刻] = 事件.get(缺.终时刻, 0) - 1
    时刻列 = sorted(事件)
    断点: list[float] = []
    值: list[int] = []
    当前 = 0
    for 位, 时刻 in enumerate(时刻列):
        if 位 > 0:
            断点.append(时刻)
            值.append(当前)
        当前 += 事件[时刻]
    断点.append(时刻列[-1])
    return 并发剖面(断点=tuple(断点), 值=tuple(值))


def 并发下界(缺口集合: 缺口集合, 中继架数: int = 2) -> dict:
    """**闸门 A**：与中继位置无关的容量下界与首批时限冲突分析。

    给出三类量：
      1. **容量下界**：$\\sum$缺口时长 / 中继架数 —— 任务完成时间不可能早于此
         （2 架中继、一对一，任一时刻最多覆盖 2 个缺口）；
      2. **并发结构**：$N(t)$ 的峰值、直方图、超限时长 —— 判断"错峰"的空间；
      3. **首批时限冲突**：首批截止时刻前后同时在缺口中的架次数 —— 时限与容量
         能否共存的关键（截止 3600 s 的架次若被迫串行，完成时间会被推后）。
    """
    剖面 = 缺口集合.并发
    总时长 = 缺口集合.总缺口时长
    容量下界 = 总时长 / 中继架数 if 中继架数 > 0 else float("inf")

    直方图 = 剖面.直方图
    超限 = {键: 值 for 键, 值 in 直方图.items() if 键 > 中继架数}

    # 首批时限冲突：取所有硬截止时刻，看各时刻的并发数
    场景 = 缺口集合.剖面表.场景
    截止列 = sorted(
        {
            float(箱["首批截止时间"])
            for 箱 in 场景.货箱
            if 箱["是否首批保障"] and 箱["首批截止时间"] is not None
        }
    )
    截止并发 = [
        {
            "截止时刻_s": 截止,
            "并发数": 剖面.取(截止),
            "仍在缺口中的架次": sorted(
                {缺.架次序号 for 缺 in 缺口集合.缺口列表 if 缺.起时刻 <= 截止 <= 缺.终时刻}
            ),
        }
        for 截止 in 截止列
    ]

    return {
        "缺口数": 缺口集合.缺口数,
        "缺口总时长_s": 总时长,
        "需中继的架次数": 缺口集合.需中继的架次数,
        "全直连架次数": 缺口集合.全直连架次数,
        "中继架数": 中继架数,
        "容量下界_完成时间_s": 容量下界,
        "并发峰值": 剖面.峰值,
        "并发直方图": 直方图,
        "超限时长_s": sum(超限.values()),
        "超限明细": 超限,
        "首批截止处的并发": 截止并发,
        "最长缺口_s": max((缺.时长 for 缺 in 缺口集合.缺口列表), default=0.0),
        "平均缺口_s": 总时长 / 缺口集合.缺口数 if 缺口集合.缺口数 else 0.0,
    }


# ===================== 口径 H 自检 =====================
def _并集(区间表) -> list[tuple[float, float]]:
    """合并区间：去零长、按起点排序、相接或重叠的合并。"""
    出: list[tuple[float, float]] = []
    for 起, 终 in sorted(区间表):
        if 终 - 起 <= 数值容差:
            continue
        if 出 and 起 <= 出[-1][1] + 数值容差:
            出[-1] = (出[-1][0], max(出[-1][1], 终))
        else:
            出.append((起, 终))
    return 出


def _交叠长度(甲: list[tuple[float, float]], 乙: list[tuple[float, float]]) -> float:
    总 = 0.0
    for 甲起, 甲终 in 甲:
        for 乙起, 乙终 in 乙:
            交 = min(甲终, 乙终) - max(甲起, 乙起)
            if 交 > 0.0:
                总 += 交
    return 总


def 缺口解析自检(剖面表, 方案, 缺口集合_=None) -> tuple[bool, list[str]]:
    """**口径 H「按需出动」的可核验断言**（与中继怎么调度无关）。

    (a) 逐架次：直连可用区间 ∪ 缺口区间 == 执行区间，且两者两两不相交、无遗漏；
    (b) 每架次的缺口按时间有序、两两不重叠（跨架次允许重叠 —— 那正是并发）；
    (c) 全程可直连的架次缺口数恒为 0；
    (d) 位姿采样非空、与位姿时刻等长、按时间升序、且落在缺口窗口之内。
    """
    集 = 缺口集合_ if 缺口集合_ is not None else 解析缺口(剖面表, 方案)

    段按架: dict[int, list[子段]] = {}
    for 段 in 集.子段列表:
        段按架.setdefault(段.架次序号, []).append(段)
    缺按架 = 集.按架次

    相交违规: list[str] = []
    覆盖失配: list[str] = []
    顺序违规: list[str] = []
    直连违规: list[str] = []
    位姿违规: list[str] = []
    最大差 = 0.0

    for 架 in 方案.架次列表:
        段表 = 段按架.get(架.序号, [])
        if not 段表:
            continue
        执行起 = min(段.起时刻 for 段 in 段表)
        执行终 = max(段.终时刻 for 段 in 段表)
        执行长 = 执行终 - 执行起

        直连 = _并集(
            (max(起, 执行起), min(终, 执行终))
            for 段 in 段表
            for 起, 终 in 段.可直连区间
        )
        缺口区 = _并集((缺.起时刻, 缺.终时刻) for 缺 in 缺按架.get(架.序号, []))

        交 = _交叠长度(直连, 缺口区)
        if 交 > 1e-6:
            相交违规.append(f"架次 {架.序号}：直连与缺口交叠 {交:.3e} s")

        直连长 = sum(终 - 起 for 起, 终 in 直连)
        缺长 = sum(终 - 起 for 起, 终 in 缺口区)
        差 = abs((直连长 + 缺长) - 执行长)
        最大差 = max(最大差, 差)
        if 差 > 1e-6:
            覆盖失配.append(
                f"架次 {架.序号}：直连 {直连长:.3f} + 缺口 {缺长:.3f} "
                f"vs 执行 {执行长:.3f}（差 {差:.3e} s）"
            )

        全直连 = all(段.全程可直连 for 段 in 段表)
        缺口数 = len(缺按架.get(架.序号, []))
        if 全直连 != (缺口数 == 0):
            直连违规.append(
                f"架次 {架.序号}：全程可直连 = {全直连}，但缺口数 = {缺口数}"
            )

        窗 = sorted((缺.起时刻, 缺.终时刻) for 缺 in 缺按架.get(架.序号, []))
        for (前起, 前终), (后起, 后终) in zip(窗, 窗[1:]):
            if 后起 < 前终 - 1e-6:
                顺序违规.append(
                    f"架次 {架.序号}：缺口 [{后起:.1f}, {后终:.1f}] 与 "
                    f"[{前起:.1f}, {前终:.1f}] 重叠"
                )

    for 序, 缺 in enumerate(集.缺口列表):
        if not 缺.位姿时刻:
            位姿违规.append(f"缺口 {序}：位姿时刻为空")
            continue
        if len(缺.位姿时刻) != len(缺.运输机位姿):
            位姿违规.append(f"缺口 {序}：位姿时刻与位姿长度不一致")
            continue
        if any(后 < 前 - 1e-9 for 前, 后 in zip(缺.位姿时刻, 缺.位姿时刻[1:])):
            位姿违规.append(f"缺口 {序}：位姿时刻非升序")
        if any(
            时刻 < 缺.起时刻 - 1e-6 or 时刻 > 缺.终时刻 + 1e-6
            for 时刻 in 缺.位姿时刻
        ):
            位姿违规.append(f"缺口 {序}：存在落在缺口窗口之外的位姿时刻")

    全局有序 = all(
        甲[:2] <= 乙[:2]
        for 甲, 乙 in zip(
            [(缺.起时刻, 缺.终时刻) for 缺 in 集.缺口列表],
            [(缺.起时刻, 缺.终时刻) for 缺 in 集.缺口列表][1:],
        )
    )

    通过 = not (
        相交违规 or 覆盖失配 or 顺序违规 or 直连违规 or 位姿违规
    ) and 全局有序

    def _小结(名: str, 表: list[str]) -> str:
        if not 表:
            return f"{名} 0 处"
        return f"{名} {len(表)} 处（例：{表[0]}）"

    return 通过, [
        f"[自检·缺口1] 口径 H · 直连∪缺口 == 执行区间：{len(方案.架次列表)} 个架次逐一核对，"
        f"{_小结('覆盖失配', 覆盖失配)}、{_小结('交叠违规', 相交违规)}，"
        f"最大覆盖差 {最大差:.3e} s → {'成立' if not (覆盖失配 or 相交违规) else '不成立！'}",
        f"[自检·缺口2] 缺口有序性与全直连架次：{_小结('重叠', 顺序违规)}、"
        f"{_小结('全直连判据矛盾', 直连违规)}、全局有序 = {全局有序} → "
        f"{'成立' if not (顺序违规 or 直连违规) and 全局有序 else '不成立！'}",
        f"[自检·缺口3] 位姿采样：{len(集.缺口列表)} 个缺口 / "
        f"{sum(缺.位姿数 for 缺 in 集.缺口列表)} 个位姿点，{_小结('异常', 位姿违规)} → "
        f"{'合规' if not 位姿违规 else '不合规！'}",
        f"[自检·缺口4] 规模：{集.统计.get('架次数')} 个运输架次 / "
        f"{集.缺口数} 个缺口（总 {集.总缺口时长:.0f} s）/ "
        f"{集.需中继的架次数} 个架次需中继 / {集.全直连架次数} 个全程直连；"
        f"并发峰值 {集.并发.峰值}",
    ]
