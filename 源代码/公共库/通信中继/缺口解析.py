"""
缺口解析 —— 运输方案 $\\pi$ → **通信缺口集合** $\\mathcal{G}(\\pi)$ 与**并发剖面** $N(t)$。

在整条计算链上的位置
--------------------
    运输方案 π  →  缺口集合 G(π)  →  中继需求 R(π)  →  中继方案

连续通信约束 C10 只**单向依赖**运输方案：给定 $\\pi$（含每个架次的三维时空轨迹），
缺口集合是**确定的**，与中继怎么调度无关。这是本任务"分层求解"成立的基石
（《联合调度与中继求解思路》§1.2 的可分离性）。

为什么能"解析"而不必逐时刻算 DEM
--------------------------------
Q2 的三段式位置模型使轨迹由**有限个子段**组成，每个子段的直连可用性都能**查表**判定
（表A 巡航剖面 / 表B 节点临界高度），**零 DEM 调用**：

    子段          判定依据                              可直连的充要条件
    起点爬升      表B(起点)，海拔由低到高              最低海拔（起点处）即可直连
    巡航段        表A，沿航线里程                       里程落在可用区间内
    终点下降      表B(终点)，海拔由高到低              最低海拔（终点处）即可直连
    投送交接      表B(终点)，海拔恒为作业高度           作业高度处可直连
    返航          同上，按 终点→起点 对称处理（即返程的爬升/巡航/下降）

于是整条时间轴被切成若干"可直连 / 失联"时段，合并相邻失联时段即得缺口集合。

口径
----
* 直连可用性**严格按通信规则原文**（遮挡为**加性损耗**，非硬阻断），见 `通信剖面`
  与 [`联合调度与中继求解条件.md`](../../联合调度与中继求解条件.md) §2.7 的《⚠️ 2026-09-24 更正》。
* 通信检验区间**含全程飞行 + 投送交接，不含工位固定准备**（口径 Q6）：
  故轨迹自"工位固定准备 + 每箱装载"结束的时刻起算。
* 位姿采样步长与 DEM 像元同尺度（30 m，口径 Q1）。搜索期可 `抽稀` 以控制算力，
  **最终校验一律用全采样**（`缺口.运输机位姿` 始终是全采样，抽稀显式调用）。

并发剖面与闸门 A
----------------
$N(t)$ = $t$ 时刻**处于通信缺口中的运输机数量**。按口径 D（中继一对一），
可行方案须满足 $\\max_t N(t) \\le 2$ —— 这就是"错峰"要解决的问题。
`并发下界` 另给出**与中继位置无关**的容量下界与首批时限冲突分析，供**闸门 A** 使用。

口径 H · 按需出动（2026-09-25 新增）
------------------------------------
运输机起飞后先与 $G01$ 直连，**飞出表A 的可直连里程之后才需要中继**；缺口之外的时间
中继**不需要在位**。本模块把这个口径**变成可核验的断言**（`缺口解析自检`）：

    (a) 逐架次：直连可用区间 ∪ 缺口区间 == 执行区间，且两者两两不相交、无遗漏；
    (b) 每架次的缺口按时间有序、两两不重叠（**跨架次的缺口允许重叠**，那正是并发）；
    (c) 全程可直连的架次缺口数恒为 0；
    (d) 位姿采样非空、与位姿时刻等长、按时间升序、且落在缺口窗口之内。

为什么必须有这条自检：整个问题的因果链是「缺口 = 失联区间的补集」，一旦这条不成立，
"中继只需补洞"就无从谈起，而此前没有任何检验项直接断言它。
"""
