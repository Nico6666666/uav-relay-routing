# ★ 前置条件：通信保障是运输任务的**准入条件**
# ============================================================================
# 问题设定（联合调度与中继）："运输无人机在**爬升、巡航、下降及物资投送阶段**
# 均应保持连续通信；与固定网关直连不可用时，可由空中中继无人机提供通信保障。"
#
# 本库把这句话读作**准入条件（前置条件）**，而不是事后校验的软指标：
#
#   1. **运输无人机只有在全程连续通信得到保障的前提下，才允许执行任务。**
#      通信保障不具备时，该架次**不得起飞**；方案必须通过**调整次序、切换方案**
#      （推迟开始时刻、改变访问顺序、改变组批与机型）来恢复通信保障，
#      而**不是**"带着中断飞"。
#   2. 因此交付方案中，任一运输架次在其执行区间内的实测通信状态
#      **中断时长恒为 0**（逐时刻为"直连"或"中继两段同时可用"）。
#      这是**硬约束**，不是目标项，也不参与任何权衡。
