"""
联合调度求解 —— 联合调度与中继的**外层多目标搜索**：分层编码（外层运输 ⊕ 内层中继）。

在整条求解链上的位置
--------------------
    外层：货箱组批 / 服务区访问顺序 / 机型          ← 遗传搜索（本模块）
      ↓  解码
    中层：架次开始时刻                                ← 受硬时限拦截的错峰（本模块）
      ↓
    内层：缺口解析 → 悬停站选址 → 中继包络排程        ← `中继排程.评估`（确定性 oracle）
      ↓
    评价：五目标 + 硬约束违反量                        ← `评价.评价联合方案`（已就位）

**外层只需搜"组批 / 顺序 / 机型"**：这三样决定了缺口的**相对时间结构**，
而它正是零中断能否达成的唯一杠杆（本文的零中断不可行性定理 定理 1：
严格下界只取决于缺口的时间结构，与能量、电池、充电周转无关）。

为什么错峰必须"受硬时限拦截"
----------------------------
实测（2026-09-25，多点多架次调度「最少架次数」方案，15 个运输架次）：

| 错峰步长 | 硬时限违反箱数 | 未覆盖缺口 | 严格下界 | 联合完成时间 |
|---|---|---|---|---|
| 0 s | **0** | 6 | 6 | 12791 s |
| 300 s | 6 | 4 | 4 | 13140 s |
| 900 s | 24 | 3 | 3 | 16987 s |
| 1800 s | 27 | **0** | **0** | 28113 s |

两件事同时成立：**零中断是可达的**（1800 s 时未覆盖 = 下界 = 0），
**但它与首批截止互斥**（把未覆盖压到 0 的每一步都在加深硬时限违反）。
所以本模块的错峰**一律受各架次"最紧硬截止允许的最晚开始"截住** ——
宁可留着未覆盖，也不顶破首批截止。**要同时拿到两者，只能靠外层改组批**：
把首批箱并到少数几个架次上（`构造启发式.种子_首批集中` 就是这颗种子），
其余架次才能自由铺开。

`错峰步长` 在外层扫掠
---------------------
步长是**求解器参数**（不进基因型），`求解联合` 对它逐个跑搜索并合并前沿 ——
扫出来的曲线就是任务要求的**权衡关系**：横轴是"愿意为通信可行性付出多少完成时间"。

⚠️ 并行化的调用方约定
---------------------
`进程数 > 1` 走的是 `multiprocessing` 的 **spawn**（Windows 上唯一可用），
子进程启动时会**按路径重新导入主模块**。因此**调用方必须把建池语句放在
`if __name__ == "__main__":` 保护之下**，否则子进程会再次执行建池语句并抛

    RuntimeError: An attempt has been made to start a new process before the
    current process has finished its bootstrapping phase.

`_确认主模块保护` 会在建池前先做一次源码级检查，把这条错误提前成一句可读的中文提示
（误报可忽略：它只检查 `__main__` 是否以 `if __name__` 开头，不做语法分析）。

口径
----
评价一律调用 `评价.评价联合方案`；编码与算子一律复用 `构造启发式` / `多目标求解`；
内层一律调用 `中继排程.评估`。本模块**不写任何物理、通信或评价公式**。
"""
