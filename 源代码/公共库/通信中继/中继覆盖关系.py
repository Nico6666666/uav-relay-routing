"""
中继覆盖关系 —— 「**哪些候选悬停点能覆盖哪些缺口**」的关系表（纯几何，与时刻无关）。

在整条计算链上的位置（口径 E「一对多守点覆盖」）
------------------------------------------------
    运输方案 π → 缺口集合 G(π) → **覆盖关系** → 驻留段族 → 驻留排程 → 中继方案

与口径 D 的 `中继覆盖求解.逐缺口选址` 的分工
------------------------------------------------
口径 D 每个缺口只需**一个**最优悬停站（一架中继一次只保障一架运输机，服务按站串行）；
口径 E 下一架中继悬停在一个点上是**同时**保障视野内的全部运输机，所以需要的是
「每个缺口被**哪些**点覆盖」的**集合**。本模块提供这个集合；
`中继驻留排程` 在其上做驻留段的时空集合覆盖。

为什么候选驻留点不是「全体候选点网格」
--------------------------------------
本场景里 15 个服务区全在 O01 周围 8.12 km 内，而运输机↔中继的无遮挡接入半径是
**6.27 km** —— 网格上约 **1428/2002** 个点都同时落在每个缺口的可达范围内，
按距离做必要条件剪枝几乎不起作用。若对全体网格逐缺口求最优悬停高度，
共有 **约 68,000** 个「点×缺口」对；其中**可行**的那些每个要花约 150 ms
（125 个位姿 × 31 个扫描高度，每个位姿都要做 DEM 视线判定）⇒ 单次冷启动数小时，不可行。

故本模块**刻意只评估一小撮有代表性的点**（`候选驻留点`）：

1. **全局枢纽**：候选网格上**地面海拔最高**的前 `覆盖候选枢纽数` 个。高处视线最好，
   实测定位在中间高地上的单点能覆盖全部缺口中的 **27~36 个** —— 枢纽点正是它们。
2. **逐缺口的贴身候选**：该缺口全部位姿**质心最近的**前 `每缺口候选点数` 个网格点。
   它们贴近运输机轨迹（水平距离近到必然走 `位姿集可行` 的 1.983 km 快路径），
   保证每个缺口都有近到必然可覆盖的候选点。

⚠️ **候选点集必须是缺口位姿的纯函数**（不得依赖缓存状态或整份方案）—— 见
`候选驻留点` 的警告。这是 oracle 确定性与「并行/串行逐位一致」的前提。

实测（2002 个候选点 × 33~48 个缺口）：网格只有 **256 个不同的覆盖掩码**，
一个掩码组最大含 233 个**完全等价**的点 —— 即覆盖能力有巨量冗余，
本模块的少量代表性点正是对这份冗余的利用。

缓存（**键的粒度必须等于计算依赖的粒度**）
------------------------------------------
键 = `("点覆盖" + 版本, 点序, 位姿指纹)`，值 = `(该点是否覆盖该缺口, 粗筛海拔)`。

⚠️ **为什么不按缺口整条缓存**：`_求一个缺口的覆盖` 的入参里有 `驻留点序`，而
`驻留点序 = 候选驻留点(整份缺口集合)` 依赖**整个缺口集合**、不只是这一个缺口的位姿。
若键只含「该缺口的位姿」，同一个键就会对应多个值 —— 实测 98 个复用键里 **85 个**
的值与冷算不同、**81 个**引用了不在当前 `驻留点序` 里的点。后果是：热缓存与冷缓存
给出不同的覆盖表、子进程与主进程不一致、并行与串行不一致、同一档位重跑得到不同的解。

故缓存必须下沉到「**点 × 位姿**」这一粒度：该函数**是**纯函数
（`最优悬停高度` 只依赖点、缺口位姿、离地上限），而「按 `驻留点序` 过滤」是
对缓存条目的**读时**操作，不参与缓存。

命中率与性能不降：`驻留点序` 的扫描原本就有，现在只是把 `最优悬停高度` 换成一次
dict 查找；键空间 = 唯一缺口位姿 × 每缺口驻留点数（实测唯一位姿仅数百个）。
位姿指纹不含时间 ⇒ 同一路线结构在不同开始时刻、不同错峰步长下仍然零重复计算；
缓存 dict 由调用方传入，随现有 `联合调度求解.保存站解缓存` 落盘跨运行复用。

口径与精度
----------
* 链路判定一律调用 `悬停高度.最优悬停高度`（内部走 `位姿集可行`，自带
  「水平距离 ≤ 无遮挡接入上限」的解析定界剪枝）。**本模块不写任何通信或物理公式**。
* 覆盖关系表用**粗扫描步长** `覆盖粗筛扫描步长_m` 换取速度，故它给出的悬停海拔是
  **粗筛值**：`中继驻留排程` 在装配每个入选驻留段前，必须用缺省步长重算或用
  `位姿集可行` 复核（`驻留段复核` 提供该入口）。**粗筛值不得直接作为交付值。**
"""
