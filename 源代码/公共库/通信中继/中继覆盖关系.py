# 无遮挡时的接入上限（km）—— 水平距离是三维距离的下界，故它作必要条件**不会误删可行解**
接入上限_无遮挡_km = 6.270

# 全局枢纽点数（按候选点地面海拔降序取前若干个）
覆盖候选枢纽数 = 48

# 每个缺口附加的「贴身候选」点数（按到位姿质心的水平距离升序取前若干个）
每缺口候选点数 = 4

# 覆盖关系表的粗筛扫描步长（m）。只影响粗筛粒度；交付前一律复核（见模块 docstring）
覆盖粗筛扫描步长_m = 50.0

# 覆盖缓存键的**版本号**。凡是改变「同一个键对应什么结果」的改动
# （缓存粒度、候选点集口径、粗筛步长、判定方式…）都必须递增它 —— 否则跨运行落盘的
# `.中继站解缓存.pkl` 里会留下**按旧口径算出**的条目，热缓存与冷进程给出不同结果，
# 直接表现为「并行与串行逐位一致」自检失败。
#
# v3（2026-09-26）：缓存粒度由「缺口位姿」下沉为「**点序 × 缺口位姿**」。
# v2 及更早的条目**不可复用**（其值还依赖整份缺口集合的 `驻留点序`），故前缀改为
# `点覆盖` —— 旧键即便仍在 .pkl 里也不会被命中，只是占空间。
覆盖缓存版本 = "v3"

# 覆盖缓存键的前缀（与 `中继覆盖求解` 的站解缓存共用同一个 dict，故必须可区分）
覆盖缓存前缀 = "点覆盖"


def 位姿指纹(位姿表) -> tuple:
    """缺口位姿集合的量化指纹（**不含时间**），用作跨方案缓存的键。

    与 `中继覆盖求解._位姿指纹` 同一量化口径（经/纬 5 位、海拔 1 位），
    但键带 `"覆盖"` 前缀，故两者可共用同一个缓存 dict 而不相撞。
    """
    return tuple(
        (round(位姿.经度, 5), round(位姿.纬度, 5), round(位姿.海拔, 1))
        for 位姿 in 位姿表
    )


# ===================== 候选驻留点 =====================
def 候选驻留点(
    剖面表,
    环境: 通信环境,
    缺口集合,
    候选点表=None,
    缓存: dict | None = None,
) -> tuple[int, ...]:
    """挑出用于评估覆盖关系的候选驻留点（返回**候选点表的下标**，升序）。

    两类来源，**都是缺口位姿的纯函数**（这一点是硬要求，见下方警告）：
    ① **全局枢纽** —— 候选网格上地面海拔最高的前 `覆盖候选枢纽数` 个（与缺口无关）；
    ② **逐缺口的贴身候选** —— 该缺口全部位姿的**质心最近的**前 `每缺口候选点数` 个网格点。

    ⚠️ **候选点集必须是缺口位姿的纯函数，不得依赖缓存状态或整份方案。**
    `驻留点序` 决定了覆盖表里**哪些点参与过滤**，故它一变，覆盖表就变。
    若候选点集随缓存累积而漂移（例如"补点"机制），同一个缺口在不同时刻就会得到
    不同的覆盖点集，进而**破坏 oracle 的确定性**，使「并行与串行逐位一致」自检失败。
    所以这里**刻意不用** `逐缺口选址`（它依赖整份缺口集合），也**不做补点**。
    （注：覆盖表**缓存**的键已下沉为「点 × 位姿」，不再受此影响 —— 见模块 docstring。）
    """
    场景 = 剖面表.场景
    if 候选点表 is None:
        候选点表 = 生成候选点(场景, 环境, 剖面表.网关)
    候选点表 = tuple(候选点表)

    枢纽 = sorted(
        range(len(候选点表)),
        key=lambda 序: (-候选点表[序].地面海拔, 序),
    )[:覆盖候选枢纽数]

    点经 = np.fromiter((点.经度 for 点 in 候选点表), dtype=float, count=len(候选点表))
    点纬 = np.fromiter((点.纬度 for 点 in 候选点表), dtype=float, count=len(候选点表))
    出 = set(枢纽)
    for 缺 in 缺口集合.缺口列表:
        经列 = np.fromiter((p.经度 for p in 缺.运输机位姿), dtype=float, count=缺.位姿数)
        纬列 = np.fromiter((p.纬度 for p in 缺.运输机位姿), dtype=float, count=缺.位姿数)
        经心, 纬心 = float(经列.mean()), float(纬列.mean())
        cosf = float(np.cos(np.radians(纬心)))
        dx = (点经 - 经心) * 米每度 * cosf
        dy = (点纬 - 纬心) * 米每度
        距 = np.hypot(dx, dy)
        序 = np.lexsort((np.arange(距.size), 距))[:每缺口候选点数]
        出.update(int(序_) for 序_ in 序)
    return tuple(sorted(出))


# ===================== 覆盖表 =====================
@dataclass(frozen=True)
class 覆盖表:
    """缺口 × 候选驻留点 的覆盖关系（与时刻无关，可跨方案缓存复用）。"""

    候选点表: tuple
    驻留点序: tuple[int, ...]                  # 参与评估的候选点下标（升序）
    点集表: tuple[tuple[int, ...], ...]        # 缺口序 → 覆盖它的**驻留点序**
    海拔表: dict[tuple[int, int], float]       # (点序, 缺口序) → 粗筛最小悬停海拔（绝对）
    掩码: dict[int, int]                       # 点序 → 覆盖缺口的 n 位掩码
    掩码组: dict[int, tuple[int, ...]]         # 掩码 → 同掩码的点序
    统计: dict = field(default_factory=dict)

    @property
    def 缺口数(self) -> int:
        return len(self.点集表)

    def 覆盖点数(self, 缺口序号: int) -> int:
        return len(self.点集表[缺口序号])

    def 海拔(self, 点序: int, 缺口序号: int) -> float:
        """覆盖该缺口所需的**粗筛**悬停海拔；调用方须先确认该点确实覆盖它。"""
        return self.海拔表[(点序, 缺口序号)]

    def 点覆盖数(self, 点序: int) -> int:
        return int(self.掩码.get(点序, 0).bit_count())


# ===================== 构造 =====================
def 候选覆盖表(
    剖面表,
    环境: 通信环境,
    缺口集合,
    候选点表=None,
    缓存: dict | None = None,
    驻留点序: tuple[int, ...] | None = None,
) -> 覆盖表:
    """构造缺口 × 候选驻留点 的覆盖关系表。

    `缓存` 传入同一个 dict 即可跨方案、跨运行复用（键按缺口位姿指纹）。
    """
    if 候选点表 is None:
        候选点表 = 生成候选点(剖面表.场景, 环境, 剖面表.网关)
    候选点表 = tuple(候选点表)
    if 驻留点序 is None:
        驻留点序 = 候选驻留点(剖面表, 环境, 缺口集合, 候选点表, 缓存)

    缺口表 = list(缺口集合.缺口列表)
    n = len(缺口表)
    机 = 读取中继机()
    离地上限 = 机.最大悬停离地高度_m
    网关 = 剖面表.网关
    记忆 = {} if 缓存 is None else 缓存

    点集表: list[tuple[int, ...]] = []
    海拔表: dict[tuple[int, int], float] = {}
    掩码: dict[int, int] = {}
    命中点数 = 0
    评估点数 = 0

    for 缺口序, 缺 in enumerate(缺口表):
        位姿 = tuple(缺.运输机位姿)
        点列, 高列, 本命中, 本评估 = _求一个缺口的覆盖(
            环境, 网关, 候选点表, 驻留点序, 位姿, 离地上限, 记忆,
        )
        命中点数 += 本命中
        评估点数 += 本评估

        点集表.append(点列)
        for 点序, 海拔 in zip(点列, 高列):
            掩码[点序] = 掩码.get(点序, 0) | (1 << 缺口序)
            海拔表[(点序, 缺口序)] = 海拔

    掩码组: dict[int, list[int]] = {}
    for 点序 in sorted(掩码):
        掩码组.setdefault(掩码[点序], []).append(点序)

    # `点集表` 的点只可能来自 `驻留点序`（`_求一个缺口的覆盖` 只遍历它），
    # 故并集在这里恒等于 `驻留点序`。保留它作为「点集表 ⊆ 驻留点序」这条不变量的
    # 廉价兜底 —— `覆盖下界` 的位号映射依赖它。
    全点序 = tuple(sorted(set(驻留点序) | set(掩码)))

    统计 = {
        "缺口数": n,
        "候选点数": len(候选点表),
        "评估驻留点数": len(全点序),
        "有覆盖能力的驻留点数": len(掩码),
        "不同掩码数": len(掩码组),
        "缓存命中点数": 命中点数,
        "缓存未命中点数": 评估点数 - 命中点数,
        "每缺口平均覆盖点数": (sum(len(列) for 列 in 点集表) / n) if n else 0.0,
        "粗筛扫描步长_m": 覆盖粗筛扫描步长_m,
        "几何无解缺口数": int(sum(1 for 列 in 点集表 if not 列)),
    }
    return 覆盖表(
        候选点表=候选点表,
        驻留点序=全点序,
        点集表=tuple(点集表),
        海拔表=海拔表,
        掩码=掩码,
        掩码组={位: tuple(序表) for 位, 序表 in 掩码组.items()},
        统计=统计,
    )


def _求一个缺口的覆盖(
    环境, 网关, 候选点表, 驻留点序, 位姿, 离地上限, 记忆: dict | None = None
) -> tuple[tuple[int, ...], tuple[float, ...], int, int]:
    """在给定的驻留点集合里，求能覆盖该缺口的点（按点序升序）。

    先用 numpy 做**必要条件剪枝**：候选点到该缺口**每一个**位姿的水平距离都必须
    ≤ 无遮挡接入上限（水平距离是三维距离的下界，故该剪枝不会误删可行解）。
    幸存的点再调用 `最优悬停高度`（**粗扫描步长**）求粗筛海拔。

    `记忆` 非空时，**逐点**缓存 `(点序, 位姿指纹) → (是否覆盖, 粗筛海拔)`。
    缓存的是**纯函数**的结果（只依赖点、位姿、离地上限），
    而「按 `驻留点序` 过滤」发生在读时 —— 故此函数对任意 `驻留点序` 都给出一致结果，
    与缓存是否命中、历史如何无关（见模块 docstring 的「缓存」一节）。

    返回 `(覆盖点序, 对应粗筛海拔, 缓存命中点数, 参与评估点数)`。
    """
    经列 = np.fromiter((位姿_.经度 for 位姿_ in 位姿), dtype=float, count=len(位姿))
    纬列 = np.fromiter((位姿_.纬度 for 位姿_ in 位姿), dtype=float, count=len(位姿))
    cosf = float(np.cos(np.radians(纬列.mean())))

    出序: list[int] = []
    出高: list[float] = []
    命中 = 0
    评估 = 0
    任务 = 覆盖任务(运输机位姿=tuple(位姿), 说明=f"缺口（{len(位姿)} 个位姿）")
    指纹 = 位姿指纹(位姿)
    for 点序 in 驻留点序:
        点 = 候选点表[点序]
        dx = (点.经度 - 经列) * 米每度 * cosf
        dy = (点.纬度 - 纬列) * 米每度
        if float(np.max(np.hypot(dx, dy))) > 接入上限_无遮挡_km * 1000.0:
            continue
        评估 += 1
        键 = (f"{覆盖缓存前缀}{覆盖缓存版本}", 点序, 指纹)
        记 = None if 记忆 is None else 记忆.get(键)
        if 记 is None:
            果 = 最优悬停高度(
                环境, 点.经度, 点.纬度, 任务, 离地上限, 网关,
                扫描步长_m=覆盖粗筛扫描步长_m,
            )
            记 = (bool(果.可行), float(果.最优海拔) if 果.可行 else None)
            if 记忆 is not None:
                记忆[键] = 记
        else:
            命中 += 1
        if 记[0]:
            出序.append(点序)
            出高.append(记[1])
    return tuple(出序), tuple(出高), 命中, 评估
