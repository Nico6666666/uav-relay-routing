"""
多目标求解 —— 自研的非支配分层遗传算法（多点多架次调度的四目标搜索内核）。

**联合调度与中继的复用方式（2026-09-25）**：算法骨架、算子、支配规则全部复用，只把
「染色体 → 个体」这一步换成**联合评价器**（`联合调度求解.构造联合评价器`），
从而在相同的搜索框架上跑**五目标 + 通信准入条件**。两处注入点即上面改动范围 ②。

搜索空间与编码（详见 `构造启发式`）：

    染色体 = (载荷包, 载荷包, …)      载荷包 = (箱表, 访问顺序)
    解码   = 修复不可行包 → 机队均衡指派机型 → 调度（无人机/电池/时刻）→ 评价

算法骨架（教科书式的 NSGA-II 结构，实现与算子均按本工作自研）：

    初始种群：`构造启发式.构造种子` 给出的确定性解 + 在其上的固定种子扰动
    选择     二元锦标赛（比较键：非支配等级 → 拥挤距离）
    交叉     架次级交叉（整包继承父 A 的子集，其余箱按父 B 的归属补齐）
    变异     移箱 / 换箱 / 合并 / 拆分 / 顺序 2-opt（轮转）
    环境选择 父代+子代合并 → 快速非支配分层 → 拥挤距离截断 → 精英保留

确定性：全部随机性来自一个显式 `random.Random(随机种子)`，调用顺序固定，
因此同一份输入必然得到同一份输出。

约束处理：
    * **结构性约束**（载质量 / 装载体积 / 返航安全余量）由解码的修复算子保证，
      任何个体的每个架次都必定满足；
    * **硬时限**（首批截止时间、医疗期望时间）与 **资源不重叠** 不由修复保证，
      而由 `可行性检验` 在评价时统计超出量，再用 **Deb 约束支配** 参与选择
      （可行解支配不可行解；不可行解之间比超出量）。因此不需要罚系数调参，
      前沿上也**不会**出现"用违约换延误"的解。
"""
