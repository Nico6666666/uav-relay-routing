# ===================== 个体 =====================
@dataclass
class 个体:
    """一个解：染色体 + 四目标 + 硬约束违反量。

    `目标向量` 恒为**未加罚**的真实四目标；硬时限通过 `违反量` 与
    `约束支配` 参与选择（见 `_约束支配`），不从目标里扣分。
    """

    包序列: tuple[载荷包, ...]
    目标向量: tuple
    评价: 评价结果
    违反量: float = 0.0
    等级: int = 0
    拥挤距离: float = 0.0
    # 产出这个个体的**错峰步长**（联合调度与中继五目标联合搜索用；多点多架次调度的四目标路径恒为 None）。
    # ⚠️ 必须记在个体上，不能用「包序列 → 步长」反查：同一条包序列在不同错峰步长下
    # 会算出**不同的目标向量**（步长改最早下界表 ⇒ 改调度 ⇒ 改完成时间/能耗），
    # 故跨步长合并后同一个包序列可能对应多个存档成员，反查表只能表示其中一个，
    # 会让「搜索时评价 → 独立重算」的一致性自检误报（实测偏差 2.9e-02）。
    来源步长: float | None = None

    @property
    def 是否可行(self) -> bool:
        return self.违反量 <= 硬约束容差_s


def 构建方案(场景, 包序列: tuple[载荷包, ...]) -> 全局方案:
    """把染色体还原为完整方案（架次 + 调度）。"""
    架次列表 = 解码(场景, 包序列)
    方案 = 全局方案(架次列表=架次列表)
    方案.调度表 = 调度架次(场景, 架次列表)
    return 方案


def 评价染色体(场景, 包序列: tuple[载荷包, ...]) -> 个体:
    """解码 + 调度 + 评价，得到真实四目标与硬约束违反量。"""
    方案 = 构建方案(场景, 包序列)
    评价 = 评价方案(场景, 方案)
    return 个体(
        包序列=包序列,
        目标向量=评价.目标向量,
        评价=评价,
        违反量=评价.硬约束超出量,
    )


# ===================== 支配关系（Deb 约束支配）=====================
def _支配(甲: tuple, 乙: tuple) -> bool:
    if any(a > b + 数值容差 for a, b in zip(甲, 乙)):
        return False
    return any(a < b - 数值容差 for a, b in zip(甲, 乙))


def _约束支配(甲: "个体", 乙: "个体") -> bool:
    """Deb 约束支配：可行支配不可行；同为不可行则比超出量；同可行则比 Pareto。"""
    甲可行 = 甲.是否可行
    乙可行 = 乙.是否可行
    if 甲可行 and not 乙可行:
        return True
    if 乙可行 and not 甲可行:
        return False
    if not 甲可行 and not 乙可行:
        return 甲.违反量 < 乙.违反量 - 硬约束容差_s
    return _支配(甲.目标向量, 乙.目标向量)


def 非支配分层(群体: list[个体]) -> list[list[个体]]:
    """按 Deb 约束支配做快速非支配分层（第 0 层即当前前沿）。"""
    n = len(群体)
    被支配数 = [0] * n
    支配集: list[list[int]] = [[] for _ in range(n)]
    层: list[list[int]] = [[]]

    for i in range(n):
        for j in range(i + 1, n):
            if _约束支配(群体[i], 群体[j]):
                支配集[i].append(j)
                被支配数[j] += 1
            elif _约束支配(群体[j], 群体[i]):
                支配集[j].append(i)
                被支配数[i] += 1

    for i in range(n):
        if 被支配数[i] == 0:
            群体[i].等级 = 0
            层[0].append(i)

    当前 = 0
    while 层[当前]:
        下一层: list[int] = []
        for i in 层[当前]:
            for j in 支配集[i]:
                被支配数[j] -= 1
                if 被支配数[j] == 0:
                    群体[j].等级 = 当前 + 1
                    下一层.append(j)
        当前 += 1
        层.append(下一层)
    层.pop()
    return [[群体[i] for i in 序号] for 序号 in 层]


def 计算拥挤距离(前沿: list[个体]) -> None:
    """按目标逐个排序累加邻接间距（首尾记为无穷大），写回 `拥挤距离`。

    同一层内可行性一致（约束支配的推论）：若该层全为不可行解，
    则改用**硬约束超出量**作为唯一的拥挤度维度。
    """
    if not 前沿:
        return
    for 个 in 前沿:
        个.拥挤距离 = 0.0

    if not 前沿[0].是否可行:
        排序 = sorted(前沿, key=lambda x: x.违反量)
        排序[0].拥挤距离 = float("inf")
        排序[-1].拥挤距离 = float("inf")
        跨度 = 排序[-1].违反量 - 排序[0].违反量
        if 跨度 <= 硬约束容差_s:
            return
        for k in range(1, len(排序) - 1):
            排序[k].拥挤距离 += (排序[k + 1].违反量 - 排序[k - 1].违反量) / 跨度
        return

    目标数 = len(前沿[0].目标向量)
    for 目 in range(目标数):
        排序 = sorted(前沿, key=lambda x: x.目标向量[目])
        排序[0].拥挤距离 = float("inf")
        排序[-1].拥挤距离 = float("inf")
        跨度 = 排序[-1].目标向量[目] - 排序[0].目标向量[目]
        if 跨度 <= 数值容差:
            continue
        for k in range(1, len(排序) - 1):
            排序[k].拥挤距离 += (
                排序[k + 1].目标向量[目] - 排序[k - 1].目标向量[目]
            ) / 跨度


# ===================== 选择 =====================
def 二元锦标赛(群体: list[个体], 随机: random.Random) -> 个体:
    """二元锦标赛：先比等级、再比拥挤距离（距大者优）。"""
    甲 = 群体[随机.randrange(len(群体))]
    乙 = 群体[随机.randrange(len(群体))]
    if 甲.等级 != 乙.等级:
        return 甲 if 甲.等级 < 乙.等级 else 乙
    if abs(甲.拥挤距离 - 乙.拥挤距离) > 数值容差:
        return 甲 if 甲.拥挤距离 > 乙.拥挤距离 else 乙
    return 甲


# ===================== 交叉与变异 =====================
def 架次级交叉(
    场景,
    甲: tuple[载荷包, ...],
    乙: tuple[载荷包, ...],
    随机: random.Random,
) -> tuple[载荷包, ...]:
    """架次级交叉：整包继承父 A 的一个随机子集，其余箱按父 B 的归属补齐。

    该算子**不会丢箱也不会重复**：先取 A 的若干整包，再从 B 的包中剔除已被覆盖的箱，
    残余部分原样保留（空包丢弃）。
    """
    if len(甲) <= 1:
        return 甲
    选取数 = 随机.randint(1, max(1, len(甲) - 1))
    继承序号 = sorted(随机.sample(range(len(甲)), 选取数))
    继承 = tuple(甲[i] for i in 继承序号)
    已覆盖 = {编号 for 包 in 继承 for 编号 in 包.箱编号列表}

    残余: list[载荷包] = []
    for 包 in 乙:
        箱区: dict[str, list[str]] = {}
        for 区, 箱编号s in 包.箱表:
            留 = [b for b in 箱编号s if b not in 已覆盖]
            if 留:
                箱区[区] = 留
        if 箱区:
            残余.append(建包(场景, 箱区))

    return tuple(修复(场景, list(继承) + 残余))


def _移除箱(箱表: tuple, 箱编号: str) -> dict[str, list[str]]:
    箱区 = {区: [b for b in 箱编号s if b != 箱编号] for 区, 箱编号s in 箱表}
    return {区: v for 区, v in 箱区.items() if v}


def 移箱变异(场景, 包序列: tuple[载荷包, ...], 随机: random.Random) -> tuple[载荷包, ...]:
    """把一个货箱从它的包移到另一个包（或独立成包）。"""
    源序 = 随机.randrange(len(包序列))
    源 = 包序列[源序]
    编号列表 = list(源.箱编号列表)
    箱编号 = 编号列表[随机.randrange(len(编号列表))]
    箱 = 场景.取货箱(箱编号)
    区 = 箱["服务区编号"]

    新序列 = [p for i, p in enumerate(包序列) if i != 源序]
    剩余 = _移除箱(源.箱表, 箱编号)
    if 剩余:
        新序列.append(建包(场景, 剩余))

    if 新序列 and 随机.random() < 0.7:
        目标序 = 随机.randrange(len(新序列))
        目标 = 新序列[目标序]
        箱区 = {k: list(v) for k, v in 目标.箱表}
        箱区[区] = 箱区.get(区, []) + [箱编号]
        新序列[目标序] = 换箱表(场景, 目标, 箱区)
    else:
        新序列.append(建包(场景, {区: [箱编号]}))
    return 修复(场景, 新序列)


def 换箱变异(场景, 包序列: tuple[载荷包, ...], 随机: random.Random) -> tuple[载荷包, ...]:
    """在两个包之间交换一个货箱。"""
    if len(包序列) < 2:
        return 包序列
    i, j = 随机.sample(range(len(包序列)), 2)
    甲, 乙 = 包序列[i], 包序列[j]
    甲箱 = list(甲.箱编号列表)
    乙箱 = list(乙.箱编号列表)
    if not 甲箱 or not 乙箱:
        return 包序列
    出甲 = 甲箱[随机.randrange(len(甲箱))]
    出乙 = 乙箱[随机.randrange(len(乙箱))]

    def 换(包: 载荷包, 去: str, 来: str) -> 载荷包:
        箱区 = {k: list(v) for k, v in 包.箱表}
        区去 = 场景.取货箱(去)["服务区编号"]
        区来 = 场景.取货箱(来)["服务区编号"]
        箱区[区去] = [b for b in 箱区[区去] if b != 去]
        箱区[区来] = sorted(箱区.get(区来, []) + [来])
        return 换箱表(场景, 包, {k: v for k, v in 箱区.items() if v})

    新 = list(包序列)
    新[i] = 换(甲, 出甲, 出乙)
    新[j] = 换(乙, 出乙, 出甲)
    return 修复(场景, 新)


def 合并变异(场景, 包序列: tuple[载荷包, ...], 随机: random.Random) -> tuple[载荷包, ...]:
    """随机合并两个包（不做可行性判断，交给修复算子处理）。"""
    if len(包序列) < 2:
        return 包序列
    i, j = 随机.sample(range(len(包序列)), 2)
    箱区: dict[str, list[str]] = {k: list(v) for k, v in 包序列[i].箱表}
    for k, v in 包序列[j].箱表:
        箱区[k] = 箱区.get(k, []) + list(v)
    合并 = 建包(场景, 箱区)
    return 修复(场景, [p for k, p in enumerate(包序列) if k not in (i, j)] + [合并])


def 拆分变异(场景, 包序列: tuple[载荷包, ...], 随机: random.Random) -> tuple[载荷包, ...]:
    """把一个包随机切成两个包。"""
    候选 = [i for i, p in enumerate(包序列) if p.总箱数 >= 2]
    if not 候选:
        return 包序列
    序 = 候选[随机.randrange(len(候选))]
    包 = 包序列[序]
    编号列表 = sorted(包.箱编号列表)
    随机.shuffle(编号列表)
    切点 = 随机.randint(1, len(编号列表) - 1)
    组甲: dict[str, list[str]] = {}
    组乙: dict[str, list[str]] = {}
    for 位, b in enumerate(编号列表):
        区 = 场景.取货箱(b)["服务区编号"]
        桶 = 组甲 if 位 < 切点 else 组乙
        桶.setdefault(区, []).append(b)
    新 = [p for k, p in enumerate(包序列) if k != 序]
    新.extend([建包(场景, 组甲), 建包(场景, 组乙)])
    return 修复(场景, 新)


def 顺序变异(场景, 包序列: tuple[载荷包, ...], 随机: random.Random) -> tuple[载荷包, ...]:
    """对某个包的访问顺序做一次 2-opt 反转；单点时改成整包重优化。"""
    候选 = [i for i, p in enumerate(包序列) if p.服务区数 >= 2]
    if not 候选:
        if not 包序列:
            return 包序列
        序 = 随机.randrange(len(包序列))
        包 = 包序列[序]
        新 = list(包序列)
        新[序] = 载荷包(箱表=包.箱表, 访问顺序=优化访问顺序(场景, 包.箱表))
        return tuple(新)

    序 = 候选[随机.randrange(len(候选))]
    包 = 包序列[序]
    顺序 = list(包.访问顺序)
    i, j = sorted(随机.sample(range(len(顺序)), 2))
    新顺序 = tuple(顺序[:i] + 顺序[i : j + 1][::-1] + 顺序[j + 1 :])
    新 = list(包序列)
    新[序] = 载荷包(箱表=包.箱表, 访问顺序=新顺序)
    return tuple(新)


变异算子表 = (移箱变异, 换箱变异, 合并变异, 拆分变异, 顺序变异)


def 变异(场景, 包序列: tuple[载荷包, ...], 随机: random.Random) -> tuple[载荷包, ...]:
    算子 = 变异算子表[随机.randrange(len(变异算子表))]
    return tuple(算子(场景, 包序列, 随机))


