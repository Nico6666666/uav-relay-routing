# ===================== 区间代数（通信覆盖的时间轴运算）=====================
def _并区间(区间表) -> tuple[tuple[float, float], ...]:
    """合并重叠或相接的区间，按起点升序返回（空区间被丢弃）。"""
    出: list[list[float]] = []
    for 起, 终 in sorted((min(a, b), max(a, b)) for a, b in 区间表):
        if 终 <= 起 + 数值容差:
            continue
        if 出 and 起 <= 出[-1][1] + 数值容差:
            出[-1][1] = max(出[-1][1], 终)
        else:
            出.append([起, 终])
    return tuple((起, 终) for 起, 终 in 出)


def _区间补集(
    总区间: tuple[float, float], 覆盖区间表
) -> tuple[tuple[float, float], ...]:
    """`总区间` 内未被 `覆盖区间表`（按并集理解）覆盖的部分。"""
    起总, 终总 = 总区间
    if 终总 - 起总 <= 数值容差:
        return ()
    出: list[tuple[float, float]] = []
    游标 = 起总
    for 起, 终 in _并区间(覆盖区间表):
        起 = max(起, 起总)
        终 = min(终, 终总)
        if 终 <= 起 + 数值容差:
            continue
        if 起 > 游标 + 数值容差:
            出.append((游标, 起))
        游标 = max(游标, 终)
        if 游标 >= 终总 - 数值容差:
            break
    if 游标 < 终总 - 数值容差:
        出.append((游标, 终总))
    return tuple(出)


# ===================== 轨迹展开与位姿重建 =====================
def _架次子段表(剖面表, 方案) -> dict[int, list]:
    """逐架次展开轨迹，并**查表**给出每个子段的绝对时刻直连可用区间。

    这一步**零 DEM 调用**（表A 判巡航里程、表B 判节点海拔），是"何时需要中继"
    的判定依据；它不依赖任何中继信息，故 ⑩ 的覆盖判据是单向的、不循环的。
    """
    场景 = 剖面表.场景
    出: dict[int, list] = {}
    for 架 in 方案.架次列表:
        记录 = 方案.调度表.get(架.序号)
        if 记录 is None:
            continue
        出[架.序号] = [
            replace(段, 可直连区间=判定子段可用(剖面表, 场景, 段))
            for 段 in 展开架次轨迹(场景, 架, 记录.开始时刻)
        ]
    return 出


def _执行区间(子段表: list) -> tuple[float, float] | None:
    """一个架次的通信检验区间（口径 Q6：含全程飞行 + 投送交接，不含地面准备）。"""
    if not 子段表:
        return None
    return (
        min(段.起时刻 for 段 in 子段表),
        max(段.终时刻 for 段 in 子段表),
    )


def _位姿_at(场景, 子段表: list, 时刻: float) -> 通信端点 | None:
    """按 Q2 三段式位置模型重建 `时刻` 的运输机位姿（两端点亦由此补齐）。"""
    最佳 = None
    for 段 in 子段表:
        if 段.起时刻 - 数值容差 <= 时刻 <= 段.终时刻 + 数值容差:
            最佳 = 段
            break
    if 最佳 is None:
        return None
    比例 = 0.0 if 最佳.时长 <= 数值容差 else (时刻 - 最佳.起时刻) / 最佳.时长
    比例 = min(max(比例, 0.0), 1.0)
    海拔 = 最佳.海拔起 + 比例 * (最佳.海拔终 - 最佳.海拔起)
    经度甲, 纬度甲 = 节点水平坐标(场景, 最佳.起点节点)
    if 最佳.垂直段:
        return 运输机端点(经度甲, 纬度甲, 海拔)
    经度乙, 纬度乙 = 节点水平坐标(场景, 最佳.终点节点)
    return 运输机端点(
        经度甲 + 比例 * (经度乙 - 经度甲),
        纬度甲 + 比例 * (纬度乙 - 纬度甲),
        海拔,
    )


def _服务区间位姿(场景, 子段表: list, 起: float, 终: float) -> list:
    """`[起, 终]` 内的运输机采样位姿（30 m 沿程采样，并显式补上两端点）。

    采样口径与 `缺口解析` 一致（Q1：与 DEM 像元同尺度），故复核用的位姿与
    "缺口是怎么算出来的"用的是同一把尺子。
    """
    记录: list[tuple[float, 通信端点]] = []
    for 段 in 子段表:
        重叠起 = max(段.起时刻, 起)
        重叠终 = min(段.终时刻, 终)
        if 重叠终 - 重叠起 <= 数值容差:
            continue
        记录.extend(子段位姿(场景, 段, 重叠起, 重叠终))
    for 端点时刻 in (起, 终):
        位姿 = _位姿_at(场景, 子段表, 端点时刻)
        if 位姿 is not None:
            记录.append((端点时刻, 位姿))

    记录.sort(key=lambda 项: 项[0])
    去重: list[tuple[float, 通信端点]] = []
    for 项 in 记录:
        if 去重 and abs(项[0] - 去重[-1][0]) <= 1e-6:
            continue
        去重.append(项)
    return 去重


# ===================== ①⑩ 通信连续性（C10）=====================
@dataclass(frozen=True)
class 通信明细:
    """一个运输架次的通信覆盖明细（⑩ 的逐架次证据，供主程序落盘）。"""

    架次序号: int
    执行区间: tuple[float, float]
    直连区间: tuple[tuple[float, float], ...]
    中继区间: tuple[tuple[float, float], ...]
    未覆盖区间: tuple[tuple[float, float], ...]
    保障站数: int
    链路复核点数: int

    @property
    def 未覆盖时长(self) -> float:
        return sum(终 - 起 for 起, 终 in self.未覆盖区间)

    @property
    def 执行时长(self) -> float:
        return self.执行区间[1] - self.执行区间[0]


def _检验_通信连续性(
    剖面表, 环境: 通信环境, 联合, 全采样复核: bool
) -> tuple[检验项, list[通信明细], list[str]]:
    """C10：每个运输架次在其执行区间内，任意时刻都有可用链路。

    覆盖来源 = ① 直连可用区间（查表）∪ ② 中继保障区间（保障记录的服务时段）。
    二者都不覆盖的时段即**中断**，按"中断总时长 + 中断段数"计违反。

    `全采样复核` 为真时，另对每条保障记录的服务区间逐位姿调用真实 `通信模型`
    复核 `中继两段可用`（运输机↔接入端 与 回传端↔G01 **同时**可用）。
    """
    场景 = 剖面表.场景
    网关 = 环境.网关端点(场景)
    子段表 = _架次子段表(剖面表, 联合.运输方案)

    按架次保障: dict[int, list] = {}
    for 条 in 联合.中继方案.保障记录:
        按架次保障.setdefault(条.运输架次序号, []).append(条)

    明细: list[通信明细] = []
    违反: list[str] = []
    链路失败: list[str] = []
    未覆盖总时长 = 0.0
    未覆盖架次数 = 0

    for 序号 in sorted(子段表):
        段表 = 子段表[序号]
        区间 = _执行区间(段表)
        if 区间 is None:
            continue
        直连区间 = _并区间([区间 for 段 in 段表 for 区间 in 段.可直连区间])
        保障表 = 按架次保障.get(序号, [])
        中继区间 = _并区间([(条.起时刻, 条.终时刻) for 条 in 保障表])
        未覆盖 = _区间补集(区间, list(直连区间) + list(中继区间))

        if 未覆盖:
            未覆盖架次数 += 1
            时长 = sum(终 - 起 for 起, 终 in 未覆盖)
            未覆盖总时长 += 时长
            违反.append(
                f"架次#{序号} 中断 {len(未覆盖)} 段共 {时长:.1f}s"
                f"（首段 {未覆盖[0][0]:.1f}~{未覆盖[0][1]:.1f}s）"
            )

        复核点数 = 0
        if 全采样复核:
            for 条 in 保障表:
                for 时刻, 位姿 in _服务区间位姿(场景, 段表, 条.起时刻, 条.终时刻):
                    复核点数 += 1
                    中继位置 = 通信端点(
                       类型=端点_中继接入端, 经度=条.悬停经度,
                       纬度=条.悬停纬度, 海拔=条.悬停海拔,
                    )
                    if 环境.中继两段可用(网关, 位姿, 中继位置):
                        continue
                    链路失败.append(
                        f"架次#{序号} t={时刻:.1f}s 保障记#{条.缺口序号}"
                        f"（中继架次#{条.中继架次序号} 站{条.站序}）：两段链路未同时可用"
                    )

        明细.append(
            通信明细(
                架次序号=序号, 执行区间=区间,
                直连区间=直连区间, 中继区间=中继区间, 未覆盖区间=未覆盖,
                保障站数=len(保障表), 链路复核点数=复核点数,
            )
        )

    违反数 = len(违反) + len(链路失败)
    说明 = (
        f"前置条件（C10）：{len(子段表)} 个架次的执行区间内，直连 ∪ 中继须覆盖全程；"
        f"实测中断 {未覆盖架次数} 个架次共 {未覆盖总时长:.1f}s"
    )
    if 全采样复核:
        说明 += f"；中继链路逐位姿复核 {sum(条.链路复核点数 for 条 in 明细)} 点"
    样例 = (违反 + 链路失败)[:5]
    return 检验项("⑩ 通信连续性", 违反数, 说明, 样例), 明细, 链路失败


# ===================== ⑪ 中继独占（C11）=====================
def _检验_中继独占(联合) -> 检验项:
    """C11：**运输机侧**的独占 —— 同一运输架次在同一时刻至多被 **1 架** 中继保障。

    这正是通信规则的原文：
        「**每架运输无人机**在任一时刻只能由 G01 或一架中继无人机提供通信保障」
    （它排除的是"一架运输机同时接两架中继"与中继多跳，**不是**"一架中继只能服务一架
    运输机"）。

    判据 (a) 检查：同一运输架次的两条保障记录时间不得重叠。**两种口径下都成立**
    （一个缺口的窗口内每时刻只需一条记录；同一架次的两个缺口彼此不重叠）。

    ⚠️ **判据 (b) ——「同一中继机同一时刻只能保障 1 架运输机」—— 只在口径 D
    成立，已按口径 E 移除。** 口径 E（一对多守点覆盖，默认）下，一架中继悬停在一个
    点上**同时**保障视野内的多架运输机是**合法且正是设计意图**；问题定义没有给出任何带宽 /
    信道数 / 干扰参数，链路判定是逐条链路的，故没有任何依据限制一架中继的服务对象数。
    残留的判据 (b) 会把每一个一对多方案全判为违反（实测：成功方案被判 25 处违反）。
    真正的独占性约束由 (a) 承担；一对多下的**中继侧**占用合法性由 ⑯（同一架次内
    各站驻留窗不重叠 + 轨道周转）与 ⑮（同一中继机架次不重叠）承担。
    """
    违反: list[str] = []

    按架次: dict[int, list] = {}
    for 条 in 联合.中继方案.保障记录:
        按架次.setdefault(条.运输架次序号, []).append(条)

    for 序号, 记录表 in 按架次.items():
        有序 = sorted(记录表, key=lambda 条: (条.起时刻, 条.终时刻))
        for 前, 后 in zip(有序, 有序[1:]):
            if 后.起时刻 < 前.终时刻 - 数值容差:
                违反.append(
                    f"架次#{序号} 在 {后.起时刻:.1f}s 同时被中继架次#{前.中继架次序号}"
                    f"与#{后.中继架次序号} 保障"
                )

    return 检验项(
        "⑪ 中继独占",
        len(违反),
        "每架运输机每时刻至多被 1 架中继保障（通信规则原文；一架中继可同时保障多架）："
        f"{len(联合.中继方案.保障记录)} 条保障关系、"
        f"{len({条.中继机编号 for 条 in 联合.中继方案.保障记录})} 架中继",
        违反[:5],
    )


# ===================== ⑫ 禁止中继多跳（C12）=====================
def _检验_中继多跳(
    剖面表, 环境: 通信环境, 联合, 子段表: dict[int, list], 全采样复核: bool
) -> 检验项:
    """C12：只允许"运输机—中继—G01"两段，**回传段必须直连固定网关**。

    本模型结构上不存在中继—中继链路（`通信模型.中继两段可用` 只构造两段），
    故本项是**回归护栏**：验证每条保障记录的**回传段单独可用**，
    即中继确实直连 G01，而不是靠某个隐含的第三跳补上余量。
    """
    场景 = 剖面表.场景
    网关 = 环境.网关端点(场景)
    违反: list[str] = []

    for 条 in 联合.中继方案.保障记录:
        段表 = 子段表.get(条.运输架次序号)
        if 段表 is None:
            continue
        回传 = 通信端点(
            类型=端点_中继回传端, 经度=条.悬停经度,
            纬度=条.悬停纬度, 海拔=条.悬停海拔,
        )
        极点 = [
            (条.起时刻, _位姿_at(场景, 段表, 条.起时刻)),
            (条.终时刻, _位姿_at(场景, 段表, 条.终时刻)),
            (
                0.5 * (条.起时刻 + 条.终时刻),
                _位姿_at(场景, 段表, 0.5 * (条.起时刻 + 条.终时刻)),
            ),
        ]
        if 全采样复核:
            极点 += _服务区间位姿(场景, 段表, 条.起时刻, 条.终时刻)
        for 时刻, 位姿 in 极点:
            if 位姿 is None:
                continue
            if not 环境.链路可用(回传, 网关):
                违反.append(
                    f"架次#{条.运输架次序号} t={时刻:.1f}s：中继回传端↔G01 不可用"
                    f"（保障记#{条.缺口序号}）"
                )
                break

    return 检验项(
        "⑫ 禁止中继多跳",
        len(违反),
        f"保障链路恰为「运输机—中继—G01」两段，回传段直连网关"
        f"（{len(联合.中继方案.保障记录)} 条保障关系"
        f"{'，逐位姿复核' if 全采样复核 else '，取起/中/终三点复核'}）",
        违反[:5],
    )


# ===================== ⑬ 中继悬停几何（C6/C7）=====================
def _检验_中继悬停几何(环境: 通信环境, 联合) -> 检验项:
    """C6：悬停点落在 DEM 有效范围内；C7：悬停离地高度 ≤ 数据文件上限（300 m）。"""
    机 = 读取中继机()
    违反: list[str] = []
    最远离地 = 0.0
    站数 = 0

    for 架 in 联合.中继方案.架次列表:
        for 站 in 架.站序列:
            站数 += 1
            地面 = 环境.地面高程_at(站.经度, 站.纬度)
            if not (地面 == 地面):
                违反.append(
                    f"中继架次#{架.序号} 站（{站.经度:.5f},{站.纬度:.5f}）落在 DEM 外"
                )
                continue
            if abs(地面 - 站.地面海拔) > 1e-6:
                违反.append(
                    f"中继架次#{架.序号} 站记录地面海拔 {站.地面海拔:.2f} m "
                    f"与 DEM {地面:.2f} m 不符"
                )
            离地 = 站.悬停海拔 - 地面
            最远离地 = max(最远离地, 离地)
            if 离地 < -数值容差:
                违反.append(f"中继架次#{架.序号} 站悬停海拔低于地面 {离地:.2f} m")
            elif 离地 > 机.最大悬停离地高度_m + 数值容差:
                违反.append(
                    f"中继架次#{架.序号} 站离地 {离地:.2f} m "
                    f"> 上限 {机.最大悬停离地高度_m:.0f} m（违反 C7）"
                )

    return 检验项(
        "⑬ 中继悬停几何",
        len(违反),
        f"悬停点在 DEM 内且离地 ≤ {机.最大悬停离地高度_m:.0f} m；"
        f"{站数} 个悬停站，最大离地 {最远离地:.2f} m",
        违反[:5],
    )


# ===================== ⑭ 中继返航电量（C5）=====================
def _检验_中继返航电量(剖面表, 环境: 通信环境, 联合) -> 检验项:
    """C5：E_R^总 ≤ (1−ρ_R)·E_R^use = 2.56 kWh，并复核架次的时间/能量闭合。

    闭合复核的做法：**用架次记录的站序列与起飞时刻重算一遍**
    `中继架次代价计算`，与记录的代价逐项比对 —— 任何被篡改的站位置、时刻或
    能耗都会在这里暴露，而不是靠记录自证。
    """
    机 = 读取中继机()
    中心 = 剖面表.场景.调度中心
    中心经度, 中心纬度 = 中心["经度"], 中心["纬度"]
    中心作业高度 = 中心["海拔"] + 调度中心作业高度增量_m
    违反: list[str] = []
    最大使用率 = 0.0

    for 架 in 联合.中继方案.架次列表:
        最大使用率 = max(最大使用率, 架.代价.能量上限占用率)
        if not 架.代价.满足返航电量:
            违反.append(
                f"中继架次#{架.序号} 能耗 {架.总能耗:.4f} kWh > "
                f"可用 {机.架次能量上限_kWh:.4f} kWh"
            )
        结束SOC = 1.0 - 架.总能耗 / 机.能源组件可用能量_kWh
        if abs(结束SOC - 架.代价.结束SOC) > 1e-9:
            违反.append(f"中继架次#{架.序号} 结束SOC 与能耗不一致")
        try:
            重算 = 中继架次代价计算(
                环境, 机, 架.站序列, 架.起飞时刻,
                中心经度, 中心纬度, 中心作业高度,
            )
        except ValueError as 错:
            # 建链/转场时序问题在 ⑯ 中单独定位；这里只记闭合失败
            违反.append(f"中继架次#{架.序号} 站序列无法在给定起飞时刻闭合：{错}")
            continue
        if abs(重算.总时长 - 架.代价.总时长) > 1e-6:
            违反.append(
                f"中继架次#{架.序号} 总时长闭合偏差 "
                f"{abs(重算.总时长 - 架.代价.总时长):.3e} s"
            )
        if abs(重算.总能耗 - 架.代价.总能耗) > 1e-9:
            违反.append(
                f"中继架次#{架.序号} 总能耗闭合偏差 "
                f"{abs(重算.总能耗 - 架.代价.总能耗):.3e} kWh"
            )

    return 检验项(
        "⑭ 中继返航电量",
        len(违反),
        f"每架次 E_R^总 ≤ (1−ρ_R)·E_R^use = {机.架次能量上限_kWh:.4f} kWh，"
        f"并逐架次重算站序列复核时间/能量闭合；"
        f"{联合.中继方案.架次数} 个中继架次，最大能量上限占用率 {最大使用率:.4f}",
        违反[:5],
    )


# ===================== ⑮ 中继机与能源组件可用性（C16/C14）=====================
def _检验_中继资源(联合) -> 检验项:
    """C16：同一中继机架次不重叠、相邻架次间 ≥ 300 s 周转。
    C14：能源组件占用不重叠、充至 100% 才复用。
    """
    机 = 读取中继机()
    池 = 构造中继资源()
    违反: list[str] = []

    # —— 中继机可用性（C16）——
    按中继: dict[str, list] = {}
    for 架 in 联合.中继方案.架次列表:
        按中继.setdefault(架.中继机编号, []).append(架)
    在架: list = []
    for 编号 in sorted(按中继):
        if 编号 not in 池.中继机表:
            违反.append(f"架次使用了库存外中继机 {编号}（库存 {list(池.中继机表)}）")
            continue
        在架.extend(按中继[编号])
    for 编号, 架次表 in 按中继.items():
        有序 = sorted(
            [架 for 架 in 架次表 if 架.中继机编号 in 池.中继机表],
            key=lambda 架: 架.起飞时刻,
        )
        for 前, 后 in zip(有序, 有序[1:]):
            if 后.起飞时刻 < 前.返回时刻 + 机.架次周转时间_s - 数值容差:
                违反.append(
                    f"{编号} 架次#{前.序号}→#{后.序号} 间隔 "
                    f"{后.起飞时刻 - 前.返回时刻:.1f}s < 周转 {机.架次周转时间_s:.0f}s"
                )

    # —— 能源组件占用与充电周转（C14）——
    组件台账 = 联合.中继方案.能源组件使用
    for 条 in 组件台账:
        编号 = 条["能源组件编号"]
        if 编号 not in 池.组件:
            违反.append(f"中继架次#{条['中继架次序号']} 使用库存外能源组件 {编号}")
            continue
        充电 = 充电时长(
            池.等效完全充电时间_s, float(条["结束SOC"])
        )
        应完成 = float(条["返回时刻_s"]) + 充电
        if abs(应完成 - float(条["充电完成时刻_s"])) > 1.0:
            违反.append(
                f"{编号} 架次#{条['中继架次序号']} 充电完成时刻 "
                f"{条['充电完成时刻_s']:.1f}s ≠ 返回 + 充电 {应完成:.1f}s"
            )

    按组件: dict[str, list] = {}
    for 架 in 在架:
        按组件.setdefault(架.能源组件编号, []).append(架)
    for 编号, 架次表 in 按组件.items():
        有序 = sorted(架次表, key=lambda 架: 架.起飞时刻)
        for 前, 后 in zip(有序, 有序[1:]):
            充电 = 充电时长(池.等效完全充电时间_s, 前.代价.结束SOC)
            可用 = 前.返回时刻 + 充电
            if 后.起飞时刻 < 可用 - 数值容差:
                违反.append(
                    f"{编号} 架次#{后.序号} 于 {后.起飞时刻:.1f}s 起飞，"
                    f"但组件充至 100% 需到 {可用:.1f}s（充电周转不足）"
                )

    return 检验项(
        "⑮ 中继机与能源组件",
        len(违反),
        f"同一中继机架次不重叠且间隔 ≥ {机.架次周转时间_s:.0f}s（C16）；"
        f"能源组件占用与充电周转不重叠（C14）；"
        f"{联合.中继方案.架次数} 架次 / {len(池.中继机表)} 架中继 / "
        f"{len(池.组件)} 组组件，已用 {len(按组件)} 组",
        违反[:5],
    )


# ===================== ⑯ 建链与移动窗口（C17/C18）=====================
def _检验_中继建链与移动窗口(剖面表, 环境: 通信环境, 联合) -> 检验项:
    """C18：每抵达一个新悬停点计一次 30 s 建链。
    C17：站间**转场期间**接入链路断开，该中继不得承担任何保障。

    判定依据全部由架次记录与数据文件参数重算，不读 `中继架次代价` 的任何派生量：

    首站：`起飞 + 工位准备 + 去程飞行时间 + 建链 ≤ 服务起`
    转场：`服务终_m + 转场飞行时间 + 建链 ≤ 服务起_{m+1}`
    末站：`服务终_M + 返航飞行时间 = 返回时刻`
    """
    场景 = 剖面表.场景
    机 = 读取中继机()
    中心 = 场景.调度中心
    中心经度, 中心纬度 = 中心["经度"], 中心["纬度"]
    中心作业高度 = 中心["海拔"] + 调度中心作业高度增量_m
    违反: list[str] = []

    for 架 in 联合.中继方案.架次列表:
        站序列 = 架.站序列
        if not 站序列:
            违反.append(f"中继架次#{架.序号} 无可服务站")
            continue

        去程 = 中继航段代价(
            环境, 机, 调度中心编号, "P1",
            中心经度, 中心纬度, 中心作业高度,
            站序列[0].经度, 站序列[0].纬度, 站序列[0].悬停海拔,
        )
        首站最晚建链起 = 架.起飞时刻 + 机.工位固定准备时间_s + 去程.飞行时间
        if 首站最晚建链起 > 站序列[0].服务起 - 机.建链时间_s + 数值容差:
            违反.append(
                f"中继架次#{架.序号} 首站建链起 {首站最晚建链起:.1f}s 晚于 "
                f"{站序列[0].服务起 - 机.建链时间_s:.1f}s（C18 建链不足）"
            )

        for 位, (前站, 后站) in enumerate(zip(站序列, 站序列[1:])):
            转场 = 中继航段代价(
                环境, 机, f"P{位 + 1}", f"P{位 + 2}",
                前站.经度, 前站.纬度, 前站.悬停海拔,
                后站.经度, 后站.纬度, 后站.悬停海拔,
            )
            到达 = 前站.服务终 + 转场.飞行时间
            建链起 = 后站.服务起 - 机.建链时间_s
            if 到达 > 建链起 + 数值容差:
                违反.append(
                    f"中继架次#{架.序号} 站{位 + 1}→{位 + 2} 转场到达 {到达:.1f}s "
                    f"晚于建链起 {建链起:.1f}s（C17 移动窗口不足）"
                )
            # C17：转场窗口 [前站服务终, 后站服务起) 内，本中继不得承担任何保障
            保障表 = [
                条 for 条 in 联合.中继方案.保障记录
                if 条.中继架次序号 == 架.序号 and 条.站序 == 位 + 2
            ]
            for 条 in 保障表:
                if 条.起时刻 < 后站.服务起 - 数值容差:
                    违反.append(
                        f"架次#{条.运输架次序号} 在 {条.起时刻:.1f}s 依赖中继架次"
                        f"#{架.序号}，但该中继此时正在站间转场（C17）"
                    )

        返航 = 中继航段代价(
            环境, 机, f"P{len(站序列)}", 调度中心编号,
            站序列[-1].经度, 站序列[-1].纬度, 站序列[-1].悬停海拔,
            中心经度, 中心纬度, 中心作业高度,
        )
        返回 = 站序列[-1].服务终 + 返航.飞行时间
        if abs(返回 - 架.返回时刻) > 1e-6:
            违反.append(
                f"中继架次#{架.序号} 返回时刻闭合偏差 "
                f"{abs(返回 - 架.返回时刻):.3e} s"
            )

    站总数 = sum(架.站数 for 架 in 联合.中继方案.架次列表)
    return 检验项(
        "⑯ 建链与移动窗口",
        len(违反),
        f"逐站计 {机.建链时间_s:.0f}s 建链（C18）；站间转场窗口内该中继不承担保障"
        f"（C17）；{站总数} 个悬停站、"
        f"{联合.中继方案.架次数} 个架次",
        违反[:5],
    )


# ===================== 汇总入口 =====================
def _检验_保障记录自洽(剖面表, 联合) -> 检验项:
    """⑰ 保障记录自洽（C10 的**账目层**）—— 堵住 ⑩ 采信自报时刻的口子。

    已知的两个静默通过口子：

    * `⑩` 把 `保障记录.[起时刻, 终时刻]` 直接当作"中继覆盖区间"，却**不校验它是否落在
      该悬停站的服务窗内**；`⑯` 的 C17 也只在 `站序` 恰好匹配时才拦 —— 于是"把起时刻
      提前"就能骗过 ⑩。
    * **缺口账目无人看守**：保障记录覆盖的缺口 ⊎ 未覆盖缺口 是否恰好等于缺口集合，
      此前没有任何检验项核对。而它正是外层搜索 Deb 违反量的输入 —— 账错了，
      "未覆盖缺口数"这个目标值就不可信。

    本项逐条比对 `站序` 越界 / 服务窗一致 / 悬停位置一致 / 缺口归属，并核销整份缺口账。

    **两种中继口径下的「服务窗一致」判据不同**（由数据自身判别：驻留站的
    `悬停站.有效服务时长` 非 None ⇒ 口径 E）：

    * **口径 D（一对一）**：一个站只保障一个缺口 ⇒ 服务窗就是缺口窗，
      故要求 `条.起/终 == 站.服务起/终`（原判据，逐字保留）；
    * **口径 E（一对多）**：驻留窗是**成员窗口的凸包**，窗内还夹着别的缺口的窗口
      与直连空档 ⇒ 保障记录必须取**该缺口自己的窗口**，并要求它落在驻留窗内。
      此时若仍用口径 D 的等式判据，一对多的成功方案会被**误判违反**。
    """
    中继方案 = 联合.中继方案
    架次按序号 = {架.序号: 架 for 架 in 中继方案.架次列表}
    缺口集合 = 解析缺口(剖面表, 联合.运输方案)
    违反: list[str] = []
    覆盖缺口: list[int] = []

    for 条 in 中继方案.保障记录:
        架 = 架次按序号.get(条.中继架次序号)
        if 架 is None:
            违反.append(f"保障记录指向不存在的中继架次 {条.中继架次序号}")
            continue
        if not 1 <= 条.站序 <= len(架.站序列):
            违反.append(f"架次 {架.序号} 的站序 {条.站序} 越界（共 {len(架.站序列)} 站）")
            continue
        站 = 架.站序列[条.站序 - 1]
        if 站.有效服务时长 is None:
            if abs(条.起时刻 - 站.服务起) > 1e-6 or abs(条.终时刻 - 站.服务终) > 1e-6:
                违反.append(
                    f"架次 {架.序号} 站 {条.站序} 的保障时段 "
                    f"[{条.起时刻:.1f}, {条.终时刻:.1f}] ≠ 该站服务窗 "
                    f"[{站.服务起:.1f}, {站.服务终:.1f}]"
                )
        elif 0 <= 条.缺口序号 < len(缺口集合.缺口列表):
            缺 = 缺口集合.缺口列表[条.缺口序号]
            if (
                abs(条.起时刻 - 缺.起时刻) > 1e-6
                or abs(条.终时刻 - 缺.终时刻) > 1e-6
            ):
                违反.append(
                    f"架次 {架.序号} 站 {条.站序} 的保障时段 "
                    f"[{条.起时刻:.1f}, {条.终时刻:.1f}] ≠ 缺口 {条.缺口序号} 自身的窗口 "
                    f"[{缺.起时刻:.1f}, {缺.终时刻:.1f}]（口径 E 要求逐缺口申报）"
                )
            if 条.起时刻 < 站.服务起 - 1e-6 or 条.终时刻 > 站.服务终 + 1e-6:
                违反.append(
                    f"架次 {架.序号} 站 {条.站序} 的保障时段 "
                    f"[{条.起时刻:.1f}, {条.终时刻:.1f}] 越出该站驻留窗 "
                    f"[{站.服务起:.1f}, {站.服务终:.1f}]"
                )
        if (
            abs(条.悬停经度 - 站.经度) > 1e-6
            or abs(条.悬停纬度 - 站.纬度) > 1e-6
            or abs(条.悬停海拔 - 站.悬停海拔) > 1e-6
        ):
            违反.append(f"架次 {架.序号} 站 {条.站序} 的悬停位置与站记录不一致")
        if 条.缺口序号 not in 站.保障缺口:
            违反.append(
                f"缺口 {条.缺口序号} 不在架次 {架.序号} 站 {条.站序} 的保障缺口集内"
            )
        覆盖缺口.append(条.缺口序号)

    应有 = set(range(len(缺口集合.缺口列表)))
    实得 = set(覆盖缺口) | set(中继方案.未覆盖缺口)
    漏账 = sorted(应有 - 实得)
    多账 = sorted(实得 - 应有)
    if 漏账:
        违反.append(
            f"缺口账目遗漏：缺口 {漏账[:5]} 既无保障记录、也不在未覆盖清单里"
        )
    if 多账:
        违反.append(f"缺口账目越界：{多账[:5]} 不在缺口集合中")
    if len(覆盖缺口) != len(set(覆盖缺口)):
        违反.append("同一缺口被多条保障记录覆盖（重复计账）")

    return 检验项(
        "⑰ 保障记录自洽",
        len(违反),
        f"{len(中继方案.保障记录)} 条保障记录 / {len(缺口集合.缺口列表)} 个缺口 / "
        f"未覆盖 {len(中继方案.未覆盖缺口)} 个；站序、服务窗、悬停位置逐条比对，"
        f"缺口账目（保障 ∪ 未覆盖）与缺口集合对齐",
        违反[:5],
    )


def 检验联合方案(
    剖面表, 环境: 通信环境, 联合, 全采样复核: bool = True
) -> tuple[list[检验项], list[通信明细]]:
    """对**联合方案**执行全部约束检验（运输侧 ①–⑨ + 通信/中继侧 ⑩–⑰）。

    先跑运输侧九项（`运输方案` 必须是 `方案结构.全局方案`），再追加八项。
    返回 (检验项列表, 逐架次通信明细)。

    `全采样复核`：⑩⑫ 是否对保障区间内**每一个** 30 m 采样位姿调用真实
    `通信模型`。交付方案一律置真；搜索中间态可用假以获得上百倍加速
    （此时 ⑩ 仍用查表判定时间覆盖，只是不做逐位姿链路重算）。
    """
    检验项表, _ = 检验全局方案(剖面表.场景, 联合.运输方案)
    子段表 = _架次子段表(剖面表, 联合.运输方案)

    通信项, 通信明细表, _ = _检验_通信连续性(剖面表, 环境, 联合, 全采样复核)
    检验项表.append(通信项)
    检验项表.append(_检验_中继独占(联合))
    检验项表.append(_检验_中继多跳(剖面表, 环境, 联合, 子段表, 全采样复核))
    检验项表.append(_检验_中继悬停几何(环境, 联合))
    检验项表.append(_检验_中继返航电量(剖面表, 环境, 联合))
    检验项表.append(_检验_中继资源(联合))
    检验项表.append(_检验_中继建链与移动窗口(剖面表, 环境, 联合))
    检验项表.append(_检验_保障记录自洽(剖面表, 联合))
    return 检验项表, 通信明细表


# 通信 / 中继项的编号前缀（用于「通信是否可行」的独立判定）
# ⚠️ 新增编号项必须同步登记在此，否则 `所有通信与中继项通过` 会静默漏掉它。
通信与中继项前缀 = ("⑩", "⑪", "⑫", "⑬", "⑭", "⑮", "⑯", "⑰")

# 运输侧「时限」项前缀（⑦ 首批截止时间、⑧ 医疗期望时间）。
# 这两项是**硬时限**，由外层搜索的 Deb 约束支配处理，**不是解码修复算子保证的**；
# 无全可行解时代表解退回「违反量最小」子集，⑦⑧ 可出现非零违反 —— 那属「未达准入」，
# 不是程序错误。故主程序校验时只对「结构项」①②③④⑤⑥⑨ 断言零违反，⑦⑧ 只如实报告。
运输时限项前缀 = ("⑦", "⑧")


def 联合是否可行(检验项表: list[检验项]) -> bool:
    """联合方案是否**全部**约束通过（运输侧 ①–⑨ 与通信/中继侧 ⑩–⑰）。"""
    return all(项.通过 for 项 in 检验项表)


def 所有通信与中继项通过(检验项表: list[检验项]) -> bool:
    """通信与中继侧八项是否全部通过 —— 即 配置.py《★ 前置条件》的准入判据。"""
    return all(
        项.通过 for 项 in 检验项表 if 项.名称[:1] in 通信与中继项前缀
    )


# ===================== 自检：人为破坏 → 必须被捕获 =====================
def _自检样例架次(剖面表, 架次数: int) -> list:
    """取多点多架次调度「最少架次数」代表方案的前 `架次数` 个架次作为自检载体。"""
    import json

    from 源代码.公共库.通信中继.构造启发式 import 解码, 载荷包
    from 源代码.公共库.通信中继.配置 import 项目根

    路径 = 项目根 / "源代码" / "求解器" / "多点多架次调度" / "多目标优化" / "输出" / "代表方案.json"
    if not 路径.exists():
        return []
    记录 = json.loads(路径.read_text(encoding="utf-8"))["代表方案"]["最少架次数"]["架次"]
    包列表 = [
        载荷包(
            箱表=tuple(
                (区, tuple(sorted(箱编号列表)))
                for 区, 箱编号列表 in zip(条["访问顺序"], 条["各区箱编号"])
            ),
            访问顺序=tuple(条["访问顺序"]),
        )
        for 条 in 记录[:架次数]
    ]
    return 解码(剖面表.场景, 包列表)


def _违反表(检验项表: list[检验项]) -> dict[str, int]:
    return {项.名称[:1]: 项.违反数 for 项 in 检验项表}


def 可行性检验自检(
    剖面表, 环境: 通信环境, 架次数: int = 4, 最大迭代: int = 6
) -> tuple[bool, list[str]]:
    """**人为破坏每一类约束，验证对应检验项必然报警**。

    判据是**相对**的：先对基线联合方案取各项违反数，再对每个变异方案重跑检验，
    断言**目标检验项**的违反数**严格增加**。这样即使基线本身未达零中断
    （2 架中继容量不足时确实会发生，见 `中继排程`），变异捕获能力依然可验证。

    每个变异只改动"目标检验项"读取的那部分数据，因此能判别是哪一项在工作；
    若某类变异因基线规模不足而无法构造（例如只有 1 个中继架次就无法制造
    能源组件复用冲突），如实记为「未构造」而不是静默通过。
    """
    from 源代码.公共库.通信中继.中继排程 import 排程

    架次列表 = _自检样例架次(剖面表, 架次数)
    if not 架次列表:
        return True, ["[自检·检验] 无多点多架次调度代表方案可读，跳过（不影响任何计算）"]

    结果 = 排程(剖面表, 环境, 架次列表, 最大迭代=最大迭代)
    基线联合 = 结果.联合方案
    中继 = 基线联合.中继方案

    基线全, 基线明细 = 检验联合方案(剖面表, 环境, 基线联合, 全采样复核=True)
    基线快, _ = 检验联合方案(剖面表, 环境, 基线联合, 全采样复核=False)
    基数全 = _违反表(基线全)
    基数快 = _违反表(基线快)

    保障表 = 中继.保障记录
    架次表 = list(中继.架次列表)

    def 换保障(联合, 变换):
        return replace(
            联合,
            中继方案=replace(
                联合.中继方案,
                保障记录=tuple(变换(条) for 条 in 联合.中继方案.保障记录),
            ),
        )

    def 移站(联合, 平移经度: float):
        """只改**保障记录**里的悬停位置：⑩⑫ 的链路判据据此复核，与 ⑬⑭⑯ 无关。"""
        return 换保障(
            联合,
            lambda 条: replace(
                条, 悬停经度=条.悬停经度 + 平移经度, 悬停纬度=条.悬停纬度 + 平移经度
            ),
        )

    def 复制保障(联合):
        return replace(
            联合,
            中继方案=replace(
                联合.中继方案,
                保障记录=联合.中继方案.保障记录
                + tuple(
                    replace(条, 缺口序号=条.缺口序号 + 9000, 站序=条.站序 + 100)
                    for 条 in 联合.中继方案.保障记录
                ),
            ),
        )
    def 抬站(联合):
        """把第一个悬停站抬到离地 400 m（> 数据文件上限 300 m）。"""
        首架 = 联合.中继方案.架次列表[0]
        return replace(
            联合,
            中继方案=replace(
                联合.中继方案,
                架次列表=(
                    replace(
                        首架,
                        站序列=tuple(
                            replace(站, 悬停海拔=站.地面海拔 + 400.0)
                            if 位 == 0
                            else 站
                            for 位, 站 in enumerate(首架.站序列)
                        ),
                    ),
                )
                + 联合.中继方案.架次列表[1:],
            ),
        )

    def 超能耗(联合):
        首架 = 联合.中继方案.架次列表[0]
        return replace(
            联合,
            中继方案=replace(
                联合.中继方案,
                架次列表=(
                    replace(
                        首架,
                        代价=replace(
                            首架.代价, 飞行能耗=首架.代价.飞行能耗 + 10.0
                        ),
                    ),
                )
                + 联合.中继方案.架次列表[1:],
            ),
        )

    def 组件冲突(联合):
        """让第 2 个架次复用第 1 个架次的能源组件，且起飞早于其充电完成。

        只改「能源组件编号 + 起飞时刻」两处，因此必定命中 ⑮ 的 C14 分支
        （组件未充至 100% 就再投用），不管基线里两个架次原本是否同组件。
        """
        架次表 = 联合.中继方案.架次列表
        首, 次 = 架次表[0], 架次表[1]
        return replace(
            联合,
            中继方案=replace(
                联合.中继方案,
                架次列表=(
                    首,
                    replace(
                        次,
                        能源组件编号=首.能源组件编号,
                        代价=replace(次.代价, 起飞时刻=首.返回时刻 + 1.0),
                    ),
                )
                + 架次表[2:],
            ),
        )

    def 周转冲突(联合):
        """把第二个架次的起飞时刻提前到首个架次返回之前（同机或异机皆可）。"""
        架次表 = 联合.中继方案.架次列表
        if len(架次表) < 2:
            return 联合
        首, 次 = 架次表[0], 架次表[1]
        return replace(
            联合,
            中继方案=replace(
                联合.中继方案,
                架次列表=(
                    首,
                    replace(
                        次,
                        中继机编号=首.中继机编号,
                        代价=replace(次.代价, 起飞时刻=首.返回时刻),
                    ),
                )
                + 架次表[2:],
            ),
        )

    def 改保障起时刻(联合):
        """把首个保障记录的**起时刻提前 120 s** → 覆盖声明超出该站的服务窗。

        ⚠️ 这是 ⑩ 的**静默通过口子**：`⑩` 把保障记录自报的 `[起时刻, 终时刻]` 直接当作
        中继覆盖区间，只要悬停位置没变、链路仍通，它就照旧"通过"。
        `⑯` 的 C17 也只在 `站序` 恰好匹配时才拦。必须由 ⑰ 的账目层抓住。
        """
        if not 联合.中继方案.保障记录:
            return 联合
        首条 = 联合.中继方案.保障记录[0]
        return replace(
            联合,
            中继方案=replace(
                联合.中继方案,
                保障记录=(
                    replace(首条, 起时刻=首条.起时刻 - 120.0),
                )
                + 联合.中继方案.保障记录[1:],
            ),
        )

    def 起飞推迟(联合):
        """把首个中继架次的起飞时刻推迟 300 s → 首站来不及在服务起前完成建链。

        ⚠️ 方向必须是**推迟**：提前起飞只会让中继更早到位、多等一会儿，
        等待在口径 Q7 下是允许的，不构成违反。只有"到得晚于建链起"才违反 C18。
        """
        首架 = 联合.中继方案.架次列表[0]
        return replace(
            联合,
            中继方案=replace(
                联合.中继方案,
                架次列表=(
                    replace(
                        首架,
                        代价=replace(首架.代价, 起飞时刻=首架.起飞时刻 + 300.0),
                    ),
                )
                + 联合.中继方案.架次列表[1:],
            ),
        )

    def 压缩转场(联合):
        """把首个多站架次第 2 站的服务起压到"前站服务终 + 1 s"（C17 转场窗口不足）。

        ⚠️ 不能只平移 30 s：站间本来就有几百秒的富余（缺口起时刻决定的），
        小位移不越界，检验项当然不报警。要构造**必然越界**的输入。
        """
        for 位, 架 in enumerate(联合.中继方案.架次列表):
            if len(架.站序列) < 2:
                continue
            前站, 后站 = 架.站序列[0], 架.站序列[1]
            if 前站.服务终 + 1.0 >= 后站.服务终:
                continue
            改 = (
                前站,
                replace(后站, 服务起=前站.服务终 + 1.0),
            ) + 架.站序列[2:]
            架次表 = (
                联合.中继方案.架次列表[:位]
                + (replace(架, 站序列=改),)
                + 联合.中继方案.架次列表[位 + 1:]
            )
            return replace(
                联合, 中继方案=replace(联合.中继方案, 架次列表=架次表)
            )
        return 联合

    多站 = any(架.站序列 for 架 in 架次表)
    转场可构造 = any(
        len(架.站序列) >= 2 and 架.站序列[0].服务终 + 1.0 < 架.站序列[1].服务终
        for 架 in 架次表
    )
    多架次 = len(架次表) >= 2

    # (目标检验项, 变异说明, 变异函数, 参照基线, 是否需全采样, 基线规模是否足够)
    计划: list[tuple[str, str, object, dict, bool, bool]] = [
        ("⑩", "把保障记录的悬停点东移 0.1°（约 11 km）→ 接入段超距",
         lambda 联: 移站(联, 0.1), 基数全, True, bool(保障表)),
        ("⑫", "把保障记录的悬停点移出 0.5°（约 55 km）→ 回传段超距",
         lambda 联: 移站(联, 0.5), 基数全, True, bool(保障表)),
        ("⑪", "把每条保障关系再复制一份 → 同一架次同时被两架中继保障",
         复制保障, 基数快, False, bool(保障表)),
        ("⑬", "把首个悬停站抬到离地 400 m（> 上限 300 m）",
         抬站, 基数快, False, 多站),
        ("⑭", "把首个中继架次的飞行能耗加 10 kWh（超 2.56 kWh 且不闭合）",
         超能耗, 基数快, False, bool(架次表)),
        ("⑮", "把全部中继架次的能源组件改成同一组（不充电复用）",
         组件冲突, 基数快, False, 多架次),
        ("⑮", "把第二个架次改派给首架中继并提前到其返回之前（周转不足）",
         周转冲突, 基数快, False, 多架次),
        ("⑯", "把首个中继架次的起飞时刻推迟 300 s（首站来不及建链，C18）",
         起飞推迟, 基数快, False, bool(架次表)),
        ("⑯", "把首个多站架次第 2 站的服务起压到「前站服务终 + 1 s」（转场窗口不足，C17）",
         压缩转场, 基数快, False, 转场可构造),
        ("⑰", "把首个保障记录的起时刻提前 120 s（覆盖声明超出站服务窗）",
         改保障起时刻, 基数快, False, bool(保障表)),
    ]

    行: list[str] = []
    全部通过 = True
    捕获数 = 0
    未构造: list[str] = []

    for 目标, 说明, 变异, 基数, 需全采样, 规模足够 in 计划:
        if not 规模足够:
            未构造.append(f"{目标} {说明}")
            continue
        变异后 = 变异(基线联合)
        项表, _ = 检验联合方案(剖面表, 环境, 变异后, 全采样复核=需全采样)
        表 = _违反表(项表)
        目标前 = 基数.get(目标, 0)
        目标后 = 表.get(目标, 0)
        捕获 = 目标后 > 目标前
        全部通过 = 全部通过 and 捕获
        捕获数 += int(捕获)
        其余 = [
            f"{编号}{表.get(编号, 0) - 基数.get(编号, 0):+d}"
            for 编号 in ("⑩", "⑪", "⑫", "⑬", "⑭", "⑮", "⑯", "⑰")
            if 编号 != 目标 and 表.get(编号, 0) != 基数.get(编号, 0)
        ]
        行.append(
            f"[自检·检验·{目标}] {说明} → 目标项违反数 {目标前} → {目标后}，"
            f"{'已捕获' if 捕获 else '**未捕获！**'}"
            + (f"；连带变化 {' '.join(其余)}" if 其余 else "")
        )

    已构造 = len(计划) - len(未构造)
    基线行 = (
        f"[自检·检验·基线] 样例联合方案（取多点多架次调度「最少架次数」前 {架次数} 个架次 → "
        f"{基线联合.架次数} 运输架次 / {中继.架次数} 中继架次 / "
        f"{中继.站数} 悬停站 / {len(保障表)} 条保障关系）；通信与中继侧违反数 "
        + " ".join(
            f"{项.名称[:1]}={项.违反数}"
            for 项 in 基线全
            if 项.名称[:1] in 通信与中继项前缀
        )
        + f"；⑩ 逐架次无中断 {sum(1 for 条 in 基线明细 if not 条.未覆盖区间)}"
        f"/{len(基线明细)} 架次"
    )
    行.insert(0, 基线行)
    行.append(
        f"[自检·检验·小结] 计划 {len(计划)} 项、已构造 {已构造} 项，"
        f"其中 {捕获数} 项被**目标检验项**捕获 → "
        f"{'全部捕获' if 全部通过 else '存在漏检！'}"
    )
    if 未构造:
        行.append(
            f"[自检·检验·未构造] {len(未构造)} 项（基线规模不足，如实记录而非静默通过）："
            + "；".join(未构造)
        )

    return 全部通过, 行




