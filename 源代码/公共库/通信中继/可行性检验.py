@dataclass
class 检验项:
    """一条约束的检验结果。"""

    名称: str
    违反数: int
    说明: str
    样例: list[str] = field(default_factory=list)

    @property
    def 通过(self) -> bool:
        return self.违反数 == 0

    def 展示(self) -> str:
        状态 = "通过" if self.通过 else "不通过"
        # "违反数 = 0" 与 "违反数 = 3 [...]" 两种写法，便于论文与自检直接引用
        if self.样例:
            return f"[{状态}] {self.名称}：{self.说明}；违反数 = {self.违反数}，样例 {self.样例}"
        return f"[{状态}] {self.名称}：{self.说明}；违反数 = {self.违反数}"


# ===================== 逐项检验 =====================
def _检验_货箱覆盖(场景, 方案) -> 检验项:
    应有 = sorted(b["货箱编号"] for b in 场景.货箱)
    实际: list[str] = []
    for 架 in 方案.架次列表:
        实际.extend(架.货箱编号列表)
    实际.sort()

    重复 = len(实际) - len(set(实际))
    缺失 = sorted(set(应有) - set(实际))
    多余 = sorted(set(实际) - set(应有))
    违反数 = 重复 + len(缺失) + len(多余)
    说明 = f"80 箱各安排一次（重复 {重复} 箱，缺失 {len(缺失)} 箱，越界 {len(多余)} 箱）"
    样例 = [f"缺失 {缺失[:5]}"] if 缺失 else []
    样例 += [f"多余 {多余[:5]}"] if 多余 else []
    return 检验项("① 货箱覆盖", 违反数, 说明, 样例)


def _检验_载质量与体积(场景, 方案) -> tuple[检验项, 检验项]:
    超质 = []
    超体 = []
    for 架 in 方案.架次列表:
        机 = 场景.机型表[架.机型编号]
        if 架.总载质量 > 机.最大载货质量 + 数值容差:
            超质.append(f"#{架.序号}({架.机型编号}) {架.总载质量:.2f}>{机.最大载货质量:.0f} kg")
        if 架.总装载体积 > 机.可用装载体积 + 数值容差:
            超体.append(f"#{架.序号}({架.机型编号}) {架.总装载体积:.4f}>{机.可用装载体积:.3f} m³")
    return (
        检验项("② 载质量", len(超质), f"每架次 Σ单箱质量 ≤ 机型最大载货质量（共 {方案.架次数} 架次）", 超质[:5]),
        检验项("③ 装载体积", len(超体), f"每架次 Σ单箱体积 ≤ 机型可用装载体积（共 {方案.架次数} 架次）", 超体[:5]),
    )


def _检验_返航余量(场景, 方案) -> 检验项:
    超能 = [
        f"#{架.序号}({架.机型编号}) {架.能耗:.4f}>{架.代价.架次能量上限:.4f} kWh"
        for 架 in 方案.架次列表
        if 架.能耗 > 架.代价.架次能量上限 + 数值容差
    ]
    最大占用 = max((架.代价.能量上限占用率 for 架 in 方案.架次列表), default=0.0)
    return 检验项(
        "④ 返航安全余量",
        len(超能),
        f"每架次 E_trip ≤ (1−ρ)·E^use，ρ=20%；最大能量上限占用率 {最大占用:.4f}",
        超能[:5],
    )


def _检验_无人机(场景, 方案) -> 检验项:
    违反: list[str] = []

    # 型号匹配 + 库存归属
    for 记录 in 方案.调度表.values():
        if 记录.无人机编号 not in 场景.无人机表:
            违反.append(f"架次#{记录.架次序号} 使用库存外无人机 {记录.无人机编号}")
            continue
        if 场景.无人机表[记录.无人机编号]["机型编号"] != 记录.机型编号:
            违反.append(
                f"架次#{记录.架次序号} 指派给 {记录.无人机编号}"
                f"（{场景.无人机表[记录.无人机编号]['机型编号']} 型），"
                f"但架次机型为 {记录.机型编号}"
            )

    # 用量不超过库存：同一无人机不得同时被两个架次占用
    用量: dict[str, int] = {}
    for 记录 in 方案.调度表.values():
        用量[记录.无人机编号] = 用量.get(记录.无人机编号, 0) + 1

    # 同一无人机的时间轴不重叠
    for 无人机编号, 架次列表 in 方案.各无人机架次().items():
        时间轴 = sorted((方案.调度表[a.序号] for a in 架次列表), key=lambda r: r.开始时刻)
        for 前, 后 in zip(时间轴, 时间轴[1:]):
            if 后.开始时刻 < 前.返回时刻 - 数值容差:
                违反.append(f"{无人机编号} 架次#{前.架次序号}与#{后.架次序号} 时间重叠")

    清单 = 场景.无人机清单
    说明用量 = " ".join(
        f"{g}:{sum(1 for r in 方案.调度表.values() if r.机型编号 == g)}/{len(清单.get(g, []))}"
        for g in sorted(清单)
    )

    return 检验项(
        "⑤ 无人机资源",
        len(违反),
        f"机型匹配、不超库存、同一无人机架次不重叠；已用/库存架次 {说明用量}",
        违反[:5],
    )


def _检验_电池(场景, 方案) -> 检验项:
    违反: list[str] = []

    for 记录 in 方案.调度表.values():
        架 = 方案.取架次(记录.架次序号)
        机 = 场景.机型表[架.机型编号]
        if 记录.机型编号 != 架.机型编号:
            违反.append(f"架次#{架.序号} 调度机型与架次机型不一致")
        if 记录.电池编号 not in 场景.电池清单.get(架.机型编号, []):
            违反.append(f"架次#{架.序号} 电池 {记录.电池编号} 不属机型 {架.机型编号}")
        if abs(记录.起始SOC - 1.0) > 数值容差:
            违反.append(f"架次#{架.序号} 电池起始 SOC = {记录.起始SOC:.4f} ≠ 100%")
        if 记录.结束SOC < 机.返航安全余量比例 - 数值容差:
            违反.append(
                f"架次#{架.序号} 电池结束 SOC {记录.结束SOC:.4f} < 返航下限 {机.返航安全余量比例:.2f}"
            )

    # 同一电池：任务不重叠 + 充电周转不重叠
    per_battery: dict[str, list] = {}
    for 记录 in 方案.调度表.values():
        per_battery.setdefault(记录.电池编号, []).append(记录)
    for 电池编号, 记录列表 in per_battery.items():
        记录列表.sort(key=lambda r: r.开始时刻)
        for 前, 后 in zip(记录列表, 记录列表[1:]):
            if 后.开始时刻 < 前.返回时刻 - 数值容差:
                违反.append(f"{电池编号} 架次#{前.架次序号}与#{后.架次序号} 占用重叠")
            elif 后.开始时刻 < 前.电池可用时刻 - 数值容差:
                违反.append(
                    f"{电池编号} 架次#{后.架次序号} 早于充电完成时刻 "
                    f"{前.电池可用时刻:.1f}s（充电周转不足）"
                )

    机型用量: dict[str, int] = {}
    for 记录 in 方案.调度表.values():
        机型用量[记录.机型编号] = 机型用量.get(记录.机型编号, 0) + 1
    说明用量 = " ".join(
        f"{g}:{机型用量.get(g, 0)}/{场景.电池表[g]['组数']}" for g in sorted(场景.电池表)
    )
    return 检验项(
        "⑥ 共享电池资源",
        len(违反),
        f"机型匹配、不超库存、占用与充电不重叠、SOC ≥ ρ；"
        f"充电周转按两阶段等效模型；电池被用次数 {说明用量}",
        违反[:5],
    )


def _检验_时限(场景, 方案) -> tuple[检验项, 检验项, list]:
    摘要 = 构造时限摘要(场景, 方案.逐箱送达())

    首批超 = [
        条 for 条 in 摘要 if 条.是否首批保障 and not 条.首批是否满足
    ]
    医疗超 = [
        条 for 条 in 摘要 if 条.是否医疗物资 and not 条.期望硬约束是否满足
    ]

    样例 = [
        f"{条.货箱编号} 送达{条.送达时刻:.0f}s > 截止{条.首批截止时间:.0f}s"
        for 条 in 首批超[:5]
    ]
    return (
        检验项(
            "⑦ 首批截止时间",
            len(首批超),
            f"首批保障货箱 送达时刻 ≤ 首批截止时间（共 {sum(1 for 条 in 摘要 if 条.是否首批保障)} 箱）",
            样例,
        ),
        检验项(
            "⑧ 医疗期望时间",
            len(医疗超),
            f"医疗物资 送达时刻 ≤ 期望送达时间（共 {sum(1 for 条 in 摘要 if 条.是否医疗物资)} 箱）",
            [f"{条.货箱编号} 送达{条.送达时刻:.0f}s > 期望{条.期望送达时间:.0f}s" for 条 in 医疗超[:5]],
        ),
        摘要,
    )


def _检验_结构(场景, 方案) -> 检验项:
    违反: list[str] = []

    if len(方案.调度表) != 方案.架次数:
        违反.append(f"调度表覆盖 {len(方案.调度表)} / {方案.架次数} 个架次")

    for 架 in 方案.架次列表:
        if 架.序号 not in 方案.调度表:
            违反.append(f"架次#{架.序号} 无调度记录")
            continue
        记录 = 方案.调度表[架.序号]
        if len(架.服务区序列) == 0:
            违反.append(f"架次#{架.序号} 未访问任何服务区")
        if len(set(架.服务区序列)) != len(架.服务区序列):
            违反.append(f"架次#{架.序号} 重复访问同一服务区")
        if 架.总箱数 == 0:
            违反.append(f"架次#{架.序号} 空架次")
        for 编号 in 架.服务区序列:
            if 编号 not in 场景.服务区表:
                违反.append(f"架次#{架.序号} 出现未知服务区 {编号}")
        if 记录.开始时刻 < -数值容差:
            违反.append(f"架次#{架.序号} 开始时刻为负")
        if 记录.返回时刻 < 记录.开始时刻 - 数值容差:
            违反.append(f"架次#{架.序号} 返回时刻早于开始时刻")
        # 节点序列必须 O01 起止
        if 架.代价.节点序列[0] != "O01" or 架.代价.节点序列[-1] != "O01":
            违反.append(f"架次#{架.序号} 节点序列未在 O01 起止")

    return 检验项(
        "⑨ 方案结构",
        len(违反),
        f"{方案.架次数} 个架次均为 O01 出发并返回 O01，服务区不重复、非空、时刻非负",
        违反[:5],
    )


# ===================== 汇总入口 =====================
def 检验全局方案(场景, 方案) -> tuple[list[检验项], list]:
    """对完整方案执行九类约束检验。

    返回 (检验项列表, 时限摘要列表)。时限摘要在评价中复用，避免重复计算。
    """
    检验项表: list[检验项] = []
    检验项表.append(_检验_货箱覆盖(场景, 方案))
    质, 体 = _检验_载质量与体积(场景, 方案)
    检验项表 += [质, 体]
    检验项表.append(_检验_返航余量(场景, 方案))
    检验项表.append(_检验_无人机(场景, 方案))
    检验项表.append(_检验_电池(场景, 方案))
    首批, 医疗, 摘要 = _检验_时限(场景, 方案)
    检验项表 += [首批, 医疗]
    检验项表.append(_检验_结构(场景, 方案))
    return 检验项表, 摘要


def 是否可行(检验项表: list[检验项]) -> bool:
    return all(项.通过 for 项 in 检验项表)


def 违反合计(检验项表: list[检验项]) -> int:
    return sum(项.违反数 for 项 in 检验项表)


