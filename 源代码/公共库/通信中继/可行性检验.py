#   * **时间覆盖**（何时必须有中继）用 `缺口解析` 的**查表**结果
#     （表A / 表B，零 DEM 调用；两表已由 `通信剖面剖面自检` 240/240 逐端点交叉一致）；
#   * **链路证据**（中继是否真的联通、悬停高度是否够）一律调用真实 `通信模型`
