"""
可行性检验 —— 全局全部约束的**唯一判定入口**。

多点多架次调度问题的要求同时满足的约束，逐条对应一个检验项：

    ① 货箱覆盖        货箱不可拆分，每个货箱只能安排一次（恰好一次）
    ② 载质量          每架次 Σ单箱质量 ≤ 机型最大载货质量
    ③ 装载体积        每架次 Σ单箱体积 ≤ 机型可用装载体积
    ④ 返航安全余量    每架次 E_trip ≤ (1 − ρ)·E^use
    ⑤ 无人机资源      机型匹配、不超库存（4A/2B/2C）、同一无人机架次不重叠
    ⑥ 共享电池资源    机型匹配、不超库存（6/4/4）、同一电池架次不重叠、
                      复用前充至 100%（充电周转不重叠）、结束 SOC ≥ ρ
    ⑦ 首批截止时间    首批保障货箱 送达时刻 ≤ 首批截止时间
    ⑧ 医疗期望时间    医疗物资 送达时刻 ≤ 期望送达时间
    ⑨ 方案结构        每架次 O01 起止、服务区不重复且非空、时刻非负、
                      调度表覆盖全部架次

第 ④⑥ 项是多点多架次调度相对单点往返与组批新增的、也最容易出错的两项，本模块给出逐条证据。

联合调度与中继新增的八项（续编 ⑩–⑰，见文件末尾《联合调度与中继扩展》一节）：

    ⑩ 通信连续性      每个运输架次在其**执行区间内**任意时刻，或直连可用、
                      或"运输机↔中继接入端"与"中继回传端↔G01"两段**同时**可用
                      —— 即 配置.py《★ 前置条件》的**准入条件**（C10）
    ⑪ 中继独占        同一运输架次同一时刻至多被 1 架中继保障（C11）
    ⑫ 禁止中继多跳    保障链路拓扑恰为"运输机—中继—G01"两段，回传直连网关（C12）
    ⑬ 中继悬停几何    悬停点在 DEM 内（C6）且离地高度 ≤ 300 m（C7）
    ⑭ 中继返航电量    E_R^总 ≤ (1−ρ_R)·E_R^use = 2.56 kWh（C5），并复核时间/能量闭合
    ⑮ 中继机与组件    同一中继机架次不重叠且相邻架次 ≥ 300 s（C16）；
                      能源组件占用不重叠、充至 100% 才复用（C14）
    ⑯ 建链与移动窗口  逐站计 30 s 建链（C18）；站间转场期间该中继不承担任何保障（C17）

判定口径（重要）
----------------
⑩ 的**时间覆盖**用 `缺口解析` 的**查表**结果（表A / 表B，零 DEM 调用，已由
`通信剖面剖面自检` 240/240 交叉一致）；⑩ 的**链路证据**与 ⑫ 一律调用真实
`通信模型`（含 DEM 视线）在采样位姿上逐一复核。这样两张证据各司其职：
表负责"何时需要中继"，真实模型负责"中继是否真的联通"。
"""

