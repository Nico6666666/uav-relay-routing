# 《求解条件》§3.6 锁定的三把尺子：三类双向门限与无/有遮挡最大距离。
# 这些数值是联合调度与中继全部可行性的依据，必须在每次运行时逐位复现。
_锁定链路 = (
    # (甲类型, 乙类型, 名称, 双向门限 dB, 无遮挡 km, 有遮挡 km)
    (端点_运输无人机, 端点_固定网关, "运输无人机 ↔ 固定网关 G01", 122.0, 12.511, 3.956),
    (端点_运输无人机, 端点_中继接入端, "运输无人机 ↔ 中继接入端", 116.0, 6.270, 1.983),
    (端点_中继回传端, 端点_固定网关, "中继回传端 ↔ 固定网关 G01", 126.0, 19.828, 6.270),
)


def _距离上限_km(环境, 门限_dB: float, 附加损耗_dB: float = 0.0) -> float:
    """由链路门限反解最大距离（km）：L_FSPL = 32.45 + 20lg f + 20lg D。"""
    常数 = 32.45 + 20.0 * math.log10(环境.参数["载波频率_MHz"])
    return 10.0 ** ((门限_dB - 附加损耗_dB - 常数) / 20.0)


def 链路尺子检查(环境) -> tuple[bool, str]:
    """三类双向门限与无/有遮挡最大距离，与《求解条件》§3.6 逐位比对。"""
    记录 = []
    最大偏差_门限 = 0.0
    最大偏差_距离 = 0.0
    for 甲, 乙, 名称, 门限锁定, 无遮挡锁定, 有遮挡锁定 in _锁定链路:
        门限 = 环境.链路门限_dB(甲, 乙)
        无遮挡 = _距离上限_km(环境, 门限)
        有遮挡 = _距离上限_km(环境, 门限, 环境.参数["地形遮挡附加损耗_dB"])
        最大偏差_门限 = max(最大偏差_门限, abs(门限 - 门限锁定))
        最大偏差_距离 = max(
            最大偏差_距离, abs(无遮挡 - 无遮挡锁定), abs(有遮挡 - 有遮挡锁定)
        )
        记录.append(
            f"{名称} {门限:.1f} dB → 无遮挡 {无遮挡:.3f} km / 有遮挡 {有遮挡:.3f} km"
        )

    通过 = 最大偏差_门限 <= 1e-9 and 最大偏差_距离 <= 1e-3
    return 通过, (
        f"[自检·通信4] 三把尺子（《求解条件》§3.6 锁定值）：门限最大偏差 {最大偏差_门限:.3e} dB、"
        f"距离最大偏差 {最大偏差_距离:.3e} km "
        f"→ {'逐位一致' if 通过 else '不一致！'}；" + "；".join(记录)
    )


# 距离粗筛的阈值：三维距离在此之下必可用、在此之上必不可用（见 中继覆盖求解）
_粗筛必可用_km = 1.983      # 有遮挡时的接入上限
_粗筛必不可用_km = 6.270    # 无遮挡时的接入上限


def 粗筛安全检查(场景, 环境) -> tuple[bool, str]:
    """验证"距离粗筛"的两条判据，这是 `中继覆盖求解` 的性能前提。

    抽样位姿上验证：
        D ≤ 1.983 km  ⇒ 接入链路**必可用**（无论是否遮挡）
        D > 6.270 km  ⇒ 接入链路**必不可用**（即使无遮挡）
    若这两条不成立，粗筛会误剪掉可行解或放过不可行解。
    """
    运输机样本 = []
    for 服务区编号 in 场景.编号顺序:
        项 = 场景.服务区表[服务区编号]
        高度 = 项["海拔"] + 服务区作业高度增量_m
        # 投送前后都在服务区上空的 30 m 作业高度，是最苛刻的位姿
        运输机样本.append((项["经度"], 项["纬度"], 高度))

    必可用_错 = 0
    必不可用_错 = 0
    样本数 = 0
    必可用_命中 = 0
    必不可用_命中 = 0

    for 经度, 纬度, 高度 in 运输机样本:
        for 偏移倍数 in (0.2, 0.6, 1.0, 1.4, 2.0, 3.0, 4.0, 5.0):
            # 沿经线方向偏移，构造确定性的中继平面位置
            平面距离 = _粗筛必可用_km * 1000.0 * 偏移倍数
            中继纬度 = 纬度 + 平面距离 / 111320.0
            地面 = 环境.地面高程_at(经度, 中继纬度)
            if not (地面 == 地面):        # NaN
                continue
            for 离地 in (0.0, 150.0, 300.0):
                中继海拔 = 地面 + 离地
                运输机 = 运输机端点(经度, 纬度, 高度)
                中继 = 中继端点(经度, 中继纬度, 中继海拔)
                三维距离_km = 环境.三维距离_km(运输机, 中继)
                可用 = 环境.链路可用(运输机, 中继)
                样本数 += 1
                if 三维距离_km <= _粗筛必可用_km:
                    必可用_命中 += 1
                    if not 可用:
                        必可用_错 += 1
                if 三维距离_km > _粗筛必不可用_km:
                    必不可用_命中 += 1
                    if 可用:
                        必不可用_错 += 1

    通过 = 必可用_错 == 0 and 必不可用_错 == 0 and 必可用_命中 > 0 and 必不可用_命中 > 0
    return 通过, (
        f"[自检·通信5] 距离粗筛安全性（{样本数} 个抽样位姿）："
        f"D ≤ {_粗筛必可用_km} km 误判不可用 {必可用_错}/{必可用_命中}，"
        f"D > {_粗筛必不可用_km} km 误判可用 {必不可用_错}/{必不可用_命中} "
        f"→ {'安全' if 通过 else '不安全！粗筛会误剪或误放'}"
    )


def 遮挡性质检查(场景, 环境) -> tuple[bool, str]:
    """两项结构性检查。

    (a) 固定网关 G01 的端点海拔 = O01 地面海拔 + 天线离地高度。通信规则原文口径，
        **不是**服务区那种 +30 m 作业高度。
    (b) **遮挡随高度单调不增** —— 这是 `悬停高度.py` 最优性命题 1 的前提：
        视线的运输机端固定、中继端抬升 ⇒ 视线上每一点按线性插值抬升，地面高程不变
        ⇒ 被判为遮挡的采样点集合只减不增。**必须由 DEM 实测验证，不能只靠推理。**
    """
    网关 = 环境.网关端点(场景)
    天线离地 = 环境.端点参数(端点_固定网关)["天线离地高度_m"]
    期望海拔 = 场景.调度中心["海拔"] + 天线离地
    海拔偏差 = abs(网关.海拔 - 期望海拔)

    # (b) 中继端抬升，检查接入链路（运输机 ↔ 中继）与回传链路（中继 ↔ G01）
    逆序次数 = 0
    样本数 = 0
    方位角表 = (0.0, 90.0, 180.0, 270.0)
    偏移表_m = (1000.0, 1500.0)
    for 服务区编号 in 场景.编号顺序:
        项 = 场景.服务区表[服务区编号]
        运输机 = 运输机端点(
            项["经度"], 项["纬度"], 项["海拔"] + 服务区作业高度增量_m
        )
        for 方位角 in 方位角表:
            弧 = math.radians(方位角)
            for 偏移 in 偏移表_m:
                中继经度 = 项["经度"] + 偏移 * math.sin(弧) / (111320.0 * math.cos(math.radians(项["纬度"])))
                中继纬度 = 项["纬度"] + 偏移 * math.cos(弧) / 111320.0
                地面 = 环境.地面高程_at(中继经度, 中继纬度)
                if not (地面 == 地面):
                    continue

                接入序列 = []
                回传序列 = []
                for 离地 in range(50, 301, 25):
                    中继 = 中继端点(中继经度, 中继纬度, 地面 + 离地)
                    接入序列.append(环境.视线遮挡(运输机, 中继))
                    回传序列.append(环境.视线遮挡(中继, 网关))
                样本数 += 1
                for 序列 in (接入序列, 回传序列):
                    # False → True 即为逆序（抬高反而被挡），违反单调性
                    逆序次数 += sum(
                        1 for 前, 后 in zip(序列, 序列[1:]) if (not 前) and 后
                    )

    通过 = 海拔偏差 <= 数值容差 and 逆序次数 == 0
    return 通过, (
        f"[自检·通信6] 遮挡性质：G01 端点海拔 {网关.海拔:.2f} m vs 期望 {期望海拔:.2f} m"
        f"（偏差 {海拔偏差:.3e} m）；{样本数} 组位姿 × 11 档高度上，"
        f"遮挡随高度单调性逆序 {逆序次数} 处 "
        f"→ {'合规（悬停高度算法前提成立）' if 通过 else '不合规！'}"
    )


