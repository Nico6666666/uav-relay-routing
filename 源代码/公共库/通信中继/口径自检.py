def _对照代表方案(场景, 路径) -> tuple[float, str]:
    """读取多点多架次调度多目标优化的代表方案，重建载荷包并**重新指派机型与调度**后比四目标。

    ⚠️ 机型不直接采用 JSON 中的值，而是让 `解码` 重新按机队均衡规则指派，
    再与 JSON 对照 —— 这样才有校验意义。
    ⚠️ 必须保持 JSON 中架次的原始顺序：`分配机型` 按 (最紧硬截止, 包序号)
    排序后指派机型，首批截止同为 3600 s 的 8 个包依靠包序号破并列。
    """
