# ===================== H 组：口径 H（按需出动）与排程器不变量 =====================
def 口径H与排程自检(剖面表, 环境) -> tuple[bool, list[str]]:
    """H 组：**口径 H 的可核验断言 + 排程器不变量**。

    (a) `缺口解析自检`：逐架次断言「直连区间 ∪ 缺口区间 == 执行区间」——
        这是"中继只需补洞"的全部依据，此前没有任何检验项直接断言它；
    (b) `排程自检`：oracle 确定性（外层搜索的前提）、证书一致性（下界 ≤ 实现值）、
        以及错峰算子对无人机与共享电池资源的零影响。
    """
    from 源代码.公共库.通信中继.中继排程 import _样例架次, 排程自检
    from 源代码.公共库.通信中继.方案结构 import 全局方案
    from 源代码.公共库.通信中继.缺口解析 import 缺口解析自检, 解析缺口
    from 源代码.公共库.通信中继.调度求解 import 调度架次

    场景 = 剖面表.场景
    记录: list[str] = []
    全部通过 = True

    架次列表 = _样例架次(剖面表)
    if not 架次列表:
        return True, ["[自检·H] 无可用样例架次（多点多架次调度代表方案缺失），跳过"]
    方案 = 全局方案(架次列表=list(架次列表))
    方案.调度表 = 调度架次(场景, list(架次列表))

    通过, 条目 = 缺口解析自检(剖面表, 方案, 解析缺口(剖面表, 方案))
    全部通过 = 全部通过 and 通过
    记录.extend(条目)

    通过, 条目 = 排程自检(剖面表, 环境)
    全部通过 = 全部通过 and 通过
    记录.extend(条目)

    from 源代码.公共库.通信中继.评价 import 联合评价自检

    通过, 条目 = 联合评价自检(剖面表, 环境)
    全部通过 = 全部通过 and 通过
    记录.extend(条目)
    return 全部通过, 记录
