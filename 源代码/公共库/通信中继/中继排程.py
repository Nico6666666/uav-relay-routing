"""
中继排程 —— 外层驱动器：**确定性 oracle + 严格证书**（2026-09-25 重塑）。

本模块现在回答两个问题
----------------------
**① oracle（`评估`）**：给定一个运输方案，中继侧最少能盖住多少缺口？怎么排？
    —— 选址（`中继覆盖求解.逐缺口选址`）→ 包络排程（`中继包络排程.包络排程`）。
    这是外层多目标搜索唯一需要的接口，确定性、无随机、可反复调用。

**② 证书（`证书`）**：这个"最少"到底是不是真下界？该运输方案有没有可能零中断？
    —— 给出**严格下界**与不可行的**证明**，把"搜不到"和"不可能"分开。

为什么必须区分这两件事（本轮实测的直接产物）
--------------------------------------------
`联合调度与中继进度与待办.md` §4.1 原本把零中断失败归因于「受 2.56 kWh 限制，中继必须回基地
换能源组件；该窗口内缺口无人可管」。**实测证明该归因不成立**：

* `中继包络排程.松弛最优` 给出的是**去掉能量约束后**的最优值 —— 它必然 ≤ 真实最优值；
* 5 个多点多架次调度代表方案上，新算法**全部达到该下界**（20 / 15 / 6 / 13 / 10），
  即**零中断在这些运输方案下数学上不可能**，与中继算法、与能源组件、与充电周转都无关。

**真正的约束是"同一条中继线上相邻两站的可串接性"**：两站要么同架次
（需 `后.服务起 ≥ 前.服务终 + 转场 + 建链`），要么不同架次
（需 `后.服务起 ≥ 前.服务终 + 回程 + 周转 + 准备 + 建链 + 去程`，约多 1300 s）。
落在两条路之间的"禁带"里的相邻站，**只能丢一个**。

因此本模块的定位随之改变
------------------------
「错峰」（抬高部分运输架次的开始时刻）**不再是主手段**：它改变的是开始时刻，
而上述下界由缺口的**相对时间结构**决定，平移通常改不动它（实测对 `最少架次数`
推 300 s 后下界不变）。真正能降下界的是**外层搜索换运输方案**（分批 / 访问顺序 / 机型），
故错峰降为**可选算子**（`启用错峰=True`），默认关闭。

`排程` / `排程结果` 的对外签名保持不变 —— `可行性检验自检` 依赖它。
"""
