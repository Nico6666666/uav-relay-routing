def _站表(剖面表, 环境: 通信环境, 站解表, 缺口表: list):
    """构造排程站表（纯几何 + 往返航段预计算，与绝对时刻无关）。"""
    中心 = 剖面表.场景.调度中心
    return 构造排程站表(
        环境, 读取中继机(), 站解表, 缺口表,
        中心["经度"], 中心["纬度"], 中心["海拔"] + 调度中心作业高度增量_m,
    )


def 评估(
    剖面表,
    环境: 通信环境,
    架次列表,
    候选点表=None,
    缓存: dict | None = None,
    最早下界表: dict[int, float] | None = None,
) -> tuple[联合方案, dict]:
    """**确定性 oracle**：给定运输架次，返回 `(联合方案, 摘要)`。

    摘要含中继方案的全部统计 + 严格下界（`未覆盖下界`）与四层归因。
    这是外层搜索唯一需要的接口 —— 不做任何随机选择，同一输入必得同一输出。

    ⚠️ `最早下界表` 是**交给 `调度求解` 的"最早开始时刻下界"**，不是权威时刻表：
    调度器会在此之上兼顾无人机/电池可用时刻，实际开始时刻可能更晚。
    **缺口一律由 `运输方案.调度表` 的"实际"开始时刻解析**
    （早期版本把下界表直接当作权威时刻喂给缺口解析，导致"调度被推后、缺口却按未推后算"
    的不一致 —— 实测会让未覆盖数从 6 错报成 16）。
    """
    场景 = 剖面表.场景
    运输方案 = _构造方案(架次列表, 场景, dict(最早下界表 or {}))
    缺口集合 = 解析缺口(剖面表, 运输方案)
    缺口表 = list(缺口集合.缺口列表)

    if 中继口径 == "一对多":
        中继方案, 摘要 = 驻留排程(剖面表, 环境, 缺口集合, 候选点表, 缓存)
        摘要 = dict(摘要)
        摘要["中继口径"] = "一对多"
        摘要["四层归因"] = 归因_一对多(缺口表, 摘要)
    else:
        站解表, 几何无解 = 逐缺口选址(剖面表, 环境, 缺口集合, 候选点表, 缓存)
        中继方案, 摘要 = 包络排程(剖面表, 环境, 站解表, 缺口表)
        摘要 = dict(摘要)
        摘要["中继口径"] = "一对一"
        摘要["无可覆盖点缺口数"] = len(几何无解)
        摘要["无可覆盖点缺口"] = list(几何无解)
        if 几何无解:
            摘要["未覆盖缺口数"] = len({*几何无解, *中继方案.未覆盖缺口})
        摘要["四层归因"] = 归因(
            剖面表, 环境, _站表(剖面表, 环境, 站解表, 缺口表), 几何无解, 摘要
        )

    联合 = 联合方案(运输方案=运输方案, 中继方案=中继方案)
    摘要["联合完成时间_s"] = round(联合.完成时间, 2)
    摘要["联合总能耗_kWh"] = round(联合.总能耗, 6)
    # 顺手给出"中断时长"（= Σ 未覆盖缺口时长）与缺口规模，省得下游再解析一次缺口。
    # ⚠️ 必须用**调度表的实际开始时刻**解析出来的缺口表（即上面的 `缺口表`）。
    # ⚠️ **不要四舍五入** —— `评价联合方案` 会拿它当精确值用（自检按 1e-9 比对）。
    未覆盖集 = set(中继方案.未覆盖缺口)
    摘要["中断时长_s"] = sum(
        缺.时长 for 序, 缺 in enumerate(缺口表) if 序 in 未覆盖集
    )
    摘要["缺口数"] = len(缺口表)
    摘要["缺口总时长_s"] = sum(缺.时长 for 缺 in 缺口表)
    摘要["硬时限违反箱数"] = _硬时限违反箱数(场景, 运输方案)
    return 联合, 摘要


# ===================== 证书 =====================
def 证书(
    剖面表,
    环境: 通信环境,
    站解表,
    缺口表: list,
) -> dict:
    """**未覆盖缺口数的严格下界** + 该运输方案是否可证不可行（供外部单独调用）。"""
    机 = 读取中继机()
    站表 = _站表(剖面表, 环境, 站解表, 缺口表)
    转场 = 转场表(环境, 机, 站表)
    松弛 = 松弛最优(站表, 转场, 机, 构造中继资源().架次周转时间_s)
    return {
        "站数": len(站表),
        "未覆盖下界": 松弛.未覆盖数,
        "可证不可行": 松弛.未覆盖数 > 0,
        "见证划分站数": [len(松弛.线[0]), len(松弛.线[1])],
    }


def 归因(
    剖面表,
    环境: 通信环境,
    排程站表,
    几何无解: list[int],
    摘要: dict,
) -> dict:
    """**四层归因**：把"盖不住"拆成互不混淆的四类，否则说不清到底为什么不行。

    ① **几何无解**：任何悬停点都覆盖不了该缺口（`求解站` 返回 `None`）；
    ② **单站能量无解**：只服务该站一次出动就超 2.56 kWh（本实例实测 **0 个**）；
    ③ **串接冲突**：包络排程排不下 —— 相邻站的时间间隔落在"同架次来不及、
       换架次也不够周转+往返"的禁带里（实测这是唯一的实际成因）；
    ④ **可达下界**：③ 的**严格下界**；`实现未覆盖 − 下界` 即算法容量的不足。
    """
    场景 = 剖面表.场景
    机 = 读取中继机()
    中心 = 场景.调度中心
    中心经度, 中心纬度 = 中心["经度"], 中心["纬度"]
    中心作业高度 = 中心["海拔"] + 调度中心作业高度增量_m

    # ② 单站能量无解：只服务该站的一次出动是否可行
    单站能量无解: list[int] = []
    for 站 in 排程站表:
        代价 = 单架次可行(
            环境, 机, (站.站,), 站.最近起飞,
            中心经度, 中心纬度, 中心作业高度,
        )
        if 代价 is None:
            单站能量无解.append(站.缺口序号)

    实现 = int(摘要.get("未覆盖缺口数", 0))
    下界 = int(摘要.get("未覆盖下界", 0))
    return {
        "几何无解": sorted(几何无解),
        "几何无解数": len(几何无解),
        "单站能量无解": sorted(单站能量无解),
        "单站能量无解数": len(单站能量无解),
        "串接冲突数": max(实现 - len(几何无解), 0),
        "可达下界": 下界,
        "实现未覆盖": 实现,
        "超出下界": max(实现 - 下界, 0),
        "已达下界": 实现 <= 下界,
        "可证不可行": 下界 > 0,
    }


def 归因_一对多(缺口表: list, 摘要: dict) -> dict:
    """**口径 E 的四层归因**：沿用与口径 D 同名的四层结构，但成因换成了驻留覆盖的机制。

    ① **几何无解**：没有任何候选悬停点能覆盖该缺口（覆盖表的点集为空）；
    ② **单缺口无段**：有覆盖点，但段族里没有任何驻留段包含它（能量或离地上限挡死）；
    ③ **并发/时间冲突**：其余未覆盖 —— 该缺口活跃时，同时活跃的缺口所需驻留点数
       超过中继线数，或与已有架次的前后周转对不上；
    ④ **可达下界**：`覆盖下界` 给出的严格下界；`实现未覆盖 − 下界` 即算法容量不足。

    ⚠️ **诚实性提示**：口径 E 下 `覆盖下界`（LB-A）在本实例上**大多是真空的**
    （实测活跃缺口数 8 时缺额约 0.11 个、20 时约 0.62 个）—— 覆盖点极稠密，
    任意时刻 2 个驻留点几乎足以覆盖全部活跃缺口。故「已达下界」**不足以证明最优**；
    真正有说服力的是「实现未覆盖 == 0」（零中断本身即最优）。
    """
    无覆盖点 = list(摘要.get("无可覆盖点缺口", []))
    各段成员 = 摘要.get("段覆盖缺口集")
    if 各段成员 is None:
        各段成员 = set()

    实现 = int(摘要.get("未覆盖缺口数", 0))
    下界 = int(摘要.get("未覆盖下界", 0))
    无段 = sorted(
        i for i, 缺 in enumerate(缺口表)
        if i not in set(无覆盖点) and i not in 各段成员
    )
    return {
        "几何无解": sorted(无覆盖点),
        "几何无解数": len(无覆盖点),
        "单缺口无段": 无段,
        "单缺口无段数": len(无段),
        "并发时间冲突数": max(实现 - len(无覆盖点) - len(无段), 0),
        "可达下界": 下界,
        "实现未覆盖": 实现,
        "超出下界": max(实现 - 下界, 0),
        "已达下界": 实现 <= 下界,
        "可证不可行": 下界 > 0,
        "下界是否真空": 下界 == 0 and 实现 == 0,
    }


# ===================== 可选错峰算子 =====================
def _中继占用(中继方案) -> dict[str, list[tuple[float, float]]]:
    """每条中继时间线上的**占用区间**（自开始工位准备到返回 O01）。"""
    出: dict[str, list[tuple[float, float]]] = {}
    for 架 in 中继方案.架次列表:
        出.setdefault(架.中继机编号, []).append((架.起飞时刻, 架.返回时刻))
    for 编号 in 出:
        出[编号].sort()
    return 出


def _包络时长(缺口, 往返飞行时间_s: float, 准备_s: float, 建链_s: float) -> float:
    """服务一个缺口所需的**出动包络**时长（不是缺口时长）。

    ⚠️ 早期版本只算 `缺口时长 + 2×建链`，**漏了工位准备与往返飞行**（实测这部分
    还有约 950~1100 s 的固定开销），于是误判"有空位"、给出根本排不下的平移量。
    """
    return 缺口.时长 + 往返飞行时间_s + 准备_s + 建链_s


def _首个空闲时刻(
    占用表: dict[str, list[tuple[float, float]]],
    时长: float,
    最早: float,
    步长: float,
    搜索上限_s: float,
) -> float | None:
    """找最早的 $t \\ge$ `最早`，使**某一条**中继在 $[t, t+\\text{时长}]$ 内空闲。"""
    时刻 = 最早
    上限 = 最早 + 搜索上限_s
    while 时刻 <= 上限:
        for 区间表 in 占用表.values():
            空闲 = all(
                时刻 + 时长 <= 起 + 数值容差 or 时刻 >= 终 - 数值容差
                for 起, 终 in 区间表
            )
            if 空闲:
                return 时刻
        时刻 += 步长
    return None


def _推迟架次(
    下界表: dict[int, float],
    推迟集合: set[int],
    架次列表,
    方案: 全局方案,
    架次序号: int,
    平移: float,
) -> int:
    """把某架次平移 `平移` 秒；受**硬时限拦截**（首批截止 / 医疗期望是硬约束）。

    返回推进数（0 或 1）。
    """
    if 平移 <= 数值容差:
        return 0
    调度条 = 方案.调度表.get(架次序号)
    if 调度条 is None:
        return 0
    架 = next((a for a in 架次列表 if a.序号 == 架次序号), None)
    if 架 is not None and 架.最紧硬截止 is not None:
        最晚环节 = max(架.代价.送达偏移)
        允许平移 = 架.最紧硬截止 - (调度条.开始时刻 + 最晚环节)
        if 平移 > 允许平移 - 数值容差:
            return 0
    新下界 = max(下界表.get(架次序号, 0.0), 调度条.开始时刻) + 平移
    if 新下界 <= 下界表.get(架次序号, -1.0) + 数值容差:
        return 0
    下界表[架次序号] = 新下界
    推迟集合.add(架次序号)
    return 1


def 排程(
    剖面表,
    环境: 通信环境,
    架次列表,
    候选点表=None,
    缓存: dict | None = None,
    最大迭代: int = 默认最大迭代,
    推迟步长_s: float = 默认推迟步长_s,
    最大搜索跨度_s: float = 默认搜索跨度_s,
    到位余量_s: float = 默认到位余量_s,
    容许硬时限违反: bool = False,
    启用错峰: bool = False,
) -> 排程结果:
    """对一批已定型的运输架次求解中继侧，返回 `排程结果`（含严格证书）。

    `启用错峰=False`（默认）时只跑一次 oracle，并用 `重新解析` 复核 —— 因为
    **错峰改不动下界**（见模块 docstring）。置 True 才进入"抬高部分架次开始时刻"的
    邻域搜索（受硬时限拦截），供需要时使用。
    """
    场景 = 剖面表.场景
    架次列表 = list(架次列表)
    if not 架次列表:
        raise ValueError("排程至少需要一个运输架次")

    基线违反 = _硬时限违反箱数(场景, _构造方案(架次列表, 场景, {}))

    下界表: dict[int, float] = {}
    历史: list[dict] = []
    最佳 = None
    推迟集合: set[int] = set()
    迭代次数 = 0
    最大轮次 = 最大迭代 if 启用错峰 else 0

    for 轮 in range(最大轮次 + 1):
        迭代次数 = 轮
        联合, 摘要 = 评估(
            剖面表, 环境, 架次列表, 候选点表, 缓存,
            最早下界表=dict(下界表),
        )
        缺口集合 = 解析缺口(剖面表, 联合.运输方案)
        中继方案 = 联合.中继方案
        违反箱数 = int(摘要["硬时限违反箱数"])

        记录 = {
            "轮次": 轮,
            "未覆盖缺口数": int(摘要["未覆盖缺口数"]),
            "未覆盖下界": int(摘要["未覆盖下界"]),
            "中继架次数": 中继方案.架次数,
            "中继总能耗_kWh": round(中继方案.总能耗, 6),
            "联合完成时间_s": 摘要["联合完成时间_s"],
            "硬时限违反箱数": 违反箱数,
            "延迟架次数": len(下界表),
        }
        历史.append(记录)

        键 = (
            int(摘要["未覆盖缺口数"]),
            联合.完成时间,
            联合.总能耗,
            轮,
        )
        if 最佳 is None or 键 < 最佳[0]:
            最佳 = (
                键, 联合, 缺口集合, 轮, dict(下界表),
                tuple(sorted(推迟集合)), 违反箱数, 摘要,
            )

        if 中继方案.零中断 or 轮 >= 最大轮次:
            break
        if 违反箱数 > 基线违反 and not 容许硬时限违反:
            break

        占用表 = _中继占用(中继方案)
        步长 = 推迟步长_s
        推进 = 0
        站解表, _ = 逐缺口选址(剖面表, 环境, 缺口集合, 候选点表, 缓存)
        站解按缺口 = {解.缺口序号: 解 for 解 in 站解表}
        机 = 读取中继机()
        for 缺口序号 in 中继方案.未覆盖缺口:
            缺口 = 缺口集合.缺口列表[缺口序号]
            站解 = 站解按缺口.get(缺口序号)
            if 站解 is None:
                continue
            架次序号 = 缺口.架次序号
            调度条 = 联合.运输方案.调度表.get(架次序号)
            if 调度条 is None:
                continue
            时长 = _包络时长(
                缺口, 站解.往返飞行时间_s,
                机.工位固定准备时间_s, 机.建链时间_s,
            )
            空位 = _首个空闲时刻(
                占用表, 时长, 缺口.起时刻 + 步长, 步长, 最大搜索跨度_s
            )
            if 空位 is not None:
                推进 += _推迟架次(
                    下界表, 推迟集合, 架次列表, 联合.运输方案,
                    架次序号, 空位 - 缺口.起时刻,
                )
                continue
            for 其他 in 缺口集合.缺口列表:
                if 其他.架次序号 == 架次序号:
                    continue
                if 其他.起时刻 >= 缺口.终时刻 + 到位余量_s:
                    continue
                if 其他.终时刻 <= 缺口.起时刻 - 到位余量_s:
                    continue
                推进 += _推迟架次(
                    下界表, 推迟集合, 架次列表, 联合.运输方案,
                    其他.架次序号, 步长,
                )
        if 推进 == 0:
            break

    _, 联合, 缺口集合, 轮, 下界终, 推迟终, 违反终, 摘要终 = 最佳
    卡 = 摘要终["四层归因"]
    说明 = (
        f"未覆盖 {摘要终['未覆盖缺口数']} 个缺口，严格下界 {摘要终['未覆盖下界']}；"
        f"{'已达下界' if 卡['已达下界'] else '未达下界（算法容量）'}。"
        + (
            "**该运输方案在 2 架中继下零中断可证不可能**，须由外层搜索换运输方案。"
            if 卡["可证不可行"]
            else "该运输方案下界为 0，零中断并非不可能 —— 需要更强的搜索。"
        )
        + f"（迭代 {迭代次数} 轮，推迟 {len(下界终)} 个架次）"
    )
    return 排程结果(
        联合方案=联合, 缺口集合=缺口集合, 迭代次数=迭代次数,
        推迟架次=推迟终, 硬时限违反箱数=违反终,
        推进历史=tuple(历史), 说明=说明, 证书=卡,
    )


def 排程自检(
    剖面表, 环境: 通信环境, 架次数: int = 6
) -> tuple[bool, list[str]]:
    """排程器的**退化与不变量**检查（不依赖具体方案的规模）。

    (a) **无错峰即恒等**：`最早下界表` 为空时，`调度求解` 的结果与不传该参数
        逐位一致（保证搬运扩展对多点多架次调度口径零影响）；
    (b) **推迟单调**：给定一个非空下界，得到的开始时刻不早于该下界；
    (c) **资源不重叠**：错峰后无人机与共享电池的占用仍不重叠、SOC 仍不低于下限；
    (d) **oracle 确定性**：`评估` 两次调用逐位一致（外层搜索的前提）；
    (e) **证书一致性**：下界 ≤ 实现未覆盖数；下界 > 0 时如实报"可证不可行"。

    `架次数` 控制自检规模 —— 确定性检查要跑两次完整求解，取前若干个架次即可。
    """
    from 源代码.公共库.通信中继.可行性检验 import 检验全局方案
    from 源代码.公共库.通信中继.调度求解 import 调度架次

    场景 = 剖面表.场景
    架次列表 = _样例架次(剖面表)[:架次数]
    if not 架次列表:
        return True, ["[自检·排程] 无可用样例架次，跳过"]

    恒等 = 调度架次(场景, 架次列表) == 调度架次(场景, 架次列表, 最早下界表={})

    下界 = {架次列表[0].序号: 9999.0}
    带下界 = 调度架次(场景, 架次列表, 最早下界表=下界)
    推迟成立 = 带下界[架次列表[0].序号].开始时刻 >= 9999.0 - 数值容差

    方案 = 全局方案(架次列表=架次列表)
    方案.调度表 = 带下界
    检验项, _ = 检验全局方案(场景, 方案)
    资源项 = [项 for 项 in 检验项 if 项.名称.startswith(("⑤", "⑥"))]
    资源无违反 = all(项.通过 for 项 in 资源项)

    缓存1: dict = {}
    联合1, 摘要1 = 评估(剖面表, 环境, 架次列表, 缓存=缓存1)
    联合2, 摘要2 = 评估(剖面表, 环境, 架次列表, 缓存=dict())
    确定 = 摘要1["未覆盖缺口数"] == 摘要2["未覆盖缺口数"] and (
        联合1.完成时间 == 联合2.完成时间
    ) and (联合1.总能耗 == 联合2.总能耗)

    卡 = 摘要1["四层归因"]
    证书一致 = 卡["可达下界"] <= 卡["实现未覆盖"] and (
        卡["可证不可行"] == (卡["可达下界"] > 0)
    )

    通过 = (
        恒等 and 推迟成立 and 资源无违反 and 确定 and 证书一致
    )
    return 通过, [
        f"[自检·排程1] 无错峰恒等性：不传 / 传空 `最早下界表` 的调度结果逐位一致 → "
        f"{'一致' if 恒等 else '不一致！'}（保证对多点多架次调度口径零影响）",
        f"[自检·排程2] 推迟单调性与资源不重叠：指定下界 9999 s 后实际开始 "
        f"{带下界[架次列表[0].序号].开始时刻:.2f} s；"
        f"无人机与共享电池检验 {'全部通过' if 资源无违反 else '出现违反！'} → "
        f"{'合规' if 推迟成立 and 资源无违反 else '不合规！'}",
        f"[自检·排程3] oracle 确定性（同一输入两次调用逐位一致）："
        f"未覆盖 {摘要1['未覆盖缺口数']} / 完成 {联合1.完成时间:.2f} s / "
        f"能耗 {联合1.总能耗:.6f} kWh → {'一致' if 确定 else '不一致！'}",
        f"[自检·排程4] 证书一致性：严格下界 {卡['可达下界']} ≤ 实现未覆盖 "
        f"{卡['实现未覆盖']}（超出 {卡['超出下界']}），可证不可行 = {卡['可证不可行']} → "
        f"{'合规' if 证书一致 else '不合规！'}",
    ]


def _样例架次(剖面表):
    """取多点多架次调度「最少架次数」代表方案的架次结构作为自检载体。"""
    路径 = 项目根 / "源代码" / "求解器" / "多点多架次调度" / "多目标优化" / "输出" / "代表方案.json"
    if not 路径.exists():
        return []
    记录 = json.loads(路径.read_text(encoding="utf-8"))["代表方案"]["最少架次数"]
    包列表 = [
        载荷包(
            箱表=tuple(
                (区, tuple(sorted(箱编号列表)))
                for 区, 箱编号列表 in zip(条["访问顺序"], 条["各区箱编号"])
            ),
            访问顺序=tuple(条["访问顺序"]),
        )
        for 条 in 记录["架次"]
    ]
    return 解码(剖面表.场景, 包列表)
