@dataclass(frozen=True)
class 排程结果:
    """中继侧的一次求解结果（oracle 输出 + 证书）。"""

    联合方案: 联合方案
    缺口集合: object
    迭代次数: int
    推迟架次: tuple[int, ...]
    硬时限违反箱数: int = 0
    推进历史: tuple[dict, ...] = ()
    说明: str = ""
    证书: dict = field(default_factory=dict)

    @property
    def 零中断(self) -> bool:
        return self.联合方案.中继方案.零中断

    @property
    def 未覆盖缺口(self) -> tuple[int, ...]:
        return self.联合方案.中继方案.未覆盖缺口

    def 历史表(self) -> list[dict]:
        return [dict(条) for 条 in self.推进历史]


def _构造方案(架次列表, 场景, 最早下界表: dict[int, float], 策略集=None) -> 全局方案:
    方案 = 全局方案(架次列表=list(架次列表))
    方案.调度表 = 调度架次(场景, 架次列表, 策略集=策略集, 最早下界表=最早下界表)
    return 方案


def _硬时限违反箱数(场景, 方案: 全局方案) -> int:
    摘要 = 构造时限摘要(场景, 方案.逐箱送达())
    return len(硬约束违反(摘要))


