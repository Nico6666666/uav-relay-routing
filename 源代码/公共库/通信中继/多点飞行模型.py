"""
多点飞行模型 —— 多点多架次调度的核心：**多航段、载荷沿途递减**的架次代价。

单点往返与组批的架次恒为 `O01 → Si → O01`（时间与能源规则 内核已实现于 `通信中继.飞行模型`）。
多点多架次调度一个架次可连续访问多个服务区：

    σ = (O01, s₁, s₂, …, s_k, O01)

在每个服务区投送后载荷减少，因此**每个航段携带的质量不同**，能耗必须逐段累加：

    航段 ℓ  (s_{ℓ-1} → s_ℓ)
        d_ℓ = 该航段水平直线距离
        H_ℓ = 该航段沿线 DEM 最高地面高程 + 50          （计划巡航海拔）
        q_ℓ = 前 ℓ-1 个服务区投送完毕后的剩余载荷（末段回 O01 时 q = 0）
        Δh⁺_ℓ = max(H_ℓ - 起点作业高度, 0)
        Δh⁻_ℓ = max(H_ℓ - 终点作业高度, 0)
        E_ℓ = E^use · d_ℓ / L_g(q_ℓ) + (m⁰ + q_ℓ)·g·Δh⁺_ℓ / (η_up·3.6e6)
        t_ℓ = Δh⁺_ℓ/v↑ + d_ℓ/v^c + Δh⁻_ℓ/v↓

    E_r     = Σ_ℓ E_ℓ                       ← 返航安全余量约束的左端项
    约束    E_r ≤ 架次能量上限 = (1 − ρ)·E^use，ρ = 返航电量下限 / 100
            等价说法：架次结束时电池剩余 SOC ≥ ρ（本场景 ρ = 20%）
    T_fly   = Σ_ℓ t_ℓ
    T_job   = 工位固定准备 + 每箱装载×总箱数 + T_fly
              + Σ_{i∈σ} (接收点基础交接 + 每箱增加交接 × 该区箱数)

逐箱送达时刻（任务要求输出）取"**完成该区交接**的时刻"：

    送达_i = t_r + 工位固定准备 + 每箱装载×总箱数
             + Σ_{ℓ≤i} t_ℓ + Σ_{j≤i} (基础交接 + 每箱增加交接 × n_j)

**退化一致性**：当 `k = 1` 时，上式逐项退化为单点往返与组批的 `单点往返代价`
（去程爬升 = H - O01作业高度、回程爬升 = H - 服务区作业高度，因为"每次投送后均从
30 米作业高度重新爬升"）。`口径自检.退化一致性检查` 会逐位比对以证明继承无漂移。

本模块**不含任何自造的物理公式**：等效航程、水平能耗、爬升能耗、航段时间
一律 import 自 `通信中继.飞行模型`。
"""
