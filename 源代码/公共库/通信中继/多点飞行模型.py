# ===================== 航段代价 =====================
@dataclass(frozen=True)
class 航段代价:
    """一个航段的完整代价（F2/F3/F4/F6/F10 在多航段下的应用）。"""

    起点编号: str
    终点编号: str
    载荷: float                # q_ℓ（kg）
    水平距离: float            # d_ℓ（m）
    巡航海拔: float            # H_ℓ（m）
    起点作业高度: float        # m
    终点作业高度: float        # m
    爬升: float                # Δh⁺_ℓ（m）
    下降: float                # Δh⁻_ℓ（m）
    水平能耗: float            # kWh
    爬升能耗: float            # kWh
    飞行时间: float            # s

    @property
    def 能耗(self) -> float:
        """E_ℓ = E^hor + E^up（kWh）。下降效率取 0 ⇒ 不计下降附加能耗。"""
        return self.水平能耗 + self.爬升能耗


# ===================== 架次代价 =====================
@dataclass(frozen=True)
class 架次代价:
    """一个 `O01 → s₁ → … → s_k → O01` 架次的完整代价。"""

    机型编号: str
    节点序列: tuple[str, ...]         # (O01, s₁, …, s_k, O01)
    服务区序列: tuple[str, ...]       # (s₁, …, s_k)
    各区箱数: tuple[int, ...]         # 与 服务区序列 对齐
    各区质量: tuple[float, ...]       # 与 服务区序列 对齐
    航段: tuple[航段代价, ...]        # 长度 k+1
    总箱数: int
    总载质量: float
    总装载体积: float
    总能耗: float                     # kWh
    飞行时间: float                   # s
    作业时间: float                   # s
    送达偏移: tuple[float, ...]       # 各服务区**完成交接**时刻相对架次开始时刻的偏移（s）
    架次能量上限: float               # (1 − ρ)·E^use（kWh），返航安全余量约束的右端上限
    能量上限占用率: float             # E_ℓ 合计 / 架次能量上限 ∈ [0, 1]；1.0 = 恰好用满允许量

    @property
    def 访问服务区数(self) -> int:
        return len(self.服务区序列)

    @property
    def 满足返航余量(self) -> bool:
        return self.总能耗 <= self.架次能量上限 + 数值容差

    @property
    def 返航时刻偏移(self) -> float:
        """返回 O01 的时刻相对架次开始时刻的偏移 = 作业时间。"""
        return self.作业时间


# ===================== 单航段代价 =====================
def 航段代价计算(场景: 场景, 机: 机型, 起点编号: str, 终点编号: str, 载荷: float) -> 航段代价:
    """按时间与能源规则 计算 起点编号 → 终点编号 一个航段的能耗与时间。

    起点/终点作业高度按节点类型取（O01 = 地面海拔；服务区 = 地面海拔 + 30 m），
    因此"从服务区起飞"的航段会自动带上 30 m 的爬升起点。
    """
    几何 = 场景.取航段(起点编号, 终点编号)
    巡航海拔 = 几何.巡航海拔
    起点作业高度 = 场景.节点作业高度(起点编号)
    终点作业高度 = 场景.节点作业高度(终点编号)

    爬升 = max(巡航海拔 - 起点作业高度, 0.0)
    下降 = max(巡航海拔 - 终点作业高度, 0.0)

    return 航段代价(
        起点编号=起点编号,
        终点编号=终点编号,
        载荷=载荷,
        水平距离=几何.水平距离,
        巡航海拔=巡航海拔,
        起点作业高度=起点作业高度,
        终点作业高度=终点作业高度,
        爬升=爬升,
        下降=下降,
        水平能耗=航段水平能耗(机, 几何.水平距离, 载荷),
        爬升能耗=航段爬升能耗(机, 爬升, 载荷),
        飞行时间=航段时间(机, 几何.水平距离, 爬升, 下降),
    )


# ===================== 多点架次代价 =====================
def 多点架次代价(
    场景: 场景,
    机: 机型,
    服务区序列: tuple[str, ...] | list[str],
    各区箱列表: list[list[dict]],
) -> 架次代价:
    """计算一个多点架次的完整代价。

    参数
    ----
    服务区序列  服务区编号的**访问顺序**（不含 O01；长度 ≥ 1，且不得重复）
    各区箱列表  与该顺序对齐的逐区货箱列表
    """
    序列 = tuple(服务区序列)
    if len(序列) == 0:
        raise ValueError("一个架次至少要访问一个服务区")
    if len(set(序列)) != len(序列):
        raise ValueError(f"一架次内同一服务区最多访问一次：{序列}")
    if len(各区箱列表) != len(序列):
        raise ValueError(f"服务区序列长度 {len(序列)} 与各区箱列表长度 {len(各区箱列表)} 不一致")
    for 编号 in 序列:
        if 编号 == 调度中心编号:
            raise ValueError(f"服务区序列中不得出现调度中心 {调度中心编号}")

    节点序列 = (调度中心编号,) + 序列 + (调度中心编号,)

    各区箱数 = tuple(len(箱) for 箱 in 各区箱列表)
    各区质量 = tuple(sum(b["质量"] for b in 箱) for 箱 in 各区箱列表)
    总载质量 = sum(各区质量)
    总装载体积 = sum(b["体积"] for 箱 in 各区箱列表 for b in 箱)
    总箱数 = sum(各区箱数)

    # 逐航段：载荷 = 出发时尚未投送的全部箱质量
    航段: list[航段代价] = []
    剩余载荷 = 总载质量
    for 位 in range(len(节点序列) - 1):
        航段.append(
            航段代价计算(场景, 机, 节点序列[位], 节点序列[位 + 1], 剩余载荷)
        )
        if 位 < len(各区质量):        # 最后一段是返航，不再投送
            剩余载荷 -= 各区质量[位]  # 到达 服务区序列[位] 并投送后
            剩余载荷 = max(剩余载荷, 0.0)

    总能耗 = sum(段.能耗 for 段 in 航段)
    飞行时间 = sum(段.飞行时间 for 段 in 航段)

    # 完成各区交接的时刻偏移
    时刻 = 机.工位固定准备时间 + 机.每箱装载时间 * 总箱数
    送达偏移 = []
    for 位, 箱数 in enumerate(各区箱数):
        时刻 += 航段[位].飞行时间                      # 飞抵该服务区
        时刻 += 机.接收点基础交接时间 + 机.每箱增加交接时间 * 箱数
        送达偏移.append(时刻)

    作业时间 = 送达偏移[-1] + 航段[-1].飞行时间         # 最后一次交接后再飞回 O01
    能量上限 = 机.架次能量上限

    return 架次代价(
        机型编号=机.编号,
        节点序列=节点序列,
        服务区序列=序列,
        各区箱数=各区箱数,
        各区质量=各区质量,
        航段=tuple(航段),
        总箱数=总箱数,
        总载质量=总载质量,
        总装载体积=总装载体积,
        总能耗=总能耗,
        飞行时间=飞行时间,
        作业时间=作业时间,
        送达偏移=tuple(送达偏移),
        架次能量上限=能量上限,
        能量上限占用率=总能耗 / 能量上限 if 能量上限 > 0 else float("inf"),
    )


def 体量可行(场景: 场景, 机型: 机型, 各区箱列表: list[list[dict]]) -> bool:
    """载质量与装载体积是否在机型上限内（不含能量项）。"""
    总质量 = sum(b["质量"] for 箱 in 各区箱列表 for b in 箱)
    总体积 = sum(b["体积"] for 箱 in 各区箱列表 for b in 箱)
    return (
        总质量 <= 机型.最大载货质量 + 数值容差
        and 总体积 <= 机型.可用装载体积 + 数值容差
    )


def 逐箱送达时刻(代价: 架次代价, 各区箱编号: list[list[str]], 开始时刻: float) -> list[tuple[str, str, float]]:
    """把架次代价折算成逐箱送达时刻。

    返回 [(货箱编号, 服务区编号, 送达时刻_s), ...]，顺序为访问顺序、区内按箱编号顺序。
    """
    if len(各区箱编号) != len(代价.服务区序列):
        raise ValueError("各区箱编号与访问顺序长度不一致")
    出 = []
    for 位, 编号列表 in enumerate(各区箱编号):
        时刻 = 开始时刻 + 代价.送达偏移[位]
        for 箱编号 in 编号列表:
            出.append((箱编号, 代价.服务区序列[位], 时刻))
    return 出


def 途经几何摘要(场景: 场景, 代价: 架次代价) -> list[dict]:
    """逐航段几何摘要，供论文表格与路线图使用。"""
    return [
        {
            "起点": 段.起点编号,
            "终点": 段.终点编号,
            "起点名称": 场景.节点名称(段.起点编号),
            "终点名称": 场景.节点名称(段.终点编号),
            "水平距离_m": round(段.水平距离, 1),
            "巡航海拔_m": round(段.巡航海拔, 2),
            "起点作业高度_m": round(段.起点作业高度, 2),
            "终点作业高度_m": round(段.终点作业高度, 2),
            "爬升_m": round(段.爬升, 2),
            "下降_m": round(段.下降, 2),
            "载荷_kg": round(段.载荷, 3),
            "水平能耗_kWh": round(段.水平能耗, 6),
            "爬升能耗_kWh": round(段.爬升能耗, 6),
            "该段能耗_kWh": round(段.能耗, 6),
            "飞行时间_s": round(段.飞行时间, 2),
        }
        for 段 in 代价.航段
    ]
