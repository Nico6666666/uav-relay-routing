"""
中继包络排程 —— 缺口集合 $\\mathcal{G}(\\pi)$ → **中继方案**：把「出动包络」排进 2 条中继线。

为什么需要新模块
----------------
原 `中继覆盖求解.拼中继架次` 的贪心择优键是「每站能耗」，倾向把尽量多的站塞进一个
连续长架次以摊薄"回基地"的开销。实测后果：R01 的首架次被锁在空中 `[0, 6721]`，
其中**服务仅 2522 s、悬停干等 1505 s** —— 而每个缺口的服务窗之间夹着大段
**直连间隔**，运输机那时根本不需要中继（口径 H）。全方案合计：中继在位 22298 s
对服务需求 10004 s（**2.23 倍**），纯等待占服务需求的 **65%**。

本模块把「哪些站拼成一个架次」交给**单线动态规划**，把「站分给哪条线」交给
**确定性局部搜索**，并如实报出无法覆盖的缺口。

三条关键性质（DP 成立的前提，逐条由 `中继模型.中继架次代价计算` 核对得出）
--------------------------------------------------------------------
**P1 · 返回与起飞无关**：`返回 = 末站.服务终 + 返航段.飞行时间`；第 2 站起的等待
`= 建链起_m − (服务终_{m−1} + 转场)` 也与起飞无关。**只有首站等待依赖起飞。**

**P2 · 起飞不是自由变量**：合法性要求 `起飞 ≤ L[b]`，其中

    $L[b] = 首站.服务起 - 建链时间 - 去程飞行时间 - 工位固定准备时间$

（晚于它则首站建链来不及）；链式要求 `起飞 ≥ 前一架次.返回 + 架次周转时间`。
由 P1，取 `起飞 = L[b]` **同时**最小化能耗（首站零等待）且不损害下游（返回不变）。
⇒ **起飞恒取 $L[b]$，永不枚举。** 这也正是口径 H「飞到失联了再派中继上天」的落实：
中继的起飞时刻由"缺口起 − 建链 − 去程 − 准备"**倒推**，绝不从 0 起飞。

**P3 · 包络只在同一条线内相互排斥**：同一中继机的相邻架次须满足
`后.起飞 ≥ 前.返回 + 架次周转时间`（C16）。**两条中继线之间没有任何时间排斥**
（它们本就并行，实测两条线的包络完全重叠）。

站序为什么是给定的
------------------
同一架次内，站 m 之后只能是服务起更晚的站：转场要求
`前站.服务终 + 转场飞行 ≤ 后站.建链起 = 后站.服务起 − 建链时间`，
而 `转场飞行 ≥ 0`、`建链时间 = 30 > 0`
⇒ `后站.服务起 − 前站.服务终 ≥ 30 > 0`。故**同一架次内的站按服务起严格升序**。

⚠️ 两个容易搞错之处（本模块已按正确口径处理）：

1. **升序只作枚举顺序，不作可行性判据**。存在服务起完全相等的站对（tie），
   此时"排序后就允许合并"是错的 —— 段可行性必须**逐步重放时间链**（见 `段扫描`），
   并以 `前站.服务终 >= 后站.服务起 − 容差` 作显式守卫。
2. **不同缺口的悬停站可以完全重合**（实测 2 组站址经/纬/海拔全等），此时
   `转场飞行 = 0`。因此"两个站不能同架次"的阈值是 `δ = 建链时间 = 30 s`，
   **不是** `转场飞行 > 0`；段扫描必须允许 `转场飞行 = 0`，不得特殊处理成"合并建链"。

单线 DP
-------
标签 `(U, k, P, E)` =（丢站数, 架次数, 上一架次返回时刻, 累计能耗），首架次 `P = −∞`；
支配 = 四项逐项 ≤。转移两条：

    ① 丢站：         Lbl[j+1] ∪= (U+1, k, P, E)        ← 必须有，否则任何排不下的站会让 DP 无解
    ② 开架次 [j..i]： 前置判 P + 周转 ≤ L[j]；再对每个可行的连续段 i
                     Lbl[i+1] ∪= (U, k+1, 返回(j,i), E + 能耗(j,i))

答案取 `Lbl[n]` 中字典序最小者。**能量是按架次计的（每架次换一组组件），不跨架次累积**，
故 `E` 不进状态；`P` 既作链式约束左端、又是该线完成时刻 —— 这是能把它压到四元组的原因。

段的可行性是**真前缀性质**（增大 `i` 只会让到达更晚、能耗更高）⇒ 首个失败即 `break`。
段内的能耗累计**逐字复刻** `中继架次代价计算` 的求和顺序与表达式，使其与该函数
**逐位一致**（`可行性检验` ⑭ 要求 `总能耗` 在 `1e-9` 内吻合），装配时再用
`中继模型.单架次可行` 复核。

口径
----
链路判定一律调用 `通信模型`；悬停高度与选址由 `中继覆盖求解` 提供（本模块只消费）；
时间与能耗一律调用 `中继模型`。**本模块不写任何通信或物理公式**，也**不 import
`调度求解` / `缺口解析`** —— 它是纯 oracle，输入只有「站表 + 缺口→架次映射」。
"""
