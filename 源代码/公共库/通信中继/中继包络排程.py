# ===================== 排程站 =====================
@dataclass(frozen=True)
class 排程站:
    """一个待覆盖缺口对应的悬停站，附带排程所需的全部预计算量。

    `最近起飞` 即 P2 的 $L[b]$：**该站作为架次首站时的最晚起飞时刻**。
    """

    序: int                      # 在全站序列中的位置（0 起，按 (服务起, 缺口序号) 升序）
    缺口序号: int
    运输架次序号: int
    站: 悬停站
    去程飞行时间: float
    去程能耗: float
    回程飞行时间: float
    回程能耗: float
    最近起飞: float

    @property
    def 服务起(self) -> float:
        return self.站.服务起

    @property
    def 服务终(self) -> float:
        return self.站.服务终

    @property
    def 服务时长(self) -> float:
        return self.站.服务终 - self.站.服务起


def 构造排程站表(
    环境: 通信环境,
    机: 中继机,
    站解表,
    缺口表: list,
    中心经度: float,
    中心纬度: float,
    中心作业高度: float,
) -> tuple[排程站, ...]:
    """把逐缺口的选址结果转成排程序列（按 `(服务起, 缺口序号)` 升序）。

    每个站预计算往返航段与 `最近起飞` —— 它们只取决于站的位置与缺口的服务窗，
    可跨方案复用（选址侧已有位姿指纹缓存）。
    """
    出: list[排程站] = []
    for 序, 站解 in enumerate(sorted(站解表, key=lambda 解: (解.服务起, 解.缺口序号))):
        缺口 = 缺口表[站解.缺口序号]
        站 = 悬停站(
            经度=站解.经度, 纬度=站解.纬度, 地面海拔=站解.地面海拔,
            悬停海拔=站解.悬停海拔,
            服务起=站解.服务起, 服务终=站解.服务终,
            保障缺口=(站解.缺口序号,), 保障架次=(缺口.架次序号,),
        )
        去时间, 去能耗, 回时间, 回能耗 = _往返航段(
            环境, 机, 站, 中心经度, 中心纬度, 中心作业高度
        )
        出.append(
            排程站(
                序=序, 缺口序号=站解.缺口序号, 运输架次序号=缺口.架次序号,
                站=站,
                去程飞行时间=去时间, 去程能耗=去能耗,
                回程飞行时间=回时间, 回程能耗=回能耗,
                最近起飞=站.服务起 - 机.建链时间_s - 去时间 - 机.工位固定准备时间_s,
            )
        )
    return tuple(出)


# 往返航段（O01 ↔ 悬停点）的记忆化表 —— **纯函数记忆化**，不改变任何语义。
# 键 = 站点位置与调度中心的量化指纹（站址由**与时刻无关**的选址给出 ⇒ 跨方案可复用）。
# 外层多目标搜索会对成千上万个运输方案反复调用 `构造排程站表`，而每站两次
# `中继航段代价` 各含一次沿线 DEM 采样 —— 实测这是外层搜索的主要瓶颈。
_往返航段缓存: dict[tuple, tuple[float, float, float, float]] = {}


def 往返航段缓存规模() -> int:
    """记忆化表的条目数（诊断量；越大说明方案间站址越分散）。"""
    return len(_往返航段缓存)


def _往返航段(
    环境: 通信环境,
    机: 中继机,
    站: 悬停站,
    中心经度: float,
    中心纬度: float,
    中心作业高度: float,
) -> tuple[float, float, float, float]:
    """`(去程时间, 去程能耗, 回程时间, 回程能耗)`，按站点位置记忆化。"""
    键 = (
        round(站.经度, 5), round(站.纬度, 5), round(站.悬停海拔, 1),
        round(中心经度, 6), round(中心纬度, 6), round(中心作业高度, 3),
    )
    值 = _往返航段缓存.get(键)
    if 值 is None:
        去程 = 中继航段代价(
            环境, 机, 调度中心编号, "P1",
            中心经度, 中心纬度, 中心作业高度,
            站.经度, 站.纬度, 站.悬停海拔,
        )
        回程 = 中继航段代价(
            环境, 机, "P1", 调度中心编号,
            站.经度, 站.纬度, 站.悬停海拔,
            中心经度, 中心纬度, 中心作业高度,
        )
        值 = (去程.飞行时间, 去程.能耗, 回程.飞行时间, 回程.能耗)
        _往返航段缓存[键] = 值
    return 值


class 转场表:
    """站间转场的 `(飞行时间, 能耗)`，惰性计算 + 记忆化（跨多次 DP 调用复用）。

    站址可以完全重合 ⇒ 允许返回 `(0.0, 0.0)`，**不得**特殊处理成"合并建链"。
    """

    def __init__(self, 环境: 通信环境, 机: 中继机, 站表: tuple[排程站, ...]) -> None:
        self._环境 = 环境
        self._机 = 机
        self._站表 = 站表
        self._缓存: dict[tuple[int, int], tuple[float, float]] = {}

    def 取(self, 甲序: int, 乙序: int) -> tuple[float, float]:
        键 = (甲序, 乙序)
        值 = self._缓存.get(键)
        if 值 is None:
            甲 = self._站表[甲序].站
            乙 = self._站表[乙序].站
            段 = 中继航段代价(
                self._环境, self._机, f"P{甲序 + 1}", f"P{乙序 + 1}",
                甲.经度, 甲.纬度, 甲.悬停海拔,
                乙.经度, 乙.纬度, 乙.悬停海拔,
            )
            值 = (段.飞行时间, 段.能耗)
            self._缓存[键] = 值
        return 值


# ===================== 段的可行性 =====================
@dataclass(frozen=True)
class 段:
    """一条中继线上**连续若干个站由同一次出动覆盖**的方案。"""

    起: int                      # 该线内的起点下标（闭区间）
    终: int
    返回时刻: float
    能耗: float
    等待时长: float
    服务时长: float
    飞行时间: float


def 段扫描(
    机: 中继机,
    局部站表: tuple[排程站, ...],
    全局下标: tuple[int, ...],
    转场: 转场表,
    起: int,
) -> list[段]:
    """自 `起` 向后扫描**由同一次出动覆盖**的全部可行连续段。

    可行性是真前缀性质（`i` 增大只会让到达更晚、能耗更高）⇒ 首个失败即 `break`。

    ⚠️ **能量累计逐字复刻** `中继模型.中继架次代价计算` 的表达式与求和顺序：

        飞行能耗 = Σ(去程, 转场…, 回程)      服务能耗 = P_服 × 服务时长 / 3600
        等待能耗 = P_悬 × 等待时长 / 3600      总能耗 = 飞行 + 服务 + 等待

    这样段内算出的能耗与 `中继架次代价计算` **逐位一致**，⑭ 的 `1e-9` 复算才不会被
    浮点误差顶破。
    """
    建链 = 机.建链时间_s
    准备 = 机.工位固定准备时间_s
    服务功率 = 机.通信服务功率_kW
    悬停功率 = 机.悬停功率_kW
    可用能量 = 机.架次能量上限_kWh

    首 = 局部站表[起]
    到达 = 首.最近起飞 + 准备 + 首.去程飞行时间
    飞行能耗 = 首.去程能耗
    等待时长 = 0.0
    服务时长 = 0.0
    飞行时间 = 首.去程飞行时间

    出: list[段] = []
    for i in range(起, len(局部站表)):
        站 = 局部站表[i]
        建链起 = 站.服务起 - 建链
        if 到达 > 建链起 + 数值容差:
            break

        等待时长 = 等待时长 + (建链起 - 到达)
        服务时长 = 服务时长 + 站.服务时长
        回程飞行时间 = 飞行时间 + 站.回程飞行时间
        总能耗 = (
            飞行能耗 + 站.回程能耗
            + 服务功率 * 服务时长 / 3600.0
            + 悬停功率 * 等待时长 / 3600.0
        )
        if 总能耗 > 可用能量 + 数值容差:
            break

        出.append(
            段(
                起=起, 终=i,
                返回时刻=站.服务终 + 站.回程飞行时间,
                能耗=总能耗,
                等待时长=等待时长,
                服务时长=服务时长,
                飞行时间=回程飞行时间,
            )
        )

        if i + 1 >= len(局部站表):
            break
        后 = 局部站表[i + 1]
        if 站.服务终 >= 后.服务起 - 数值容差:
            # 服务窗重叠或相接（tie）⇒ 不能同架次。这是"升序只作枚举顺序"的守卫。
            break
        转场时间, 转场能耗 = 转场.取(全局下标[i], 全局下标[i + 1])
        到达 = 站.服务终 + 转场时间
        飞行能耗 = 飞行能耗 + 转场能耗
        飞行时间 = 回程飞行时间 + 转场时间
    return 出


# ===================== 单线动态规划 =====================
@dataclass(frozen=True)
class 单线解:
    """一条中继线上的最优切分。"""

    丢站: tuple[int, ...]                     # 未能覆盖的**站序号**（全局下标，升序）
    架次: tuple[tuple[int, int], ...]          # 每架次覆盖的段 [起, 终]（该线内下标，闭区间）
    架次数: int
    完成时刻: float
    总能耗: float

    @property
    def 键(self) -> tuple:
        """与分配键同源的四元组前缀：`(丢站数, 架次数, 完成时刻, 总能耗)`。"""
        return (
            len(self.丢站), self.架次数,
            round(self.完成时刻, 6), round(self.总能耗, 9),
        )


@dataclass
class _标签:
    """DP 的标签：`(U, k, P, E)` + 回溯信息。"""

    U: int
    k: int
    P: float
    E: float
    父: _标签 | None
    动作: tuple


def _剪枝(标签表: list[_标签]) -> list[_标签]:
    """按 `(U, k, P, E)` 的支配关系剪枝 —— **先按 `(U, k)` 归并、只留 P 最小者**。

    为什么可以这样归并（这一步是精确的，不是近似）
    ----------------------------------------------
    `P` 在两个地方被用到，而**两处都只要求"P 越小越好"**：

    1. 最终目标 `(U, k, P, E)` 的字典序第 3 位；
    2. 链式约束 `P + 周转 ≤ 最近起飞[j]`。

    故对固定的 `(U, k)`，P 较大的标签**在任何意义下都不比 P 最小者更优**：
    目标上它更差，可行性上它更紧。⇒ 只保留 P 最小的那个（P 再平则留 E 最小者）**不丢解**。

    效果（实测）：前沿规模从「数百个」压到「至多非支配的 (U,k) 对数」，
    `_剪枝` 里支配比较的生成器迭代次数下降约**一个数量级**——
    它是外层搜索的第一热点（profile 占累计耗时 76%）。
    """
    最小: dict[tuple[int, int], _标签] = {}
    for 标 in 标签表:
        键 = (标.U, 标.k)
        甲 = 最小.get(键)
        if 甲 is None or (标.P, 标.E) < (甲.P, 甲.E):
            最小[键] = 标

    代表 = sorted(最小.values(), key=lambda 标: (标.U, 标.k, 标.P, 标.E))
    保留: list[_标签] = []
    for 标 in 代表:
        if any(
            甲.U <= 标.U
            and 甲.k <= 标.k
            and 甲.P <= 标.P + 数值容差
            and 甲.E <= 标.E + 数值容差
            for 甲 in 保留
        ):
            continue
        保留.append(标)
    return 保留


def 单线最优(
    机: 中继机,
    站表: tuple[排程站, ...],
    子序列: tuple[int, ...],
    转场: 转场表,
    周转: float,
) -> 单线解:
    """对分配给**一条**中继线的站（全局下标升序）求最优切分。

    返回字典序最小的 `(丢站数, 架次数, 完成时刻, 总能耗)` 对应的 `单线解`。
    """
    if not 子序列:
        return 单线解(丢站=(), 架次=(), 架次数=0, 完成时刻=0.0, 总能耗=0.0)

    局部站表 = tuple(站表[序] for 序 in 子序列)
    m = len(局部站表)
    段表 = [段扫描(机, 局部站表, 子序列, 转场, j) for j in range(m)]

    标签表: list[list[_标签]] = [[] for _ in range(m + 1)]
    标签表[0].append(_标签(U=0, k=0, P=float("-inf"), E=0.0, 父=None, 动作=()))

    for j in range(m):
        当前 = _剪枝(标签表[j])
        标签表[j] = 当前
        for 标 in 当前:
            标签表[j + 1].append(
                _标签(U=标.U + 1, k=标.k, P=标.P, E=标.E, 父=标, 动作=("丢", j))
            )
            if 标.P + 周转 > 局部站表[j].最近起飞 + 数值容差:
                continue
            for 段 in 段表[j]:
                标签表[段.终 + 1].append(
                    _标签(
                        U=标.U, k=标.k + 1,
                        P=段.返回时刻, E=标.E + 段.能耗,
                        父=标, 动作=("段", 段.起, 段.终),
                    )
                )

    终态 = _剪枝(标签表[m])
    if not 终态:
        raise RuntimeError("单线 DP 无终态标签（丢站转移保证恒有解）")
    最佳 = min(终态, key=lambda 标: (标.U, 标.k, 标.P, 标.E))

    段列: list[tuple[int, int]] = []
    丢站列: list[int] = []
    游标: _标签 | None = 最佳
    while 游标 is not None:
        if 游标.动作:
            if 游标.动作[0] == "段":
                段列.append((游标.动作[1], 游标.动作[2]))
            elif 游标.动作[0] == "丢":
                丢站列.append(子序列[游标.动作[1]])
        游标 = 游标.父
    段列.reverse()
    丢站列.reverse()

    return 单线解(
        丢站=tuple(sorted(丢站列)),
        架次=tuple(段列),
        架次数=len(段列),
        完成时刻=最佳.P if 段列 else 0.0,
        总能耗=最佳.E,
    )


# ===================== 两线分配 =====================
def _冲突(甲: 排程站, 乙: 排程站, 转场: 转场表, 建链: float) -> bool:
    """两个站**永远不能共享一条中继线**（用**真实转场时间**判定，不是弱化的 δ=建链）。

    同架次需 `后.服务起 ≥ 前.服务终 + 转场飞行 + 建链`；
    不同架次需 `后.服务起 ≥ 前.服务终 + 回程 + 周转 + 准备 + 建链 + 去程`，更严。
    故只要"同架次"这一支两个方向都不成立，两站就绝不可能同线。

    ⚠️ 为什么不能用 `转场 = 0` 的弱判据：站间转场实测可达数百秒，用 0 会漏判大量冲突，
    着色时就会把根本排不到一起的站放进同一条线 —— 实测后果是线0 被塞进 17 站、
    其中 7 站排不下，而线1 只有 8 站。
    """
    距 = 转场.取(甲.序, 乙.序)[0]
    return not (乙.服务起 >= 甲.服务终 + 距 + 建链) and not (
        甲.服务起 >= 乙.服务终 + 距 + 建链
    )


@dataclass(frozen=True)
class 分配:
    """站分派给两条中继线的结果。

    `未派` 是不属于任何一条线的站（全局下标升序）—— 它必须与"已派但被 DP 丢掉"区分开：
    DP 的段必须覆盖线内中间的所有站，把一个注定盖不住的站塞进线里，会**切断**段的连续性，
    连累原本能盖住的站。故"不派"是一个独立、必要的选择。
    """

    线: tuple[tuple[int, ...], tuple[int, ...]]
    单线: tuple[单线解, 单线解]
    未派: tuple[int, ...] = ()

    @property
    def 键(self) -> tuple:
        return 分配键(self.单线[0], self.单线[1], len(self.未派))

    @property
    def 未覆盖站(self) -> tuple[int, ...]:
        return tuple(sorted({*self.单线[0].丢站, *self.单线[1].丢站, *self.未派}))


def 分配键(甲: 单线解, 乙: 单线解, 未派数: int = 0) -> tuple:
    """两线方案的排序键（与 `中继排程` 的键同源，去掉运输侧的硬时限分量）。

    ⚠️ 完成时间取 **max 不取 sum**：两条线并行，联合完成时刻由较晚者决定。
    ⚠️ 组件缺口数不在此键内（它需要装配后才知道），由 `包络排程` 在最终结果上如实报告；
       实测池有余量（见 `充电余量`），不影响选择的正确性。
    """
    return (
        len(甲.丢站) + len(乙.丢站) + 未派数,
        甲.架次数 + 乙.架次数,
        round(max(甲.完成时刻, 乙.完成时刻), 6),
        round(甲.总能耗 + 乙.总能耗, 9),
    )


@dataclass
class _分配器:
    """两线分配的求值上下文（持有单线 DP 的记忆化缓存，避免邻域搜索重复计算）。"""

    机: 中继机
    站表: tuple[排程站, ...]
    转场: 转场表
    周转: float
    _缓存: dict[tuple[int, ...], 单线解] = field(default_factory=dict)

    def 单线(self, 子序列: tuple[int, ...]) -> 单线解:
        解 = self._缓存.get(子序列)
        if 解 is None:
            解 = 单线最优(self.机, self.站表, 子序列, self.转场, self.周转)
            self._缓存[子序列] = 解
        return 解

    def 求解(
        self,
        线: tuple[tuple[int, ...], tuple[int, ...]],
        未派: tuple[int, ...] = (),
    ) -> 分配:
        return 分配(
            线=线, 单线=(self.单线(线[0]), self.单线(线[1])), 未派=tuple(未派)
        )


def 最少删除深度降二(区间: list[tuple[float, float]]) -> tuple[int, ...]:
    """使区间图任意时刻**深度 ≤ 2** 的**最少删除下标集**（贪心；已与穷举最优对拍 400 例）。

    **这是「未覆盖缺口数」的严格下界**，理由：

    1. 同一条中继线上的两个站必须**非冲突**（同架次要 `后.服务起 ≥ 前.服务终 + 建链`；
       不同架次更严）⇒ 两条线 ⇒ 保留站的冲突图必须**二分**；
    2. 冲突判据 `i~j ⟺ s_j < e_i + δ 且 s_i < e_j + δ` 恰是区间
       $[s_i,\\; e_i + \\delta]$ 与 $[s_j,\\; e_j + \\delta]$ 相交（δ = 建链时间）；
    3. 区间图二分 ⟺ 无三角形 ⟺（区间图的 Helly 性质）任意时刻深度 ≤ 2。

    故最少删除数 ≤ 实际未覆盖数。贪心：按左端点扫描，深度超过 2 时删**右端点最大**者
    （它最容易与后续区间冲突）。
    """
    活动: list[tuple[float, int]] = []
    删除: list[int] = []
    for 序, 起, 终 in sorted(
        ((序, 起, 终) for 序, (起, 终) in enumerate(区间)),
        key=lambda 项: (项[1], 项[0]),
    ):
        活动 = [项 for 项 in 活动 if 项[0] > 起]
        bisect.insort(活动, (终, 序))
        if len(活动) > 2:
            _, 删序 = 活动.pop()
            删除.append(删序)
    return tuple(sorted(删除))


def _着色(
    站表: tuple[排程站, ...],
    保留集: set[int],
    转场: 转场表,
    机: 中继机,
    均衡: bool,
) -> tuple[tuple[int, ...], tuple[int, ...]]:
    """对 `保留集` 做 2-着色（冲突判据用**真实转场**）。

    `均衡=True` 时在可选色里挑**当前负载更轻**的那条线（并列取小号），否则取最小可用色。
    不在保留集里的站最后挂到较轻的那条线上，由 DP 自行决定接纳或丢弃。
    """
    线 = [0] * len(站表)
    负载 = [0, 0]
    for i in range(len(站表)):
        if i not in 保留集:
            continue
        占用 = {
            线[j]
            for j in range(i)
            if j in 保留集 and _冲突(站表[j], 站表[i], 转场, 机.建链时间_s)
        }
        可用 = [a for a in range(中继线数) if a not in 占用]
        if not 可用:
            线[i] = 0
        elif 均衡:
            线[i] = min(可用, key=lambda a: (负载[a], a))
        else:
            线[i] = 可用[0]
        负载[线[i]] += 1

    轻 = 0 if 负载[0] <= 负载[1] else 1
    for i in range(len(站表)):
        if i not in 保留集:
            线[i] = 轻
    return (
        tuple(i for i in range(len(站表)) if 线[i] == 0),
        tuple(i for i in range(len(站表)) if 线[i] == 1),
    )


@dataclass(frozen=True)
class 松弛解:
    """松弛问题（去掉能量约束）的最优解：未覆盖数 + **一个达到它的站划分**。

    划分即"见证解" —— 它告诉我们"若不计能量，这 2 条线最省能盖住哪些站"，
    交给 `初始解_见证` 当作两线分配的起点，能把上界压向下界。
    """

    未覆盖数: int
    线: tuple[tuple[int, ...], tuple[int, ...]]


def 松弛最优(
    站表: tuple[排程站, ...], 转场: 转场表, 机: 中继机, 周转: float
) -> 松弛解:
    """**未覆盖缺口数的严格下界** + 达到它的划分：去掉「单架次能量 ≤ 2.56 kWh」后的最优值。

    松弛为什么成立
    --------------
    去掉能量约束后，把一条线上的站**全部并进一个架次**代价只减不增（省掉架次周转与
    回基地往返），故松弛问题等价于：

        把站分给两条线，使每条线内**按服务起相邻**的两站满足有向链式条件，
        最少丢几站。

    而真实可行解必然满足同一条件 —— 对同一条线内相邻的 p（前）、q（后）：

    * 若同架次：`后.服务起 ≥ 前.服务终 + 转场飞行 + 建链`；
    * 若不同架次：p 必是该架次的**末站**（否则 p、q 之间还有本线的站，与"相邻"矛盾），
      故 `前架次.返回 = 前.服务终 + 回程`，且
      `后架次.起飞 ≥ 前架次.返回 + 周转`、`后架次.起飞 ≤ 后.服务起 − 建链 − 去程 − 准备`
      ⇒ `后.服务起 ≥ 前.服务终 + 回程 + 周转 + 准备 + 建链 + 去程`。

    两条路取**较松者**即得判据 `δ = min(转场 + 建链, 回程_p + 周转 + 准备 + 建链 + 去程_q)`。
    于是真实可行解的丢站数 ≥ 松弛最优值 ⇒ **该值是严格下界**。

    实测（5 个多点多架次调度代表方案）：平衡拐点 15/15、最少架次数 6/6、最省能耗 10/10 ——
    **已达下界即该运输方案在 2 架中继下零中断不可能**，与中继算法好坏无关。

    DP：按服务起逐站推进，状态 = 两条线各自最后放的站（`-1` 表示还空着），转移
    「丢站（代价 +1）」/「放进 0 号线」/「放进 1 号线」；状态数是 $O(n^2)$，故总时间 $O(n^3)$。
    """
    n = len(站表)
    if n == 0:
        return 松弛解(未覆盖数=0, 线=((), ()))
    建链 = 机.建链时间_s
    准备 = 机.工位固定准备时间_s
    相容 = [[False] * n for _ in range(n)]
    for a in range(n):
        for b in range(a + 1, n):
            距 = 转场.取(a, b)[0]
            δ = min(
                距 + 建链,
                站表[a].回程飞行时间 + 周转 + 准备 + 建链 + 站表[b].去程飞行时间,
            )
            相容[a][b] = 站表[b].服务起 >= 站表[a].服务终 + δ - 数值容差

    # 层[i][状态] = (代价, 前驱状态, 本步去向)；状态 = (末0, 末1)，去向 ∈ {−1 丢, 0, 1}
    层: list[dict[tuple[int, int], tuple[int, tuple[int, int] | None, int]]] = [
        {} for _ in range(n + 1)
    ]
    层[0][(-1, -1)] = (0, None, -1)

    for i in range(n):
        候选: list[tuple[int, tuple[int, int], int, tuple[int, int]]] = []
        for (末0, 末1), (丢, _, _) in 层[i].items():
            候选.append((丢 + 1, (末0, 末1), -1, (末0, 末1)))          # 丢站
            if 末0 == -1 or 相容[末0][i]:
                候选.append((丢, (i, 末1), 0, (末0, 末1)))            # 放进 0 号线
            if 末1 == -1 or 相容[末1][i]:
                候选.append((丢, (末0, i), 1, (末0, 末1)))            # 放进 1 号线
        for 值, 新键, 去向, 旧键 in 候选:
            已有 = 层[i + 1].get(新键)
            if 已有 is None or 值 < 已有[0]:
                层[i + 1][新键] = (值, 旧键, 去向)

    终键, (终值, _, _) = min(层[n].items(), key=lambda 项: 项[1][0])
    去向表: list[int] = []
    键 = 终键
    for i in range(n, 0, -1):
        _, 前键, 去向 = 层[i][键]
        去向表.append(去向)
        键 = 前键  # type: ignore[assignment]
    去向表.reverse()

    线: list[list[int]] = [[], []]
    for i, 去向 in enumerate(去向表):
        if 去向 >= 0:
            线[去向].append(i)
    return 松弛解(未覆盖数=终值, 线=(tuple(线[0]), tuple(线[1])))


def 松弛下界(站表: tuple[排程站, ...], 转场: 转场表, 机: 中继机, 周转: float) -> int:
    """只要 `松弛最优` 的数值（供摘要与证书使用）。"""
    return 松弛最优(站表, 转场, 机, 周转).未覆盖数


def 初始解_见证(站表: tuple[排程站, ...], 转场: 转场表, 机: 中继机, 周转: float):
    """初始解之五（最强）：直接用**松弛下界的见证划分**，其余站一律**不派**。

    松弛问题（去掉能量约束）的最优划分是最接近下界的候选。实测「最及时」的见证划分
    交给 DP 后**丢 0 站、只用 3 个架次** —— 即下界 13 是可达的。

    ⚠️ 必须保留"未派"这一档：早期版本把松弛丢掉的站"补齐"塞回两条线，结果**掉到 16 个丢站**。
    原因是 DP 的段必须覆盖线内中间的所有站，塞进一个注定盖不住的站会切断段的连续性。
    """
    解 = 松弛最优(站表, 转场, 机, 周转)
    甲, 乙 = set(解.线[0]), set(解.线[1])
    未派 = tuple(sorted(set(range(len(站表))) - 甲 - 乙))
    return (tuple(sorted(甲)), tuple(sorted(乙))), 未派


def 初始解_交替(站表: tuple[排程站, ...], 转场: 转场表, 机: 中继机, 周转: float) -> tuple[tuple[int, ...], tuple[int, ...]]:
    """初始解之四：按时间逐站投给"接得上且余量最大"的那条线（并列取站少者）。

    这条模拟"两条线交替使用"的直觉 —— 单线局部搜索会收敛在某个局部最优，
    一个更"铺开"的初始解能覆盖到它够不着的解。
    """
    线: list[list[int]] = [[], []]
    for i in range(len(站表)):
        得分 = []
        for a in range(中继线数):
            末 = 线[a][-1] if 线[a] else -1
            if 末 == -1:
                得分.append((0.0, 0, a))
                continue
            距 = 转场.取(末, i)[0]
            δ = min(
                距 + 机.建链时间_s,
                站表[末].回程飞行时间 + 周转 + 机.工位固定准备时间_s
                + 机.建链时间_s + 站表[i].去程飞行时间,
            )
            余量 = 站表[i].服务起 - (站表[末].服务终 + δ)
            得分.append((-余量, len(线[a]), a))
        得分.sort()
        线[得分[0][2]].append(i)
    return tuple(线[0]), tuple(线[1])


def 初始解_深度着色(
    站表: tuple[排程站, ...], 转场: 转场表, 机: 中继机
) -> tuple[tuple[int, ...], tuple[int, ...]]:
    """初始解之三（最强）：先取下界对应的**保留集**，再对保留集做**均衡** 2-着色。

    保留集 = 全体站减去 `最少删除深度降二` 的删除集 —— 其规模恰好等于未覆盖的**下界**。
    """
    区间 = [(站.服务起, 站.服务终 + 机.建链时间_s) for 站 in 站表]
    保留 = set(range(len(站表))) - set(最少删除深度降二(区间))
    return _着色(站表, 保留, 转场, 机, 均衡=True)


def 初始解_着色(
    站表: tuple[排程站, ...], 转场: 转场表, 机: 中继机, 均衡: bool = True
) -> tuple[tuple[int, ...], tuple[int, ...]]:
    """初始解之一：按 `(服务起, 缺口序号)` 升序对**真实冲突图**贪心 2-着色。

    放不进任何一条线的站归到负载较轻的那条线，由 DP 决定丢或不丢。
    """
    return _着色(站表, set(range(len(站表))), 转场, 机, 均衡=均衡)


def 初始解_贪心(求值: _分配器) -> tuple[tuple[int, ...], tuple[int, ...]]:
    """初始解之二：按服务起升序逐站投入"使两线全局键最小"的那条线（并列取线号小者）。"""
    线: list[list[int]] = [[], []]
    for i in range(len(求值.站表)):
        候选 = []
        for a in range(中继线数):
            试 = (list(线[0]), list(线[1]))
            试[a].append(i)
            解 = 求值.求解((tuple(试[0]), tuple(试[1])))
            候选.append((解.键, a))
        候选.sort(key=lambda 项: (项[0], 项[1]))
        线[候选[0][1]].append(i)
    return tuple(线[0]), tuple(线[1])


def 求解分配(求值: _分配器, 迭代上限: int = 默认迭代上限) -> tuple[分配, dict]:
    """两线分配的**确定性**局部搜索：多档初始解取优 + 严格改进的邻域搜索。

    邻域（固定遍历序；best-improvement，只接受**严格改进**）：

        N1 move      线间迁移：1→2、2→1；站按源线内升序
        N2 swap      线1 的站（升序）× 线2 的站（升序）
        N3 blockmove 源线升序；起点升序；块长 2..min(最大块长, 剩余)
        N4 派/退派   线 → 未派、未派 → 线（**必要**：见 `分配.未派` 的说明）

    带 `visited` 集（键 = 站集三元划分）防绕圈。返回 `(最优分配, 迭代统计)`。
    """
    站数 = len(求值.站表)
    候选初始: list[tuple[tuple[tuple[int, ...], tuple[int, ...]], tuple[int, ...]]] = [
        初始解_见证(求值.站表, 求值.转场, 求值.机, 求值.周转),
        (初始解_深度着色(求值.站表, 求值.转场, 求值.机), ()),
        (初始解_着色(求值.站表, 求值.转场, 求值.机), ()),
        (初始解_着色(求值.站表, 求值.转场, 求值.机, 均衡=False), ()),
        (初始解_交替(求值.站表, 求值.转场, 求值.机, 求值.周转), ()),
        (初始解_贪心(求值), ()),
        ((tuple(range(站数)), ()), ()),
    ]
    最佳 = min(
        (求值.求解(线, 未派) for 线, 未派 in 候选初始), key=lambda A: A.键
    )

    已访 = {_划分键(最佳.线, 最佳.未派)}
    迭代 = 0
    改进次数 = 0
    while 迭代 < 迭代上限:
        迭代 += 1
        改进: 分配 | None = None
        for 线, 未派 in _邻域(最佳.线, 最佳.未派):
            键划分 = _划分键(线, 未派)
            if 键划分 in 已访:
                continue
            已访.add(键划分)
            试 = 求值.求解(线, 未派)
            if 试.键 < 最佳.键 and (改进 is None or 试.键 < 改进.键):
                改进 = 试
        if 改进 is None:
            break
        最佳 = 改进
        改进次数 += 1

    return 最佳, {
        "迭代次数": 迭代,
        "改进次数": 改进次数,
        "已访问划分": len(已访),
        "是否耗尽预算": 迭代 >= 迭代上限,
    }


def _划分键(
    线: tuple[tuple[int, ...], tuple[int, ...]], 未派: tuple[int, ...]
) -> tuple:
    """站集三元划分的规范化键（用于 visited 集）。"""
    甲, 乙 = tuple(sorted(线[0])), tuple(sorted(线[1]))
    return tuple(sorted((甲, 乙, tuple(sorted(未派)))))


def _邻域(
    线: tuple[tuple[int, ...], tuple[int, ...]], 未派: tuple[int, ...]
):
    """按固定遍历序产出邻域候选（只产出划分，不求值）。"""
    甲, 乙 = set(线[0]), set(线[1])
    漏 = set(未派)
    for i in sorted(甲):                      # N1：甲 → 乙
        yield (tuple(sorted(甲 - {i})), tuple(sorted(乙 | {i}))), tuple(sorted(漏))
    for j in sorted(乙):                      # N1：乙 → 甲
        yield (tuple(sorted(甲 | {j})), tuple(sorted(乙 - {j}))), tuple(sorted(漏))
    for i in sorted(甲 | 乙):                  # N4：线 → 未派
        yield (
            (tuple(sorted(甲 - {i})), tuple(sorted(乙))),
            tuple(sorted(漏 | {i})),
        )
    for i in sorted(漏):                      # N4：未派 → 线
        yield ((tuple(sorted(甲 | {i})), tuple(sorted(乙))), tuple(sorted(漏 - {i})))
        yield ((tuple(sorted(甲)), tuple(sorted(乙 | {i}))), tuple(sorted(漏 - {i})))
    for i in sorted(甲):                      # N2 swap
        for j in sorted(乙):
            yield (
                (tuple(sorted(甲 - {i} | {j})), tuple(sorted(乙 - {j} | {i}))),
                tuple(sorted(漏)),
            )
    for 源 in (0, 1):                          # N3 blockmove
        for 起 in range(len(线[源])):
            for 块长 in range(2, min(最大块长, len(线[源]) - 起) + 1):
                块 = set(线[源][起 : 起 + 块长])
                甲新 = (甲 - 块) if 源 == 0 else (甲 | 块)
                乙新 = (乙 - 块) if 源 == 1 else (乙 | 块)
                yield (tuple(sorted(甲新)), tuple(sorted(乙新))), tuple(sorted(漏))


