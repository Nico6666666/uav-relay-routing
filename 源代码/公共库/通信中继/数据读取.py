# ===================== 通信链路参数 =====================
# 数据文件「参数类别」列到本包端点常量的一一映射。固定网关在数据文件中写作
# "固定网关 G01"，此处归一到 配置.端点_固定网关，使收发参数表可用端点常量索引。
_类别归一 = {
    "运输无人机": 端点_运输无人机,
    "中继接入端": 端点_中继接入端,
    "中继回传端": 端点_中继回传端,
    "固定网关 G01": 端点_固定网关,
}


def _按类别名称取(行表: list[dict], 类别: str, 名称: str) -> float:
    命中 = [行 for 行 in 行表 if 行["参数类别"] == 类别 and 行["参数名称"] == 名称]
    if not 命中:
        raise KeyError(f"通信链路参数中不存在 [{类别}] / [{名称}]")
    if len(命中) > 1:
        raise RuntimeError(f"通信链路参数中 [{类别}] / [{名称}] 出现 {len(命中)} 次，应为唯一")
    return float(命中[0]["参数值"])


def 读取通信参数() -> dict:
    """返回通信规则 链路计算所需的全部参数。

    结构：
        载波频率_MHz / 系统损耗_dB / 地形遮挡附加损耗_dB /
        接收灵敏度_dBm / 衰落裕量_dB
        端点参数: {端点类型: {发射功率_dBm, 天线增益_dBi[, 天线离地高度_m]}}
    """
    行表 = _读表("通信链路参数", "通信参数")

    端点参数: dict[str, dict] = {}
    for 行 in 行表:
        类别 = 行["参数类别"]
        if 类别 not in _类别归一:
            continue  # 传播参数 / 接收参数 不属于端点收发参数
        端点 = _类别归一[类别]
        端点参数.setdefault(端点, {})
        名称 = 行["参数名称"]
        if 名称 == "发射功率（dBm）":
            端点参数[端点]["发射功率_dBm"] = float(行["参数值"])
        elif 名称 == "天线增益（dBi）":
            端点参数[端点]["天线增益_dBi"] = float(行["参数值"])
        elif 名称 == "天线离地高度（m）":
            端点参数[端点]["天线离地高度_m"] = float(行["参数值"])

    应有 = {端点_运输无人机, 端点_中继接入端, 端点_中继回传端, 端点_固定网关}
    缺失 = sorted(应有 - set(端点参数))
    if 缺失:
        raise KeyError(f"通信链路参数缺少端点 {缺失} 的收发参数，实际有 {sorted(端点参数)}")
    for 端点, 参数 in 端点参数.items():
        for 必需 in ("发射功率_dBm", "天线增益_dBi"):
            if 必需 not in 参数:
                raise KeyError(f"端点 [{端点}] 缺少参数 [{必需}]")

    return {
        "载波频率_MHz": _按类别名称取(行表, "传播参数", "载波频率（MHz）"),
        "系统损耗_dB": _按类别名称取(行表, "传播参数", "系统损耗（dB）"),
        "地形遮挡附加损耗_dB": _按类别名称取(行表, "传播参数", "地形遮挡附加损耗（dB）"),
        "接收灵敏度_dBm": _按类别名称取(行表, "接收参数", "接收灵敏度（dBm）"),
        "衰落裕量_dB": _按类别名称取(行表, "接收参数", "衰落裕量（dB）"),
        "端点参数": 端点参数,
    }
