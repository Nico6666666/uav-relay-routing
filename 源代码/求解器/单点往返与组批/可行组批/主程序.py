    轴2.plot(顺序, 时, "s--", color="#e6550d", label="服务区作业时间")
    轴2.set_ylabel("作业时间 (s)", color="#e6550d")
    轴.set_ylabel("总能耗 (kWh)")
    轴.set_xlabel("服务区")
    轴.set_title("图3 各服务区总能耗与作业时间")
    轴.grid(alpha=0.3, axis="y")
    轴2.legend(loc="center left", bbox_to_anchor=(1.02, 0.5), fontsize=9)
    图.tight_layout()
    for 后缀 in ("png", "svg"):
        p = 图表目录 / f"图3_能耗与作业时间.{后缀}"
        图.savefig(p, dpi=300, bbox_inches="tight")
        产出.append(p)
