def 绘图(场景, 全局: Z.全局方案) -> list[Path]:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    plt.rcParams["font.sans-serif"] = ["Microsoft YaHei", "SimHei", "SimSun"]
    plt.rcParams["axes.unicode_minus"] = False
    plt.rcParams["svg.fonttype"] = "none"

    顺序 = 场景.编号顺序
    产出 = []

    架次数 = [全局.各区方案[s].架次数 for s in 顺序]
    质量 = [sum(b["质量"] for b in 场景.取项(s).货箱) for s in 顺序]
    图, 轴 = plt.subplots(figsize=(11, 4.5))
    轴.bar(顺序, 架次数, color="#4a90d9")
    for i, (n, m) in enumerate(zip(架次数, 质量)):
        轴.text(i, n + 0.05, f"{n}", ha="center", fontsize=9)
    轴2 = 轴.twinx()
    轴2.plot(顺序, 质量, "o--", color="#e6550d", label="该区需求总质量")
    轴2.set_ylabel("需求总质量 (kg)", color="#e6550d")
    轴.set_ylabel("架次数")
    轴.set_xlabel("服务区")
    轴.set_title(f"图1 各服务区架次数（贪婪可行解，合计 {全局.总架次数} 架次）")
    轴.grid(alpha=0.3, axis="y")
    轴2.legend(loc="center left", bbox_to_anchor=(1.02, 0.5), fontsize=9)
    图.tight_layout()
    for 后缀 in ("png", "svg"):
        p = 图表目录 / f"图1_各服务区架次数.{后缀}"
        图.savefig(p, dpi=300, bbox_inches="tight")
