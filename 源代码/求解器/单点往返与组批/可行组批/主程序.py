# ==================================================================
def 求解组批(场景, 最大载荷结果) -> tuple[Z.全局方案, dict[str, Z.服务区上下文]]:
    载荷 = 载荷字典(最大载荷结果)
    全局 = Z.全局方案()
    上下文表: dict[str, Z.服务区上下文] = {}
    for 项 in 场景.各项:
        上下文 = Z.构造上下文(
            服务区编号=项.编号,
            水平距离=项.水平距离,
            巡航海拔=项.巡航海拔,
            O01地面海拔=场景.调度中心["海拔"],
            服务区地面海拔=项.地面海拔,
            最大载荷={g: 载荷[g][项.编号] for g in 载荷},
            货箱列表=项.货箱,
        )
        上下文表[项.编号] = 上下文
        全局.各区方案[项.编号] = Z.贪心组批(上下文, 项.货箱, 场景.机型表)
    return 全局, 上下文表


# ==================================================================
# 自检
# ==================================================================
def 自检(场景, 最大载荷结果, 全局: Z.全局方案, 上下文表) -> list[str]:
    记录 = []
    载荷 = 载荷字典(最大载荷结果)

    # 自检1：q* 与最大安全载荷输出一致（口径继承）
    if 十0输出.exists():
        旧 = json.loads(十0输出.read_text(encoding="utf-8"))["最大安全载荷"]
        最大差 = 0.0
        for g in 载荷:
            for s in 载荷[g]:
                最大差 = max(最大差, abs(载荷[g][s] - 旧[g][s]["最大安全载荷_kg"]))
        记录.append(f"[自检1] 与最大安全载荷输出的 q* 最大偏差 = {最大差:.3e} kg（应为 0）")
    else:
        记录.append("[自检1] 未找到最大安全载荷输出，跳过 q* 一致性比对")

    # 自检2：每箱恰好被安排一次
    错配 = []
    for 项 in 场景.各项:
        实际 = sorted(b for a in 全局.各区方案[项.编号].架次列表 for b in a.箱编号)
        应有 = sorted(b["货箱编号"] for b in 项.货箱)
        if 实际 != 应有:
            错配.append(项.编号)
    记录.append(f"[自检2] 货箱覆盖不一致的服务区 = {len(错配)}" + (f" {错配}" if 错配 else "（每箱恰好一次）"))

    # 自检3：逐架次约束
    越限 = []
    for 项 in 场景.各项:
        上下文 = 上下文表[项.编号]
        for 序号, 架 in enumerate(全局.各区方案[项.编号].架次列表, 1):
            机 = 场景.机型表[架.机型编号]
            上限 = 上下文.最大载荷[架.机型编号]
            if 架.质量 > 上限 + 1e-9:
                越限.append((项.编号, 序号, "质量", 架.质量, 上限))
            if 架.体积 > 机.可用装载体积 + 1e-9:
                越限.append((项.编号, 序号, "体积", 架.体积, 机.可用装载体积))
            if 架.箱数 == 0:
                越限.append((项.编号, 序号, "空架次", 0, 0))
    记录.append(f"[自检3] 违反约束的架次数 = {len(越限)}" + (f" {越限[:5]}" if 越限 else "（质量/体积/非空 全部满足）"))

    # 自检4：架次能耗不超过架次能量上限（返航安全余量约束）
    超能 = [
        (项.编号, 架.机型编号, 架.能耗, 场景.机型表[架.机型编号].架次能量上限)
        for 项 in 场景.各项
        for 架 in 全局.各区方案[项.编号].架次列表
        if 架.能耗 > 场景.机型表[架.机型编号].架次能量上限 + 1e-9
    ]
    记录.append(f"[自检4] 超出返航安全余量约束的架次数 = {len(超能)}" + (f" {超能[:5]}" if 超能 else "（全部满足约束）"))

    return 记录


