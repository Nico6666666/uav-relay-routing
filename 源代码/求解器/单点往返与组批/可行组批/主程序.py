def 写架次CSV(场景, 全局: Z.全局方案, 路径: Path) -> None:
    列 = ["服务区", "服务区名称", "架次序号", "机型", "箱数", "装载质量_kg", "载重上限_kg",
          "装载体积_m3", "体积上限_m3", "架次能耗_kWh", "作业时间_s", "货箱清单"]
    with 路径.open("w", newline="", encoding="utf-8-sig") as f:
        写 = csv.writer(f)
        写.writerow(列)
        for 项 in 场景.各项:
            方案 = 全局.各区方案[项.编号]
            for 序号, 架 in enumerate(方案.架次列表, 1):
                机 = 场景.机型表[架.机型编号]
                写.writerow([
                    项.编号, 项.服务区["名称"], 序号, 架.机型编号, 架.箱数,
                    round(架.质量, 2), 机.最大载货质量,
                    round(架.体积, 4), 机.可用装载体积,
                    round(架.能耗, 4), round(架.作业时间, 1),
                    " ".join(架.箱编号),
                ])


def 写汇总CSV(场景, 全局: Z.全局方案, 路径: Path) -> None:
    列 = ["服务区", "服务区名称", "货箱数", "需求总质量_kg", "架次数", "机型构成",
          "总装载质量_kg", "总能耗_kWh", "服务区作业时间_s"]
    with 路径.open("w", newline="", encoding="utf-8-sig") as f:
        写 = csv.writer(f)
        写.writerow(列)
        for 项 in 场景.各项:
            方案 = 全局.各区方案[项.编号]
            构成: dict[str, int] = {}
            for 架 in 方案.架次列表:
                构成[架.机型编号] = 构成.get(架.机型编号, 0) + 1
            写.writerow([
                项.编号, 项.服务区["名称"], len(项.货箱),
                round(sum(b["质量"] for b in 项.货箱), 2),
                方案.架次数,
                " ".join(f"{g}×{构成[g]}" for g in sorted(构成)),
                round(方案.总质量, 2), round(方案.总能耗, 4), round(方案.作业时间, 1),
            ])


