def 平衡拐点(存档: list[个体]) -> 个体:
    """平衡拐点：在**全部按期送达**（f1 = 0）的解中取四目标归一化等权和最小者。

    若无 f1 = 0 的解，则退化为在全部可行解中取归一化等权和最小者。
    选择 f1 = 0 作为门槛的理由：及时性含硬门槛，把"整体按期"作为前提
    再在其余三目标间取平衡，比给出一个部分货箱逾期的解更符合问题背景。
    """
    候选 = [个 for 个 in 存档 if 个.评价.加权总延误 <= 1e-9] or 存档
    归一 = 归一化向量(候选)
    return min(
        候选,
        key=lambda x: (
            sum(v / s for v, s in zip(x.评价.目标向量, 归一)),
            x.评价.架次数,
        ),
    )


def 代表解(存档: list[个体]) -> dict[str, 个体]:
    """四个单目标端点解 + 一个平衡拐点（重复的目标向量只保留一个方案）。"""
    可行 = [个 for 个 in 存档 if 个.是否可行] or 存档
    候选 = {
        "最少架次数": min(可行, key=lambda x: (x.评价.架次数, x.评价.完成时间, x.评价.总能耗)),
        "最短完成时间": min(可行, key=lambda x: (x.评价.完成时间, x.评价.架次数, x.评价.总能耗)),
        "最省能耗": min(可行, key=lambda x: (x.评价.总能耗, x.评价.架次数, x.评价.完成时间)),
        "最及时": min(
            可行, key=lambda x: (x.评价.加权总延误, x.评价.架次数, x.评价.完成时间)
        ),
    }
    拐点 = 平衡拐点(可行)
    if all(拐点.评价.目标向量 != 个.评价.目标向量 for 个 in 候选.values()):
        候选["平衡拐点"] = 拐点
    return {名: 候选[名] for 名 in 代表方案序 if 名 in 候选}


def 交换比曲线(存档: list[个体]) -> list[dict]:
    """沿「架次数上界」分层：给出放宽架次数能换来的完成时间与能耗收益。"""
    可行 = [个 for 个 in 存档 if 个.是否可行]
    if not 可行:
        return []
    出 = []
    for 上界 in sorted({个.评价.架次数 for 个 in 可行}):
        子集 = [个 for 个 in 可行 if 个.评价.架次数 <= 上界]
        出.append(
            {
                "架次数上界": 上界,
                "样本数": len(子集),
                "最小能耗_kWh": min(x.评价.总能耗 for x in 子集),
                "最短完成时间_s": min(x.评价.完成时间 for x in 子集),
                "最小加权总延误": min(x.评价.加权总延误 for x in 子集),
            }
        )
    return 出


def 相邻交换比(存档: list[个体], 横轴: int, 纵轴: int) -> list[dict]:
    """沿横轴递增排序前沿，给出相邻点之间的交换比 d纵轴/d横轴。"""
    有序 = sorted((个 for 个 in 存档 if 个.是否可行), key=lambda x: x.评价.目标向量[横轴])
    出 = []
    for 甲, 乙 in zip(有序, 有序[1:]):
        差横 = 乙.评价.目标向量[横轴] - 甲.评价.目标向量[横轴]
        差纵 = 乙.评价.目标向量[纵轴] - 甲.评价.目标向量[纵轴]
        if abs(差横) <= 1e-12:
            continue
        出.append(
            {
                "横轴": 目标名称[横轴],
                "纵轴": 目标名称[纵轴],
                "横轴增量": 差横,
                "纵轴增量": 差纵,
                "交换比": 差纵 / 差横,
            }
        )
    return 出


