def 绘图(存档: list[个体], 代表: dict[str, 个体], 曲线) -> list[Path]:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    plt.rcParams["font.sans-serif"] = ["Microsoft YaHei", "SimHei", "SimSun"]
    plt.rcParams["axes.unicode_minus"] = False
    plt.rcParams["svg.fonttype"] = "none"
    产出: list[Path] = []

    可行 = [个 for 个 in 存档 if 个.是否可行]
    数据 = 可行 or 存档
    矩阵 = np.array([个.评价.目标向量 for 个 in 数据], dtype=float)

    # ---- 图1：四目标两两投影（6 对）----
    对 = [(0, 1), (0, 2), (0, 3), (1, 2), (1, 3), (2, 3)]
    图, 轴组 = plt.subplots(2, 3, figsize=(16, 9))
    for 轴, (i, j) in zip(轴组.ravel(), 对):
        轴.scatter(矩阵[:, i], 矩阵[:, j], s=26, c="#4a90d9", alpha=0.8, edgecolors="none")
        代表点 = np.array([个.评价.目标向量 for 个 in 代表.values()], dtype=float)
        轴.scatter(代表点[:, i], 代表点[:, j], s=90, marker="*",
                   c="#d62728", zorder=5, label="代表方案")
        轴.set_xlabel(f"{目标名称[i]} ({目标单位[i]})")
        轴.set_ylabel(f"{目标名称[j]} ({目标单位[j]})")
        轴.grid(alpha=0.3)
    轴组[0, 0].legend(fontsize=8)
    图.suptitle(
        f"图1 Pareto 前沿的四目标两两投影（{len(数据)} 个非支配解，全部满足硬约束；★ 为代表方案）"
    )
    图.tight_layout()
    for 后缀 in ("png", "svg"):
        p = 图表目录 / f"图1_Pareto前沿投影.{后缀}"
        图.savefig(p, dpi=300)
        产出.append(p)
    plt.close(图)

    # ---- 图2：按架次数上界的交换曲线 ----
    图, 轴 = plt.subplots(figsize=(11, 4.8))
    位置 = np.arange(len(曲线))
    轴.bar(位置, [条["最小能耗_kWh"] for 条 in 曲线], color="#8c6bb1", label="可达最小总能耗")
    for i, 条 in enumerate(曲线):
        轴.text(i, 条["最小能耗_kWh"] + 0.1, f"{条['最小能耗_kWh']:.1f}",
                ha="center", fontsize=8)
    轴.set_xticks(位置)
    轴.set_xticklabels([f"≤{条['架次数上界']}" for 条 in 曲线])
    轴.set_xlabel("架次数上界 N（允许最多 N 个架次）")
    轴.set_ylabel("可达最小总能耗 (kWh)")
    轴2 = 轴.twinx()
    轴2.plot(位置, [条["最短完成时间_s"] for 条 in 曲线], "s--", color="#e6550d",
             label="可达最短完成时间")
    轴2.set_ylabel("可达最短完成时间 (s)", color="#e6550d")
    轴.set_title("图2 放宽架次数上界能换来的能耗与完成时间")
    轴.grid(alpha=0.3, axis="y")
    轴.legend(loc="upper left", fontsize=9)
    轴2.legend(loc="upper right", fontsize=9)
    图.tight_layout()
    for 后缀 in ("png", "svg"):
        p = 图表目录 / f"图2_权衡交换比.{后缀}"
        图.savefig(p, dpi=300)
        产出.append(p)
    plt.close(图)

    # ---- 图3：代表方案的四目标对比（各目标归一化到自身最大值）----
    名表 = list(代表)
    目标矩阵 = np.array([代表[名].评价.目标向量 for 名 in 名表], dtype=float)
    归一 = np.where(目标矩阵.max(axis=0) > 0, 目标矩阵.max(axis=0), 1.0)
    图, 轴 = plt.subplots(figsize=(12, 5))
    宽 = 0.2
    for i, 名 in enumerate(目标名称):
        轴.bar(np.arange(len(名表)) + (i - 1.5) * 宽, 目标矩阵[:, i] / 归一[i],
               宽, label=f"{名}（满值 {归一[i]:.4g}）")
    轴.set_xticks(np.arange(len(名表)))
    轴.set_xticklabels(名表)
    轴.set_ylabel("各目标 / 自身最大值")
    轴.set_title("图3 代表方案的四目标对比（逐目标归一化，全部按期才为零延误）")
    轴.grid(alpha=0.3, axis="y")
    轴.legend(fontsize=8, ncol=2)
    图.tight_layout()
    for 后缀 in ("png", "svg"):
        p = 图表目录 / f"图3_代表方案对比.{后缀}"
        图.savefig(p, dpi=300)
        产出.append(p)
    plt.close(图)

    # ---- 图4：代表方案的机型构成 ----
    图, 轴 = plt.subplots(figsize=(12, 5))
    底 = np.zeros(len(名表))
    for g in ("A", "B", "C"):
        值 = np.array([代表[名].评价.按机型架次数.get(g, 0) for 名 in 名表], dtype=float)
        轴.bar(名表, 值, bottom=底, color=机型颜色[g], label=f"机型 {g}")
        for i, v in enumerate(值):
            if v > 0:
                轴.text(i, 底[i] + v / 2, f"{int(v)}", ha="center", va="center",
                        fontsize=9, color="white")
        底 = 底 + 值
    轴.set_ylabel("架次数")
    轴.set_title("图4 代表方案的机型构成")
    轴.grid(alpha=0.3, axis="y")
    轴.legend()
    图.tight_layout()
    for 后缀 in ("png", "svg"):
        p = 图表目录 / f"图4_代表方案机型构成.{后缀}"
        图.savefig(p, dpi=300)
        产出.append(p)
    plt.close(图)

    return 产出


