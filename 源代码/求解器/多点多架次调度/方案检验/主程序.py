                    段["终点"], 段["终点名称"],
                    段["水平距离_m"], 段["巡航海拔_m"],
                    段["起点作业高度_m"], 段["终点作业高度_m"],
                    段["爬升_m"], 段["下降_m"], 段["载荷_kg"],
                    段["水平能耗_kWh"], 段["爬升能耗_kWh"],
                    段["该段能耗_kWh"], 段["飞行时间_s"],
