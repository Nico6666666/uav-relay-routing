"""
多点多架次调度 / 方案检验 —— 多点多架次运输调度方案呈现与资源可行性检验

任务要求（多点多架次调度，要求 2）：
    「给出运输路线、架次安排、逐箱送达时刻以及无人机和电池的资源使用情况，
      并检验方案的资源可行性。」

`多目标优化` 已确认**不做单点推荐**，因此本任务对 `多目标优化/输出/代表方案.json` 中的**每个代表方案**
（最少架次数 / 最短完成时间 / 最省能耗 / 最及时 / 平衡拐点）都给出完整的一套结果。
本任务 **不重新优化**，只做两件事：

    1. **方案呈现**：从 JSON 继承每个代表方案的架次结构，独立重建载荷包 →
       重新解码 → 重新调度，输出运输路线 / 架次安排 / 逐箱送达时刻 /
       无人机使用 / 电池使用与充电 五张表与五张图；
    2. **资源可行性检验**：对每个重建出的方案执行 `运输调度.可行性检验` 的九类约束检查，
       并把每个架次的返航余量、每组电池的 SOC 与充电周转逐条列出作为证据。

独立性：本任务不读取 `多目标优化` 的任何中间对象，只读 JSON 中的
(访问顺序, 各区箱编号)；四目标由本任务**独立重算**后与 JSON 对照，超出
JSON 的四舍五入误差即报错。这样"方案检验复算 = 多目标优化结论"是一个真的检查。

运行：
    python "源代码/求解器/多点多架次调度/方案检验/主程序.py"
"""
