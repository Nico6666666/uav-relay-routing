def 写逐箱送达(场景, 方案: 全局方案, 摘要, 路径: Path) -> None:
    归属 = 方案.箱归属表()
    列 = ["货箱编号", "服务区编号", "服务区名称", "物资类型", "质量_kg", "体积_m3",
          "应急优先系数", "是否首批保障", "首批截止时间_s", "期望送达时间_s",
          "所属架次", "机型", "送达时刻_s", "首批是否满足", "是否准时", "延误_s",
          "是否医疗物资（期望为硬约束）", "硬约束是否满足"]
    with 路径.open("w", newline="", encoding="utf-8-sig") as f:
        写 = csv.writer(f)
        写.writerow(列)
        for 条 in sorted(摘要, key=lambda t: (t.送达时刻, t.货箱编号)):
            箱 = 场景.取货箱(条.货箱编号)
            架 = 方案.取架次(归属[条.货箱编号])
            写.writerow([
                条.货箱编号, 条.服务区编号, 场景.服务区表[条.服务区编号]["名称"],
                条.物资类型, 箱["质量"], 箱["体积"], 条.应急优先系数,
                "是" if 条.是否首批保障 else "否",
                条.首批截止时间 if 条.首批截止时间 is not None else "",
                条.期望送达时间, 架.序号, 架.机型编号,
                round(条.送达时刻, 3),
                "是" if 条.首批是否满足 else "否",
                "是" if 条.是否准时 else "否",
                round(条.延误, 3),
                "是" if 条.是否医疗物资 else "否",
                "是" if 条.硬约束是否满足 else "否",
            ])


def 写无人机使用(场景, 方案: 全局方案, 路径: Path) -> None:
    架次表 = 方案.各无人机架次()
    列 = ["无人机编号", "机型", "架次数", "累计作业时间_s", "累计飞行时间_s", "累计能耗_kWh",
          "首次起飞_s", "最后返回_s", "占用率(相对完成时间)", "架次序号清单"]
    完成 = 方案.完成时间 or 1.0
    with 路径.open("w", newline="", encoding="utf-8-sig") as f:
        写 = csv.writer(f)
        写.writerow(列)
        for 编号 in sorted(场景.无人机表):
            清单 = 架次表.get(编号, [])
            记录 = [方案.调度表[a.序号] for a in 清单]
            作业 = sum(r.返回时刻 - r.开始时刻 for r in 记录)
            写.writerow([
                编号, 场景.无人机表[编号]["机型编号"], len(清单),
                round(作业, 3), round(sum(a.飞行时间 for a in 清单), 3),
                round(sum(a.能耗 for a in 清单), 6),
                round(min((r.开始时刻 for r in 记录), default=0.0), 3),
                round(max((r.返回时刻 for r in 记录), default=0.0), 3),
                round(作业 / 完成, 4),
                " ".join(str(a.序号) for a in 清单),
            ])


def 写电池使用(场景, 方案: 全局方案, 路径: Path) -> None:
    """每块电池每次占用/充电事件逐条列出。"""
    事件: dict[str, list] = {}
    for 架 in 方案.架次列表:
        r = 方案.调度表[架.序号]
        事件.setdefault(r.电池编号, []).append((r, 架))

    with 路径.open("w", newline="", encoding="utf-8-sig") as f:
        写 = csv.writer(f)
        写.writerow([
            "共享电池编号", "机型", "事件序", "事件类型", "架次序号",
            "占用开始_s", "占用结束_s", "起始SOC", "结束SOC", "放电量_kWh",
            "充电开始_s", "充电完成_s", "充电时长_s", "等效完全充电时间_s",
            "是否满足返航下限",
        ])
        for 机型编号 in sorted(场景.电池表):
            for 电池编号 in 场景.电池清单[机型编号]:
                记录列表 = sorted(事件.get(电池编号, []), key=lambda x: x[0].开始时刻)
                下限 = 场景.机型表[机型编号].返航安全余量比例
                for 位, (r, 架) in enumerate(记录列表, 1):
                    写.writerow([
                        电池编号, 机型编号, 位, "任务占用", 架.序号,
                        round(r.开始时刻, 3), round(r.返回时刻, 3),
                        round(r.起始SOC, 4), round(r.结束SOC, 4),
                        round(架.能耗, 6),
                        round(r.返回时刻, 3), round(r.电池可用时刻, 3),
                        round(r.充电时长, 3),
                        场景.电池表[机型编号]["等效完全充电时间"],
                        "是" if r.结束SOC >= 下限 - 1e-9 else "否",
                    ])


