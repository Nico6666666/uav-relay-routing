# 容差取多目标优化写入 JSON 时的四舍五入精度之半：
# `_个体摘要` 把完成时间/加权总延误保留 2 位小数、能耗保留 4 位小数。
复算项 = (
    ("架次数", lambda e: e.架次数, 0.0),
    ("全部任务完成时间_s", lambda e: e.完成时间, 5e-3),
    ("总能耗_kWh", lambda e: e.总能耗, 5e-5),
    ("加权总延误", lambda e: e.加权总延误, 5e-3),
)


def 复算一致性自检(场景, 方案: 全局方案, 记录: dict, 摘要, 名: str) -> tuple[list[str], float]:
    """把本任务独立重算的四目标与多目标优化的 JSON 对照，返回 (记录行, 最大偏差)。"""
    评价 = 评价方案(场景, 方案, 摘要)
    最大偏差 = 0.0
    错 = []
    for 名称, 取值, 容差 in 复算项:
        本程序值 = float(取值(评价))
        偏差 = abs(本程序值 - float(记录[名称]))
        最大偏差 = max(最大偏差, 偏差)
        if 偏差 > max(容差, 1e-9):
            错.append(f"{名称} 偏差 {偏差:.3e} > 容差 {容差:.1e}"
                      f"（本任务 {本程序值} vs 多目标优化 {记录[名称]}）")
    if 错:
        raise RuntimeError(f"方案检验复算与多目标优化的代表方案 [{名}] 不一致：" + "；".join(错))
    return (
        [
            f"[复算] 方案「{名}」四目标与多目标优化一致（最大偏差 {最大偏差:.3e}，"
            f"均在 JSON 舍入误差内）：架次 {评价.架次数}，"
            f"完成时间 {评价.完成时间:.2f} s，能耗 {评价.总能耗:.6f} kWh，"
            f"加权总延误 {评价.加权总延误:.2f}"
        ],
        最大偏差,
    )


