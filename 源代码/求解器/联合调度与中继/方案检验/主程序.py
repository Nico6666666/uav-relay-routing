def _存图(图, 目录: Path, 名: str) -> list[Path]:
    出 = []
    目录.mkdir(parents=True, exist_ok=True)
    for 后缀 in ("png", "svg"):
        p = 目录 / f"{名}.{后缀}"
        图.savefig(p, dpi=300)
        出.append(p)
    return 出


def _节点坐标(场景) -> dict[str, tuple[float, float]]:
    出 = {"O01": (场景.调度中心["经度"], 场景.调度中心["纬度"])}
    for 编号, 区 in 场景.服务区表.items():
        出[编号] = (区["经度"], 区["纬度"])
    return 出


