"""
联合调度与中继 / 方案检验 —— 联合调度方案呈现与通信保障 / 资源可行性检验

任务要求（联合调度与中继）：
    「给出运输路线、架次安排、逐箱送达时刻以及无人机和电池的资源使用情况，
      并检验方案的资源可行性。」
    ＋ 联合调度与中继新增：**通信保障关系**与中继侧（2 架中继、6 组共享能源组件）的资源使用。

`五目标优化` 已确认**不做单点推荐**，因此本任务对 `五目标优化/输出/代表方案.json` 中的**每个代表方案**
（最少运输架次数 / 最短联合完成时间 / 最省联合能耗 / 最及时 / 最少中继架次数，
以及目标向量不重复时才追加的平衡拐点 —— 个数上限 6、随规模档位而定）
各给一套完整结果。本任务 **不重新优化**，只做两件事：

    1. **方案呈现**：从 JSON 继承每个代表方案的组批与访问顺序，独立重建载荷包 →
       重新解码 → 重新调度 → 重新解析缺口 → 重新排中继，输出 **9 张表 × N 个方案**
       （N = JSON 里实际给出的代表方案数）
       （运输路线 / 架次安排 / 逐箱送达时刻 / 无人机使用 / 共享电池使用与充电 /
       中继架次与悬停站 / **中继能源组件使用与充电** / **通信保障关系** /
       通信缺口清单）与 6 张图；
    2. **可行性检验**：对每个重建出的方案执行 `通信中继.可行性检验.检验联合方案` 的
       **十七项约束**（运输 ①–⑨ ＋ 通信/中继 ⑩–⑰），并把逐架次的返航余量、
       每组电池与能源组件的 SOC 与充电周转、每一条保障关系逐条列出作为证据。

独立性（与多点多架次调度方案检验同一口径）
-------------------------------
本任务**不 import `五目标优化` 的任何对象**，只读 JSON 里的组批结构（访问顺序 / 各区箱编号）
与它记录的错峰步长；五目标由本任务**独立重算**后与 JSON 对照，超出 JSON 的四舍五入
误差即报错。这样「方案检验复算 = 五目标优化结论」是一个真的检查，而不是自我印证。

**准入结论的传递**：若 `五目标优化` 在本规模下未搜到全可行解，本任务**如实照录**，
不把「违反量最小的参考解」包装成「可行方案」—— 每个方案页首都会标注它到准入
还差多少（未覆盖缺口数 / 硬时限违反箱数），并给出严格下界作为"是否只是算法没做好"的判据。

运行：
    python "源代码/求解器/联合调度与中继/方案检验/主程序.py"
"""
