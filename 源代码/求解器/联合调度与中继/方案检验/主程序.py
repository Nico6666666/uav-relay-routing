# 容差取五目标优化写入 JSON 时的四舍五入精度之半：
# `_个体摘要` 把及时性/完成时间保留 3 位小数、能耗保留 6 位小数。
复算项 = (
    ("运输架次数", lambda e: e.运输架次数, 0.0),
    ("中继架次数", lambda e: e.中继架次数, 0.0),
    ("物资配送及时性", lambda e: e.加权总延误, 5e-4),
    ("联合任务完成时间_s", lambda e: e.联合完成时间, 5e-4),
    ("联合总能耗_kWh", lambda e: e.联合总能耗, 5e-7),
    ("未覆盖缺口数", lambda e: e.未覆盖缺口数, 0.0),
    ("未覆盖下界", lambda e: e.未覆盖下界, 0.0),
)


def 复算一致性自检(剖面表, 联合, 摘要, 条: dict, 名: str) -> tuple[list[str], float]:
    """把本任务独立重算的五目标与五目标优化的 JSON 逐项对照，返回 (记录行, 最大偏差)。"""
    评价 = 评价联合方案(剖面表, 联合, 摘要)
    最大偏差 = 0.0
    错 = []
    for 名称, 取值, 容差 in 复算项:
        本程序值 = float(取值(评价))
        偏差 = abs(本程序值 - float(条[名称]))
        最大偏差 = max(最大偏差, 偏差)
        if 偏差 > max(容差, 1e-12):
            错.append(
                f"{名称} 偏差 {偏差:.3e} > 容差 {容差:.1e}"
                f"（本任务 {本程序值} vs 五目标优化 {条[名称]}）"
            )
    if 错:
        raise RuntimeError(f"方案检验复算与五目标优化的代表方案 [{名}] 不一致：" + "；".join(错))
    return (
        [
            f"[复算] 方案「{名}」五目标与五目标优化一致（最大偏差 {最大偏差:.3e}，"
            f"均在 JSON 舍入误差内）：及时性 {评价.加权总延误:.3f}，"
            f"完成 {评价.联合完成时间:.3f} s，能耗 {评价.联合总能耗:.6f} kWh，"
            f"运输 {评价.运输架次数} 架次，中继 {评价.中继架次数} 架次，"
            f"未覆盖 {评价.未覆盖缺口数}（下界 {评价.未覆盖下界}）"
        ],
        最大偏差,
    )


