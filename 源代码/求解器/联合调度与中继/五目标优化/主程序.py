def 写方案CSV(联合, 摘要: dict, 路径: Path) -> None:
    """一个代表方案的**运输与中继联合排程表**（逐架次一行）。"""
    列 = [
        "类型", "架次序号", "载具", "能源资源", "开始/起飞时刻_s", "返回时刻_s",
        "访问顺序 / 悬停站序", "服务区数 / 站数", "箱数 / 保障缺口数",
        "能耗_kWh", "能量上限占用率", "结束SOC", "返航/保障是否合规",
        "保障运输架次", "组件充电完成时刻_s",
    ]
    台账 = {条["中继架次序号"]: 条 for 条 in 联合.中继方案.能源组件使用}

    with 路径.open("w", newline="", encoding="utf-8-sig") as f:
        写 = csv.writer(f)
        写.writerow(列)
        for 架 in 联合.运输方案.架次列表:
            r = 联合.运输方案.调度表[架.序号]
            写.writerow([
                "运输", 架.序号, f"{架.机型编号}型/{r.无人机编号}", r.电池编号,
                round(r.开始时刻, 2), round(r.返回时刻, 2),
                "O01→" + "→".join(架.服务区序列) + "→O01",
                架.访问服务区数, 架.总箱数,
                round(架.能耗, 4), round(架.代价.能量上限占用率, 4),
                round(r.结束SOC, 4),
                "是" if 架.代价.满足返航余量 else "否", "", "",
            ])
        for 架 in 联合.中继方案.架次列表:
            条 = 台账.get(架.序号, {})
            写.writerow([
                "中继", 架.序号, 架.中继机编号, 架.能源组件编号,
                round(架.起飞时刻, 2), round(架.返回时刻, 2),
                "→".join(f"({站.经度:.5f}, {站.纬度:.5f})" for 站 in 架.站序列)
                or "（无站）",
                架.站数, 架.保障缺口数,
                round(架.总能耗, 4), round(条.get("能量上限占用率", 0.0), 4),
                round(条.get("结束SOC", 1.0), 4),
                "是" if 条.get("满足返航电量", True) else "否",
                ",".join(str(x) for x in 架.保障架次),
                round(条.get("充电完成时刻_s", 0.0), 2),
            ])


