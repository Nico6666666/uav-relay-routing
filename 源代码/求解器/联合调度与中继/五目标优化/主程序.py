def 错峰扫掠表(结果: 联合搜索结果) -> list[dict]:
    """逐错峰步长的**对撞指标**：同一步长下搜索能同时取到的最好水平。

    ★ 本任务最要紧的一张表 —— 它把「零中断可达」与「首批截止」之间的互斥关系
    摆成一条可读的曲线：把未覆盖缺口往下压的每一步，硬时限违反箱数是否同步上升
    （见 `联合调度与中继进度与待办.md` §2.3.1 与 §2.3 的四层归因）。
    """
    出 = []
    for 步长, 子结果, 统计 in 结果.逐步长:
        存档 = list(子结果.存档)
        出.append(
            {
                "错峰步长_s": 步长,
                "存档规模": len(存档),
                "全可行数": 统计["可行"],
                "零中断数": 统计["零中断"],
                "最优未覆盖缺口数": 统计["最优未覆盖"],
                "最优严格下界": min(
                    (getattr(个.评价, "未覆盖下界", -1) for 个 in 存档), default=-1
                ),
                "最少硬时限违反箱数": min(
                    (_评价(个).运输评价.硬约束违反箱数 for 个 in 存档), default=0
                ),
                "最少违反量_s": round(统计["最少违反量"], 2),
                "最短联合完成时间_s": min(
                    (_评价(个).联合完成时间 for 个 in 存档), default=0.0
                ),
            }
        )
    return 出


def 按目标分层(存档: list, 维: int) -> list[dict]:
    """沿第 `维` 个目标**上界**分层：给出放宽它能换来的其余目标的收益。"""
    可行 = _候选子集(存档)
    if not 可行:
        return []
    出 = []
    for 上界 in sorted({_评价(个).目标向量[维] for 个 in 可行}):
        子集 = [个 for 个 in 可行 if _评价(个).目标向量[维] <= 上界]
        出.append(
            {
                "上界": 上界,
                "样本数": len(子集),
                **{
                    f"最小{联合目标名称[j]}": min(
                        _评价(x).目标向量[j] for x in 子集
                    )
                    for j in range(len(联合目标名称))
                    if j != 维
                },
            }
        )
    return 出


def 相邻交换比(存档: list, 横轴: int, 纵轴: int) -> list[dict]:
    """沿横轴递增排序前沿，给出相邻点之间的交换比 d纵轴/d横轴。"""
    有序 = sorted(存档, key=lambda x: _评价(x).目标向量[横轴])
    出 = []
    for 甲, 乙 in zip(有序, 有序[1:]):
        差横 = _评价(乙).目标向量[横轴] - _评价(甲).目标向量[横轴]
        差纵 = _评价(乙).目标向量[纵轴] - _评价(甲).目标向量[纵轴]
        if abs(差横) <= 1e-12:
            continue
        出.append(
            {
                "横轴": 联合目标名称[横轴],
                "纵轴": 联合目标名称[纵轴],
                "横轴增量": 差横,
                "纵轴增量": 差纵,
                "交换比": 差纵 / 差横,
            }
        )
    return 出


