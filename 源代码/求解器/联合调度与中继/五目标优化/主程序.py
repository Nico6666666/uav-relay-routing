def _评价(个):
    """局部只读别名：把 `个.评价`（联合评价结果）取出来，供键函数使用。"""
    return 个.评价


def 平衡拐点(存档: list) -> object:
    """平衡拐点：在**全可行**（零中断且全部硬时限满足）的解中取五目标归一化等权和最小者。

    无全可行解时按「零中断 → 全部违反量最小的子集」逐级退化（`候选子集` 与
    `代表解` 用同一套退化口径，见 `_候选子集`）。
    """
    候选 = _候选子集(存档)
    归一 = 归一化向量(候选)
    return min(
        候选,
        key=lambda x: (
            sum(v / s for v, s in zip(x.评价.目标向量, 归一)),
            x.评价.目标向量,
        ),
    )


def _候选子集(存档: list) -> list:
    """代表方案的候选集，按准入条件逐级退化（顺序即优先级）。

    1. **全可行**：零中断 **且** 全部硬时限满足 —— 唯一可直接交付的集合；
    2. **零中断**：通信达标但首批截止未满足 —— 说明"通信换时间"的张力；
    3. **违反量最小**：连零中断都没搜到 —— 取距离准入最近者，
       并在报告里如实标注"本规模未搜到准入方案"。
    """
    return (
        [个 for 个 in 存档 if 个.是否可行]
        or [个 for 个 in 存档 if getattr(个.评价, "零中断", False)]
        or 存档
    )


def 代表解(存档: list) -> dict[str, object]:
    """五个单目标端点解 + 一个平衡拐点（重复的目标向量只保留一个方案）。

    全可行子集非空时一律从它里面取（通信是准入条件）；否则按 `_候选子集` 退化，
    并在报告首页显著标注 —— 这本身就是「零中断与首批截止互斥」这一结论的证据
    （见 本文的零中断不可行性定理 与进度文档 §2.3.1）。
    """
    可行 = _候选子集(存档)
    候选 = {
        "最少运输架次数": min(
            可行, key=lambda x: (_评价(x).运输架次数, _评价(x).联合完成时间)
        ),
        "最短联合完成时间": min(
            可行, key=lambda x: (_评价(x).联合完成时间, _评价(x).运输架次数)
        ),
        "最省联合能耗": min(
            可行, key=lambda x: (_评价(x).联合总能耗, _评价(x).运输架次数)
        ),
        "最及时": min(
            可行, key=lambda x: (_评价(x).加权总延误, _评价(x).运输架次数)
        ),
        "最少中继架次数": min(
            可行,
            key=lambda x: (
                _评价(x).中继架次数, _评价(x).未覆盖缺口数, _评价(x).联合完成时间
            ),
        ),
    }
    拐点 = 平衡拐点(存档)
    if all(拐点.评价.目标向量 != 个.评价.目标向量 for 个 in 候选.values()):
        候选["平衡拐点"] = 拐点
    return {名: 候选[名] for 名 in 代表方案序 if 名 in 候选}


