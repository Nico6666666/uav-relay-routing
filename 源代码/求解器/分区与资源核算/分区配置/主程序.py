def 四方面比较行(上下文: "上下文") -> list[list]:
    """任务要求 1 的四个方面 × 2/3 分区的并列对比。

    列含义：组数 / 方面 / 指标 / 取值 / 对照值 / 增量或缺口。
    明细行的「对照值」是库存，「增量或缺口」是缺口 —— 由指标文字说明。
    """
    行 = []
    for k in 配置.分区组数候选:
        数据 = 上下文.结果[k]
        账表 = 数据["账表"]
        规模 = sum(账.各组峰值之和 for 账 in 账表)
        基线规模 = sum(账.全局峰值 for 账 in 账表)
        冗余 = sum(账.跨组复用丢失 for 账 in 账表)
        缺口 = sum(账.缺口 for 账 in 账表)
        数据["规模"], 数据["基线规模"], 数据["冗余"], 数据["缺口"] = 规模, 基线规模, 冗余, 缺口
        行.append([k, "资源配置规模", "资源单位合计", 规模, 基线规模, 规模 - 基线规模])
        行.append([k, "资源冗余", "跨组复用丢失 Δ 合计", 冗余, 0, 冗余])
        行.append([k, "组间工作量均衡", "架次极差", 数据["方案"].架次极差, "", ""])
        行.append([k, "组间工作量均衡", "能耗极差_kWh", round(数据["方案"].能耗极差, 6), "", ""])
        行.append([k, "组间工作量均衡", "时间极差_s", round(数据["方案"].时间极差, 1), "", ""])
        行.append([k, "资源缺口", "缺口单位合计", 缺口, "", ""])
        for 账 in 账表:
            行.append([k, f"缺口明细·{账.显示名}", "各组需求 / 库存", 账.各组峰值之和, 账.库存, 账.缺口])
    return 行


