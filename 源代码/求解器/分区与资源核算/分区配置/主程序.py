def 写分配证书(上下文: "上下文") -> list[dict]:
    """把 `最少单位分配` 的编号翻译成「逻辑资源号 → 承担哪些任务」，作为可行性证书。

    区间图是完美图 ⇒ 占用单位数恒等于峰值并发 ⇒ 这张表本身就是「峰值个单位够用」的
    构造性证明：同号单位的任务两两不重叠，可依次由同一架/一组资源承担。
    """
    行表: list[dict] = []
    for k in 配置.分区组数候选:
        数据 = 上下文.结果[k]
        槽位 = 配置.资源类顺序
        for 序, (方案, 组需求表) in enumerate(zip(数据["候选"], 数据["组需求"]), start=1):
            架次组 = 资源核算.架次到组(方案)
            for 组需求 in 组需求表:
                for 键 in 槽位:
                    分配 = 组需求.单位分配.get(键)
                    if 分配 is None:
                        continue
                    成员 = [
                        x
                        for x in 上下文.区间表.取(*键)
                        if 组需求.组号 - 1 in 资源核算.归属组(x, 架次组)
                    ]
                    if len(成员) != len(分配):
                        raise RuntimeError(
                            f"k={k} 候选{序} 组{组需求.组号} {键} 的区间数 {len(成员)} "
                            f"与单位分配数 {len(分配)} 不一致"
                        )
                    for 成员区间, 号 in zip(成员, 分配):
                        行表.append({
                            "k": k, "候选序": 序, "组号": 组需求.组号,
                            "资源类": 键[0], "子类": 键[1], "逻辑资源号": 号 + 1,
                            "承担任务": [
                                f"{成员区间.载体}[{成员区间.左_s:.1f},"
                                f"{成员区间.右_s:.1f}]"
                            ],
                        })
    return 行表


