def 自检(上下文: "上下文") -> list[str]:
    """内核自检 + 原子 + 枚举完备性 + 逐方案合法性与资源账恒等式。"""
    条目 = list(
        口径自检.内核自检(
            上下文.基线, 上下文.机型表, 上下文.电池表, 上下文.中继机型,
            上下文.中继无人机, 上下文.组件表, 上下文.区间表, 上下文.库存,
        )
    )
    条目.extend(服务区原子.原子自检(上下文.基线, 上下文.原子表, 上下文.服务区表))
    条目.append(
        f"[自检] 无缝接力收口：触发 {len(上下文.区间表.收口)} 处，"
        f"收口量 {[round(x.收口量_s, 9) for x in 上下文.区间表.收口]}"
        f"（保留分支：复算残差被对齐到同一刻度）"
    )
    条目.extend(分区枚举.枚举对拍(2)[:2])
    条目.extend(不分区需求与启封对照(上下文))

    for k, 数据 in 上下文.结果.items():
        条目.extend(分区方案.分区自检(k, 数据["方案"], 上下文.原子表, 上下文.基线))
        条目.extend(资源账.资源账自检(数据["账表"]))
        条目.append(
            f"[自检] k={k} 候选数与独立实现一致：{数据['候选数']} == 斯特林数 "
            f"S({len(上下文.原子表)},{k}) = {分区枚举.规范形合法方案数(k, len(上下文.原子表))}"
        )
    return 条目


def 不分区需求与启封对照(上下文: "上下文") -> list[str]:
    """把「不分区需求」与「联合调度与中继实际启封的资源」对照。

    这是精度陷阱的**硬证据**：若复算路径引入了系统性偏差（例如用打印精度的
    `结束SOC` 反推充电时长），峰值会虚增，这里立刻表现为「需求 > 启封」。
    """
    启封机: dict[str, set[str]] = {}
    启封电: dict[str, set[str]] = {}
    for 架 in 上下文.基线.运输架次:
        启封机.setdefault(架.机型, set()).add(架.无人机)
        启封电.setdefault(架.机型, set()).add(架.共享电池)
    启封组件 = {架.能源组件 for 架 in 上下文.基线.中继架次}

    条目 = []
    错 = []
    for 资源类, 子类 in 配置.资源类顺序:
        需求 = 上下文.全局需求.取(资源类, 子类)
        if 资源类 == "运输无人机":
            启封 = len(启封机.get(子类, set()))
        elif 资源类 == "共享电池":
            启封 = len(启封电.get(子类, set()))
        elif 资源类 == "中继无人机":
            启封 = len({架.中继机 for 架 in 上下文.基线.中继架次})
        else:
            启封 = len(启封组件)
        if 需求 > 启封:
            错.append(f"{资源类}{子类} 需求 {需求} > 联合调度与中继实际启封 {启封}")
        条目.append(f"    不分区 {资源类}{子类}：需求 {需求} / 启封 {启封}")
    if 错:
        raise RuntimeError(
            "不分区资源需求超过联合调度与中继实际启封（疑似复算路径引入了系统性偏差）：" + "；".join(错)
        )
    return ["[自检] 不分区需求 ≤ 联合调度与中继实际启封（逐资源对照，见下）"] + 条目


