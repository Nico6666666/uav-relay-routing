def 写CSV(行表: list[dict], 列: list, 路径: Path) -> None:
    """列定义表 + lambda 的写法集中管理列，避免手写 writerow 时列错位（规范 §8.1）。"""
    with 路径.open("w", newline="", encoding="utf-8-sig") as f:
        写 = csv.writer(f)
        写.writerow([名 for 名, _ in 列])
        for 行 in 行表:
            写.writerow([取(行) for _, 取 in 列])


