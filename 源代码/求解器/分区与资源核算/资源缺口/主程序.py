def 读四之一() -> dict:
    if not 上游分区方案文件.exists():
        raise FileNotFoundError(
            f"未找到分区配置的输出 {上游分区方案文件}，请先运行 源代码/求解器/分区与资源核算/分区配置/主程序.py"
        )
    return json.loads(上游分区方案文件.read_text(encoding="utf-8"))


class 上下文:
    """复算所得的全部中间对象（本任务**不依赖分区配置的中间量**）。"""

    def __init__(self, 四之一: dict, 方案名: str | None) -> None:
        self.四之一 = 四之一
        self.方案名 = 四之一["口径"]["基线方案名"]
        if 方案名 is not None and 方案名 != self.方案名:
            raise ValueError(
                f"命令行指定的方案名 {方案名} 与分区配置输出中的 {self.方案名} 不一致；"
                f"请用同一基线重跑分区配置"
            )
        self.基线 = 上游读取.读取基线(self.方案名)
        if self.基线.文件SHA256 != 四之一["口径"]["上游文件SHA256"]:
            raise RuntimeError(
                "上游代表方案.json 的 SHA-256 与分区配置输出记录的不一致："
                "上游已被改动，请重跑分区配置"
            )
        self.机型表 = 数据读取.机型表()
        self.电池表 = 数据读取.共享电池表()
        self.中继机型 = 数据读取.中继机型表()
        self.中继无人机 = 数据读取.中继无人机表()
        self.组件表 = 数据读取.中继能源组件表()
        self.服务区表 = 数据读取.服务区表()
        self.库存 = 数据读取.库存()
        self.驻留段 = 上游读取.驻留段表(self.基线)
        self.区间表 = 资源占用.全部区间(
            self.基线, self.机型表, self.电池表, self.中继机型,
            self.中继无人机, self.组件表, self.驻留段,
        )
        self.原子表 = 服务区原子.构建原子(self.基线, self.服务区表)
        self.全局需求 = 资源核算.全局核算(self.区间表)
        self.结果: dict[int, dict] = {}

    def 方案_of(self, k: int, 序: int) -> 分区方案.分区方案:
        """按分区配置落盘的原子索引还原第 `序` 个候选分区。"""
        条目 = self.四之一["分区"][str(k)]["最优及并列"][序]
        分配 = [0] * len(self.原子表)
        for 号, 组 in enumerate(条目["分区_原子索引"]):
            for 原子号 in 组:
                分配[原子号] = 号
        return 分区方案.建方案(k, tuple(分配), self.原子表)


