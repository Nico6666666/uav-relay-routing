def 复算对照(上下文: "上下文") -> list[str]:
    """本任务独立复算 vs 分区配置的输出，逐位比对（§10.2）。

    比对范围：每个候选分区、每个组、每个资源槽的峰值，以及加总 / 库存 / 缺口。
    """
    条目 = []
    错 = []
    for k in 配置.分区组数候选:
        数据 = 上下文.结果[k]
        for 序, (方案, 组需求表) in enumerate(zip(数据["候选"], 数据["组需求"]), start=1):
            条目四之一 = 上下文.四之一["分区"][str(k)]["最优及并列"][序 - 1]
            for 需求 in 组需求表:
                条 = next(x for x in 条目四之一["组资源需求"] if x["组号"] == 需求.组号)
                for 资源类, 子类 in 配置.资源类顺序:
                    名 = f"{资源类}{子类}"
                    if 需求.峰值.get((资源类, 子类), 0) != 条[名]:
                        错.append(f"k={k} 候选{序} 组{需求.组号} {名} 峰值")
            for j, (资源类, 子类) in enumerate(配置.资源类顺序):
                账 = 数据["账表"][j]
                名 = f"{资源类}{子类}"
                for 字段, 本程序值, 四之一值 in (
                    ("加总", 账.各组峰值之和, 条目四之一["加总"][名]),
                    ("库存", 账.库存, 条目四之一["库存"][名]),
                    ("缺口", 账.缺口, 条目四之一["缺口"][名]),
                    ("冗余", 账.冗余, 条目四之一["冗余"][名]),
                ):
                    if 本程序值 != 四之一值:
                        错.append(f"k={k} 候选{序} {名} {字段}（{本程序值} vs {四之一值}）")
    if 错:
        raise RuntimeError(
            f"资源缺口复算与分区配置输出不一致（共 {len(错)} 处）：" + "；".join(错[:10])
        )
    for k in 配置.分区组数候选:
        条目.append(
            f"[自检] 复算对照 k={k}：{len(上下文.结果[k]['候选'])} 个候选 × 各组峰值 / 加总 / "
            f"库存 / 缺口 / 冗余 与本任务独立复算逐位一致（偏差 0）"
        )
    return 条目


def 自检(上下文: "上下文") -> list[str]:
    条目 = list(
        口径自检.内核自检(
            上下文.基线, 上下文.机型表, 上下文.电池表, 上下文.中继机型,
            上下文.中继无人机, 上下文.组件表, 上下文.区间表, 上下文.库存,
        )
    )
    条目.append(
        f"[自检] 同一份上游：分区配置与本任务读到的方案名均为「{上下文.方案名}」，"
        f"代表方案.json 的 SHA-256 一致（{上下文.基线.文件SHA256[:16]}…）"
    )
    条目.extend(复算对照(上下文))
    for k in 配置.分区组数候选:
        条目.append(
            f"[自检] k={k} 候选方案数独立核对：分区配置报出 "
            f"{上下文.四之一['分区'][str(k)]['候选方案数']}，本任务按斯特林数 S({len(上下文.原子表)},{k}) "
            f"算得 {分区枚举.规范形合法方案数(k, len(上下文.原子表))}，一致"
        )
        if (
            上下文.四之一["分区"][str(k)]["候选方案数"]
            != 分区枚举.规范形合法方案数(k, len(上下文.原子表))
        ):
            raise RuntimeError(f"k={k} 的候选方案数与独立实现不符，分区配置的枚举结果可疑")
    for k in 配置.分区组数候选:
        条目.extend(缺口归因.归因自检(上下文.结果[k]["归因"]))
    条目.append(
        "[自检] 逐刻度恒等式：各组并发数之和 == 全体并发数（由区间图的段表定义直接保证），"
        "「跨组复用丢失」全部结论建立在此算术自洽之上"
    )
    return 条目


