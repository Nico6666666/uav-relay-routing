def 取命令参数() -> argparse.Namespace:
    解析 = argparse.ArgumentParser(description="分区与资源核算资源缺口：资源缺口及其原因")
    解析.add_argument("--方案", default=None, choices=配置.方案名可选值,
                      help="校验用：必须与分区配置输出中的基线方案名一致")
    return 解析.parse_args()


def main() -> None:
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except Exception:  # 仅为兼容旧终端的编码设置，失败可忽略（规范 §6 允许的无害尝试）
        pass

    输出目录.mkdir(parents=True, exist_ok=True)
    图表目录.mkdir(parents=True, exist_ok=True)

    四之一 = 读四之一()
    参数 = 取命令参数()
    上下文对象 = 上下文(四之一, 参数.方案)

    print("=" * 78)
    print(f"分区与资源核算 · 资源缺口：资源缺口及其原因（基线 {上下文对象.方案名}）")
    print("=" * 78)

    print("\n[1/5] 读分区配置输出并独立复算")
    for k in 配置.分区组数候选:
        条目 = 四之一["分区"][str(k)]
        候选 = [上下文对象.方案_of(k, 序) for 序 in range(len(条目["最优及并列"]))]
        组需求 = tuple(
            资源核算.逐组核算(方案, 上下文对象.区间表, 上下文对象.基线) for 方案 in 候选
        )
        账表 = 资源核算.核算汇总(组需求[0], 上下文对象.全局需求, 上下文对象.库存)
        归因 = 缺口归因.归因(账表, 上下文对象.区间表, 候选[0], 组需求[0])
        证据 = 缺口归因.紧约束明细(上下文对象.区间表, 上下文对象.全局需求, 组需求[0])
        上下文对象.结果[k] = {
            "候选": 候选, "组需求": 组需求, "账表": 账表, "归因": 归因, "证据": 证据,
        }
        print(f"     k={k}：候选 {条目['候选方案数']} 个，复算缺口 "
              f"{sum(账.缺口 for 账 in 账表)} 单位")

    print("\n[2/5] 自检")
    自检记录 = 自检(上下文对象)
    for 条 in 自检记录:
        print("     " + 条)

    print("\n[3/5] 写出结果")
    逐资源行 = [
        {"k": k, **资源账.资源账字典(项.账), "跨组段数": 项.跨组段数,
         "重复计数增量": 项.重复计数增量, "主因": 项.主因}
        for k in 配置.分区组数候选
        for 项 in 上下文对象.结果[k]["归因"]
    ]
    写CSV(逐资源行, 逐资源列, 输出目录 / "资源缺口_逐资源.csv")
    写CSV(
        [{"k": k, **行} for k in 配置.分区组数候选 for 行 in 上下文对象.结果[k]["证据"]],
        证据列, 输出目录 / "紧约束区间_逐资源.csv",
    )
    # 占用区间与分区无关（k 只决定组归属），故只落一份，避免重复行
    区间行 = []
    for 键, 区间 in 上下文对象.区间表.区间.items():
        for x in 区间:
            起, 终 = 区间图.量化区间(x)
            区间行.append({
                "资源类": 键[0], "子类": 键[1], "载体": x.载体,
                "左_s": x.左_s, "右_s": x.右_s, "来源": x.来源,
                "服务架次": x.服务架次, "刻度起": 起, "刻度终": 终,
            })
    写CSV(区间行, 区间列, 输出目录 / "资源占用区间.csv")
    写JSON(上下文对象, 自检记录, 输出目录 / "资源缺口.json")
    写Markdown(上下文对象, 自检记录, 输出目录 / "资源缺口与原因.md")
    print(f"     已写出 3 个表与 1 份 JSON/1 份 Markdown：{输出目录}")

    print("\n[4/5] 出图")
    for p in 绘图(上下文对象):
        print(f"     {p.relative_to(项目根)}")

    print("\n[5/5] 摘要")
    for k in 配置.分区组数候选:
        账表 = 上下文对象.结果[k]["账表"]
        缺口 = "；".join(f"{账.显示名} +{账.缺口}" for 账 in 账表 if 账.缺口) or "无"
        print(f"{k} 分区：Δ 合计 {sum(账.跨组复用丢失 for 账 in 账表)}，缺口合计 "
              f"{sum(账.缺口 for 账 in 账表)}（{缺口}）")
    print(f"\n输出目录：{输出目录}")


if __name__ == "__main__":
    main()
