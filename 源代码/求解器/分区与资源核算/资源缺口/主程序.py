def _存图(图, 名: str) -> list[Path]:
    import matplotlib.pyplot as plt

    产出 = []
    for 后缀 in ("png", "svg"):
        p = 图表目录 / f"{名}.{后缀}"
        图.savefig(p, dpi=300)
        产出.append(p)
    plt.close(图)
    return 产出


def _初始化绘图():
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    plt.rcParams["font.sans-serif"] = ["Microsoft YaHei", "SimHei", "SimSun"]
    plt.rcParams["axes.unicode_minus"] = False
    plt.rcParams["svg.fonttype"] = "none"
    return plt


def 图_缺口与分解(上下文: "上下文", 名: str) -> list[Path]:
    plt = _初始化绘图()
    槽 = [f"{a}{b}" for a, b in 配置.资源类顺序]
    图, 轴表 = plt.subplots(1, 2, figsize=(14, 5.5))
    轴 = 轴表[0]
    宽 = 0.35
    for i, k in enumerate(配置.分区组数候选):
        数据 = 上下文.结果[k]
        值 = [项.账.缺口 for 项 in 数据["归因"]]
        轴.bar([x + (i - 0.5) * 宽 for x in range(len(槽))], 值, 宽,
               label=f"{k} 分区", color=组颜色[i])
        for x, v in enumerate(值):
            if v:
                轴.annotate(str(v), (x + (i - 0.5) * 宽, v), ha="center", va="bottom", fontsize=9)
    轴.set_xticks(range(len(槽)))
    轴.set_xticklabels(槽, rotation=20)
    轴.set_ylabel("缺口（架 / 组）")
    轴.set_title("图1 各资源的资源缺口")
    轴.legend()
    轴.grid(alpha=0.3, axis="y", linestyle=":")

    轴 = 轴表[1]
    for i, k in enumerate(配置.分区组数候选):
        数据 = 上下文.结果[k]
        轴.bar([x + (i - 0.5) * 宽 for x in range(len(槽))],
               [项.账.跨组复用丢失 for 项 in 数据["归因"]], 宽,
               label=f"{k} 分区 Δ", color=组颜色[i])
    轴.set_xticks(range(len(槽)))
    轴.set_xticklabels(槽, rotation=20)
    轴.set_ylabel("跨组复用丢失 Δ（架 / 组）")
    轴.set_title("图2 跨组复用丢失 Δ（缺口 = max(Δ + 全局峰值 − 库存, 0)）")
    轴.legend()
    轴.grid(alpha=0.3, axis="y", linestyle=":")
    图.suptitle(f"资源缺口与其分解（{上下文.方案名}基线，口径 E）")
    return _存图(图, 名)


def 图_并发时间线与紧约束(上下文: "上下文", 槽: tuple[str, str], k: int, 编号: str, 名: str) -> list[Path]:
    """占用区间甘特图 + 各组峰段标注（紧约束证据的可视化）。"""
    plt = _初始化绘图()
    数据 = 上下文.结果[k]
    图, 轴 = plt.subplots(figsize=(12, 6))
    有序 = sorted(上下文.区间表.取(*槽), key=lambda x: x.左_s)
    颜色 = 中继色 if 槽[0] == "中继无人机" else 机型颜色.get(槽[1], 组颜色[0])
    for y, 成员 in enumerate(有序):
        轴.barh(y, 成员.右_s - 成员.左_s, left=成员.左_s, height=0.6, color=颜色)
        轴.annotate(
            f"{成员.载体}（{成员.来源}）", (成员.左_s, y),
            xytext=(3, -3), textcoords="offset points", fontsize=7,
        )
    轴.set_yticks([])
    轴.set_ylim(-0.8 - k * 0.6, max(len(有序), 1))
    轴.set_xlabel("时刻（s）")
    轴.set_title(
        f"图{编号} {槽[0]}{槽[1]} 占用区间与各组峰段"
        f"（{k} 分区；不分区峰值 {上下文.全局需求.取(*槽)}）"
    )
    for 需求 in 数据["组需求"][0]:
        团 = 需求.紧约束.get(槽)
        if 团 is None or 团.峰值 == 0:
            continue
        轴.axvspan(团.峰段起_s, 团.峰段终_s, alpha=0.12, color=组颜色[需求.组号 - 1])
        轴.annotate(
            f"组{需求.组号} 峰值 {团.峰值}",
            (团.峰段起_s, -0.6 - 需求.组号 * 0.55),
            color=组颜色[需求.组号 - 1], fontsize=9,
        )
    轴.grid(alpha=0.3, axis="x", linestyle=":")
    return _存图(图, 名)


def 绘图(上下文: "上下文") -> list[Path]:
    return [
        *图_缺口与分解(上下文, "图1_资源缺口与跨组复用丢失"),
        *图_并发时间线与紧约束(上下文, ("中继无人机", ""), 3, "2", "图2_中继驻留段与各组峰段_3分区"),
        *图_并发时间线与紧约束(
            上下文, ("运输无人机", "C"), 3, "3", "图3_运输无人机C占用与各组峰段_3分区"
        ),
    ]


